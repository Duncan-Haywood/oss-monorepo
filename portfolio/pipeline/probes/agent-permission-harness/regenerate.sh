#!/usr/bin/env bash
# Single source of truth for how the committed results file is produced.
#
# The file is harness.py's output with a provenance header prepended. CI
# rebuilds it the same way and diffs, so anyone regenerating by hand with a
# bare `python3 harness.py > results-...md` drops the header and turns the
# check red without touching a single finding — which is what kept happening
# while the header and the README each documented that bare command.
#
# Usage: ./regenerate.sh            # rewrite the committed snapshot in place
#        ./regenerate.sh /dev/stdout # print it instead (CI diffs this)
set -euo pipefail

cd "$(dirname "$0")"

SNAPSHOT="results-2026-08-23.md"
OUT="${1:-$SNAPSHOT}"

{
  echo "<!-- Generated by harness.py against main. Regenerate: ./regenerate.sh -->"
  echo
  python3 harness.py
} > "$OUT"
