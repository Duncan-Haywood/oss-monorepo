#!/usr/bin/env python3
"""Assert the committed results file still describes this checkout.

Why this is not a plain `diff`
------------------------------

The obvious check is to regenerate the markdown and `diff -u` it against the
committed file. That is what CI did until 2026-08-24, and on a repository that
merges continuously it is permanently red, for a reason no author can fix from
inside their own pull request:

R7's finding text embeds `len(closure)` -- the size of the transitive set of
documents the agent prompt directs a read of. That set is a function of the
*whole repository's prose*, not of the probe's inputs. So a pull request that
adds an ordinary markdown file naming a new path enlarges the number, and:

  * the number is correct at that PR's head, so the PR is green; and
  * `main` then carries a results file whose number is one merge out of date,
    so the next push to `main` is red;
  * regenerating the snapshot produces a PR that is itself stale by the time
    it merges, because other pull requests keep landing.

Runs 436, 442, 447, 458 and 463 on `main` were all this, and the snapshot-regen
pull requests chasing them (#954, #955) could not win the race. Byte-equality
on a whole-repo-derived measurement is the bug, not the staleness it reports.

What is still gated
-------------------

Everything that is a claim about the probe rather than a census of the
repository. The finding set, the rules that fire and stay silent, the workflow
and job and line each finding names, the severities, the per-rule counts and
all of the surrounding prose are compared byte for byte. A workflow edit that
adds, removes or moves a finding still fails here, which is the failure mode
this file exists to catch -- "a stale results file that still reads as a
measurement".

What is normalised
------------------

Only R7's volatile census: the closure total, its per-depth histogram, the
first-hop count, and the sampled file list. Both sides are normalised, so a
change to any of them alone is not a failure; a change to anything around them
still is.

Also each finding's line number, added 2026-08-24 after the census masking
landed. It is the same argument one level in: a line number is where a finding
is, not which finding it is, and every finding below an edit shifts. Without
masking it the gate fails on a workflow change that alters no grant -- adding a
comment, a step, or the very `permissions:` block R5 recommends -- which is
again drift the author cannot act on except by regenerating. The finding's
rule, workflow, job and severity are still compared, so a finding relocating to
a *different job* still fails; only a pure line shift stops failing.

Dropping the exact number from the gate loses no assertion, because the test
suite never pinned it either. `TestHeadlineNumbersAgainstThisRepo` deliberately
asserts the *claim* -- that the closure is an order of magnitude larger than
the prompt, and that its fixed point is strictly past the first hop -- and says
why: "The exact count moves with every venture added". This script brings the
CI gate in line with the assertion the tests already chose.

The committed file keeps the real numbers, so a reader still sees a measurement
rather than a placeholder. They are refreshed whenever someone regenerates it;
they are simply no longer a merge-blocking assertion about a moving repository.

Exit status is 0 when current, 1 when the committed file needs regenerating.

Pass `--write` to regenerate the committed file instead of checking it. That is
the only supported way to produce it: this module owns HEADER, so writing the
file from here is what keeps the documented command and the checked command
from drifting apart.
"""

from __future__ import annotations

import difflib
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results-2026-08-23.md"
HEADER = (
    "<!-- Generated by harness.py against main. "
    "Regenerate: python3 check_results_current.py --write -->"
)

# Each pattern brackets a number or list that counts repository documents. The
# replacement keeps the sentence shape so that an edit to the *prose* around a
# number is still a diff -- only the census itself is masked.
VOLATILE = (
    # "agent instruction set is 78 repository files, not the 1 prompt file(s)"
    # The prompt-file count is deliberately left alone: it is a property of the
    # workflow under test, not of the repository's prose.
    (re.compile(r"agent instruction set is \d+ repository files"),
     "agent instruction set is <closure-size> repository files"),
    # "which resolve to 4 files in this checkout"
    (re.compile(r"which resolve to \d+ files in this checkout"),
     "which resolve to <first-hop> files in this checkout"),
    # "the fixed point of that is 78 files (4 at depth 1, 37 at depth 2, ...)"
    (re.compile(r"fixed point of that is \d+ files \([^)]*\)"),
     "fixed point of that is <closure-size> files (<per-depth>)"),
    # ", among them `A`, `B`, ... . Every one is" -- a sample of the closure,
    # so its membership moves for the same reason the count does. Anchored on
    # the sentence that follows so an empty sample stays distinguishable.
    (re.compile(r", among them .*?\. Every one is", re.DOTALL),
     ", among them <sample>. Every one is"),
    # "job `opencode-agent` (line 109)** --" -- where a finding is, not which
    # finding it is. Every finding below an edit shifts, so without this the
    # gate fails on a workflow change that alters no grant at all: adding a
    # comment, a step, or the very `permissions:` block R5 recommends. That is
    # the same shape as the census problem this file was written to fix -- a
    # gate reporting drift that the author cannot act on -- one level in, and
    # it trains the "regenerate without reading" reflex that would let a real
    # posture change through unexamined.
    #
    # This is not a hole in the gate. The rule, workflow, job, severity,
    # writer set, privilege and every surrounding sentence are still compared
    # byte for byte, so a finding that appears, disappears, changes rule or
    # moves to a *different job* still fails here. Only a pure line shift
    # stops failing, and a pure line shift is not a posture change.
    (re.compile(r"\(line \d+\)"), "(line <n>)"),
)


def normalise(text: str) -> str:
    """Mask the repository-census numbers R7 reports, on both sides."""
    for pattern, replacement in VOLATILE:
        text = pattern.sub(replacement, text)
    return text


def regenerate() -> str:
    """Render the results document: harness.py's output under HEADER.

    This is the only place that recipe lives. It used to be spelled out in
    three: here, in the workflow, and in the header line itself -- and the
    header's spelling was `python3 harness.py > results-2026-08-23.md`, which
    omits the header and so produced a file this check rejects. Anyone who
    regenerated the way the file told them to turned CI red without changing a
    finding. `--write` exists so the recipe has exactly one spelling and the
    documented command is the one that runs.
    """
    proc = subprocess.run(
        [sys.executable, "harness.py"],
        cwd=HERE,
        capture_output=True,
        text=True,
        check=True,
    )
    return f"{HEADER}\n\n{proc.stdout}"


def main(argv: list[str] = ()) -> int:
    # Defaults to no arguments rather than reading sys.argv, so that calling
    # main() from a test does not pick up the test runner's own argv. The
    # entry point below passes the real arguments explicitly.
    argv = list(argv)
    if argv == ["--write"]:
        RESULTS.write_text(regenerate())
        print(f"Wrote {RESULTS.name}")
        return 0
    if argv:
        print(f"usage: {Path(__file__).name} [--write]", file=sys.stderr)
        return 2

    committed = RESULTS.read_text()
    generated = regenerate()

    if normalise(committed) == normalise(generated):
        return 0

    # Report the real diff, not the normalised one: the masked form exists to
    # decide the question, but a human fixing this needs the actual text.
    diff = difflib.unified_diff(
        committed.splitlines(keepends=True),
        generated.splitlines(keepends=True),
        fromfile=str(RESULTS.name),
        tofile="regenerated",
    )
    sys.stdout.writelines(diff)
    print(
        f"\n{RESULTS.name} no longer matches harness.py against this checkout, "
        "in a way that is not just the closure census.\n"
        f"Regenerate it:  cd {HERE} && python3 {Path(__file__).name} --write",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
