#!/usr/bin/env python3
"""Install the pinned scanners listed in tools.json, verifying each by checksum.

Go tools (gitleaks, OSV-Scanner, Trivy, OpenTofu): `go mod download -json
<module>@<version>` fetches the module zip from the Go module proxy, the go
command checks it against sum.golang.org, and this script then refuses to build
unless the zip's h1: hash equals the `sum` pinned in tools.json. The binary is
built from that exact source with the module's own go.sum verifying every
dependency (`-mod=readonly`). Building inside the module directory means the
module's own `replace` lines apply, which `go install mod@ver` refuses.

Why not the GitHub release binaries: the cloud sessions that write and test
this code cannot reach github.com release assets through their proxy (HTTP
403), and one install path for CI and sessions keeps the two from drifting.

Python tools (Semgrep, Checkov, zizmor): one virtualenv each, installed with
`pip install --require-hashes --no-deps -r requirements/<tool>.txt`, a lock
generated by `uv pip compile --generate-hashes` (README.md, "Bumping a
scanner").

    python3 platform/security/scan/install.py                 # all tools
    python3 platform/security/scan/install.py --only gitleaks,semgrep
    python3 platform/security/scan/install.py --print-dir     # where they live

Tools land in $SCAN_TOOLS_DIR (default ~/.cache/oss-monorepo-security-scan):
bin/<tool> plus a .pin file per tool, so a rerun with unchanged pins is a no-op.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS_FILE = HERE / "tools.json"


def load_tools(path: Path = TOOLS_FILE) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def tools_dir() -> Path:
    return Path(os.environ.get("SCAN_TOOLS_DIR") or Path.home() / ".cache" / "oss-monorepo-security-scan")


def pin_of(kind: str, spec: dict, requirements_text: str = "") -> str:
    """The string a tool's .pin file must hold for the install to count as current."""
    if kind == "go":
        return f"go {spec['module']}@{spec['version']} {spec['sum']} {spec.get('package', '')} {spec.get('ldflags', '')}".strip()
    import hashlib
    return f"py {spec['version']} " + hashlib.sha256(requirements_text.encode()).hexdigest()


def check_sum(name: str, expected: str, got: str | None) -> None:
    """Refuse a module whose downloaded hash differs from the pinned one."""
    if not got or got != expected:
        raise SystemExit(f"install: {name}: checksum mismatch: pinned {expected}, downloaded {got!r}. "
                         "Refusing to build. A version bump needs its new sum (README.md).")


def requirements_are_hashed(text: str) -> bool:
    """Every requirement line carries at least one --hash (pip enforces it too; fail early and clearly)."""
    reqs = 0
    blocks = text.replace("\\\n", " ").splitlines()
    for line in blocks:
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        reqs += 1
        if "--hash=sha256:" not in line:
            return False
    return reqs > 0


def is_current(dest: Path, name: str, pin: str) -> bool:
    marker = dest / "pins" / f"{name}.pin"
    return (dest / "bin" / name).exists() and marker.exists() and marker.read_text().strip() == pin


def mark(dest: Path, name: str, pin: str) -> None:
    (dest / "pins").mkdir(parents=True, exist_ok=True)
    (dest / "pins" / f"{name}.pin").write_text(pin + "\n")


def install_go(dest: Path, name: str, spec: dict) -> None:
    if not shutil.which("go"):
        raise SystemExit("install: the go command is needed to build the Go scanners (actions/setup-go in CI)")
    env = dict(os.environ, CGO_ENABLED="0", GOFLAGS="-mod=readonly", GOTOOLCHAIN=os.environ.get("GOTOOLCHAIN", "auto"))
    env.pop("GONOSUMDB", None)
    env.pop("GONOSUMCHECK", None)
    env.pop("GOFLAGS_EXTRA", None)
    if env.get("GOSUMDB") == "off":
        raise SystemExit("install: GOSUMDB=off would skip the checksum database; unset it")
    ref = f"{spec['module']}@{spec['version']}"
    with tempfile.TemporaryDirectory() as tmp:
        out = subprocess.run(["go", "mod", "download", "-json", ref], cwd=tmp, env=env,
                             capture_output=True, text=True)
    info = json.loads(out.stdout or "{}")
    if out.returncode or info.get("Error"):
        raise SystemExit(f"install: {name}: go mod download failed: {info.get('Error') or out.stderr.strip()}")
    check_sum(name, spec["sum"], info.get("Sum"))
    (dest / "bin").mkdir(parents=True, exist_ok=True)
    cmd = ["go", "build", "-trimpath", "-o", str(dest / "bin" / name)]
    if spec.get("ldflags"):
        cmd += ["-ldflags", spec["ldflags"]]
    cmd.append(spec["package"])
    print(f"install: building {name} {spec['version']} (sum verified)", flush=True)
    subprocess.run(cmd, cwd=info["Dir"], env=env, check=True)


def install_py(dest: Path, name: str, spec: dict) -> None:
    req = HERE / spec["requirements"]
    if not requirements_are_hashed(req.read_text(encoding="utf-8")):
        raise SystemExit(f"install: {req} has a requirement without --hash; regenerate it (README.md)")
    venv = dest / "venvs" / name
    if venv.exists():
        shutil.rmtree(venv)
    subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    print(f"install: pip {name} {spec['version']} (hash-locked)", flush=True)
    subprocess.run([str(venv / "bin" / "python"), "-m", "pip", "install", "--quiet", "--disable-pip-version-check",
                    "--require-hashes", "--no-deps", "--only-binary=:all:", "-r", str(req)], check=True)
    (dest / "bin").mkdir(parents=True, exist_ok=True)
    link = dest / "bin" / spec["bin"]
    if link.exists() or link.is_symlink():
        link.unlink()
    link.symlink_to(venv / "bin" / spec["bin"])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--only", help="comma-separated tool names (default: all)")
    ap.add_argument("--print-dir", action="store_true", help="print the tools directory and exit")
    args = ap.parse_args(argv)
    dest = tools_dir()
    if args.print_dir:
        print(dest)
        return 0
    tools = load_tools()
    wanted = set(args.only.split(",")) if args.only else None
    known = set(tools["go"]) | set(tools["python"])
    if wanted and wanted - known:
        raise SystemExit(f"install: unknown tool(s): {', '.join(sorted(wanted - known))}")
    for kind in ("go", "python"):
        for name, spec in tools[kind].items():
            if wanted and name not in wanted:
                continue
            req_text = (HERE / spec["requirements"]).read_text(encoding="utf-8") if kind == "python" else ""
            pin = pin_of(kind, spec, req_text)
            if is_current(dest, spec.get("bin", name), pin):
                print(f"install: {name} {spec['version']} already installed")
                continue
            (install_go if kind == "go" else install_py)(dest, name, spec)
            mark(dest, spec.get("bin", name), pin)
    print(dest / "bin")
    return 0


if __name__ == "__main__":
    sys.exit(main())
