// Write `ventures/README.md`: the catalogue of every tool in `ventures/`,
// grouped the way the site groups it, each linked to its live page.
//
// Why it exists. `ventures/` holds over 1,300 directories and GitHub's folder
// view stops listing at 1,000, so a visitor browsing the repository could not
// see a quarter of the tools, and the folder page told a searcher nothing about
// what any of them does. This file is that folder's front page: plain titles a
// person would search for, a link to the usable page, and a link to the code.
//
// Everything is read from what the site build already uses (`discoverSurfaces`,
// `groupByCategory`, `readMeta`), so the README and the site cannot file a tool
// differently. Re-run it after adding tools; a tool missing from this list is
// still on the site, and `ventures-readme.test.mjs` fails only if the list
// names a directory that no longer exists.
//
//   node platform/pages/ventures-readme.mjs          # rewrite ventures/README.md
//   node platform/pages/ventures-readme.mjs --stdout # print instead

import { readFile, readdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  REPO_ROOT, DEFAULT_BASE_URL, discoverSurfaces, groupByCategory, readMeta, categoryPagePath,
} from './build.mjs';

const VENTURES = path.join(REPO_ROOT, 'ventures');

/** One list line. Markdown-special characters in a title are escaped. */
export function toolLine({ slug, title, baseUrl = DEFAULT_BASE_URL }) {
  const text = title.replace(/([\\[\]])/g, '\\$1');
  return `- [${text}](${baseUrl}${slug}/) · [code](${slug}/)`;
}

export function renderVenturesReadme({ groups, others = [], baseUrl = DEFAULT_BASE_URL }) {
  const total = groups.reduce((n, g) => n + g.items.length, 0);
  const out = [];
  out.push('# Free business calculators, CSV checkers and self-hosted apps: the full catalogue');
  out.push('');
  out.push(`Every tool in this folder (${total} when this list was last generated), grouped the way the live site`);
  out.push('groups them. Each line links to the **free web version**, which needs no account and, for all but the');
  out.push('self-hosted apps, runs entirely in your browser, and to its **source code** here, MIT licensed, so you');
  out.push('can run, fork or self-host your own copy.');
  out.push('');
  out.push(`**Search and use them all at [${baseUrl}](${baseUrl}).**`);
  out.push('Looking for your trade or kind of business? The [repository front page](../README.md) links a page of');
  out.push('free tools for each one (roofers, Etsy sellers, landlords, freelancers and more).');
  out.push('');
  out.push('## Sections');
  out.push('');
  for (const { category, items } of groups) {
    out.push(`- [${category.title}](#${anchor(category.title)}) (${items.length})`);
  }
  if (others.length) out.push(`- [Other directories](#other-directories) (${others.length})`);
  out.push('');
  for (const { category, items } of groups) {
    out.push(`## ${category.title}`);
    out.push('');
    out.push(`${category.blurb} [Browse this section on the site →](${baseUrl}${categoryPagePath(category.id)})`);
    out.push('');
    for (const item of items) out.push(toolLine({ ...item, baseUrl }));
    out.push('');
  }
  if (others.length) {
    out.push('## Other directories');
    out.push('');
    out.push('Projects here without a page of their own on the site (servers, infrastructure, the portfolio\'s own tooling):');
    out.push('');
    for (const slug of others) out.push(`- [\`${slug}\`](${slug}/)`);
    out.push('');
  }
  out.push('## How a tool folder is laid out');
  out.push('');
  out.push('Each `ventures/<name>/` is self-contained: an `index.html` that is the tool itself (open it in a browser,');
  out.push('no build step), its own `README.md` and tests, a `VENTURE.yaml` the portfolio reads, and an MIT `LICENSE`.');
  out.push('Some also ship a command-line version or a server you can deploy. How to build one:');
  out.push('[`PRODUCT_PLAYBOOK.md`](../PRODUCT_PLAYBOOK.md).');
  out.push('');
  out.push('<!-- Generated by platform/pages/ventures-readme.mjs. Edit that script, not this file. -->');
  out.push('');
  return out.join('\n');
}

/** GitHub's heading anchor: lowercase, punctuation dropped, spaces to hyphens. */
export function anchor(heading) {
  return heading.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');
}

export async function collect(venturesDir = VENTURES) {
  const surfaces = await discoverSurfaces(venturesDir);
  const titled = await Promise.all(surfaces.map(async (s) => ({
    ...s, title: readMeta(await readFile(s.entryFile, 'utf8'), s.slug).title,
  })));
  const listed = new Set(surfaces.map((s) => s.slug));
  const others = [];
  for (const entry of await readdir(venturesDir, { withFileTypes: true })) {
    if (entry.isDirectory() && !listed.has(entry.name) && !entry.name.startsWith('.')) {
      try {
        await stat(path.join(venturesDir, entry.name, 'README.md'));
        others.push(entry.name);
      } catch { /* not a project directory */ }
    }
  }
  return { groups: groupByCategory(titled), others: others.sort() };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = renderVenturesReadme(await collect());
  if (process.argv.includes('--stdout')) process.stdout.write(md);
  else {
    await writeFile(path.join(VENTURES, 'README.md'), md);
    console.log(`wrote ventures/README.md (${md.length} bytes)`);
  }
}
