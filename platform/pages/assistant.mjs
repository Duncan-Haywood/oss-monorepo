// The site assistant, as the build ships it.
//
// Voice, chat and agents are first-class ways into every tool here, beside
// the visual form (owner direction, 2026-10-20; PRODUCT_PLAYBOOK.md §4, "Every way in").
// The working code is in assistant/:
//
//   assistant/fill.mjs    sentence -> form values, no model   -> /pf-fill.js
//   assistant/client.js   the panel, engines, voice, WebMCP   -> /pf-assistant.js
//   assistant/worker.js   on-device LLM and Whisper           -> /pf-ai-worker.js
//   assistant/evals.json  real sentences against real forms   (scored below)
//
// This file decides how little of it a page pays for. Every page gets
// `ASSISTANT_LAUNCHER_JS` inside pf-site.js, which it already loads: well
// under a kilobyte that turns the header's "Ask" link (and, on a calculator, a
// voice button) into a lazy `import()` of pf-assistant.js. A visitor who never
// asks downloads nothing more; a visitor who asks downloads ~40 KB; a model
// or speech recogniser downloads only after a click that names its size.

import { readFileSync } from 'node:fs';
