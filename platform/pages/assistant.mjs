/**
 * The files the build writes at the site root. `pf-search.js` is generated
 * from the hub's own tested search functions, passed in, so the assistant
 * ranks tools exactly as the search box does.
 */
export function renderAssistantFiles({ searchVariants, searchScore }) {
  const files = {};
  for (const [published, source] of Object.entries(ASSISTANT_FILES)) {
    files[published] = readFileSync(path.join(REPO_ROOT, source), 'utf8');
  }
  // byok.mjs's usage comment names its repository filename; served, it is this one.
  files['pf-byok.js'] = files['pf-byok.js'].replace(/'\.\/byok\.mjs'/g, "'./pf-byok.js'");
  files['pf-search.js'] = `// Generated by platform/pages/assistant.mjs from build.mjs's search functions.\nexport ${searchVariants.toString()}\nexport ${searchScore.toString()}\n`;
  return files;
}

