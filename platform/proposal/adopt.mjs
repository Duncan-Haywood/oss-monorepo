/**
 * What the page calls the two functions the proposal has to call.
 *
 * `grep -c 'function readInput'` cannot tell `readInput` from `readInputs` —
 * it matches the plural as a substring — and a proposal calling the wrong one
 * throws `readInput is not defined` at click time while every text-level test
 * stays green. Match the open parenthesis.
 *
 * The call site is matched with **any** arguments, not only `readInput()`.
 * The house pattern is `function readInput(rows = readRows())`, so `update`
 * passes rows it has already read and every other caller takes the default —
 * and a calculator whose only call site happens to be the one inside `update`
 * is not thereby unable to adopt. What the generated proposal actually needs
 * is that the reader is callable with *no* arguments, and that is checked
 * directly by `readerTakesNoArguments` rather than inferred from a call site.
 */
function detectFunctions(html) {
  const reader = /function\s+(readInputs?)\s*\(/.exec(html)?.[1];
  const calcFn = /\b(calculate[A-Za-z]*|priceJob|priceBid)\s*\(\s*(readInputs?)\s*\(/.exec(html)?.[1];
  return { reader, calcFn };
}

/**
 * Whether `readInput()` — with the empty argument list the generated proposal
 * uses — yields a whole input.
 *
 * A reader declared `function readInput(rows)` with no default is called by
 * the proposal as `readInput()`, so `rows` is `undefined`: the calculator
 * either throws inside the print handler or, worse, prices the job without
 * its rows and puts that number on a customer's quote. Neither is visible to
 * a text-level test. Every declared parameter must therefore carry a default.
 */
function readerTakesNoArguments(html, reader) {
  if (!reader) return false;
  const at = new RegExp(`function\\s+${reader}\\s*\\(`).exec(html);
  if (!at) return false;
  // Balance the parenthesis rather than matching `[^)]*`: the first `)` in
  // `readInput(a = one(), b)` belongs to the default's own call, and stopping
  // there hides the parameter that has no default at all.
  const open = at.index + at[0].length - 1;
  let depth = 0;
  let close = -1;
  for (let i = open; i < html.length; i += 1) {
    if (html[i] === '(') depth += 1;
    else if (html[i] === ')') { depth -= 1; if (depth === 0) { close = i; break; } }
  }
  if (close < 0) return false;
  const params = html.slice(open + 1, close).trim();
  if (params === '') return true;
  return splitParameters(params).every(param => param.includes('='));
}

/**
 * Split a parameter list on the commas that separate parameters, ignoring the
 * commas inside a default value — `rows = readRows(a, b)` is one parameter,
 * and a naive `.split(',')` reads it as two, the second of which has no `=`
 * and would fail the check above.
 */
function splitParameters(params) {
  const out = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < params.length; i += 1) {
    const ch = params[i];
    if (ch === '(' || ch === '[' || ch === '{') depth += 1;
    else if (ch === ')' || ch === ']' || ch === '}') depth -= 1;
    else if (ch === ',' && depth === 0) {
      out.push(params.slice(start, i));
      start = i + 1;
    }
  }
  out.push(params.slice(start));
  return out.map(part => part.trim()).filter(part => part !== '');
}

/**
 * The expression that yields the price the customer is quoted.
 *
 * Most calculators here let the contractor type a price they are considering
 * (`proposed`); the customer must be quoted that one when it is set, and the
 * calculated price otherwise. A calculator without the field just quotes its
 * own price — detected from the result shape rather than assumed, because
 * `result.proposed` on a page that has no such field is `undefined`, and
 * `undefined.price` throws inside the print handler.
 */
function priceExpressionFor(resultKeys, priceField) {
  if (resultKeys && resultKeys.includes('proposed')) {
    return `result.proposed === null || result.proposed === undefined ? result.${priceField} : result.proposed.price`;
  }
  return `result.${priceField}`;
}

/**
 * The top-level keys of the object the calculator returns.
 *
 * Read from `calc.mjs` rather than taken on trust from `trades.json`, so
 * `proposed` cannot be claimed for a calculator that has no such field — which
 * would put `undefined.price` inside the print handler.
 */
function resultKeysOf(slug) {
  const file = path.join(VENTURES, slug, 'calc.mjs');
  if (!fs.existsSync(file)) return [];
  const source = fs.readFileSync(file, 'utf8');
  // The *entry* function, not merely the first `calculate*` in the file.
  //
  // These modules export their stages as well as their entry point, and the
  // stages are declared first because the entry calls them: `security-camera`
  // exports `calculateStorage`, `calculatePoe` and `calculateCabling` above
  // `calculateBid`. Taking the first match read `calculateStorage`'s return —
  // terabytes and retention days — and then reported that the venture's own
  // `bidPrice` did not exist, which is a confusing way to say "looked at the
  // wrong function".
  //
  // So prefer the conventional entry names, in the order a page would call
  // them, and keep the original first-match as the fallback. For every venture
  // whose entry is also its first `calculate*` — which is all 100 adopters —
  // this returns exactly what it returned before.
  const entry = /export function (calculateBid|priceJob|priceBid)\s*\(/.exec(source)
    ?? /export function (calculate[A-Za-z]*|priceJob|priceBid)\s*\(/.exec(source);
  if (!entry) return [];

  // Only the entry function's *own* body. The matcher below is greedy across
  // whatever it is given, and these modules declare more functions after the
  // entry — so on a calculator whose entry returns on one line, it ran past
  // the end of that function and matched the next multi-line `return {` in the
  // file. `appliance-repair-quote-calculator` is the first such adopter: the
  // keys came back as `compareServiceCallVsReplace`'s, so `target` read as a
  // field the calculator does not return, when it is the field it quotes.
  // Bounding the region is the same "looked at the wrong function" mistake the
  // entry selection above was already fixed for, one step later in the parse.
  const after = source.slice(entry.index);
  const nextDeclaration = after.slice(1).search(/\n(?:export )?function /);
  const region = nextDeclaration === -1 ? after : after.slice(0, nextDeclaration + 1);

  const returned = /\n {2}return \{\n([\s\S]*?)\n {2}\};/.exec(region);
  if (returned) {
    return [...returned[1].matchAll(/^ {4}([A-Za-z0-9_]+)\s*[:,]/gm)].map((m) => m[1]);
  }

  // A single-line `return { ... };`, which no adopter wrote until this one.
  const inline = /\n {2}return \{([^\n]*?)\};/.exec(region);
  return inline ? topLevelKeys(inline[1]) : [];
}

/**
 * Keys of a one-line object literal body, split at bracket depth zero.
 *
 * Splitting on every comma would break on a value that carries its own —
 * `effectiveRate: target / Math.max(laborHours, 0.01)` is one line of a real
 * calculator — and would then report `0.01` as a field name.
 */
function topLevelKeys(body) {
  const keys = [];
  let depth = 0;
  let start = 0;
  const take = (chunk) => {
    const match = /^\s*([A-Za-z0-9_$]+)\s*(?::|$)/.exec(chunk);
    if (match) keys.push(match[1]);
  };
  for (let i = 0; i < body.length; i += 1) {
    const char = body[i];
    if (char === '(' || char === '[' || char === '{') depth += 1;
    else if (char === ')' || char === ']' || char === '}') depth -= 1;
    else if (char === ',' && depth === 0) { take(body.slice(start, i)); start = i + 1; }
  }
  take(body.slice(start));
  return keys;
}

/**
 * The proposal's colours, read off the calculator's own stylesheet.
 *
 * Three values, and only the first two are cosmetic. `.eyebrow` carries each
 * page's accent and `.result` its dark panel, so the printed sheet keeps a
 * family resemblance to the tool that produced it without being a printout of
 * a website.
 *
 * The third is a legibility fix, not a preference. Every hand-port copied
 * `.proposal-status`'s colour from `.summary-status` — which is correct there,
 * because that status sits inside the dark `.result` panel, and wrong here,
 * because `#proposalSection` is an ordinary light-background section in the
 * input column. `#e8c79a` on white is roughly 1.8:1. The status line is where
 * "Add your business name before printing" appears, so a contractor who cannot
 * read it cannot find out why nothing printed. Take `.hint`'s colour, which is
 * the muted-on-light tone the rest of the column already uses.
 */
export function derivePalette(html) {
  const style = /<style>([\s\S]*?)<\/style>/.exec(html)?.[1] ?? '';
  const pick = (pattern, fallback) => pattern.exec(style)?.[1] ?? fallback;
  return {
    accent: pick(/\.eyebrow\s*\{[^}]*?color:\s*(#[0-9a-fA-F]{3,8})/, '#8a5a22'),
    strong: pick(/\.result\s*\{[^}]*?background:\s*(#[0-9a-fA-F]{3,8})/, '#3a2a16'),
    statusColor: pick(/\.hint\s*\{[^}]*?color:\s*(#[0-9a-fA-F]{3,8})/, '#5c5854'),
  };
}

/** Preconditions. A page that fails any of these is reported, not edited. */
function inspect(slug) {
  const dir = path.join(VENTURES, slug);
  const file = path.join(dir, 'index.html');
  const problems = [];

  if (!fs.existsSync(file)) return { problems: ['no index.html'] };

  const raw = fs.readFileSync(file, 'utf8');
  const generated = raw.includes(MARK.html[0]);

  // A page this tool wrote can be rewritten; a hand-ported one cannot. The
  // hand-ports carry ~200 lines of wiring nobody generated, and overwriting
  // them from `trades.json` would silently drop whatever was tuned by hand.
  if (!generated && fs.existsSync(path.join(dir, 'proposal.mjs'))) {
    return { problems: ['adopted by hand, not generated — edit the page, not trades.json'] };
  }

  if (!fs.existsSync(path.join(dir, 'calc.mjs'))) problems.push('no calc.mjs');
  if (!fs.existsSync(path.join(dir, 'usage.mjs'))) problems.push('no usage.mjs to count with');

  // Every precondition below is about the venture's *own* page, so they are
  // checked against the page with our regions removed — otherwise a re-run
  // trips over the `@media print` block and the `#proposalSection` it wrote
  // itself last time.
  const html = generated ? stripGenerated(raw) : raw;
  const { reader, calcFn } = detectFunctions(html);
  if (!reader) problems.push('no readInput()/readInputs() to read the job from');
  else if (!readerTakesNoArguments(html, reader)) {
    problems.push(`${reader}() has a parameter with no default, so the proposal would price the job without it`);
  }
  if (!calcFn) problems.push('no calculate*(readInput()) call to price it with');
  if (!/const el = id => document\.getElementById\(id\)|function el\(/.test(html)) problems.push('no el() helper');
  if (!/function count\(/.test(html)) problems.push('no count() helper');
  if (!html.includes('</style>')) problems.push('no </style> to add the print rules before');
  if (!html.includes('</main>')) problems.push('no </main> to add the form before');
  if (/@media print/.test(html)) {
    // Not a refusal on its own, but the venture already prints something of its
    // own and the two stylesheets have to be separated by a body class rather
    // than by one silently winning. See the README.
    problems.push('page already has an @media print block — hand-port, see README');
  }
  if (html.includes('id="proposalSection"')) problems.push('page already has a proposal section');

  return { file, html, reader, calcFn, problems };
}

