/**
 * The wiring, appended to the page's own module.
 *
 * `refreshProposal` is delegated from the document rather than called inside
 * the page's `update()`: every calculator here has its own `update()` with its
 * own shape, and one listener that works in all of them is what makes this
 * generated at all.
 */
/**
 * The extra values a trade's scope templates may read, beyond the result.
 *
 * Calculators mostly keep the *id* of the preset the contractor chose —
 * `result.pump` is `'half-hp'`, not `'1/2 HP submersible'` — so a template
 * reading `{pump}` puts a slug on a customer's quote and one reading
 * `{pump.name}` puts nothing there at all. Both have shipped.
 *
 * Two ways to get a word a homeowner can read:
 *
 *   { "select": "pump" }              the option text the contractor is looking
 *                                     at, straight off the <select>
 *   { "select": "pit", "map": {...} } that option's value, rewritten — for the
 *                                     labels that are shorthand for the trade
 *                                     ("Rec room — the cheap special") and must
 *                                     not reach the customer in those words
 *   { "from": "resultKey", "map": {...} }   same, keyed off the result instead
 *
 * A mapped value of `""` drops the line, which is how "No backup this bid"
 * becomes silence on the sheet rather than a line saying nothing was done.
 */
/**
 * Row-level rewriting, for the trades that price a job made of rows.
 *
 * `fields` above reaches the top of the result only, so a row's own words go to
 * the customer exactly as the *estimator's form* spells them — and a form label
 * is written for the person entering the number, not the person reading the
 * quote. `hood-cleaning` printed "Canopy hood (listed sq ft) — 40", where the
 * parenthetical is an instruction to the estimator and the 40 has no unit.
 *
 * `rowFields` in trades.json maps a field inside a named collection:
 *
 *   "rowFields": {
 *     "components": { "name": { "map": { "Canopy hood (listed sq ft)": "sq ft of canopy hood" } } }
 *   }
 *
 * An unmapped value falls through to the row's own, never to `undefined`. That
 * matters more here than at the top level: a missing placeholder makes
 * `scopeLines` drop the whole line, so a preset nobody added to the map would
 * silently delete a component from the scope the customer is agreeing to.
 * Falling through prints today's wording, which is the defect this fixes rather
 * than a new one.
 */
export function declaredRowFields(rowFields = {}) {
  return Object.entries(rowFields).map(([collection, fields]) => {
    const assignments = Object.entries(fields).map(([name, spec]) => {
      // Read the source off the untouched row, so two mapped fields can both
      // key off the same original value regardless of the order written here.
      const source = `row[${jsString(spec.from || name)}]`;
      return spec.map
        ? `            ${JSON.stringify(name)}: (${JSON.stringify(spec.map)})[${source}] ?? ${source},`
        : `            ${JSON.stringify(name)}: ${source},`;
    });
    return `        ${JSON.stringify(collection)}: (Array.isArray(result[${jsString(collection)}]) ? result[${jsString(collection)}] : [])
          .map(row => ({
            ...row,
${assignments.join('\n')}
          })),`;
  });
}

export function declaredFields(fields = {}, rowFields = {}) {
  const rowLines = declaredRowFields(rowFields);
  const entries = Object.entries(fields);
  if (!entries.length && !rowLines.length) return '';
  const lines = entries.map(([name, spec]) => {
    const map = spec.map ? JSON.stringify(spec.map) : null;
    if (spec.select) {
      const raw = `el(${jsString(spec.select)})`;
      return map
        ? `        ${JSON.stringify(name)}: (${map})[${raw}?.value],`
        : `        ${JSON.stringify(name)}: ${raw}?.selectedOptions?.[0]?.textContent?.trim(),`;
    }
    if (spec.from) {
      return map
        ? `        ${JSON.stringify(name)}: (${map})[result[${jsString(spec.from)}]],`
        : `        ${JSON.stringify(name)}: result[${jsString(spec.from)}],`;
    }
    // A plain `<input>` the scope needs to quote but the calculator does not
    // return. Every spec above reads either a `<select>`'s label or a key of
    // the result, which covers a trade whose scope is made of the choices and
    // the figures it prices — but not one whose scope names something the
    // customer supplied and the arithmetic never touches: a language pair, a
    // reference number, a document title. Those had no route onto the sheet
    // short of widening the calculator's return value, which is the wrong
    // place to put a string nothing computes.
    //
    // `scopeLines` treats a blank as missing and drops the whole line, so an
    // optional field left empty removes its sentence rather than printing a
    // half one.
    if (spec.input) {
      const raw = `el(${jsString(spec.input)})?.value?.trim()`;
      return map
        ? `        ${JSON.stringify(name)}: (${map})[${raw}],`
        : `        ${JSON.stringify(name)}: ${raw},`;
    }
    // A numeric `<input>`. Separate from `input` above rather than sniffed,
    // because the difference is not cosmetic: an input's value is a *string*,
    // and `"0"` is truthy, so a `when` guarding a line on an optional charge
    // the user left at zero passed and the line printed anyway. That put "Rush
    // or weekend delivery" on a customer's quote with nothing for it in the
    // price — the sheet promising work the price does not cover, which is the
    // failure mode this whole module is careful about everywhere else.
    //
    // `Number('')` is 0, so an empty optional field drops its line too, and
    // `Number('abc')` is NaN, which `scopeLines` already treats as missing.
    if (spec.number) {
      const raw = `Number(el(${jsString(spec.number)})?.value)`;
      return map
        ? `        ${JSON.stringify(name)}: (${map})[${raw}],`
        : `        ${JSON.stringify(name)}: ${raw},`;
    }
    return `        ${JSON.stringify(name)}: undefined,`;
  });
  return `
    /**
     * Customer-readable words for the choices the contractor made, since the
     * result mostly carries preset ids. See \`fields\` in trades.json.
     */
    function proposalFields(result) {
      return {
        ...result,
${[...lines, ...rowLines].join('\n')}
      };
    }
`;
}

function wiring({ slug, trade, reader, calcFn, priceExpression }) {
  const scopeTemplates = JSON.stringify(trade.scope, null, 2)
    .split('\n').map((line, index) => (index === 0 ? line : `      ${line}`)).join('\n');
  const fields = declaredFields(trade.fields, trade.rowFields);
  const values = fields ? 'proposalFields(result)' : 'result';

  return `
    // ---- Customer-facing proposal -------------------------------------------
    //
    // Generated by \`platform/proposal/adopt.mjs\` from this venture's entry in
    // \`platform/proposal/trades.json\`. Edit the trade copy there and re-run it
    // rather than editing this block, or the next sweep will overwrite you.

    const COMPANY_KEY = '${companyKey(slug)}';
    const CLIENT_IDS = ['clientName', 'clientAddress'];
    const TERM_IDS = ['depositPercent', 'validDays', 'paymentTerms', 'proposalNotes', 'proposalExclusions'];

    // Printed at the foot of the customer's copy. It names what the document is
    // (the contractor's own price) and what it is not, so the sheet cannot be
    // read as this tool certifying the work. Typographic apostrophes only: a
    // straight one closes this string and the whole module stops parsing.
    const PROPOSAL_DISCLAIMER = ${jsString(disclaimerFor(trade))};

    /**
     * Default scope lines from the job the user actually priced, so the
     * proposal is useful before they type anything. Left alone once edited — a
     * recalculation must never overwrite wording already sent to a customer.
     *
     * Templates rather than string concatenation: \`scopeLines\` drops a line
     * whose figure is missing instead of printing the word "undefined" on a
     * customer's quote, which is the defect every hand-port hit at least once.
     */
    const SCOPE_TEMPLATES = ${scopeTemplates};
${fields}
    function restoreCompany() {
      const saved = loadCompany(localStorage, COMPANY_KEY);
      for (const field of COMPANY_FIELDS) {
        if (saved[field]) el(field).value = saved[field];
      }
    }

    function suggestScope(result) {
      const scope = el('proposalScope');
      if (scope.dataset.edited) return;
      scope.value = scopeLines(SCOPE_TEMPLATES, ${values}).join('\\n');
    }

    function readProposalInput(result) {
      const values = Object.fromEntries(
        [...COMPANY_FIELDS, ...CLIENT_IDS, ...TERM_IDS].map(id => [id, el(id).value]),
      );
      return {
        ...values,
        // Printing a different number from the one on screen would be the worst
        // bug this feature can have.
        price: ${priceExpression},
        jobTitle: scopeLines([${jsString(trade.jobTitle)}], ${values})[0] || ${jsString(trade.jobTitleFallback ?? trade.jobTitle.replace(/\{[^}]*\}/g, '').replace(/[\s—–-]+$/, '').replace(/\s+/g, ' ').trim())},
        scope: el('proposalScope').value,
      };
    }

    function showProposal() {
      const result = ${calcFn}(${reader}());
      const proposal = buildProposal(readProposalInput(result));
      saveCompany(localStorage, COMPANY_KEY, Object.fromEntries(
        COMPANY_FIELDS.map(field => [field, el(field).value]),
      ));
      el('proposalDoc').innerHTML =
        '<p class="pr-print-hint hint">This is the customer’s copy. Your costs, wages, and margin are not on it, and they are not printed.</p>'
        + renderProposalHtml(proposal, { disclaimer: PROPOSAL_DISCLAIMER${currencyOption(trade)} });
      el('proposalDoc').hidden = false;
      return proposal;
    }

    /**
     * Keep the proposal honest as the bid changes. Bubble phase, so it runs
     * after the page's own field handlers have recorded the change.
     */
    function refreshProposal(event) {
      // Editing the proposal's own fields is not a change to the figures.
      if (event && event.target.closest && event.target.closest('#proposalSection')) return;
      let result;
      try {
        result = ${calcFn}(${reader}());
      } catch {
        // An unpriceable job has no proposal; leaving the last one on screen
        // invites printing a price the inputs no longer support.
        el('proposalDoc').hidden = true;
        return;
      }
      suggestScope(result);
      // A stale sheet showing the previous price is how the wrong number
      // reaches a customer. Any recalculation retires the rendered document.
      if (!el('proposalDoc').hidden) {
        el('proposalDoc').hidden = true;
        el('proposalStatus').textContent = 'Figures changed — print again for an updated proposal';
      }
    }

    function printProposal() {
      let proposal;
      try {
        proposal = showProposal();
      } catch (error) {
        el('proposalStatus').textContent = error.message;
        return;
      }
      el('proposalStatus').textContent = \`Proposal \${proposal.reference} ready\`;
      count('proposal_printed');
      el('proposalDoc').scrollIntoView({ behavior: 'smooth', block: 'start' });
      // After paint, so the browser renders the document before the sheet is
      // captured; without it an empty page can go to the printer.
      requestAnimationFrame(() => requestAnimationFrame(() => window.print()));
    }

    el('proposalScope').addEventListener('input', () => { el('proposalScope').dataset.edited = '1'; });
    document.addEventListener('input', refreshProposal);
    document.addEventListener('change', refreshProposal);
    el('printProposal').addEventListener('click', printProposal);
    el('forgetCompany').addEventListener('click', () => {
      forgetCompany(localStorage, COMPANY_KEY);
      for (const field of COMPANY_FIELDS) el(field).value = '';
      el('proposalDoc').hidden = true;
      el('proposalStatus').textContent = 'Business details removed from this device';
      count('company_forgotten');
    });

    restoreCompany();
    refreshProposal();
`;
}

