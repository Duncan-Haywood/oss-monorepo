// The edit
// ---------------------------------------------------------------------------

function adopt(slug, trades, { dry = false } = {}) {
  const trade = trades[slug];
  if (!trade) return { slug, ok: false, why: 'no entry in trades.json' };

  const found = inspect(slug);
  if (found.problems.length) return { slug, ok: false, why: found.problems.join('; ') };

  const { file, reader, calcFn } = found;
  const priceExpression = priceExpressionFor(resultKeysOf(slug), trade.priceField ?? 'price');

  // Everything this tool has previously written comes out first, so a re-run
  // applies the current trade copy instead of layering a second proposal on
  // top of the last one.
  const html = found.html;
  let next = stripGenerated(html);

  // 1. Stylesheet, before the page's own </style>. Colours come off the page
  //    unless the trade entry overrides them.
  const palette = { ...derivePalette(next), ...(trade.palette ?? {}) };
  next = spliceBefore(next, '</style>', wrap('css', stylesheet(palette)));

  // 2. The form, at the end of <main>; then the document itself, after it.
  //    `#proposalDoc` sits outside <main> because the print stylesheet hides
  //    <main> outright — inside it, the customer's copy would print blank.
  next = spliceBefore(next, '</main>', wrap('html', markup(trade)));
  next = spliceAfter(next, '</main>', wrap('html', `
  <!-- The proposal the customer receives. Hidden on screen until previewed, and
       the only thing on the page when it prints. -->
  <div id="proposalDoc" class="pr-shell" hidden></div>
`));

  // 3. The vendored module, imported next to the page's other local imports.
  //
  // Either quote style. The single-quote spelling is this repository's house
  // style and is what all 102 bid calculators use, but it is a formatting
  // convention rather than anything this tool depends on — and a page that
  // writes `from "./usage.mjs"` was refused with a message ("no usage.mjs
  // import") that reads as if the import were missing when it is right there.
  // The quote character is captured so the emitted import matches the page it
  // is inserted into rather than switching styles mid-module.
  const usageImport = /import \{[^}]*\} from (['"])\.\/usage\.mjs\1;\n/.exec(next);
  if (!usageImport) return { slug, ok: false, why: 'no usage.mjs import to anchor the proposal import to' };
  const quote = usageImport[1];
  // The trailing newline lives inside the markers: outside them, `strip` leaves
  // it behind and every re-run adds another blank line to the page.
  next = next.replace(usageImport[0], `${usageImport[0]}${wrap('js', `
    import {
      COMPANY_FIELDS, buildProposal, renderProposalHtml, scopeLines, loadCompany, saveCompany, forgetCompany,
    } from ${quote}./proposal.mjs${quote};
`)}`);

  // 4. The wiring, at the very end of the page's own module. After the page's
  //    own bootstrap, so `restoreCompany()` runs against a rendered form.
  //
  // The anchor was the literal `'  </script>'` — the two-space indentation the
  // bid calculators happen to close their module with. A page that closes at
  // column zero was refused for having "no closing </script>" while the tag sat
  // in plain sight, which is the same class of false negative as the quote
  // style above. Find the tag, then walk back over its own indentation so the
  // wiring is still spliced in before the whole line rather than into the
  // middle of it — for a `  </script>` that lands on exactly the byte the old
  // literal did.
  const closingTag = next.lastIndexOf('</script>');
  if (closingTag < 0) return { slug, ok: false, why: 'no closing </script> to append the wiring to' };
  let closing = closingTag;
  while (closing > 0 && (next[closing - 1] === ' ' || next[closing - 1] === '\t')) closing -= 1;
  next = next.slice(0, closing)
    + wrap('js', wiring({ slug, trade, reader, calcFn, priceExpression }))
    + next.slice(closing);

  if (dry) return { slug, ok: true, dry: true, bytes: next.length - html.length };

  fs.writeFileSync(file, next);
  for (const name of VENDORED) {
    fs.copyFileSync(path.join(HERE, name), path.join(VENTURES, slug, name));
  }
  return { slug, ok: true, bytes: next.length - html.length };
}

/**
 * Repoint `.proposal-status` at each page's own muted-on-light tone.
 *
 * The hand-ports took this colour from `.summary-status`, which lives inside
 * the dark `.result` panel; `#proposalSection` is an ordinary light section, so
 * fourteen calculators render the status line at under 2:1 — `#e8c79a` on
 * white. That line is where "Add your business name before printing a
 * proposal" appears, so a contractor whose print did nothing cannot read why.
 *
 * Colour only: the generated pages already derive this, and this brings the
 * hand-ported ones to the same place without touching their wiring.
 */
function restyle() {
  const changed = [];
  for (const slug of fs.readdirSync(VENTURES)) {
    const file = path.join(VENTURES, slug, 'index.html');
    if (!fs.existsSync(path.join(VENTURES, slug, 'proposal.mjs')) || !fs.existsSync(file)) continue;
    const html = fs.readFileSync(file, 'utf8');
    const rule = /(\.proposal-status\s*\{[^}]*?color:\s*)(#[0-9a-fA-F]{3,8})/.exec(html);
    if (!rule) continue;
    const wanted = derivePalette(html).statusColor;
    if (rule[2].toLowerCase() === wanted.toLowerCase()) continue;
    fs.writeFileSync(file, html.replace(rule[0], `${rule[1]}${wanted}`));
    changed.push(`${slug}: ${rule[2]} -> ${wanted}`);
  }
  return changed;
}

/** Re-vendor the canonical module into every venture that has already adopted. */
function sync() {
  const copied = [];
  for (const slug of fs.readdirSync(VENTURES)) {
    const target = path.join(VENTURES, slug, 'proposal.mjs');
    if (!fs.existsSync(target)) continue;
    for (const name of VENDORED) {
      fs.copyFileSync(path.join(HERE, name), path.join(VENTURES, slug, name));
    }
    copied.push(slug);
  }
  return copied;
}

