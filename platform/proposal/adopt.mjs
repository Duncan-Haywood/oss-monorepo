function spliceBefore(html, marker, insertion) {
  const at = html.indexOf(marker);
  if (at < 0) throw new Error(`no ${marker}`);
  return html.slice(0, at) + insertion + html.slice(at);
}

function spliceAfter(html, marker, insertion) {
  const at = html.indexOf(marker);
  if (at < 0) throw new Error(`no ${marker}`);
  return html.slice(0, at + marker.length) + insertion + html.slice(at + marker.length);
}

function escapeAttribute(value) {
  return String(value)
    .replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/\n/g, '&#10;');
}

/**
 * A JS single-quoted literal that cannot break the module.
 *
 * The apostrophe in "a licensed engineer's" closing the string is the defect
 * that killed a whole batch's proposals while their pages still rendered. Every
 * straight apostrophe becomes the typographic one, which is what the rest of
 * the copy uses anyway; anything else that could close the literal is escaped.
 */
export function jsString(value) {
  const copy = String(value).replace(/'/g, '’');
  return `'${copy.replace(/\\/g, '\\\\').replace(/\n/g, '\\n')}'`;
}

/** The localStorage key holding this venture's saved business block. */
export function companyKey(slug) {
  return `${slug.replace(/-bid-calculator$/, '').replace(/-calculator$/, '')}-bid-company`;
}

/** The footer sentence: a shared spine plus whatever this trade must disclaim. */
export function disclaimerFor(trade) {
  const spine = 'This proposal states the price offered by the business named above, '
    + 'who is solely responsible for its scope, figures, and performance. It was laid out with a free '
    + 'browser tool that performs arithmetic only; the tool’s authors are not a party to it and give no '
    + 'warranty.';
  const tail = String(trade.disclaimerTail ?? '').trim();
  return tail ? `${spine} ${tail}` : spine;
}

