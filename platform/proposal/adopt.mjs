#!/usr/bin/env node
// Wire the customer proposal into a bid calculator.
//
// Why this exists
// ---------------
// Adoption was a hand-port: ~200 lines of stylesheet, markup and wiring copied
// into `ventures/<slug>/index.html`, six calculators to a session, with 74 to
// go. The README lists five traps that batch after batch fell into, and every
// one of them is mechanical — a straight apostrophe closing a JS string, a
// reader called `readInputs` not `readInput`, a print rule that a bare id
// selector outranks. Those are not judgement calls. They are the same edit,
// made by hand, seventy-four more times.
//
// So the edit is code now, and the judgement — what this trade calls the job,
// what the scope lines say, which regulator the disclaimer must not imply —
// stays data, in `trades.json`.
//
// What stays the author's job
// ---------------------------
// The trade copy. A generated proposal with a generic scope is worth less than
// no proposal: "Perform the work described above" is not a scope a homeowner
// can compare against another bid. `trades.json` is where a person writes the
// lines, and `verify.mjs` drives the finished page in a real browser to check
// that what they wrote actually resolves against the calculator's result.
//
// Usage
//   node platform/proposal/adopt.mjs <slug>...   adopt one or more calculators
//   node platform/proposal/adopt.mjs --all       adopt every slug in trades.json
//   node platform/proposal/adopt.mjs --sync      re-vendor the canonical module
//   node platform/proposal/adopt.mjs --list      what is adopted, what is left
//   ... --dry                                    report the edit, write nothing

