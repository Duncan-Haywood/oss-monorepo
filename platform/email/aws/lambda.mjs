// The agent inboxes on AWS Lambda (README.md, "Portability", step 4): the
// same `createService` the Cloudflare Worker builds, on the DynamoDB + S3
// store, sending through SES. Three kinds of event reach one function:
//
//   SES        a receipt from the email-ops stack's rule: SES has written
//              the raw message to S3; `ses-inbound.mjs` reads it back and
//              makes the Worker's `ingest` call. Spam, virus and failed
//              DMARC (p=reject) mail is dropped first, as the edge API does.
//   schedule   an EventBridge rule, once a day: retention purge and the
//              owner digest (`service.scheduled()`).
//   HTTP       a function-URL request (payload 2.0): the agent API
//              (`service.api`), bearer tokens as on the Worker.
//
// What differs from the Worker, and why:
//
// - Secrets. The four values the Worker's README asked the owner to paste
//   (agent, read and owner tokens, the unsubscribe key) are generated by the
//   stack and kept in one Secrets Manager secret, read once per container.
//   No one types them; an agent session reads the agent token with its role
//   (task inboxes-without-owner).
// - The owner's address is OWNER_FORWARD_TO, which the stack takes from the
//   address the AWS bootstrap already asks for (AWS_BUDGET_ALERT_EMAIL).
// - No `message.forward`. SES has no forward of the original; the inboxes
//   that forwarded (privacy@, security@) are `flag_all`, so every message
//   to them already sends the owner an alert at once, and the digest lists it.
// - Replies leave from the inbox they answer: one SES sender per From
//   address, each checking the email-ops consent table before it sends.

import cfg from '../inboxes.json' with { type: 'json' };
import { createService } from '../service.mjs';
import { portSender, noSender } from '../senders.mjs';
import { sesInboundHandler } from './ses-inbound.mjs';
import { dynamoS3Store, s3Bucket } from './dynamo-store.mjs';
import { awsClient, jsonProtocol } from '../../edge/aws/sigv4.mjs';
import { sesSender } from '../../aws/stacks/email-ops/sender/ses-sender.mjs';
import { consentStore } from '../../aws/stacks/email-ops/sender/consent-store.mjs';

const MIN_SECRET = 24;

// Small copies of the edge Lambda's adapters (platform/edge/aws/lambda.mjs),
// so this zip does not carry the edge Worker it would otherwise import.

/** SES's own verdicts: spam, virus and failed DMARC (p=reject) mail is not stored. */
export function sesVerdictDrop(receipt = {}) {
  if (receipt.spamVerdict?.status === 'FAIL') return 'spam';
  if (receipt.virusVerdict?.status === 'FAIL') return 'virus';
  if (receipt.dmarcVerdict?.status === 'FAIL' && receipt.dmarcPolicy === 'REJECT') return 'dmarc';
  return '';
}

/** Pure: a function-URL event (payload 2.0) to a web Request. */
export function toRequest(event, host = 'mail.invalid') {
  const method = event.requestContext?.http?.method || 'GET';
  const headers = new Headers();
  for (const [k, v] of Object.entries(event.headers || {})) headers.set(k, v);
  const qs = event.rawQueryString ? `?${event.rawQueryString}` : '';
  const body = method === 'GET' || method === 'HEAD' || event.body == null
    ? undefined
    : event.isBase64Encoded ? Buffer.from(event.body, 'base64') : event.body;
  return new Request(`https://${host}${event.rawPath || '/'}${qs}`, { method, headers, body });
}

/** A web Response to the function-URL result shape. */
export async function fromResponse(res) {
  const headers = {};
  res.headers.forEach((v, k) => { headers[k] = v; });
  return { statusCode: res.status, headers, body: await res.text(), isBase64Encoded: false };
}

/**
 * Pure: the secret's JSON to the service's tokens. A missing or short value
 * is dropped (the service then refuses that scope), never defaulted.
 */
export function parseSecrets(json) {
  let s = {};
  try { s = JSON.parse(json || '{}'); } catch { s = {}; }
  const ok = (v) => (typeof v === 'string' && v.length >= MIN_SECRET ? v : '');
  return {
    tokens: { agent: ok(s.agent_token), read: ok(s.read_token), owner: ok(s.owner_token) },
    unsubscribeSecret: ok(s.unsubscribe_secret),
  };
}

/** Which of the three event kinds this is. */
export function eventKind(event) {
  if (Array.isArray(event?.Records) && event.Records[0]?.eventSource === 'aws:ses') return 'ses';
  if (event?.source === 'aws.events' || event?.['detail-type'] === 'Scheduled Event') return 'schedule';
  return 'http';
}

/**
 * Build the handler. `deps.service(secrets)` makes the service once the
 * secrets are known; `deps.secrets()` resolves the secret's JSON;
 * `deps.getObject(bucket, key)` reads the raw message SES wrote.
 */
export function createMailHandler({ service: makeService, secrets, getObject, domain = cfg.domain, config = {}, log = () => {} }) {
  const inbound = { bucket: config.RAW_BUCKET || '', prefix: config.INBOUND_PREFIX || '' };
  let svc;
  // Built once per container; a failure (Secrets Manager down) is not
  // cached, so the next event tries again.
  const load = () => (svc ||= (async () => makeService(parseSecrets(await secrets())))().catch((e) => { svc = null; throw e; }));

  return async function handler(event) {
    const kind = eventKind(event);
    const service = await load();
    if (kind === 'ses') {
      const keep = [];
      for (const r of event.Records) {
        const drop = sesVerdictDrop(r.ses?.receipt);
        if (drop) log({ mail: 'dropped', why: drop });
        else keep.push(r);
      }
      const { results } = await sesInboundHandler({ service, getObject, domain, ...inbound })({ Records: keep });
      // Ids and inboxes only: a message's text never reaches the logs.
      log({ mail: 'ingested', results: results.map((x) => ({ id: x.id, inbox: x.inbox, skipped: x.skipped, reject: x.reject })) });
      return { disposition: 'CONTINUE' };
    }
    if (kind === 'schedule') {
      const r = await service.scheduled();
      log({ mail: 'scheduled', r });
      return r;
    }
    try {
      return await fromResponse(await service.api(toRequest(event, config.HOST || 'mail.invalid')));
    } catch (e) {
      log({ mail: 'api-error', error: String(e?.message || e).slice(0, 200) });
      return { statusCode: 500, headers: { 'content-type': 'application/json' }, body: '{"error":"internal"}', isBase64Encoded: false };
    }
  };
}

/**
 * A sender per From address (the inbox a reply leaves from), built on first
 * use. Each is the email-ops `sesSender` on the transactional stream, which
 * checks the shared consent and suppression table before calling SES.
 * Marketing is refused here (logged as failed, nothing sent): it belongs on
 * the email-ops `marketing` stream and its own domain, so a complaint about
 * a newsletter cannot pause support replies. `addsCompliance` stays false so
 * the service keeps adding its own footer and headers, as on Cloudflare.
 */
export function perAddressSender({ make, name = 'ses' }) {
  const byFrom = new Map();
  return {
    name,
    addsCompliance: false,
    async send(m) {
      if (m.stream && m.stream !== 'transactional') throw new Error(`the ${m.stream} stream is not sent from the inboxes on AWS`);
      const from = String(m.from || '').toLowerCase();
      if (!from) throw new Error('no From address');
      if (!byFrom.has(from)) byFrom.set(from, portSender(make(from), { name, addsCompliance: false }));
      return byFrom.get(from).send(m);
    },
  };
}

/** The real dependencies, from the function's environment variables. */
export function fromEnvironment(env = process.env) {
  const region = env.AWS_REGION || 'us-east-2';
  const ddb = jsonProtocol({ target: 'DynamoDB_20120810', region, service: 'dynamodb' });
  const sm = jsonProtocol({ target: 'secretsmanager', version: '1.1', region, service: 'secretsmanager' });
  const secret = async (id) => (id ? (await sm('GetSecretValue', { SecretId: id })).SecretString : '');
  const s3 = (bucket) => awsClient({ region, service: 's3', endpoint: `https://${bucket}.s3.${region}.amazonaws.com` });
  const raw = s3Bucket({ request: s3(env.RAW_BUCKET) });
  const inboundGet = async (bucket, key) => {
    const res = await s3(bucket)({ method: 'GET', path: `/${key.split('/').map(encodeURIComponent).join('/')}` });
    if (!res.ok) throw new Error(`s3 GetObject ${res.status}`);
    return new Uint8Array(await res.arrayBuffer());
  };
  const publicUrl = String(env.PUBLIC_URL || '').replace(/\/$/, '');

  return {
    secrets: () => secret(env.MAIL_SECRET_ID),
    getObject: inboundGet,
    config: { HOST: env.HOST || 'mail.invalid', RAW_BUCKET: env.RAW_BUCKET || '', INBOUND_PREFIX: env.INBOUND_PREFIX || '' },
    log: (o) => console.log(JSON.stringify(o)),
    service: async ({ tokens, unsubscribeSecret }) => {
      const pepper = await secret(env.CONSENT_PEPPER_SECRET_ID);
      const consent = consentStore({ call: ddb, table: env.CONSENT_TABLE, pepper });
      const make = (from) => sesSender({ region, from, stream: 'transactional', configurationSet: env.SES_CONFIGURATION_SET, consent });
      // Owner alerts need only SES; replies also need sending switched on in inboxes.yaml.
      const canSend = Boolean(env.SES_CONFIGURATION_SET && env.CONSENT_TABLE && pepper);
      const sending = canSend && cfg.sending.provider !== 'none' ? perAddressSender({ make }) : noSender;
      const compliance = env.SENDER_NAME && env.POSTAL_ADDRESS && publicUrl && unsubscribeSecret
        ? { sender: env.SENDER_NAME, postalAddress: env.POSTAL_ADDRESS, unsubscribeUrl: `${publicUrl}/u` } : null;
      return createService({
        store: dynamoS3Store({ call: ddb, table: env.TABLE_NAME, bucket: raw }),
        sender: sending,
        alerter: canSend ? perAddressSender({ make, name: 'ses-alert' }) : noSender,
        cfg,
        ownerAddress: env.OWNER_FORWARD_TO || '',
        tokens,
        unsubscribeSecret,
        publicUrl,
        fromName: env.MAIL_FROM_NAME || '',
        compliance,
        log: (s) => console.log(s),
      });
    },
  };
}

let live;
/** The Lambda entry point (`email/aws/lambda.handler`). */
export const handler = (event) => (live ||= createMailHandler(fromEnvironment()))(event);
