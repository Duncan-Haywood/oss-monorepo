#!/usr/bin/env python3
"""Give every research README a plain link to its live page.

Each `research/<slug>/` has a home page on the GitHub Pages site
(`research/_homepage/build.py`, published under `research/<slug>/`). The
repository README is what GitHub and search engines index first, so it should
say where the readable version lives, as the venture READMEs already do.

    python3 platform/ci/research_live_links.py          # report; exit 1 if any is missing
    python3 platform/ci/research_live_links.py --write  # insert the line (idempotent)

The line goes after the first paragraph under the title. Only projects listed
in `research/_homepage/projects.json` are touched, since those are the ones
that get a page.

The same goes one level up: `research/README.md` carries a "Browse by topic"
list linking each theme's page (`research/topics/<id>/`), between the
`<!-- topics:start -->` and `<!-- topics:end -->` markers. The README lists
700+ projects alphabetically by history, so the topic list is the only way in
for a reader who knows the subject but not the slug. `--write` regenerates it.
A new project's bullet is its `lede` in `research/<slug>/project.json`, generated
between `<!-- projects:start -->` and `<!-- projects:end -->` at the end of the
README, so a new project edits no shared file but that sorted block.
"""
import argparse
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = "https://duncan-haywood.github.io/oss-monorepo/research/"
LINE = "**Live page:** {url}"


def url_for(slug):
    return f"{BASE}{slug}/"


TOPICS_START, TOPICS_END = "<!-- topics:start -->", "<!-- topics:end -->"


def topics_block(data):
    """The "Browse by topic" list for research/README.md, from projects.json."""
    lines = [TOPICS_START, "## Browse by topic", "",
             f"**Read it all at [{BASE}]({BASE}).** Each topic page lists its projects with a summary:", ""]
    for t in data["themes"]:
        if t.get("id") and t.get("name"):
            # No per-topic count: it would go stale with every project added.
            name = html.unescape(re.sub(r"<[^>]+>", "", t["name"]))
            lines.append(f"- [{name}]({BASE}topics/{t['id']}/)")
    lines += ["", "<!-- Generated by platform/ci/research_live_links.py --write from _homepage/projects.json. -->",
              TOPICS_END]
    return "\n".join(lines)


def with_topics(text, block):
    """Replace the marked block, or insert it before the first list item."""
    if TOPICS_START in text and TOPICS_END in text:
        head, rest = text.split(TOPICS_START, 1)
        return head + block + rest.split(TOPICS_END, 1)[1]
    lines = text.split("\n")
    i = next((k for k, line in enumerate(lines) if line.startswith("- ")), len(lines))
    lines[i:i] = [block, "", "## All projects", ""]
    return "\n".join(lines)


PROJECTS_START, PROJECTS_END = "<!-- projects:start -->", "<!-- projects:end -->"


def projects_block(data):
    """README bullets for projects whose own project.json carries a `lede`, sorted by slug.

    Sorted, not appended, so two new projects rarely edit adjacent lines."""
    cards = sorted((p["slug"], p["lede"]) for t in data["themes"] for p in t["projects"] if p.get("lede"))
    lines = [PROJECTS_START,
             "<!-- Generated by platform/ci/research_live_links.py --write from research/<slug>/project.json `lede`. -->"]
    lines += [f"- [`research/{s}`]({s}) — {lede}" for s, lede in cards]
    return "\n".join(lines + [PROJECTS_END])


def with_projects(text, block):
    """Replace the marked block, or append it at the end."""
    if PROJECTS_START in text and PROJECTS_END in text:
        head, rest = text.split(PROJECTS_START, 1)
        return head + block + rest.split(PROJECTS_END, 1)[1]
    return text.rstrip("\n") + "\n" + block + "\n"


def load_registry(root):
    sys.path.insert(0, str(ROOT / "research" / "_homepage"))
    import registry
    return registry.load(root / "research")


def slugs(root=ROOT):
    data = load_registry(root)
    return sorted(p["slug"] for t in data["themes"] for p in t["projects"])


def has_link(text, slug):
    return url_for(slug) in text


def insert_link(text, slug):
    """Return text with the live-page line after the first paragraph under the title."""
    if has_link(text, slug):
        return text
    # A live-page line for an older base URL (e.g. /monorepo-projects/) is moved, not duplicated.
    old = re.compile(r"^\*\*Live page:\*\* \S*/research/%s/[ \t]*$" % re.escape(slug), re.M)
    if old.search(text):
        return old.sub(LINE.format(url=url_for(slug)), text, count=1)
    lines = text.split("\n")
    i = 0
    while i < len(lines) and not lines[i].startswith("# "):
        i += 1
    if i == len(lines):
        i = -1  # no title: start from the top
    i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    in_fence = False
    while i < len(lines) and (lines[i].strip() or in_fence):
        if lines[i].lstrip().startswith("```"):
            in_fence = not in_fence
        i += 1
    line = LINE.format(url=url_for(slug))
    lines[i:i] = ["", line] if i < len(lines) else ["", line, ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    missing = []
    for slug in slugs(args.root):
        f = args.root / "research" / slug / "README.md"
        text = f.read_text()
        if has_link(text, slug):
            continue
        missing.append(slug)
        if args.write:
            f.write_text(insert_link(text, slug))
    verb = "updated" if args.write else "missing a live-page link"
    print(f"{len(missing)} research READMEs {verb}")
    if missing and not args.write:
        print("\n".join(f"  research/{s}/README.md" for s in missing[:20]))
    stale_topics = False
    index = args.root / "research" / "README.md"
    if index.exists():
        data = load_registry(args.root)
        text = index.read_text()
        want = with_projects(with_topics(text, topics_block(data)), projects_block(data))
        if want != text:
            stale_topics = not args.write
            if args.write:
                index.write_text(want)
                print("research/README.md: generated lists regenerated")
            else:
                print("research/README.md: topic or project list is missing or stale; run with --write")
    return 1 if (missing or stale_topics) and not args.write else 0


if __name__ == "__main__":
    sys.exit(main())
