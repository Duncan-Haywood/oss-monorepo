#!/usr/bin/env node
// Copy the shared Paddle client into every venture that sells a pack, and
// write each venture's checkout.mjs from the catalogue.
//
//   node platform/billing/sync.mjs          write
//   node platform/billing/sync.mjs --check  exit 1 if any venture is out of date
//
// A venture's page is served from its own directory and cannot import
// platform/, so it carries a byte-for-byte copy (paddle.mjs). This script, not
// a run's memory, keeps the copies equal (CLAUDE.md, "software for the routine").

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOGUE, productConfig } from "./catalogue.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");

export function checkoutSource(product, cat = CATALOGUE) {
  const cfg = productConfig(product, cat);
  return [
    "// Generated by platform/billing/sync.mjs from platform/billing/catalogue.mjs:",
    "// edit the catalogue, then run the sync, not this file.",
    "// Where this pack is sold: Paddle, the portfolio's merchant of record. Every value",
    "// is public (a client-side token, a price id, an Ed25519 public key, the edge",
    "// Worker's address). While any is empty the page shows no Buy button and",
    "// everything that is free today stays free (paddle.mjs, onSale).",
    `export const PADDLE = ${JSON.stringify(cfg, null, 2)};`,
    "",
  ].join("\n");
}

/** @returns {{ file: string, want: string }[]} */
export function plan(cat = CATALOGUE, root = ROOT) {
  const client = fs.readFileSync(path.join(HERE, "client.mjs"), "utf8");
  const out = [];
  for (const slug of Object.keys(cat.products)) {
    const dir = path.join(root, "ventures", slug);
    out.push({ file: path.join(dir, "paddle.mjs"), want: client });
    out.push({ file: path.join(dir, "checkout.mjs"), want: checkoutSource(slug, cat) });
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const { file, want } of plan()) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (have === want) continue;
    stale.push(path.relative(ROOT, file));
    if (!check) fs.writeFileSync(file, want);
  }
  if (check && stale.length) {
    console.error("out of date (run node platform/billing/sync.mjs):\n  " + stale.join("\n  "));
    process.exit(1);
  }
  console.log(check ? "billing copies in sync" : stale.length ? "wrote:\n  " + stale.join("\n  ") : "nothing to write");
}
