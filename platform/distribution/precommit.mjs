/**
 * pre-commit distribution: turns each venture linter that the GitHub Actions
 * channel already qualifies into a hook in a root `.pre-commit-hooks.yaml`, so
 * any repository can run it locally and in CI with
 *
 *   repos:
 *     - repo: https://github.com/duncan-haywood/oss-monorepo
 *       rev: main        # pin a commit in real use
 *       hooks:
 *         - id: actions-timeout-check
 *
 *   node platform/distribution/precommit.mjs            # dry run: lists the hooks
 *   node platform/distribution/precommit.mjs --write    # (re)generate .pre-commit-hooks.yaml
 *   node platform/distribution/precommit.mjs --check    # exit 1 when it is stale
 *
 * Off by default and needs no account, token or publish step: the file is
 * committed, and pre-commit reads it from a clone. Qualification is exactly
 * ghaction.mjs's (stdlib-only, no network, no process spawning, MIT, a
 * description), so the two channels cannot disagree. Hooks use
 * `language: script` on the venture's own check.py (one source of truth, so
 * the file must be executable), scan the whole repository and do not take
 * filenames, because these linters read a tree (workflows, Dockerfiles,
 * manifests) rather than one staged file.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan as actionPlan } from './ghaction.mjs';
import { descriptionOf } from './npm.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..');
export const HOOKS_FILE = '.pre-commit-hooks.yaml';

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const title = (slug) => slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

export function hookYaml({ slug, description }) {
  return `- id: ${slug}
  name: ${q(title(slug))}
  description: ${q(description.length <= 200 ? description : description.slice(0, 199).replace(/\s+\S*$/, '') + '…')}
  entry: ventures/${slug}/check.py
  language: script
  args: ['--fail-on-risk', '.']
  pass_filenames: false
  always_run: true
`;
}

/** { text, slugs } for the ventures that qualify as GitHub Actions. */
export async function build({ root = REPO_ROOT } = {}) {
  const { ok } = await actionPlan({ root });
  let text = '# Generated by platform/distribution/precommit.mjs. Do not edit.\n';
  for (const { slug } of ok) {
    const description = descriptionOf(await fs.readFile(path.join(root, 'ventures', slug, 'VENTURE.yaml'), 'utf8'));
    text += hookYaml({ slug, description });
  }
  return { text, slugs: ok.map((p) => p.slug) };
}

/** Problems with the committed file: stale text, or a hook whose script is not executable. */
export async function stale({ root = REPO_ROOT } = {}) {
  const { text, slugs } = await build({ root });
  const bad = [];
  if ((await fs.readFile(path.join(root, HOOKS_FILE), 'utf8').catch(() => null)) !== text) bad.push(HOOKS_FILE);
  for (const slug of slugs) {
    const st = await fs.stat(path.join(root, 'ventures', slug, 'check.py'));
    if (!(st.mode & 0o100)) bad.push(`ventures/${slug}/check.py (not executable; chmod +x)`);
  }
  return bad;
}

export async function write({ root = REPO_ROOT } = {}) {
  const { text, slugs } = await build({ root });
  await fs.writeFile(path.join(root, HOOKS_FILE), text);
  for (const slug of slugs) await fs.chmod(path.join(root, 'ventures', slug, 'check.py'), 0o755);
  return slugs.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const flag = process.argv[2];
  if (flag === '--write') {
    console.log(`wrote ${await write()} hooks to ${HOOKS_FILE}`);
  } else if (flag === '--check') {
    const bad = await stale();
    if (bad.length) { console.error(`stale (run --write):\n  ${bad.join('\n  ')}`); process.exit(1); }
    console.log('pre-commit hooks are current');
  } else {
    const { slugs } = await build();
    console.log(`${slugs.length} venture linters qualify as pre-commit hooks`);
    for (const s of slugs) console.log(`  - id: ${s}`);
  }
}
