/**
 * GitHub Actions distribution: turns each stdlib-only venture linter that takes
 * `[--format] [--fail-on-risk] path(s)` into a reusable composite action, so any
 * repository can add it to CI with one `uses:` line. Off by default and needs
 * no account, token or publish step: the actions are plain files in this
 * repository, addressed as
 *
 *   uses: duncan-haywood/oss-monorepo/platform/distribution/actions/<slug>@main
 *
 *   node platform/distribution/ghaction.mjs            # dry run: lists what qualifies
 *   node platform/distribution/ghaction.mjs --write    # (re)generate actions/<slug>/action.yml
 *   node platform/distribution/ghaction.mjs --check    # exit 1 when a committed action is stale
 *
 * The action runs the venture's own `check.py` straight from the checked-out
 * action repository (`github.action_path`), so there is one source of truth
 * and the tool never makes a network call. Qualification reuses the PyPI
 * channel's stdlib allowlist (no network, no process spawning) plus an MIT
 * LICENSE and a description.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toolUrl } from './bluesky.mjs';
import { tagUrl } from './attribution.mjs';
import { descriptionOf } from './npm.mjs';
import { disqualifying, discover } from './pypi.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..');
export const ACTIONS_DIR = 'platform/distribution/actions';
export const USES_PREFIX = 'duncan-haywood/oss-monorepo/' + ACTIONS_DIR;

/** The CLI contract an action can wrap: --format, --fail-on-risk and a path positional. */
export function hasContract(src) {
  const arg = (name) => new RegExp(`add_argument\\(\\s*["']${name}["']`).test(src);
  const positional = /add_argument\(\s*["']paths?["']/.test(src);
  return arg('--format') && arg('--fail-on-risk') && positional;
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const short = (d) => (d.length <= 125 ? d : d.slice(0, 124).replace(/\s+\S*$/, '') + '…');
const title = (slug) => slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

export function actionYaml({ slug, description }) {
  const name = title(slug).slice(0, 60);
  return `# Generated by platform/distribution/ghaction.mjs from ventures/${slug}/check.py. Do not edit.
name: ${q(name)}
description: ${q(short(description))}
author: oss-monorepo contributors
branding:
  icon: shield
  color: gray-dark
inputs:
  path:
    description: Space-separated files or directories to scan, relative to the workspace.
    required: false
    default: '.'
  fail-on-risk:
    description: Exit non-zero (2) when the tool reports a finding. Set to 'false' to only report.
    required: false
    default: 'true'
  format:
    description: Output format (text or json; some tools also support sarif).
    required: false
    default: text
runs:
  using: composite
  steps:
    - shell: bash
      env:
        TOOL: \${{ github.action_path }}/../../../../ventures/${slug}/check.py
        SCAN_PATH: \${{ inputs.path }}
        FAIL_ON_RISK: \${{ inputs.fail-on-risk }}
        OUT_FORMAT: \${{ inputs.format }}
      run: |
        set -f
        args=(--format "$OUT_FORMAT")
        if [ "$FAIL_ON_RISK" = "true" ]; then args+=(--fail-on-risk); fi
        # $SCAN_PATH is split on spaces on purpose (several paths); globbing is off.
        python3 "$TOOL" "\${args[@]}" $SCAN_PATH
`;
}

/** { ok: [{slug, files}], skipped: [{slug, reason}] } for the ventures tree under root. */
export async function plan({ root = REPO_ROOT, slugs } = {}) {
  const ok = [];
  const skipped = [];
  for (const slug of slugs ?? await discover(root)) {
    const dir = path.join(root, 'ventures', slug);
    const src = await fs.readFile(path.join(dir, 'check.py'), 'utf8');
    const bad = disqualifying(src);
    if (bad) { skipped.push({ slug, reason: `imports "${bad}"` }); continue; }
    if (!hasContract(src)) { skipped.push({ slug, reason: 'no --format/--fail-on-risk/path contract' }); continue; }
    const license = await fs.readFile(path.join(dir, 'LICENSE'), 'utf8').catch(() => '');
    if (!/MIT License/i.test(license)) { skipped.push({ slug, reason: 'no MIT LICENSE' }); continue; }
    const description = descriptionOf(await fs.readFile(path.join(dir, 'VENTURE.yaml'), 'utf8').catch(() => ''));
    if (!description) { skipped.push({ slug, reason: 'no description in VENTURE.yaml' }); continue; }
    ok.push({
      slug,
      files: {
        [`${ACTIONS_DIR}/${slug}/action.yml`]: actionYaml({ slug, description }),
        [`${ACTIONS_DIR}/${slug}/README.md`]: `# ${title(slug)} (GitHub Action)\n\n${description}\n\n\`\`\`yaml\n- uses: actions/checkout@v4\n- uses: ${USES_PREFIX}/${slug}@main\n  with:\n    path: .\n\`\`\`\n\nFor a stable pin, replace \`@main\` with a full commit SHA, or with a \`${slug}-v<version>\` tag from this repository's Releases once one exists (portfolio/distribution/versions.json has the current version).\n\nRuns [\`ventures/${slug}/check.py\`](../../../../ventures/${slug}/check.py) (MIT, stdlib-only Python, no network calls). Docs: ${tagUrl(toolUrl(slug), 'gh-action')}\n`,
      },
    });
  }
  return { ok, skipped };
}

/** Paths whose committed content differs from the plan, plus orphaned action dirs. */
export async function stale({ root = REPO_ROOT } = {}) {
  const { ok } = await plan({ root });
  const bad = [];
  const want = new Set();
  for (const p of ok) {
    for (const [rel, text] of Object.entries(p.files)) {
      want.add(rel);
      if ((await fs.readFile(path.join(root, rel), 'utf8').catch(() => null)) !== text) bad.push(rel);
    }
  }
  const dir = path.join(root, ACTIONS_DIR);
  for (const e of await fs.readdir(dir, { withFileTypes: true }).catch(() => [])) {
    if (e.isDirectory() && !ok.some((p) => p.slug === e.name)) bad.push(`${ACTIONS_DIR}/${e.name} (no longer qualifies)`);
  }
  return bad;
}

export async function write({ root = REPO_ROOT } = {}) {
  const { ok } = await plan({ root });
  for (const p of ok) {
    for (const [rel, text] of Object.entries(p.files)) {
      await fs.mkdir(path.dirname(path.join(root, rel)), { recursive: true });
      await fs.writeFile(path.join(root, rel), text);
    }
  }
  return ok.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const flag = process.argv[2];
  if (flag === '--write') {
    console.log(`wrote ${await write()} actions under ${ACTIONS_DIR}/`);
  } else if (flag === '--check') {
    const bad = await stale();
    if (bad.length) { console.error(`stale (run --write):\n  ${bad.join('\n  ')}`); process.exit(1); }
    console.log('actions are current');
  } else {
    const { ok, skipped } = await plan();
    console.log(`${ok.length} of ${ok.length + skipped.length} venture CLIs qualify as GitHub Actions`);
    for (const p of ok) console.log(`  uses: ${USES_PREFIX}/${p.slug}@main`);
  }
}
