/**
 * Nix flake distribution: the stdlib-only venture linters that the GitHub
 * Actions channel already qualifies become packages and apps of a root
 * `flake.nix`, so anyone with Nix can run one without installing anything:
 *
 *   nix run github:duncan-haywood/oss-monorepo#actions-timeout-check -- --fail-on-risk .
 *
 *   node platform/distribution/nixflake.mjs            # dry run: lists the packages
 *   node platform/distribution/nixflake.mjs --write    # (re)generate flake.nix
 *   node platform/distribution/nixflake.mjs --check    # exit 1 when it is stale
 *
 * Off by default and needs no account, token or publish step: the flake is a
 * committed file that Nix reads from a clone. Qualification is ghaction.mjs's,
 * so the channels cannot disagree. Each package wraps the venture's own
 * check.py with python3 (one source of truth, no network, no dependencies).
 * No flake.lock is committed: the flake pins nothing but nixpkgs-unstable's
 * python3, and Nix writes a lock locally on first use.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan as actionPlan } from './ghaction.mjs';
import { descriptionOf } from './npm.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..');
export const FLAKE_FILE = 'flake.nix';

const nixStr = (s) => '"' + s.replace(/[\\"]/g, '\\$&').replace(/\$\{/g, '\\${').replace(/\n/g, ' ') + '"';
// descriptionOf leaves YAML's '' escape in place; Nix wants a plain apostrophe.
const short = (d) => {
  d = d.replace(/''/g, "'");
  return d.length <= 200 ? d : d.slice(0, 199).replace(/\s+\S*$/, '') + '…';
};

export function entry({ slug, description }) {
  return `      ${nixStr(slug)} = tool ${nixStr(slug)} ${nixStr(short(description))};\n`;
}

export function render(items) {
  return `# Generated by platform/distribution/nixflake.mjs. Do not edit.
# Free, open-source venture linters from this repository, runnable with Nix:
#   nix run github:duncan-haywood/oss-monorepo#<name> -- --fail-on-risk .
{
  description = "Free open-source CLI linters from the oss-monorepo catalogue (MIT)";

  inputs.nixpkgs.url = "github:NixOS/nixpkgs/nixpkgs-unstable";

  outputs = { self, nixpkgs }:
    let
      systems = [ "x86_64-linux" "aarch64-linux" "x86_64-darwin" "aarch64-darwin" ];
      forAll = f: nixpkgs.lib.genAttrs systems (system: f nixpkgs.legacyPackages.\${system});
      toolsFor = pkgs:
        let
          tool = slug: description: pkgs.writeShellApplication {
            name = slug;
            runtimeInputs = [ pkgs.python3 ];
            text = ''exec python3 \${./ventures + "/\${slug}/check.py"} "$@"'';
            meta = { inherit description; license = pkgs.lib.licenses.mit; mainProgram = slug; };
          };
        in {
${items.map(entry).join('')}        };
    in {
      packages = forAll toolsFor;
      apps = forAll (pkgs: builtins.mapAttrs (name: p: { type = "app"; program = pkgs.lib.getExe p; }) (toolsFor pkgs));
    };
}
`;
}

export async function build({ root = REPO_ROOT } = {}) {
  const { ok } = await actionPlan({ root });
  const items = [];
  for (const { slug } of ok) {
    const description = descriptionOf(await fs.readFile(path.join(root, 'ventures', slug, 'VENTURE.yaml'), 'utf8'));
    items.push({ slug, description });
  }
  return { text: render(items), slugs: items.map((i) => i.slug) };
}

export async function stale({ root = REPO_ROOT } = {}) {
  const { text } = await build({ root });
  return (await fs.readFile(path.join(root, FLAKE_FILE), 'utf8').catch(() => null)) === text ? [] : [FLAKE_FILE];
}

export async function write({ root = REPO_ROOT } = {}) {
  const { text, slugs } = await build({ root });
  await fs.writeFile(path.join(root, FLAKE_FILE), text);
  return slugs.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const flag = process.argv[2];
  if (flag === '--write') {
    console.log(`wrote ${await write()} packages to ${FLAKE_FILE}`);
  } else if (flag === '--check') {
    const bad = await stale();
    if (bad.length) { console.error(`stale (run --write): ${bad.join(', ')}`); process.exit(1); }
    console.log('flake.nix is current');
  } else {
    const { slugs } = await build();
    console.log(`${slugs.length} venture linters qualify as Nix packages`);
    for (const s of slugs) console.log(`  ${s}`);
  }
}
