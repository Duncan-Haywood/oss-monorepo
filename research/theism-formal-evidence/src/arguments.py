"""The arguments, written as premises and a conclusion, with where each comes from.

Every entry is a *reconstruction*: the standard textbook form of a published
argument, simplified to the fragment logic.py decides.  The point of formalising is
not to prove God exists or does not; validity is cheap.  It is to find, exactly, which
premises carry the weight (the minimal inconsistent subsets of premises plus the
denied conclusion), so the disagreement can be moved to evidence about those premises.
"""
