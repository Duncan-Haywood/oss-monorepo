"""E2: run the evidence ledger.

    python3 research/theism-formal-evidence/experiments/e2_ledger/run.py
Writes results.json and results.md next to this file.
"""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from bayes import (box_bounds, contrast_shares, flip_threshold, mid, monte_carlo,  # noqa: E402
                   posterior, prior_vector, quantiles, unwin)
from ledger import CHRISTIAN, HYPOTHESES, ITEMS, LABELS, PRIOR_DEFAULT, PUBLISHED_POSTERIORS, THEISM  # noqa: E402

CONTRASTS = {
    "theism_vs_naturalism": (THEISM, ["N"]),
    "christianity_vs_rest": (CHRISTIAN, ["N", "T_other"]),
    "catholic_vs_orthodox": (["C_catholic"], ["C_orthodox"]),
}


def run():
    out = {}
    out["unwin_reproduced"] = round(unwin(0.5, PUBLISHED_POSTERIORS[0]["reproduce"]["D"]), 4)
    priors = {"pew_shares": PRIOR_DEFAULT["within"],
              "equal_shares": {"C_catholic": 1, "C_orthodox": 1, "C_other": 1}}
    no_res = [it for it in ITEMS if it["id"] != "resurrection"]
    out["midpoint"] = {}  # resurrection excluded: its range spans 44 orders of magnitude
    out["box"] = {}
    for name, within in priors.items():
        pr = prior_vector(PRIOR_DEFAULT["theism"], PRIOR_DEFAULT["christian_given_theism"], within)
        out["midpoint"][name] = {h: posterior(pr, {it["id"]: mid(it) for it in no_res}, no_res)[h] for h in HYPOTHESES}
        out["box"][name] = {g: box_bounds(pr, members) for g, members in
                            {"N": ["N"], "Christian": CHRISTIAN, "C_catholic": ["C_catholic"], "C_orthodox": ["C_orthodox"]}.items()}
    # the same with the resurrection item excluded (its range dwarfs the rest)
    pr = prior_vector(PRIOR_DEFAULT["theism"], PRIOR_DEFAULT["christian_given_theism"], PRIOR_DEFAULT["within"])
    out["box_without_resurrection"] = {"N": box_bounds(pr, ["N"], no_res), "Christian": box_bounds(pr, CHRISTIAN, no_res)}
    out["shares"] = {}  # theism contrast without the resurrection item (it does not move it)
    for name, (A, B) in CONTRASTS.items():
        sh, var = contrast_shares((A, B), no_res if name == "theism_vs_naturalism" else ITEMS)
        # add the prior's own uncertainty (logit-uniform 0.01-0.99 -> log10 odds uniform on +-1.996)
        prior_var = (2 * math.log10(99)) ** 2 / 12 if name != "catholic_vs_orthodox" else 0.0
        tot = var + prior_var
        out["shares"][name] = {"prior": prior_var / tot, **{k: v * var / tot for k, v in sh.items() if v > 0}}
    out["flip"] = {}  # without the resurrection item; its own threshold is reported below
    for name, (A, B) in CONTRASTS.items():
        if name == "christianity_vs_rest":
            continue
        out["flip"][name] = {it["id"]: flip_threshold(pr, it["id"], A, B, no_res) for it in no_res
                             if flip_threshold(pr, it["id"], A, B, no_res) is not None}
    # resurrection: the Bayes factor needed for P(Christian) > 0.5, by prior, with the
    # theism-level items at their midpoints
    out["resurrection_threshold"] = {}
    for t in (0.1, 0.5, 0.9):
        for c in (0.1, 0.5, 0.9):
            prc = prior_vector(t, c, PRIOR_DEFAULT["within"])
            out["resurrection_threshold"][f"P(theism)={t}, P(C|theism)={c}"] = flip_threshold(
                prc, "resurrection", CHRISTIAN, ["N", "T_other"])
    out["mc"] = {}
    for rho in (1.0, 0.5):
        draws = monte_carlo(n=20000, seed=1, rho=rho, items=no_res)
        out["mc"][f"rho={rho}"] = {
            "P(N)": quantiles([d["N"] for d in draws]),
            "P(Christian)": quantiles([sum(d[h] for h in CHRISTIAN) for d in draws]),
            "P(Catholic | Christian)": quantiles([d["C_catholic"] / sum(d[h] for h in CHRISTIAN) for d in draws]),
            "P(Orthodox | Christian)": quantiles([d["C_orthodox"] / sum(d[h] for h in CHRISTIAN) for d in draws]),
            "share of draws with P(N) > 0.5": sum(d["N"] > 0.5 for d in draws) / len(draws),
        }
    return out


def fmt(x):
    return f"{x:.3g}" if isinstance(x, float) else str(x)


def markdown(r):
    L = ["# E2 results: the evidence ledger", "", "Generated by `run.py` from `src/ledger.py`. Probabilities are model outputs given the ledger's ranges, not findings about the world.", ""]
    L.append(f"**Unwin (2003) reproduced:** {r['unwin_reproduced']} (published 0.67).\n")
    L.append("## Posterior at the midpoint of every range except the resurrection item (prior P(theism)=0.5, P(Christian|theism)=0.5)\n")
    L.append("| hypothesis | Pew shares within Christianity | equal shares |\n|---|---|---|")
    for h in HYPOTHESES:
        L.append(f"| {LABELS[h]} | {fmt(r['midpoint']['pew_shares'][h])} | {fmt(r['midpoint']['equal_shares'][h])} |")
    L.append("\n## Bounds over every likelihood ratio in its range (default priors)\n")
    L.append("| group | Pew shares | equal shares |\n|---|---|---|")
    for g in r["box"]["pew_shares"]:
        a, b = r["box"]["pew_shares"][g]; c, d = r["box"]["equal_shares"][g]
        L.append(f"| {g} | {fmt(a)} to {fmt(b)} | {fmt(c)} to {fmt(d)} |")
    a, b = r["box_without_resurrection"]["N"]; c, d = r["box_without_resurrection"]["Christian"]
    L.append(f"\nWithout the resurrection item: P(N) {fmt(a)} to {fmt(b)}; P(Christian) {fmt(c)} to {fmt(d)}.\n")
    L.append("## Where the disagreement comes from (share of the variance of log posterior odds)\n")
    for name, sh in r["shares"].items():
        parts = ", ".join(f"{k} {v:.1%}" for k, v in sorted(sh.items(), key=lambda kv: -kv[1]))
        L.append(f"- **{name}:** {parts}")
    L.append("\n## Flip thresholds (log10 LR at which the contrast's odds reach 1, others at midpoints)\n")
    for name, fl in r["flip"].items():
        L.append(f"- **{name}:** " + ", ".join(f"{k} {v:+.2f}" for k, v in fl.items()))
    L.append("\n## Resurrection: log10 Bayes factor needed for P(Christian) > 0.5 (other items at midpoints)\n")
    for k, v in r["resurrection_threshold"].items():
        L.append(f"- {k}: {v:+.2f} (Bayes factor {10 ** v:.3g})")
    L.append("\n## Monte Carlo without the resurrection item (log LRs uniform on ranges, priors logit-uniform on 0.01-0.99; 5th / 50th / 95th percentiles)\n")
    for k, v in r["mc"].items():
        L.append(f"- **{k}:** " + "; ".join(f"{kk} {fmt(vv) if not isinstance(vv, list) else ' / '.join(fmt(x) for x in vv)}" for kk, vv in v.items()))
    return "\n".join(L)


if __name__ == "__main__":
    r = run()
    (HERE / "results.json").write_text(json.dumps(r, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(r) + "\n")
    print(markdown(r))
