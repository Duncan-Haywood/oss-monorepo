"""E1: decide every argument in src/arguments.py, in each modal system where relevant,
and list its cruxes (minimal inconsistent subsets of premises + denied conclusion).

    python3 research/theism-formal-evidence/experiments/e1_arguments/run.py
Writes results.json and results.md next to this file.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from arguments import ARGUMENTS  # noqa: E402
from logic import A, All, Box, Dia, Imp, Not, P, check, is_modal, maximal_consistent_subsets, minimal_unsat_subsets, show  # noqa: E402

SYSTEMS = ["K", "T", "B", "S4", "S5"]


def run():
    rows = []
    for arg in ARGUMENTS:
        prem = [f for _, f in arg["premises"]]
        concl = arg["conclusion"][1]
        modal = any(is_modal(f) for f in prem + [concl])
        verdicts = {}
        for sysname in (SYSTEMS if modal else ["FO"]):
            r = check(prem, concl, sysname if modal else "S5", max_worlds=None if sysname == "S5" else 3)
            verdicts[sysname] = {"valid": r["valid"], "certified": r["certified"], "countermodel": r["countermodel"]}
        claims = prem + ([Not(concl)] if concl != ("bot",) else [])
        labels = [t for t, _ in arg["premises"]] + (["NOT: " + arg["conclusion"][0]] if concl != ("bot",) else [])
        cruxes = [[labels[i] for i in m] for m in minimal_unsat_subsets(claims, "S5")]
        rows.append({"id": arg["id"], "name": arg["name"], "side": arg["side"], "source": arg["source"],
                     "premises": [[t, show(f)] for t, f in arg["premises"]],
                     "conclusion": [arg["conclusion"][0], show(concl)],
                     "verdicts": verdicts, "cruxes": cruxes, "note": arg.get("note", "")})
    return rows


G = A("G")
JOINT = {
    "ontological_pair": [
        ("Anselm's principle []( G -> []G )", Box(Imp(G, Box(G)))),
        ("Possibly God exists", Dia(G)),
        ("Possibly God does not exist", Dia(Not(G)))],
    "church_disputes": [
        ("c1 Ex cathedra papal teaching cannot err (Vatican I)", All("x", Imp(P("ExCathedra", "x"), Not(P("Erred", "x"))))),
        ("c2 What an ecumenical council condemns as heresy is error", All("x", Imp(P("Condemned", "x"), P("Erred", "x")))),
        ("c3 Constantinople III condemned Honorius's letter", P("Condemned", "h")),
        ("c4 Honorius's letter was ex cathedra", P("ExCathedra", "h")),
        ("c5 Ecumenical councils cannot err", All("x", Imp(P("Ecumenical", "x"), Not(P("Erred", "x"))))),
        ("c6 Florence (1439) was ecumenical", P("Ecumenical", "f")),
        ("c7 If the Filioque is false, Florence erred", Imp(Not(A("Filioque")), P("Erred", "f"))),
        ("c8 The Filioque is false", Not(A("Filioque")))],
}


def joint():
    out = {}
    for name, claims in JOINT.items():
        fs = [f for _, f in claims]
        labels = [t for t, _ in claims]
        out[name] = {"claims": [[t, show(f)] for t, f in claims],
                     "minimal_inconsistent": [[labels[i] for i in m] for m in minimal_unsat_subsets(fs)],
                     "maximal_consistent_positions": [[labels[i] for i in m] for m in maximal_consistent_subsets(fs)]}
    return out


def markdown(rows):
    out = ["# E1 results: validity and cruxes", "",
           "Generated by `run.py`. FO = monadic first-order (decided exactly). Modal rows: S5 decided exactly;",
           "K/T/B/S4 'valid' means no countermodel with <= 3 worlds (proof in `lean/`), 'invalid' is a certified countermodel.", ""]
    for r in rows:
        out.append(f"## {r['name']} (`{r['id']}`)")
        out.append(f"*Source:* {r['source']}  ")
        for t, f in r["premises"]:
            out.append(f"- {t}: `{f}`")
        out.append(f"- **Conclusion** {r['conclusion'][0]}: `{r['conclusion'][1]}`")
        v = ", ".join(f"{k}: {'valid' if x['valid'] else 'INVALID'}{'' if x['certified'] else ' (bounded)'}" for k, x in r["verdicts"].items())
        out.append(f"- **Verdict:** {v}")
        for k, x in r["verdicts"].items():
            if x["countermodel"]:
                out.append(f"  - countermodel ({k}): `{json.dumps(x['countermodel'], sort_keys=True)}`")
        out.append(f"- **Cruxes** (each set is jointly inconsistent; give up at least one):")
        for c in r["cruxes"]:
            out.append("  - " + " + ".join(c))
        if r["note"]:
            out.append(f"- {r['note']}")
        out.append("")
    for name, j in joint().items():
        out.append(f"## Joint analysis: {name}")
        out.append("Claims: " + "; ".join(f"{t}" for t, _ in j["claims"]))
        out.append("")
        out.append("Minimal inconsistent sets:")
        for m in j["minimal_inconsistent"]:
            out.append("- " + " + ".join(m))
        out.append("")
        out.append(f"Maximal consistent positions ({len(j['maximal_consistent_positions'])}), each the claims a coherent person can hold together:")
        for m in j["maximal_consistent_positions"]:
            out.append("- " + "; ".join(x.split(" ")[0] if x[:1] == "c" and x[1:2].isdigit() else x for x in m))
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    rows = run()
    (HERE / "results.json").write_text(json.dumps({"arguments": rows, "joint": joint()}, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(rows) + "\n")
    for r in rows:
        print(r["id"], {k: ("valid" if x["valid"] else "invalid") for k, x in r["verdicts"].items()}, "cruxes:", len(r["cruxes"]))
