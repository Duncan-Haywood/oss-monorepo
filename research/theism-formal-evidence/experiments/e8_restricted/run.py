"""E8: Anderson's emendation with RESTRICTED property families (follow-up to E7).

    python3 research/theism-formal-evidence/experiments/e8_restricted/run.py

E7 found no multi-world model when every set of (world, individual) cells is a property.
Here the property space is a Boolean algebra: all unions of the blocks of a partition of the
cells.  Every partition of the cells is tried (Bell(n) of them, n = worlds x individuals <= 5),
so the question is "does ANY algebra of properties give a multi-world model of A1, A2, A3', A5'?".
Same definitions as E7.  Writes results.json and results.md next to this file.
"""
import itertools, json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def partitions(n):
    def rec(i, blocks):
        if i == n:
            yield [list(b) for b in blocks]; return
        for b in blocks:
            b.append(i); yield from rec(i + 1, blocks); b.pop()
        blocks.append([i]); yield from rec(i + 1, blocks); blocks.pop()
    yield from rec(0, [])


def algebra(blocks):
    masks = [sum(1 << c for c in b) for b in blocks]
    out = set()
    for r in range(len(masks) + 1):
        for s in itertools.combinations(masks, r):
            out.add(sum(s))
    return sorted(out)


def search(w, d, props):
    cells = w * d
    full = (1 << cells) - 1
    cell = lambda wi, xi: wi * d + xi
    box_mask = [sum(1 << cell(wi, xi) for wi in range(w)) for xi in range(d)]
    has_box = lambda f, xi: (f & box_mask[xi]) == box_mask[xi]
    pairs = [(f, full ^ f) for f in props if f < full ^ f]
    n = 0
    nontrivial = 0
    for choice in itertools.product((0, 1), repeat=len(pairs)):
        P = [pr[c] for pr, c in zip(pairs, choice)]
        Pset = set(P)
        if any((f | g) == g and g not in Pset for f in P for g in props):
            continue
        gstar = [xi for xi in range(d) if all((f in Pset) == has_box(f, xi) for f in props)]
        G = sum(box_mask[xi] for xi in gstar)
        if G not in Pset:
            continue
        NE = 0
        for xi in range(d):
            ok = True
            for f in props:
                if all(has_box(g, xi) == ((f | g) == g) for g in props):
                    if any(not any(f >> cell(wj, yi) & 1 for yi in range(d)) for wj in range(w)):
                        ok = False; break
            if ok:
                NE |= box_mask[xi]
        if NE not in Pset:
            continue
        n += 1
        if G != 0 and 0 not in Pset:
            nontrivial += 1   # G* non-empty somewhere, and no positive property is empty
    return n, nontrivial


def contingent(props, w, d):
    """Some property holds of some individual at one world and not at another."""
    for f in props:
        for xi in range(d):
            vals = {(f >> (wi * d + xi)) & 1 for wi in range(w)}
            if len(vals) > 1:
                return True
    return False


def run():
    rows = []
    for w, d in [(1, 2), (1, 3), (2, 1), (2, 2), (3, 1), (4, 1), (5, 1)]:
        n = w * d
        tot = models = nontriv = skipped = 0
        example = None
        for blocks in partitions(n):
            props = algebra(blocks)
            if w >= 2 and not contingent(props, w, d):
                skipped += 1   # all properties rigid: a one-world model in disguise
                continue
            tot += 1
            m, nt = search(w, d, props)
            models += m > 0
            nontriv += nt > 0
            if nt and example is None and w >= 2:
                example = [sorted(b) for b in blocks]
        rows.append({"w": w, "d": d, "algebras": tot, "skipped_rigid": skipped, "algebras_with_model": models,
                     "algebras_with_nontrivial_model": nontriv, "example_multiworld": example})
    return rows


def markdown(rows):
    L = ["# E8 results: Anderson's emendation over restricted property algebras", "",
         "Generated by `run.py`. One row per size; an algebra is the set of unions of blocks of a partition of the cells.", "",
         "| worlds | individuals | algebras with contingent properties (rigid-only skipped) | with a model | with a model where G* is instantiated and no positive property is empty | example partition (cells = world*d+individual) |",
         "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['w']} | {r['d']} | {r['algebras']} | {r['algebras_with_model']} | {r['algebras_with_nontrivial_model']} | {r['example_multiworld']} |")
    return "\n".join(L)


def test_single_world_has_models():
    assert search(1, 2, algebra([[0], [1]]))[0] == 2


if __name__ == "__main__":
    rows = run()
    (HERE / "results.json").write_text(json.dumps(rows, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(rows) + "\n")
    print(markdown(rows))
    test_single_world_has_models(); print("ok")
