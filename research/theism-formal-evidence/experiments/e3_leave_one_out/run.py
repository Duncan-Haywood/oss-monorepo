"""E3: leave-one-out over the evidence ledger (milestone M2).

    python3 research/theism-formal-evidence/experiments/e3_leave_one_out/run.py
Drops each item in turn and reports the change in the midpoint posterior of naturalism
(resurrection excluded, as in E2) and in the box bounds of P(Christian).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from bayes import box_bounds, mid, posterior, prior_vector  # noqa: E402
from ledger import CHRISTIAN, ITEMS, PRIOR_DEFAULT  # noqa: E402


def run():
    pr = prior_vector(PRIOR_DEFAULT["theism"], PRIOR_DEFAULT["christian_given_theism"], PRIOR_DEFAULT["within"])
    base_items = [it for it in ITEMS if it["id"] != "resurrection"]

    def pn(items):
        return posterior(pr, {i["id"]: mid(i) for i in items}, items)["N"]

    full = pn(base_items)
    out = {"full_P_N": full, "verdict_full": full > 0.5, "items": {}}
    for it in base_items:
        rest = [j for j in base_items if j is not it]
        v = pn(rest)
        lo, hi = box_bounds(pr, CHRISTIAN, rest)
        out["items"][it["id"]] = {"basis": it["basis"], "level": it["level"], "P_N": v, "delta": v - full,
                                  "verdict_flips": (v > 0.5) != (full > 0.5), "P_christian_box": [lo, hi]}
    out["max_abs_delta_sourced"] = max(abs(r["delta"]) for r in out["items"].values() if r["basis"] == "published")
    out["max_abs_delta_item"] = max(out["items"], key=lambda k: abs(out["items"][k]["delta"]))
    out["flippers"] = [k for k, r in out["items"].items() if r["verdict_flips"]]
    return out


def markdown(r):
    L = ["# E3 results: leave-one-out over the ledger", "",
         "Generated by `run.py`. Midpoint P(naturalism), resurrection excluded, default priors "
         f"(full ledger: {r['full_P_N']:.3f}). Model outputs, not findings about the world.", "",
         "| item dropped | basis | P(N) without it | change | flips P(N) > 0.5? |", "|---|---|---|---|---|"]
    for k, v in sorted(r["items"].items(), key=lambda kv: -abs(kv[1]["delta"])):
        L.append(f"| {k} | {v['basis']} | {v['P_N']:.3f} | {v['delta']:+.3f} | {'yes' if v['verdict_flips'] else 'no'} |")
    L.append(f"\nLargest single-drop change: **{r['max_abs_delta_item']}**. Largest change from a published-basis item: "
             f"{r['max_abs_delta_sourced']:.3f}. Items that flip the verdict: {r['flippers'] or 'none'}.")
    return "\n".join(L)


if __name__ == "__main__":
    r = run()
    (HERE / "results.json").write_text(json.dumps(r, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(r) + "\n")
    print(markdown(r))
