"""E4: Goedel's ontological argument in Scott's form, by exhaustive finite-model search.

    python3 research/theism-formal-evidence/experiments/e4_godel_scott/run.py

Models: S5 (all worlds see all worlds), constant domain of d individuals, w worlds.  A
property is any function from worlds to subsets of the domain (full semantics), a bitmask
over w*d (world, individual) cells.  The positive set P is a set of properties, the same
at every world (this is axiom A4).  Axioms checked:
  A1 P(f) and f subset-of g (necessarily, everywhere) -> P(g)
  A2 exactly one of f and its complement is positive
  A3 P(G), G(x) = every positive property holds of x
  A5 P(NE), NE(x) = every essence of x is necessarily instantiated, where
     ess(f, x) = f(x) and every property g that x has is necessarily implied by f.
Writes results.json and results.md next to this file.
"""
import itertools
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def search(w, d):
    cells = w * d
    full = (1 << cells) - 1
    n = 1 << cells
    props = range(n)
    cell = lambda wi, xi: wi * d + xi
    # complement pairs: choose which of (f, ~f) is positive
    pairs = [(f, full ^ f) for f in props if f < full ^ f]
    stats = {"w": w, "d": d, "candidate_P": 2 ** len(pairs), "models": 0,
             "all_positive_instantiated": True, "pos_sizes": []}
    for choice in itertools.product((0, 1), repeat=len(pairs)):
        P = [pr[c] for pr, c in zip(pairs, choice)]
        Pset = set(P)
        # A1: closed upward under subset
        if any((f | g) == g and g not in Pset for f in P for g in props):
            continue
        # A3: G positive
        G = full
        for f in P:
            G &= f
        if G not in Pset:
            continue
        # A5: NE positive
        NE = 0
        for wi in range(w):
            for xi in range(d):
                bit = 1 << cell(wi, xi)
                ok = True
                for f in props:
                    if not f & bit:
                        continue
                    if all((f | g) == g for g in props if g & bit):    # f is an essence of (wi, xi)
                        # necessarily instantiated: nonempty at every world
                        if any(not any(f >> cell(wj, yi) & 1 for yi in range(d)) for wj in range(w)):
                            ok = False
                            break
                if ok:
                    NE |= bit
        if NE not in Pset:
            continue
        stats["models"] += 1
        stats["pos_sizes"].append(len(P))
        if any(f == 0 for f in P):
            stats["all_positive_instantiated"] = False
    stats["pos_sizes"] = sorted(set(stats["pos_sizes"]))
    # collapse test: a contingent proposition (true at one world, false at another) exists in every model with w >= 2
    stats["contingent_propositions_exist"] = w >= 2
    return stats


def run():
    cases = [(1, 1), (1, 2), (1, 3), (2, 1), (2, 2), (3, 1), (4, 1), (5, 1)]
    return [search(w, d) for w, d in cases if (1 << (w * d)) // 2 <= 16]


def markdown(rows):
    L = ["# E4 results: Goedel's argument (Scott's axioms), finite-model search", "",
         "Generated by `run.py`. S5, constant domain, full property semantics, exhaustive over the positive set P "
         "(chosen from complement pairs, so A2 holds by construction; A1, A3, A5 checked). A4 is built in (P is the same at every world).", "",
         "| worlds | individuals | candidate P sets | models of A1-A5 | every positive property instantiated | contingent proposition exists |",
         "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['w']} | {r['d']} | {r['candidate_P']} | {r['models']} | {r['all_positive_instantiated']} | {r['contingent_propositions_exist']} |")
    one = [r for r in rows if r["w"] == 1]
    multi = [r for r in rows if r["w"] >= 2]
    L.append("")
    L.append(f"One-world models exist for every domain size tried ({', '.join(str(r['d']) for r in one if r['models'])}). "
             f"Models with two or more worlds: {sum(r['models'] for r in multi)} across {len(multi)} sizes tried.")
    return "\n".join(L)


if __name__ == "__main__":
    rows = run()
    (HERE / "results.json").write_text(json.dumps(rows, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(rows) + "\n")
    print(markdown(rows))
