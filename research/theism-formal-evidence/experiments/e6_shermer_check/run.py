"""E6: re-compute Shermer's published 2% from his six published D values (milestone M2).

    python3 research/theism-formal-evidence/experiments/e6_shermer_check/run.py
"""
import json
import sys
from itertools import permutations
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from bayes import unwin  # noqa: E402
from ledger import PUBLISHED_POSTERIORS  # noqa: E402

NAMES = ["goodness", "moral evil", "natural evil", "intranatural miracles", "extranatural miracles", "religious experience"]
rows = []
for pub in PUBLISHED_POSTERIORS[:2]:
    r = pub["reproduce"]
    prod = 1.0
    for d in r["D"]:
        prod *= d
    rows.append(dict(who=pub["who"], published=pub["claim"], product=prod, computed=unwin(r["prior"], r["D"])))
sh = PUBLISHED_POSTERIORS[1]["reproduce"]["D"]
orders = {round(unwin(0.5, list(o)), 12) for o in permutations(sh)}
need = 0.02 / 0.98
# Single-D changes that would make the column's 2% true: required value of each D given the other five.
fixes = []
for i, n in enumerate(NAMES):
    rest = 1.0
    for j, d in enumerate(sh):
        if j != i:
            rest *= d
    fixes.append(dict(item=n, published_D=sh[i], D_needed=need / rest))
out = dict(rows=rows, order_invariant=len(orders) == 1, odds_needed_for_2pct=need, single_D_fixes=fixes)
(HERE / "results.json").write_text(json.dumps(out, indent=1))
md = ["# E6 results: does Shermer's 2% follow from his six D values?", "",
      "Generated by `run.py`. Inputs transcribed from the column (Scientific American, July 2004); the formula is Unwin's, as the column describes it (start at 50%, multiply the odds by each D).", "",
      "| who | published | product of six D | computed P(God) |", "|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['who']} | {r['published']} | {r['product']:.6g} | {r['computed']:.6g} |")
md += ["", f"Order of application does not matter: {out['order_invariant']}. For the column's 2% the six D would need to multiply to {need:.4f}, "
       f"{need / rows[1]['product']:.0f} times what they do.", "",
       "Single input that, changed alone, would make 2% true:", "", "| item | published D | D needed |", "|---|---|---|"]
for f in fixes:
    md.append(f"| {f['item']} | {f['published_D']} | {f['D_needed']:.3g} |")
md += ["", "Reading: Unwin's 67% reproduces exactly (E2); Shermer's 2% does not follow from his inputs under the same formula. "
       "We cannot tell from the column whether a D or the final figure is a typo; the neutral report is that inputs and output disagree by about 80-fold in odds. "
       "No claim is made about which side Shermer meant."]
(HERE / "results.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
