"""E25: reproduce Swinburne's (2003) 0.97 from his four published inputs, and find what moves it (milestone M2).

    python3 research/theism-formal-evidence/experiments/e25_swinburne/run.py

Inputs are those quoted verbatim, with the book's page numbers, in Otte's NDPR review (2003.09.04);
see src/ledger.py, PUBLISHED_POSTERIORS. Exact rational arithmetic (fractions.Fraction), stdlib only.
"""
import json
import math
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from ledger import PUBLISHED_POSTERIORS  # noqa: E402

SW = next(p for p in PUBLISHED_POSTERIORS if p["who"].startswith("R. Swinburne"))["reproduce"]
INPUTS = {k: F(v) for k, v in SW.items()}


def posterior(p_t, p_i, a, b):
    """P(c|f&k) with P(c|k) = p_t * p_i, P(f|c&k) = a, P(f|~c&k) = b."""
    pc = p_t * p_i
    return pc * a / (pc * a + (1 - pc) * b)


def solve_pc(target, lr):
    """P(c|k) at which the posterior equals target, given the likelihood ratio lr."""
    o = target / (1 - target) / lr
    return o / (1 + o)


def thresholds(target, x):
    """Single-input values (others at Swinburne's) that make the posterior equal target."""
    pc = x["p_theism"] * x["p_divided_incarnation_given_theism"]
    a, b = x["p_f_given_c"], x["p_f_given_not_c"]
    need_odds = target / (1 - target)
    prior_odds = pc / (1 - pc)
    lr = a / b
    pc_star = solve_pc(target, lr)
    return {
        "P(c|k)": pc_star,
        "P(t|k)": pc_star / x["p_divided_incarnation_given_theism"],
        "P(divided incarnation|t)": pc_star / x["p_theism"],
        "P(f|c&k)": need_odds / prior_odds * b,
        "P(f|~c&k)": a * prior_odds / need_odds,
        "LR": need_odds / prior_odds,
    }


def fmt(q):
    return f"{q.numerator}/{q.denominator}" if q.denominator != 1 else str(q.numerator)


def main():
    x = INPUTS
    pc = x["p_theism"] * x["p_divided_incarnation_given_theism"]
    lr = x["p_f_given_c"] / x["p_f_given_not_c"]
    post = posterior(x["p_theism"], x["p_divided_incarnation_given_theism"], x["p_f_given_c"], x["p_f_given_not_c"])
    decomposition = {"log10 prior odds": math.log10(pc / (1 - pc)), "log10 LR": math.log10(lr),
                     "log10 posterior odds": math.log10(post / (1 - post))}
    th = {str(t): thresholds(t, x) for t in (F(1, 2), F(1, 3))}
    # Otte's alternative: P(incarnation | God) = 1/3 rather than 1/2.
    otte = posterior(x["p_theism"], F(1, 3), x["p_f_given_c"], x["p_f_given_not_c"])
    # Otte's coherence point: a share u of the incarnation probability goes to a unified incarnation.
    # P(c|k) = (1/2)(1/2)(1 - u); posterior = 1/2 at u*.
    u_star = 1 - th["1/2"]["P(c|k)"] / pc
    u_rows = [(u, posterior(x["p_theism"], x["p_divided_incarnation_given_theism"] * (1 - u), x["p_f_given_c"], x["p_f_given_not_c"]))
              for u in (F(0), F(1, 2), F(9, 10), F(99, 100))]
    # Two-way grid over the two priors, evidence at Swinburne's ratio: where is the posterior >= 1/2?
    grid = [F(1, 1000), F(1, 100), F(1, 20), F(1, 10), F(1, 4), F(1, 2), F(3, 4), F(9, 10)]
    table = [[posterior(t, i, x["p_f_given_c"], x["p_f_given_not_c"]) for i in grid] for t in grid]
    # The ledger's resurrection item spans log10 LR 0..44 (E2, E5); Swinburne's whole f is 2.
    out = dict(inputs={k: fmt(v) for k, v in x.items()}, p_c_given_k=fmt(pc), likelihood_ratio=fmt(lr),
               posterior=fmt(post), posterior_float=float(post), published="somewhere around .97",
               reproduces=abs(float(post) - 0.97) < 0.005, decomposition=decomposition,
               thresholds={t: {k: fmt(v) for k, v in d.items()} for t, d in th.items()},
               otte_one_third=fmt(otte), otte_one_third_float=float(otte), unified_share_threshold=fmt(u_star),
               unified_rows=[(fmt(u), float(p)) for u, p in u_rows],
               grid=[fmt(g) for g in grid], grid_posterior=[[float(v) for v in r] for r in table])
    (HERE / "results.json").write_text(json.dumps(out, indent=1))

    md = ["# E25 results: does Swinburne's 0.97 follow from his four inputs, and what moves it?", "",
          "Generated by `run.py` (exact rational arithmetic). Inputs as quoted, with the book's page numbers, in Otte's review "
          "(NDPR 2003.09.04); not yet checked against the book itself.", "",
          "| input | value | source (book page, via Otte) |", "|---|---|---|",
          f"| P(t\\|k), theism on background knowledge | {fmt(x['p_theism'])} | review note 2 |",
          f"| P(divided incarnation \\| God) | {fmt(x['p_divided_incarnation_given_theism'])} | pp. 50, 211 |",
          f"| P(f\\|c&k), the evidence if God became incarnate | {fmt(x['p_f_given_c'])} | p. 212 |",
          f"| P(f\\|~c&k), the evidence otherwise | {fmt(x['p_f_given_not_c'])} | p. 213 |", "",
          f"P(c|k) = {fmt(pc)}; likelihood ratio = {fmt(lr)}; **P(c|f&k) = {fmt(post)} = {float(post):.4f}** "
          f"(published: \"somewhere around .97\"; reproduces: {out['reproduces']}).", "",
          f"Log10 odds: prior {decomposition['log10 prior odds']:+.3f}, evidence {decomposition['log10 LR']:+.3f}, "
          f"posterior {decomposition['log10 posterior odds']:+.3f}.", "",
          "Single input that, changed alone, puts the posterior at the target:", "",
          "| input | Swinburne | for 1/2 | for 1/3 |", "|---|---|---|---|"]
    base = {"P(c|k)": pc, "P(t|k)": x["p_theism"], "P(divided incarnation|t)": x["p_divided_incarnation_given_theism"],
            "P(f|c&k)": x["p_f_given_c"], "P(f|~c&k)": x["p_f_given_not_c"], "LR": lr}
    for k in base:
        md.append(f"| {k.replace('|', chr(92) + '|')} | {fmt(base[k])} | {fmt(th['1/2'][k])} ({float(th['1/2'][k]):.4g}) | {fmt(th['1/3'][k])} ({float(th['1/3'][k]):.4g}) |")
    md += ["", f"Otte's alternative, P(incarnation | God) = 1/3: posterior {fmt(otte)} = {float(otte):.4f}.", "",
           f"Otte's coherence point, a share u of the incarnation probability on a unified incarnation: posterior falls to 1/2 at "
           f"u = {fmt(u_star)} = {float(u_star):.4f}.", "",
           "| u | posterior |", "|---|---|"] + [f"| {fmt(u)} | {float(p):.4f} |" for u, p in u_rows]
    md += ["", "Posterior with the evidence at Swinburne's ratio (100), over the two priors (rows P(t|k), columns P(divided incarnation | God)):", "",
           "| P(t\\|k) \\ P(inc\\|t) | " + " | ".join(fmt(g) for g in grid) + " |", "|---" * (len(grid) + 1) + "|"]
    for t, r in zip(grid, table):
        md.append(f"| {fmt(t)} | " + " | ".join(f"{float(v):.3f}" for v in r) + " |")
    md += ["", "Reading: the 0.97 follows exactly from the four inputs. The evidence term is a likelihood ratio of 100 (2 in log10); "
           "a sceptic who keeps the evidence term and lowers the product of the two priors below 1/101 gets under 1/2, and one who keeps the "
           "priors needs only P(f|~c&k) above 1/30, a thirty-fold change in the input Otte says gets the least defence. "
           "No single input in this table is attributed to a critic as the one that gives 0.33."]
    (HERE / "results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
