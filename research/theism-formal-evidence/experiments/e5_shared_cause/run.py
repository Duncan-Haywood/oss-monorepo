"""E5: shared-cause dependence for the resurrection testimony (milestone M4).

    python3 research/theism-formal-evidence/experiments/e5_shared_cause/run.py
E2 discounted dependence crudely (every log LR times rho).  Here the testimony items share
one latent reliability, and the combined Bayes factor is BF = 1 + omega (L - 1), with L the
independent product and omega the sceptic's credence in the source after the reports
(bayes.shared_cause_bf).  Reports how far dependence can move the threshold question.
"""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from bayes import (flip_threshold, mid, posterior, prior_vector, shared_cause_bf,  # noqa: E402
                   shared_cause_bf_enumerated)
from ledger import CHRISTIAN, ITEMS, PRIOR_DEFAULT  # noqa: E402

LOG_L = 44.0                 # McGrew & McGrew product (secondary report), log10
OMEGAS = [1.0, 0.5, 1e-3, 1e-6, 1e-12, 1e-24, 1e-36, 1e-43, 1e-44]
PRIORS = {"even (0.5, 0.5)": (0.5, 0.5), "sceptical (0.1, 0.1)": (0.1, 0.1), "devout (0.9, 0.9)": (0.9, 0.9)}


def required_log_bf(theism, cgt):
    pr = prior_vector(theism, cgt, PRIOR_DEFAULT["within"])
    others = [it for it in ITEMS if it["id"] != "resurrection"]
    base = {it["id"]: mid(it) for it in others}
    p = posterior(pr, {**base, "resurrection": 0.0}, ITEMS)
    odds = sum(p[h] for h in CHRISTIAN) / sum(p[h] for h in ("N", "T_other"))
    return -math.log10(odds)


def run():
    L = 10 ** LOG_L
    out = {"log10_L": LOG_L, "table": [], "priors": {}, "enumeration_check": {}}
    for w in OMEGAS:
        bf = shared_cause_bf(1, L, w)                  # ratio**n = L, so n = 1 carries the product
        out["table"].append({"omega": w, "log10_BF": math.log10(bf),
                             "rho_equivalent": math.log10(bf) / LOG_L})
    for name, (t, c) in PRIORS.items():
        need = required_log_bf(t, c)
        # largest omega at which BF still reaches the required value
        # need <= 0 means the other items already put P(Christian) at or above 0.5: no threshold
        w_star = (10 ** need - 1) / (L - 1) if need > 0 else None
        out["priors"][name] = {"required_log10_BF": need, "omega_threshold": w_star,
                               "log10_omega_threshold": math.log10(w_star) if w_star else None}
    # the closed form against enumeration of the explicit joint model (n = 4 items)
    for (n, a, b, u, r) in [(4, 0.9, 0.3, 0.6, 0.7), (6, 0.8, 0.1, 0.5, 0.9), (3, 0.5, 0.25, 0.4, 0.5)]:
        bf_e, om = shared_cause_bf_enumerated(n, a, b, u, r)
        bf_c = shared_cause_bf(n, a / b, om)
        out["enumeration_check"][f"n={n},a={a},b={b},u={u},r={r}"] = {"enumerated": bf_e, "closed_form": bf_c, "omega": om}
    return out


def markdown(r):
    L = ["# E5 results: shared-cause dependence for the resurrection testimony", "",
         "Generated by `run.py`. Model outputs given stated inputs; the independent product 10^44 is the McGrews' figure "
         "as reported secondarily, not checked against the chapter.", "",
         "BF = 1 + omega (L - 1), L = 10^44. omega = the sceptic's credence in the source's reliability after the reports.", "",
         "| omega | log10 BF | equivalent rho (E2's crude discount) |", "|---|---|---|"]
    for t in r["table"]:
        L.append(f"| {t['omega']:.0e} | {t['log10_BF']:.2f} | {t['rho_equivalent']:.3f} |")
    L += ["", "Largest omega at which the testimony still lifts P(Christian) to 0.5 (other items at their midpoints):", "",
          "| priors (P(theism), P(Christian given theism)) | required log10 BF | omega threshold |", "|---|---|---|"]
    for k, v in r["priors"].items():
        th = "none needed (other items suffice)" if v["log10_omega_threshold"] is None else f"10^{v['log10_omega_threshold']:.1f}"
        L.append(f"| {k} | {v['required_log10_BF']:.2f} | {th} |")
    L += ["", "Closed form against direct enumeration of the joint model:", "", "| case | enumerated | closed form |", "|---|---|---|"]
    for k, v in r["enumeration_check"].items():
        L.append(f"| {k} | {v['enumerated']:.6g} | {v['closed_form']:.6g} |")
    return "\n".join(L)


if __name__ == "__main__":
    r = run()
    (HERE / "results.json").write_text(json.dumps(r, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(r) + "\n")
    print(markdown(r))
