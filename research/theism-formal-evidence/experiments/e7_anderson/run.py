"""E7: Anderson's emendation of Goedel's ontological argument, by exhaustive finite-model search.

    python3 research/theism-formal-evidence/experiments/e7_anderson/run.py

Same model class as E4 (S5, constant domain, w worlds, d individuals, full property semantics,
positive set P rigid across worlds, A2 by construction from complement pairs).  Differences:
  A3' P(G*), G*(x) iff for every property f: P(f) <-> box f(x)   (x has f at every world)
  ess'(f, x) iff for every property g: box g(x) <-> box forall y (f(y) -> g(y))
  A5' P(NE'), NE'(x) iff every ess'-essence of x is necessarily instantiated.
A1 is unchanged (P closed under necessary implication).
Writes results.json and results.md next to this file.
"""
import itertools
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def search(w, d):
    cells = w * d
    full = (1 << cells) - 1
    props = range(1 << cells)
    cell = lambda wi, xi: wi * d + xi
    # box f(x): f holds of individual x at every world
    box_mask = [sum(1 << cell(wi, xi) for wi in range(w)) for xi in range(d)]
    has_box = lambda f, xi: (f & box_mask[xi]) == box_mask[xi]
    pairs = [(f, full ^ f) for f in props if f < full ^ f]
    stats = {"w": w, "d": d, "candidate_P": 2 ** len(pairs), "models": 0,
             "all_positive_instantiated": True, "example_pos_sizes": []}
    for choice in itertools.product((0, 1), repeat=len(pairs)):
        P = [pr[c] for pr, c in zip(pairs, choice)]
        Pset = set(P)
        if any((f | g) == g and g not in Pset for f in P for g in props):   # A1
            continue
        # G*: individuals whose necessary properties are exactly the positive ones
        gstar = [xi for xi in range(d) if all((f in Pset) == has_box(f, xi) for f in props)]
        G = sum(box_mask[xi] for xi in gstar)
        if G not in Pset:                                                    # A3'
            continue
        NE = 0
        for xi in range(d):
            ok = True
            for f in props:
                # f ess' x: for all g, box g(x) <-> f necessarily implies g (everywhere, all individuals)
                if all(has_box(g, xi) == ((f | g) == g) for g in props):
                    if any(not any(f >> cell(wj, yi) & 1 for yi in range(d)) for wj in range(w)):
                        ok = False
                        break
            if ok:
                NE |= box_mask[xi]
        if NE not in Pset:                                                   # A5'
            continue
        stats["models"] += 1
        if len(stats["example_pos_sizes"]) < 3:
            stats["example_pos_sizes"].append(len(P))
        if any(f == 0 for f in P):
            stats["all_positive_instantiated"] = False
    return stats


def run():
    cases = [(1, 1), (1, 2), (1, 3), (2, 1), (2, 2), (3, 1), (4, 1), (5, 1)]
    return [search(w, d) for w, d in cases if w * d <= 5]


def markdown(rows):
    L = ["# E7 results: Anderson's emendation, finite-model search", "",
         "Generated by `run.py`. Same model class as E4; G* and essence as in Anderson (1990).", "",
         "| worlds | individuals | candidate P sets | models | every positive property instantiated |",
         "|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['w']} | {r['d']} | {r['candidate_P']} | {r['models']} | {r['all_positive_instantiated']} |")
    multi = sum(r["models"] for r in rows if r["w"] >= 2)
    L += ["", f"Models with two or more worlds across the sizes tried: {multi}."]
    return "\n".join(L)


if __name__ == "__main__":
    rows = run()
    (HERE / "results.json").write_text(json.dumps(rows, indent=1, sort_keys=True) + "\n")
    (HERE / "results.md").write_text(markdown(rows) + "\n")
    print(markdown(rows))
