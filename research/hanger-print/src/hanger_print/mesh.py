"""Triangle meshes for the hanger shells, ASCII STL and OpenSCAD output. Stdlib only."""
import math

from . import geom


def _ccw(tri):
    (ax, ay), (bx, by), (cx, cy) = tri
    return (bx - ax) * (cy - ay) - (cx - ax) * (by - ay) > 0


def _prism(pts, tris, loops, depth):
    """Extrude a planar triangulation. `pts` are 2D vertices, `tris` index triples of the cap,
    `loops` the boundary loops (outer CCW; holes CW) as index lists. Returns (verts, faces)
    with outward-facing triangles."""
    n = len(pts)
    verts = [(x, y, 0.0) for x, y in pts] + [(x, y, depth) for x, y in pts]
    faces = []
    for a, b, c in tris:
        if not _ccw((pts[a], pts[b], pts[c])):
            b, c = c, b
        faces.append((a, c, b))                       # bottom faces down
        faces.append((n + a, n + b, n + c))           # top faces up
    for loop in loops:
        for i in range(len(loop)):
            a, b = loop[i], loop[(i + 1) % len(loop)]
            faces.append((a, b, n + b))
            faces.append((a, n + b, n + a))
    return verts, faces


def shell_mesh(shell, depth, n=48, arc=16, d=None):
    name, out = shell["name"], shell["outline"]
    if name.startswith("arm"):
        top, bot, ce, apts = geom.arm_parts(d, n, arc)
        mirror = name.endswith("left")
        sgn = -1.0 if mirror else 1.0
        P = [(sgn * x, y) for x, y in top + apts + bot[::-1]]
        # index map: top 0..n, arc n+1..n+arc-1, bot reversed n+arc .. 2n+arc
        nb = len(bot)
        ia = lambda i: i
        ib = lambda i: n + arc + (nb - 1 - i)
        ic = len(P)
        P.append((sgn * ce[0], ce[1]))
        tris = []
        for i in range(n - 1):
            tris += [(ia(i), ib(i), ib(i + 1)), (ia(i), ib(i + 1), ia(i + 1))]
        tris += [(ia(n - 1), ib(n - 1), ic), (ia(n - 1), ic, ia(n)), (ib(n - 1), ib(n), ic)]
        ring = [ia(n)] + list(range(n + 1, n + arc)) + [ib(n)]
        for a, b in zip(ring, ring[1:]):
            tris.append((ic, a, b))
        loop = list(range(len(P) - 1))
        if geom.area([P[i] for i in loop]) < 0:
            loop.reverse()
        return _prism(P, tris, [loop], depth)
    if "hole" in shell:
        o, h = shell["outline"], shell["hole"]
        m = len(o)
        P = o + h
        tris = []
        for i in range(m):
            j = (i + 1) % m
            tris += [(i, j, m + i), (j, m + j, m + i)]
        return _prism(P, tris, [list(range(m)), list(range(2 * m - 1, m - 1, -1))], depth)
    P = out
    tris = [(0, i, i + 1) for i in range(1, len(P) - 1)]
    return _prism(P, tris, [list(range(len(P)))], depth)


def hanger_mesh(d, n=48, arc=16):
    """Per-shell (verts, faces) of the whole hanger."""
    return [(s["name"], shell_mesh(s, d.depth, n, arc, d)) for s in geom.shells(d, n, arc)]


def volume(verts, faces):
    v = 0.0
    for a, b, c in faces:
        (x1, y1, z1), (x2, y2, z2), (x3, y3, z3) = verts[a], verts[b], verts[c]
        v += (x1 * (y2 * z3 - y3 * z2) - y1 * (x2 * z3 - x3 * z2) + z1 * (x2 * y3 - x3 * y2)) / 6.0
    return v


def edge_counts(faces):
    """Directed edge multiset check: in a closed, consistently oriented manifold every directed
    edge appears once and so does its reverse. Returns (n_bad_edges)."""
    from collections import Counter
    c = Counter()
    for a, b, d in faces:
        for e in ((a, b), (b, d), (d, a)):
            c[e] += 1
    bad = 0
    for (a, b), k in c.items():
        if k != 1 or c.get((b, a), 0) != 1:
            bad += 1
    return bad


def stl(meshes, name="hanger"):
    out = [f"solid {name}"]
    for _, (verts, faces) in meshes:
        for a, b, c in faces:
            p, q, r = verts[a], verts[b], verts[c]
            ux, uy, uz = q[0] - p[0], q[1] - p[1], q[2] - p[2]
            vx, vy, vz = r[0] - p[0], r[1] - p[1], r[2] - p[2]
            nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
            m = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
            out.append(f" facet normal {nx / m:.6f} {ny / m:.6f} {nz / m:.6f}\n  outer loop")
            for v in (p, q, r):
                out.append(f"   vertex {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}")
            out.append("  endloop\n endfacet")
    out.append(f"endsolid {name}")
    return "\n".join(out) + "\n"


def scad(d, label="", n=24, arc=12):
    """OpenSCAD source: the same outlines, as polygon() extruded to the depth. Not rendered in
    this project's tests (no OpenSCAD in the run image); the polygons are the ones the STL uses."""
    def poly(pts):
        return "[" + ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in pts) + "]"
    lines = [f"// hanger-print: {label} w={d.w} cm slope={d.slope} deg bow={d.bow} cm r={d.r} cm depth={d.depth} mm",
             "// Print flat (layers parallel to the page). Generated by hanger_print.mesh.scad; do not edit by hand.",
             f"depth = {d.depth};", "union() {"]
    for s in geom.shells(d, n, arc):
        if "hole" in s:
            lines.append(f"  linear_extrude(height = depth) difference() {{ polygon({poly(s['outline'])}); "
                         f"polygon({poly(s['hole'])}); }}")
        else:
            lines.append(f"  linear_extrude(height = depth) polygon({poly(s['outline'])});")
    lines.append("}")
    return "\n".join(lines) + "\n"
