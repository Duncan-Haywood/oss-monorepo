"""Which raw permit types does the harmonised class map send to 'other'? (session 69)

Session 68 found the harmonised class (`transfer.harmonise`) barely overlaps between cities,
and that Seattle and Chicago put most rows in the catch-all 'other'. This lists, per city,
the raw `permit_type` strings that fall to 'other', with their share of the city's rows,
so a retuned map can be written against each feed's real vocabulary.

Stdlib only: it reads `RULES` out of transfer.py's source with `ast`, so the rules cannot
drift and pandas/lightgbm are not needed. Run:
  python3 src/other_vocab.py DATA_DIR [--top 12] [--min-year 2015]
Writes results/other_vocab.json and results/other_vocab.md.
"""
import argparse, ast, collections, csv, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CITIES = ["chicago", "sf", "austin", "seattle"]


def load_rules():
    """Read RULES from transfer.py without importing it (it imports lightgbm)."""
    tree = ast.parse(open(os.path.join(HERE, "transfer.py")).read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "RULES" for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit("RULES not found in transfer.py")


RULES = load_rules()


def harmonise(s):
    t = s.lower()
    for name, pat in RULES:
        if re.search(pat, t):
            return name
    return "other"


def count(path, min_year):
    """(permit_type counts, work_class counts among rows whose permit_type falls to 'other')."""
    types, wc_other = collections.Counter(), collections.Counter()
    with open(path, newline="") as fh:
        for r in csv.DictReader(fh):
            a = r.get("applied") or ""
            if not a or int(a[:4]) < min_year:
                continue
            t = r.get("permit_type") or ""
            types[t] += 1
            if harmonise(t) == "other":
                wc_other[r.get("work_class") or ""] += 1
    return types, wc_other


def summarise(types, top, wc_other=None):
    n = sum(types.values())
    cls = collections.Counter()
    for t, k in types.items():
        cls[harmonise(t)] += k
    other = [(t, k) for t, k in types.most_common() if harmonise(t) == "other"]
    return dict(n_rows=n, n_types=len(types),
                class_share={c: cls[c] / n for c in sorted(cls)} if n else {},
                other_share=cls["other"] / n if n else 0.0,
                n_other_types=len(other),
                top_other=[dict(permit_type=t, rows=k, share=k / n) for t, k in other[:top]],
                other_work_class=[dict(work_class=w, rows=k, share=k / n, cls=harmonise(w) if w else "other")
                                  for w, k in (wc_other or collections.Counter()).most_common(top)])


def markdown(res, min_year):
    out = [f"# Raw permit types the harmonised class map sends to 'other' (applied year >= {min_year})", "",
           "Generated by `src/other_vocab.py` from the pulled feeds; shares are of the city's rows.", ""]
    for city, s in res.items():
        out += [f"## {city}: {s['other_share']:.1%} of {s['n_rows']:,} rows in 'other' "
                f"({s['n_other_types']} of {s['n_types']} raw types)", "",
                "| raw permit_type | rows | share |", "|---|---|---|"]
        out += [f"| {d['permit_type'] or '(empty)'} | {d['rows']:,} | {d['share']:.1%} |" for d in s["top_other"]]
        out += ["", "Work class of those 'other' rows (and the class the same keyword map would give it):", "",
                "| work_class | rows | share of city | class from work_class |", "|---|---|---|---|"]
        out += [f"| {d['work_class'] or '(empty)'} | {d['rows']:,} | {d['share']:.1%} | {d['cls']} |"
                for d in s["other_work_class"]]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("data_dir")
    ap.add_argument("--top", type=int, default=12)
    ap.add_argument("--min-year", type=int, default=2015)
    a = ap.parse_args()
    res = {}
    for c in CITIES:
        p = os.path.join(a.data_dir, f"{c}.csv")
        if os.path.exists(p):
            types, wc = count(p, a.min_year)
            res[c] = summarise(types, a.top, wc)
    rd = os.path.join(HERE, "..", "results")
    json.dump(dict(min_year=a.min_year, cities=res), open(os.path.join(rd, "other_vocab.json"), "w"), indent=1)
    open(os.path.join(rd, "other_vocab.md"), "w").write(markdown(res, a.min_year) + "\n")
    for c, s in res.items():
        print(c, f"other={s['other_share']:.3f}", [d["permit_type"] for d in s["top_other"][:5]])
