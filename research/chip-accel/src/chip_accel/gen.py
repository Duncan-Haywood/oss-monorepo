"""Generate Verilog for the P-lane MAC accelerator with the quantised weights baked in as ROM functions.

Schedule: layer L has fan-in 8; neurons are processed P at a time. Each group takes 8 MAC cycles plus 1
write-back cycle; one extra cycle moves layer-0 outputs to the input register. Total cycles from `start` to `done` are given by `cycles()` and checked against the RTL.
"""
from .model import NIN, NH, NOUT

NEURONS = (NH, NOUT)


def cycles(p):
    """Cycles from the start pulse to done: 1 load + per layer ceil(N/P) groups of (8 MAC + 1 write-back) + 1 transfer."""
    return 2 + sum(-(-n // p) * (NIN + 1) for n in NEURONS)


def _rom(name, q, key, width_expr):
    lines = []
    if key == "W":
        for layer, w in enumerate((q["W0"], q["W1"])):
            for k in range(w.shape[0]):
                for n in range(w.shape[1]):
                    if w[k, n]:
                        lines.append(f"      {{1'd{layer}, 4'd{n}, 3'd{k}}}: {name} = {int(w[k, n])};")
        sig = "input layer, input [3:0] n, input [2:0] k"
        sel = "{layer, n, k}"
    else:
        for layer, b in enumerate((q["B0"], q["B1"])):
            for n in range(len(b)):
                if b[n]:
                    lines.append(f"      {{1'd{layer}, 4'd{n}}}: {name} = {int(b[n])};")
        sig = "input layer, input [3:0] n"
        sel = "{layer, n}"
    body = "\n".join(lines)
    return (f"  function signed [{width_expr}-1:0] {name}({sig});\n    begin\n      {name} = 0;\n"
            f"      case ({sel})\n{body}\n      default: {name} = 0;\n      endcase\n    end\n  endfunction\n")


def verilog(q, p):
    wb, aw = q["wb"], q["aw"]
    qmax = 2 ** (wb - 1) - 1
    return f"""// Generated by chip_accel.gen: P={p} MAC lanes, WB={wb}-bit weights/activations, AW={aw}-bit accumulators.
module accel(input clk, input rst, input start, input [{NIN*wb}-1:0] x, output reg done, output [{NOUT*wb}-1:0] y);
  localparam P = {p}, WB = {wb}, AW = {aw};
  localparam signed [AW-1:0] QMAX = {qmax}, QMIN = -{qmax + 1};
{_rom('wrom', q, 'W', 'WB')}
{_rom('brom', q, 'B', 'AW')}
  localparam IDLE = 0, RUN = 1, WBK = 2, XFER = 3;
  reg [1:0] st;
  reg layer;
  reg [3:0] grp;
  reg [3:0] k;
  reg [{NIN}*WB-1:0] act;
  reg [{NIN}*WB-1:0] nxt;
  reg [P*AW-1:0] acc;
  assign y = nxt[{NOUT}*WB-1:0];
  integer j;
  reg signed [AW-1:0] a, v;
  reg [3:0] n;
  always @(posedge clk) begin
    done <= 0;
    if (rst) begin st <= IDLE; layer <= 0; grp <= 0; k <= 0; acc <= 0; nxt <= 0; act <= 0; end
    else case (st)
      IDLE: if (start) begin act <= x; layer <= 0; grp <= 0; k <= 0; acc <= 0; st <= RUN; end
      RUN: begin
        for (j = 0; j < P; j = j + 1) begin
          n = grp * P + j;
          a = acc[j*AW +: AW];
          acc[j*AW +: AW] <= a + $signed(act[k*WB +: WB]) * wrom(layer, n, k[2:0]);
        end
        if (k == {NIN - 1}) st <= WBK; else k <= k + 1;
      end
      WBK: begin
        for (j = 0; j < P; j = j + 1) begin
          n = grp * P + j;
          if (n < (layer ? {NOUT} : {NH})) begin
            v = acc[j*AW +: AW] + brom(layer, n);
            if (layer == 0) begin
              v = (v < 0) ? 0 : (v >>> {q['s0']});
              if (v > QMAX) v = QMAX;
            end else begin
              v = v >>> {q['s1']};
              if (v > QMAX) v = QMAX;
              if (v < QMIN) v = QMIN;
            end
            nxt[n*WB +: WB] <= v[WB-1:0];
          end
        end
        acc <= 0; k <= 0;
        if ((grp + 1) * P < (layer ? {NOUT} : {NH})) begin grp <= grp + 1; st <= RUN; end
        else if (layer == 0) begin
          layer <= 1; grp <= 0; st <= XFER;
        end else begin done <= 1; st <= IDLE; end
      end
      XFER: begin act <= nxt; st <= RUN; end
    endcase
  end
endmodule
"""
