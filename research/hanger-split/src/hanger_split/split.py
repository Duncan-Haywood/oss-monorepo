"""A two-piece hanger. Geometry in mm, frontal plane, hook at the origin, as in `hanger_print.geom`.

The right half is the right arm, a half-disc hub (flat face on x = 0), half the post, and three
round bosses centred on x = 0: two bolt bosses (hole = bolt clearance) at y = +/- BOLT_Y and the
rail loop boss at the top of the post. The bosses are depth/2 thick and sit on the back face. The
left half is the same part turned 180 degrees about the vertical axis, so its bosses sit on the
front face and lie against the right half's: one part prints twice, and the bolts clamp the lap.
"""
import math
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "hanger-print" / "src"))
from hanger_print import geom, mesh  # noqa: E402

LOOP_Y = geom.POST_H          # loop boss centre, as in hanger-print
LOOP_R, LOOP_HOLE = geom.LOOP_RO, geom.LOOP_RI


@dataclass(frozen=True)
class Joint:
    bolt_d: float = 4.0       # mm, nominal bolt diameter (M4)
    boss_r: float = 8.0       # mm, bolt boss radius
    y_low: float = -17.0      # mm, bolt centres on x = 0
    y_high: float = 16.0
    clearance: float = 0.4    # mm, hole is bolt_d + clearance

    @property
    def spacing(self):
        return self.y_high - self.y_low

    @property
    def hole_d(self):
        return self.bolt_d + self.clearance


def _circle(cx, cy, r, seg=48):
    return [(cx + r * math.cos(2 * math.pi * k / seg), cy + r * math.sin(2 * math.pi * k / seg)) for k in range(seg)]


def half_shells(d, j, seg=48):
    """Shells of the right half: dicts {name, outline, [hole], z0, z1} with the extrusion span."""
    r = d.r * 10.0
    t = d.depth
    half_hub = [(0.0, -r)] + [(r * math.sin(a), -r * math.cos(a)) for a in
                              [math.pi * k / (seg // 2) for k in range(1, seg // 2)]] + [(0.0, r)]
    post = [(0.0, 0.0), (geom.POST_W / 2, 0.0), (geom.POST_W / 2, geom.POST_H), (0.0, geom.POST_H)]
    out = [{"name": "arm_right", "outline": geom.arm_outline(d), "z0": 0.0, "z1": t},
           {"name": "hub", "outline": half_hub, "z0": 0.0, "z1": t},
           {"name": "post", "outline": post, "z0": 0.0, "z1": t}]
    for nm, y in (("boss_low", j.y_low), ("boss_high", j.y_high)):
        out.append({"name": nm, "outline": _circle(0.0, y, j.boss_r, seg), "hole": _circle(0.0, y, j.hole_d / 2, seg),
                    "z0": 0.0, "z1": t / 2})
    out.append({"name": "boss_loop", "outline": _circle(0.0, LOOP_Y, LOOP_R, seg), "hole": _circle(0.0, LOOP_Y, LOOP_HOLE, seg),
                "z0": 0.0, "z1": t / 2})
    return out


def half_points(d, j):
    pts = []
    for s in half_shells(d, j):
        pts += s["outline"]
    return pts


def bed_fit(d, j, bed, step=5):
    """(fits, best_angle_deg, bbox_w, bbox_h) of one half turned in the plane, smallest longer side."""
    pts = half_points(d, j)
    best = None
    for a in range(0, 90, step):
        c, s = math.cos(math.radians(a)), math.sin(math.radians(a))
        xs = [c * x - s * y for x, y in pts]
        ys = [s * x + c * y for x, y in pts]
        bw, bh = max(xs) - min(xs), max(ys) - min(ys)
        if best is None or max(bw, bh) < best[0]:
            best = (max(bw, bh), a, bw, bh)
    return best[0] <= bed, best[1], best[2], best[3]


def half_mesh(d, j):
    """Per-shell (name, (verts, faces)) of the right half, bosses shifted to their z span."""
    out = []
    for s in half_shells(d, j):
        shell = {k: v for k, v in s.items() if k in ("name", "outline", "hole")}
        verts, faces = mesh.shell_mesh(shell, s["z1"] - s["z0"], d=d)
        out.append((s["name"], ([(x, y, z + s["z0"]) for x, y, z in verts], faces)))
    return out


def turned(meshes, depth):
    """The same meshes turned 180 degrees about the vertical axis (x -> -x, z -> depth - z)."""
    out = []
    for name, (verts, faces) in meshes:
        v = [(-x, y, depth - z) for x, y, z in verts]
        out.append((name + "_L", (v, list(faces))))
    return out


def scad(d, j, label=""):
    def poly(pts):
        return "[" + ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in pts) + "]"
    lines = [f"// hanger-split: {label} w={d.w} cm slope={d.slope} deg bow={d.bow} cm r={d.r} cm depth={d.depth} mm",
             f"// Print this half twice, flat. Turn the second half 180 degrees about the vertical axis, lay the",
             f"// bosses together and clamp with two M{j.bolt_d:g} bolts through the {j.hole_d:g} mm holes.",
             "// Generated by hanger_split.split.scad; not rendered in this run (no OpenSCAD in the image).",
             f"depth = {d.depth};", "union() {"]
    for s in half_shells(d, j, 24):
        h = s["z1"] - s["z0"]
        if "hole" in s:
            lines.append(f"  linear_extrude(height = {h:g}) difference() {{ polygon({poly(s['outline'])}); polygon({poly(s['hole'])}); }}")
        else:
            lines.append(f"  linear_extrude(height = {h:g}) polygon({poly(s['outline'])});")
    lines.append("}")
    return "\n".join(lines) + "\n"
