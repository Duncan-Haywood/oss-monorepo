"""Milestone 161: cosmetic rewrites of one mapped netlist (the rewriters, the canonical form, and the committed flow table)."""
import importlib.util
import random
from pathlib import Path

NN = Path(__file__).resolve().parents[1] / "experiments" / "netlist_noise"

NET = """/* Generated by Yosys 0.71 */
module t(a, y);
  input [2:0] a;
  wire [2:0] a;
  output y;
  wire y;
  wire _0_;
  wire _1_;
  wire _2_;
  sky130_fd_sc_hd__inv_1 _3_ (
    .A(a[0]),
    .Y(_0_)
  );
  sky130_fd_sc_hd__inv_1 _4_ (
    .A(a[1]),
    .Y(_1_)
  );
  sky130_fd_sc_hd__nand3_1 _5_ (
    .A(_0_),
    .B(_1_),
    .C(a[2]),
    .Y(_2_)
  );
  assign y = _2_;
endmodule
"""


def _load():
    spec = importlib.util.spec_from_file_location("vdse_t161", NN / "run.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_emit_round_trips_and_variants_are_the_same_circuit():
    m = _load()
    assert m.variant(NET, "orig", "s") == NET
    for v in ("O1", "O2", "W", "R"):
        for seed in range(5):
            x = m.variant(NET, v, f"s{seed}")
            assert m.same_circuit(NET, x), v
    r = m.variant(NET, "R", "s")
    assert "_3_" not in r and "assign y = _n" in r


def test_canonical_form_ignores_names_and_order():
    m = _load()
    c0, _ = m.canonical(NET)
    for seed in range(10):
        x = m.variant(m.variant(NET, "R", f"r{seed}"), "O1", f"o{seed}")
        assert m.canonical(x)[0] == c0
    assert m.same_circuit(NET, c0)
    assert m.canonical(NET.replace(".A(a[1])", ".A(a[2])").replace(".C(a[2])", ".C(a[1])"))[0] != c0


def test_canonical_form_on_a_symmetric_netlist():
    # two identical inverter chains: refinement leaves them tied, individualisation must still give one text
    m = _load()
    net = NET.replace(".A(a[1])", ".A(a[0])")
    c0, ties = m.canonical(net)
    assert ties >= 2
    rng = random.Random(1)
    for _ in range(10):
        assert m.canonical(m.variant(m.variant(net, "R", rng.random()), "O1", rng.random()))[0] == c0


def test_committed_results():
    m = _load()
    out = m.analyse(NN / "results_check.txt", quiet=True)
    (NN / "results_check.txt").unlink()
    assert out["n"] == 90 and out["ctl"] == 90
    # order is inert, names move routing, the canonical form removes the dependence on both
    assert out["held"] == [False, True, False, False, True, True, True]
    assert (NN / "results.txt").read_text().splitlines()[0].startswith("Milestone 161")
