"""Milestone 160: one OpenROAD binary, two Yosys builds (analysis of the committed flow table; no EDA tools needed)."""
import importlib.util
from pathlib import Path

YS = Path(__file__).resolve().parents[1] / "experiments" / "yosys_swap"

NET = """/* Generated by Yosys 0.70 */
module t(a, y);
  input [1:0] a;
  wire [1:0] a;
  output y;
  wire y;
  wire _0_;
  wire _1_;
  sky130_fd_sc_hd__inv_1 _2_ (
    .A(a[0]),
    .Y(_0_)
  );
  sky130_fd_sc_hd__nand2_1 _3_ (
    .A(_0_),
    .B(a[1]),
    .Y(_1_)
  );
  assign y = _1_;
endmodule
"""


def _load():
    spec = importlib.util.spec_from_file_location("vdse_t160", YS / "run.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_fingerprint_ignores_names_order_and_banner():
    m = _load()
    a = m.fingerprint(NET)
    renamed = NET.replace("_0_", "_9_").replace("Yosys 0.70", "Yosys 0.71")
    head, inv, nand = renamed.split("  sky130")[0], "  sky130" + renamed.split("  sky130")[1], "  sky130" + renamed.split("  sky130")[2]
    swapped = head + nand.split("  assign")[0] + inv + "  assign" + nand.split("  assign")[1]
    b = m.fingerprint(swapped)
    assert a["wl"] == b["wl"] and a["cells"] == b["cells"] and a["sha"] != b["sha"]
    assert m.fingerprint(NET.replace("Yosys 0.70", "Yosys 0.71"))["sha"] == a["sha"]  # banner stripped


def test_fingerprint_sees_rewiring_and_cells():
    m = _load()
    a = m.fingerprint(NET)
    assert m.fingerprint(NET.replace(".B(a[1])", ".B(a[0])").replace(".A(a[0])", ".A(a[1])"))["wl"] != a["wl"]
    assert m.fingerprint(NET.replace("nand2_1", "nand2_2"))["cells"] != a["cells"]


def test_sample_is_fixed():
    m = _load()
    p = m.sample()
    assert [c for c, *_ in p].count("S") == 60 and len(p) == 90
    assert all(m.equal(a, b, ["synth_netlist_area", "synth_netlist_wns"]) for c, d, a, b in p if c == "S")


def test_rerun_reproduces_results(tmp_path):
    m = _load()
    out = m.analyse(tmp_path / "r.txt")
    assert (tmp_path / "r.txt").read_text() == (YS / "results.txt").read_text()
    assert out["n"] == 90


def test_posthoc_reproduces(tmp_path):
    spec = importlib.util.spec_from_file_location("vdse_t160p", YS / "posthoc.py")
    p = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(p)
    p.summary(tmp_path / "p.txt")
    assert (tmp_path / "p.txt").read_text() == (YS / "posthoc.txt").read_text()
