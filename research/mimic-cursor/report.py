"""Summarise results/run_*.json into results.txt and results/crossplay.json.

Cross-play scores every final detector against every final imitator on the
held-out people, so each condition's detector meets imitators it never saw.
"""
import collections
import glob
import json
import os

import numpy as np
from sklearn.metrics import roc_auc_score

import game as G
import programs as P
import run

HERE = os.path.dirname(os.path.abspath(__file__))
B = 2000


def ci(xs, rng):
    xs = np.asarray(xs, float)
    m = rng.choice(xs, (B, len(xs))).mean(axis=1)
    return xs.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def paired(a, b, rng):
    d = np.asarray(a) - np.asarray(b)
    m = rng.choice(d, (B, len(d))).mean(axis=1)
    return d.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def det_score(d, feats):
    X = P.stack(feats, d["groups"])
    return ((X - np.array(d["mean"])) / np.array(d["scale"])) @ np.array(d["coef"]) + d["intercept"]


def main():
    rng = np.random.default_rng(0)
    runs = collections.defaultdict(dict)
    for f in sorted(glob.glob(os.path.join(run.RES, "run_*.json"))):
        r = json.load(open(f))
        runs[r["condition"]][r["seed"]] = r
    conds = [c for c in G.CONDITIONS if c in runs]
    seeds = sorted(set.intersection(*(set(runs[c]) for c in conds)))
    R = len(runs[conds[0]][seeds[0]]["rounds"]) - 1
    L = []
    w = L.append
    w("mimic-cursor results (generated by report.py; numbers are not edited by hand)")
    w(f"conditions {conds}, seeds {seeds}, rounds {R}, budget {G.BUDGET} candidates per side per round,")
    w(f"K = {G.K} feature functions per detector, {G.N_CTX} contexts per evaluation, copy cap {G.MAX_COPY}")
    w("")
    w("== A. Reference AUROC by round (mean over seeds; 0.5 = people and imitator indistinguishable to it)")
    w("round " + " ".join(conds))
    for t in range(R + 1):
        w(f"{t} " + " ".join(f"{np.mean([runs[c][s]['rounds'][t]['reference'] for s in seeds]):.4f}" for c in conds))
    w("")
    w("== B. Loop detector AUROC on held-out people by round (mean over seeds)")
    w("round " + " ".join(conds))
    for t in range(1, R + 1):
        w(f"{t} " + " ".join(f"{np.mean([runs[c][s]['rounds'][t]['loop_test'] for s in seeds]):.4f}" for c in conds))
    w("")
    w("== C. Final round, mean over seeds with 95% bootstrap interval")
    w("condition | reference AUROC | best reference in any round | loop detector AUROC | copy rate")
    fin = {}
    for c in conds:
        ref = [runs[c][s]["rounds"][R]["reference"] for s in seeds]
        best = [min(x["reference"] for x in runs[c][s]["rounds"]) for s in seeds]
        loop = [runs[c][s]["rounds"][R]["loop_test"] for s in seeds]
        cp = [runs[c][s]["rounds"][R]["copy_rate"] for s in seeds]
        fin[c] = {"reference": ref, "loop": loop}
        f3 = lambda x: "%.3f (%.3f to %.3f)" % ci(x, rng)
        w(f"{c} | {f3(ref)} | {f3(best)} | {f3(loop)} | {np.mean(cp):.3f} (max {np.max(cp):.3f})")
    w("")
    w("== D. Paired differences in final reference AUROC against blind (negative = better imitator)")
    for c in conds[1:]:
        w(f"{c} - blind: %.3f (%.3f to %.3f)" % paired(fin[c]["reference"], fin["blind"]["reference"], rng))
    w("")
    w("== E. Components in the final imitators (count over seeds)")
    for c in conds:
        cnt = {g: collections.Counter(runs[c][s]["rounds"][R]["genome"][g]["kind"] for s in seeds)
               for g in ("path", "clock", "dur", "round", "noise")}
        w(f"{c}: " + "; ".join(f"{g} " + ", ".join(f"{k} {v}" for k, v in cn.most_common()) for g, cn in cnt.items()))
    w("")
    w("== F. Feature functions in the final detectors (count over seeds)")
    for c in conds:
        cn = collections.Counter(g for s in seeds for g in runs[c][s]["rounds"][R]["groups"])
        w(f"{c}: " + ", ".join(f"{k} {v}" for k, v in cn.most_common()))
    w("")

    # cross-play on held-out people
    pool, test, copyref = run.split()
    P.set_human(pool)
    _, tst = run.fixed_sets(pool, test)
    fh = P.features(tst)
    ims = [(c, s, P.features(G.imitate(runs[c][s]["rounds"][R]["genome"], tst, 202)))
           for c in conds for s in seeds]
    dets = [(c, s, runs[c][s]["rounds"][R]["detector"]) for c in conds for s in seeds]
    M = np.empty((len(dets), len(ims)))
    y = np.r_[np.ones(len(tst)), np.zeros(len(tst))]
    for i, (_, _, d) in enumerate(dets):
        sh = det_score(d, fh)
        for j, (_, _, fi) in enumerate(ims):
            M[i, j] = roc_auc_score(y, np.r_[sh, det_score(d, fi)])
    w("== G. Cross-play: mean AUROC of each condition's final detectors (rows) against each")
    w("condition's final imitators (columns), on held-out people, own-run pairs excluded")
    w("detector \\ imitator | " + " | ".join(conds) + " | row mean")
    idx = {c: [k for k, (cc, _, _) in enumerate(dets) if cc == c] for c in conds}
    for a in conds:
        cells = []
        for b in conds:
            v = [M[i, j] for i in idx[a] for j in idx[b] if dets[i][1] != ims[j][1] or a != b]
            cells.append(np.mean(v))
        others = [M[i, j] for i in idx[a] for j in range(len(ims)) if j != i]
        w(f"{a} | " + " | ".join(f"{x:.3f}" for x in cells) + f" | {np.mean(others):.3f}")
    w("")
    w("== H. Detector strength against other runs' imitators, per seed, paired against blind")
    strength = {c: [np.mean([M[i, j] for j in range(len(ims)) if j != i]) for i in idx[c]] for c in conds}
    for c in conds[1:]:
        w(f"{c} - blind: %.3f (%.3f to %.3f)" % paired(strength[c], strength["blind"], rng))
    base = os.path.join(run.RES, "baselines.json")
    if os.path.exists(base):
        w("")
        w("== I. Fixed generators for scale (baselines.py)")
        for k, v in json.load(open(base)).items():
            w(f"{k}: " + ", ".join(f"{a} {b:.3f}" for a, b in v.items()))
    ceil = os.path.join(run.RES, "ceiling.json")
    if os.path.exists(ceil):
        w("")
        w("== J. Ceiling: a (1+4) evolution strategy against a logistic regression on every feature (ceiling.py)")
        for o in json.load(open(ceil)):
            g = o["genome"]
            w(f"restart {o['restart']}: {o['evaluations']} evaluations, reference {o['reference']:.3f}, "
              f"copy rate {o['copy_rate']:.3f}, path {g['path']['kind']}, clock {g['clock']['kind']}, "
              f"dur {g['dur']['kind']}")
    with open(os.path.join(run.RES, "crossplay.json"), "w") as f:
        json.dump({"detectors": [[c, s] for c, s, _ in dets], "imitators": [[c, s] for c, s, _ in ims],
                   "auroc": M.round(4).tolist()}, f)
    with open(os.path.join(HERE, "results.txt"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
