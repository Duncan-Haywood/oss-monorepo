def parse_hotel_ranking(text):
    """Return (rows, fn03): rows are (hotel W, mono Fn, {rung: ratio}) from the per-hotel lines;
    fn03 is the hotel load at which the monohull's best speed first passes Froude number 0.3."""
    rows, fn03 = [], None
    for line in text.splitlines():
        m = re.match(r"^hotel\s+([\d.]+) W .* Fn ([\d.]+)\s", line)
        if m:
            rat = {n: float(v) for n, v in re.findall(r"(catamaran|SWATH|planing|hydrofoil) ([\d.]+) \(", line)}
            rows.append((float(m[1]), float(m[2]), rat))
        m = re.match(r"monohull best speed first above Fn 0.3 at hotel ([\d.]+) W", line)
        if m:
            fn03 = float(m[1])
    return rows, fn03


