"""Build the paper's generated inputs from the committed results files (stdlib only).

Writes `fig_solar_mc.tex`, a TikZ bar chart of km/day (median, 5% to 95% band) for the 4 m and
5 m monohull at the five NASA POWER sites, parsed from `../experiments/results_solar_mc.txt`.
Also writes `fig_range_speed.tex` (milestone 7t): range against speed per rung (panel a, log
speed axis) and the monohull at five hotel loads (panel b), from `../experiments/results_range_speed.txt`.
And `fig_glider_hotel.tex` (milestone 7u): glider/AUV range ratio and the share of cases the
glider wins against the AUV/glider hotel-load ratio, from `../experiments/results_glider_hotel_curve.txt`.
And `fig_hotel_ranking.tex` (milestone 7v): each rung's peak range over the monohull's against hotel
load, 1 W to 10 kW, from `../experiments/results_hotel_ranking.txt`.
And `fig_energy_split.tex` (milestone 7zb, the method figure): the central monohull's energy per km
split into friction, form, Michell wave and hotel terms, from `../experiments/results_energy_split.txt`.
Run from anywhere: `python3 research/marine-hull/paper/make_figures.py`. No number is typed here;
`check_numbers.py` checks the hand-copied numbers in `main.tex` against the results files.
"""
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "..", "experiments", "results_solar_mc.txt")
OUT = os.path.join(HERE, "fig_solar_mc.tex")
RS_RESULTS = os.path.join(HERE, "..", "experiments", "results_range_speed.txt")
RS_OUT = os.path.join(HERE, "fig_range_speed.tex")
GH_RESULTS = os.path.join(HERE, "..", "experiments", "results_glider_hotel_curve.txt")
GH_OUT = os.path.join(HERE, "fig_glider_hotel.tex")
HR_RESULTS = os.path.join(HERE, "..", "experiments", "results_hotel_ranking.txt")
HR_OUT = os.path.join(HERE, "fig_hotel_ranking.tex")
ES_RESULTS = os.path.join(HERE, "..", "experiments", "results_energy_split.txt")
ES_OUT = os.path.join(HERE, "fig_energy_split.tex")
HR_RUNGS = ["catamaran", "SWATH", "hydrofoil", "planing"]
RUNGS = ["monohull", "catamaran", "SWATH", "hydrofoil", "planing"]
HOTELS = ["hotel5", "hotel15", "hotel30", "hotel60", "hotel120"]
STYLES = {"monohull": "black, thick", "catamaran": "black, dashed", "SWATH": "black, dotted, thick",
          "hydrofoil": "gray, line width=1.6pt", "planing": "gray, dashed, thick"}

ROW = re.compile(
    r"^(?P<len>\d) m (?P<site>\S+)\s+km/day median\s+(?P<med>[\d.]+) "
    r"\(5%-95%:\s+(?P<lo>[\d.]+) to\s+(?P<hi>[\d.]+);"
)
LABELS = {"Equator-Pacific": "Equator", "Florida-Straits": "Florida", "Gulf-of-Maine": r"Gulf of\\Maine",
          "North-Sea": r"North\\Sea", "Gulf-of-Alaska": r"Gulf of\\Alaska"}
SITES = ["Equator-Pacific", "Florida-Straits", "Gulf-of-Maine", "North-Sea", "Gulf-of-Alaska"]


def parse(text):
    """Return {(length_m, site): (median, p5, p95)} from results_solar_mc.txt."""
    rows = {}
    for line in text.splitlines():
        m = ROW.match(line.strip())
        if m:
            rows[(int(m["len"]), m["site"])] = (float(m["med"]), float(m["lo"]), float(m["hi"]))
    return rows


def tikz(rows, ymax=150.0, height=4.0, bar=0.32):
    """A two-series bar chart with whiskers; y in km/day scaled to `height` cm."""
    s = height / ymax
    out = ["% generated by make_figures.py from ../experiments/results_solar_mc.txt; do not edit",
           r"\begin{tikzpicture}[x=1.45cm,y=1cm,font=\footnotesize]"]
    for tick in range(0, int(ymax) + 1, 50):
        out.append(rf"\draw[gray!40] (-0.1,{tick * s:.3f}) -- (4.6,{tick * s:.3f});")
        out.append(rf"\node[left] at (-0.1,{tick * s:.3f}) {{{tick}}};")
    out.append(rf"\node[rotate=90] at (-0.75,{height / 2:.2f}) {{km/day}};")
    for i, site in enumerate(SITES):
        for j, (length, fill) in enumerate(((4, "gray!45"), (5, "black!80"))):
            med, lo, hi = rows[(length, site)]
            x0 = i + 0.1 + j * bar
            out.append(rf"\fill[{fill}] ({x0:.2f},0) rectangle ({x0 + bar - 0.04:.2f},{med * s:.3f});")
            xc = x0 + (bar - 0.04) / 2
            out.append(rf"\draw ({xc:.3f},{lo * s:.3f}) -- ({xc:.3f},{hi * s:.3f});")
            out.append(rf"\draw ({xc - 0.05:.3f},{lo * s:.3f}) -- ({xc + 0.05:.3f},{lo * s:.3f});")
            out.append(rf"\draw ({xc - 0.05:.3f},{hi * s:.3f}) -- ({xc + 0.05:.3f},{hi * s:.3f});")
        label = LABELS[site]
        out.append(rf"\node[below,align=center] at ({i + 0.1 + bar - 0.02:.2f},0) {{{label}}};")
    out.append(rf"\fill[gray!45] (0.2,{height + 0.25:.2f}) rectangle (0.4,{height + 0.45:.2f});")
    out.append(rf"\node[right] at (0.4,{height + 0.35:.2f}) {{4 m}};")
    out.append(rf"\fill[black!80] (1.2,{height + 0.25:.2f}) rectangle (1.4,{height + 0.45:.2f});")
    out.append(rf"\node[right] at (1.4,{height + 0.35:.2f}) {{5 m}};")
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n"


def parse_curves(text):
    """Return {name: [(speed, km)]} for the feasible grid points of results_range_speed.txt."""
    out = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[0] == "curve" and parts[3] != "-":
            out.setdefault(parts[1], []).append((float(parts[2]), float(parts[3])))
    return out


def _poly(pts, fx, fy, style):
    return rf"\draw[{style}] " + " -- ".join(f"({fx(u):.3f},{fy(k):.3f})" for u, k in pts) + ";"


def tikz_range_speed(curves, w=7.6, h=3.6):
    """Panel (a): rungs, log10 speed 0.3 to 20 m/s, km 0 to 900. Panel (b): monohull at five hotel
    loads, speed 0.3 to 3 m/s linear, km 0 to 2800. Peak of each curve marked with a dot."""
    out = ["% generated by make_figures.py from ../experiments/results_range_speed.txt; do not edit",
           r"\begin{tikzpicture}[font=\footnotesize]"]
    lx0, lx1 = math.log10(0.3), math.log10(20.0)
    fx = lambda u: (math.log10(u) - lx0) / (lx1 - lx0) * w
    fy = lambda k: k / 900.0 * h
    for t in range(0, 901, 300):
        out.append(rf"\draw[gray!35] (0,{fy(t):.3f}) -- ({w},{fy(t):.3f}); \node[left] at (0,{fy(t):.3f}) {{{t}}};")
    for t in (0.3, 0.5, 1, 2, 5, 10, 20):
        out.append(rf"\draw (({fx(t):.3f},0) -- ({fx(t):.3f},-0.08); \node[below] at ({fx(t):.3f},-0.05) {{{t:g}}};".replace("((", "("))
    out.append(rf"\draw (0,0) rectangle ({w},{h});")
    for name in RUNGS:
        pts = [(u, k) for u, k in curves[name] if 0.3 <= u <= 20.0]
        out.append(_poly(pts, fx, fy, STYLES[name]))
        ku, kk = max(pts, key=lambda p: p[1])
        out.append(rf"\fill ({fx(ku):.3f},{fy(kk):.3f}) circle (1.4pt);")
    for j, name in enumerate(RUNGS):
        y = h - 0.3 - 0.34 * j
        out.append(rf"\draw[{STYLES[name]}] ({w - 2.3:.2f},{y:.2f}) -- ({w - 1.75:.2f},{y:.2f}); "
                   rf"\node[right] at ({w - 1.75:.2f},{y:.2f}) {{{name}}};")
    out.append(rf"\node at ({w / 2:.2f},-0.6) {{speed (m/s), log scale}};")
    out.append(rf"\node[rotate=90] at (-0.8,{h / 2:.2f}) {{range (km)}};")
    out.append(rf"\node[anchor=north west] at (0.05,{h - 0.05:.2f}) {{(a) 30\,W hotel}};")
    # panel (b), below
    oy = -h - 1.3
    gx = lambda u: (u - 0.3) / 2.7 * w
    gy = lambda k: oy + k / 2800.0 * h
    for t in range(0, 2801, 700):
        out.append(rf"\draw[gray!35] (0,{gy(t):.3f}) -- ({w},{gy(t):.3f}); \node[left] at (0,{gy(t):.3f}) {{{t}}};")
    for t in (0.5, 1.0, 1.5, 2.0, 2.5, 3.0):
        out.append(rf"\draw ({gx(t):.3f},{oy:.3f}) -- ({gx(t):.3f},{oy - 0.08:.3f}); \node[below] at ({gx(t):.3f},{oy - 0.05:.3f}) {{{t:g}}};")
    out.append(rf"\draw (0,{oy:.3f}) rectangle ({w},{oy + h:.3f});")
    peaks = []
    for name in HOTELS:
        pts = [(u, k) for u, k in curves[name] if u <= 3.0]
        out.append(_poly(pts, gx, gy, "black"))
        ku, kk = max(pts, key=lambda p: p[1])
        peaks.append((ku, kk))
        out.append(rf"\fill ({gx(ku):.3f},{gy(kk):.3f}) circle (1.4pt);")
        out.append(rf"\node[right,font=\scriptsize] at ({gx(ku) + 0.05:.3f},{gy(kk) + 0.12:.3f}) {{{name[5:]}\,W}};")
    out.append(_poly(peaks, gx, gy, "gray, dashed"))
    out.append(rf"\node at ({w / 2:.2f},{oy - 0.6:.2f}) {{speed (m/s)}};")
    out.append(rf"\node[rotate=90] at (-0.8,{oy + h / 2:.2f}) {{range (km)}};")
    out.append(rf"\node[anchor=north east] at ({w - 0.05:.2f},{oy + h - 0.05:.2f}) {{(b) monohull, hotel load varied}};")
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n"


def parse_hotel_curve(text):
    """Return (rows, wide, (band_lo, band_hi), breakeven): rows and wide are lists of
    (x, share, p10, p50, p90) on the 4b speed grid and on the post-hoc 0.1 to 4 m/s grid."""
    rows, wide, band, be = [], [], None, None
    for line in text.splitlines():
        parts = line.split("\t")
        try:
            vals = [float(v) for v in parts[-5:]]
        except ValueError:
            vals = None
        if len(parts) == 5 and vals:
            rows.append(tuple(vals))
        elif len(parts) == 6 and parts[0] == "wide" and vals:
            wide.append(tuple(vals))
        m = re.search(r"REMUS-100 band .*: x ([\d.]+) to ([\d.]+);", line)
        if m:
            band = (float(m[1]), float(m[2]))
        m = re.match(r"median ratio reaches 1 at x = ([\d.]+)", line)
        if m:
            be = float(m[1])
    return rows, wide, band, be


