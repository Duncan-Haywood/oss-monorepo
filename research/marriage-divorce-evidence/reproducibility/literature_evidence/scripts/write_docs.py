#!/usr/bin/env python3
"""Regenerate SOURCES.md and the record index at the end of EVIDENCE.md from
evidence.json, SOURCES.json and doi_check.json (the hand-written part of EVIDENCE.md,
above the INDEX marker, is left alone).

    python3 scripts/write_docs.py
"""
import collections, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = '<!-- INDEX: generated by scripts/write_docs.py; edits below this line are overwritten -->'


def fmt(x):
    if x is None:
        return ''
    return f'{x:g}' if isinstance(x, (int, float)) else str(x)


def main():
    ev = json.load(open(os.path.join(ROOT, 'evidence.json'), encoding='utf-8'))['records']
    src = json.load(open(os.path.join(ROOT, 'SOURCES.json'), encoding='utf-8'))['sources']
    dois = json.load(open(os.path.join(ROOT, 'doi_check.json'), encoding='utf-8'))

    # ---- SOURCES.md
    by_src = collections.defaultdict(list)
    for r in ev:
        by_src[r['source']].append(r)
        for e in r.get('extra_quotes') or []:
            by_src[e['source']].append(r)
    cites = collections.OrderedDict()
    for r in sorted(ev, key=lambda r: r['citation']):
        cites.setdefault(r['citation'], r)
    L = ['# Sources', '',
         'Every work an evidence record cites, then every text a quote was checked against. Source texts are not in the repository '
         '(copyright); `SOURCES.json` says how to rebuild each one into `source_cache/` for `scripts/verify_quotes.py`. '
         'Generated by `scripts/write_docs.py`.', '', '## Works cited', '',
         '| Citation | DOI (Crossref check) | Records | Provenance |', '|---|---|---|---|']
    per_cite = collections.Counter(r['citation'] for r in ev)
    prov = collections.defaultdict(set)
    for r in ev:
        prov[r['citation']].add(r['provenance'])
    for c, r in cites.items():
        d = r.get('doi')
        dc = f"[{d}](https://doi.org/{d}) ({dois.get(d, {}).get('status', 'unchecked')})" if d else 'none'
        L.append(f"| {c} | {dc} | {per_cite[c]} | {', '.join(sorted(prov[c]))} |")
    L += ['', '## Texts the quotes were checked against', '',
          '| Key | Source | Kind | Licence / reuse | Records |', '|---|---|---|---|---|']
    for k in sorted(src):
        s = src[k]
        n = len({r['id'] for r in by_src.get(k, [])})
        if not n:
            continue
        note = f" ({s['note']})" if s.get('note') else ''
        L.append(f"| `{k}` | [{s['title']}]({s['url']}){note} | {s['kind']} | {s.get('license', '')} | {n} |")
    open(os.path.join(ROOT, 'SOURCES.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

    # ---- record index in EVIDENCE.md
    p = os.path.join(ROOT, 'EVIDENCE.md')
    head = open(p, encoding='utf-8').read().split(MARK)[0] if os.path.exists(p) else ''
    groups = collections.OrderedDict()
    for r in ev:
        if r['id'].startswith(('BM2002', 'Copen2012')):
            continue
        groups.setdefault(r['predictor'], []).append(r)
    I = [MARK, '', '## Record index (non-NCHS records)', '',
         'Every non-NCHS record, grouped by predictor. Estimate and interval are as stored (CI unless marked "range"); '
         '"derived" means the value is recomputed from printed numbers by the stated method. The 151 NCHS table rows are in '
         '`evidence.json` and, with all durations, in `app/data/nchs_disruption_tables.json`.', '']
    for g, rs in groups.items():
        I += [f'### {g}', '', '| Record | Contrast | Measure | Estimate | Interval | Provenance | Verified | App |', '|---|---|---|---|---|---|---|---|']
        for r in rs:
            if r.get('range_low') is not None:
                iv = f"range {fmt(r['range_low'])}–{fmt(r['range_high'])}"
            elif r.get('ci_low') is not None:
                iv = f"{fmt(r['ci_low'])}–{fmt(r['ci_high'])}" + (' (derived)' if r.get('derivation') else '')
            else:
                iv = ''
            est = fmt(r.get('estimate')) + (' (derived)' if r.get('derivation') and r['derivation']['method'] in ('percent_change', 'exp_coef') else '')
            app = 'used' if r.get('usable_in_app') else ('withheld' if r.get('usable_withheld') else '')
            I.append(f"| `{r['id']}` | {r['contrast']} | {r['measure']} | {est} | {iv} | {r['provenance']} | {'yes' if r['verified'] else 'NO'} | {app} |")
        I.append('')
    open(p, 'w', encoding='utf-8').write(head + '\n'.join(I) + '\n')
    print('wrote SOURCES.md and the EVIDENCE.md index')


if __name__ == '__main__':
    main()
