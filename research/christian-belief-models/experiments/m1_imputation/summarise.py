#!/usr/bin/env python3
"""Turn results/*.csv into results/summary.md and results/auc_by_item.svg (no raw data needed).

    python3 experiments/m1_imputation/summarise.py
"""
from pathlib import Path
import sys
import pandas as pd

R = Path(__file__).resolve().parent / 'results'
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'src'))
import gss  # noqa: E402

LABEL = {k: v[2].split(' [')[0] for k, v in {**gss.TARGETS, **gss.CATHOLIC_ONLY}.items()}
TRADS = ['Catholic', 'Evangelical Protestant', 'Mainline Protestant', 'Black Protestant']


def f3(x):
    return '' if pd.isna(x) else f'{x:.3f}'


def ci(lo, hi):
    return '' if pd.isna(lo) else f'[{lo:+.3f}, {hi:+.3f}]'


def main():
    out = ['# Milestone 1 results (generated by summarise.py)', '',
           'Weighted (wtssps) 5-fold cross-validated AUC. Intervals are paired respondent bootstrap 95% (300 draws).', '']
    w = pd.read_csv(R / 'within_tradition_cv.csv')
    out += ['## A. Within-tradition cross-validation', '',
            '| tradition | item | n | share | prior AUC | logistic AUC | boosting AUC | boosting − logistic [95%] |',
            '|---|---|---:|---:|---:|---:|---:|---|']
    for _, r in w.iterrows():
        if pd.notna(r.get('note')):
            out.append(f'| {r.tradition} | {LABEL[r.target]} | {int(r.n)} | | | | | too few respondents |')
            continue
        out.append(f'| {r.tradition} | {LABEL[r.target]} | {int(r.n)} | {r.hgb_base_rate:.2f} | {f3(r.prior_auc)} | '
                   f'{f3(r.logit_auc)} | {f3(r.hgb_auc)} | {r.hgb_auc - r.logit_auc:+.3f} '
                   f'{ci(r.hgb_minus_logit_auc_lo, r.hgb_minus_logit_auc_hi)} |')
    t = pd.read_csv(R / 'temporal_holdout_catholic.csv')
    out += ['', '## B. Catholics, train 1972–2014, test 2016–2024', '',
            '| item | n train | n test | test share | prior AUC | logistic AUC | boosting AUC | prior log loss | boosting log loss |',
            '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for _, r in t.iterrows():
        if pd.notna(r.get('note')):
            out.append(f'| {LABEL[r.target]} | {int(r.n_train)} | {int(r.n_test)} | | | | | | too few |')
            continue
        out.append(f'| {LABEL[r.target]} | {int(r.n_train)} | {int(r.n_test)} | {r.hgb_base_rate:.2f} | '
                   f'{f3(r.prior_auc)} | {f3(r.logit_auc)} | {f3(r.hgb_auc)} | {f3(r.prior_logloss)} | {f3(r.hgb_logloss)} |')
    g = pd.read_csv(R / 'generation_transfer_catholic.csv')
    out += ['', '## C. Foreign-born (first-generation) Catholics: third-plus-generation model vs pooled model', '',
            '| item | n gen-1 | gen-1 share | gen-3+ share | gen-3 model mean prediction | AUC gen-3 model | AUC pooled | difference [95%] |',
            '|---|---:|---:|---:|---:|---:|---:|---|']
    for _, r in g.iterrows():
        if pd.notna(r.get('note')):
            out.append(f'| {LABEL[r.target]} | {int(r.n_gen1)} | | | | | | too few |')
            continue
        out.append(f'| {LABEL[r.target]} | {int(r.n_gen1)} | {r.gen1_base_rate:.2f} | {r.gen3_base_rate:.2f} | '
                   f'{r.mean_pred_gen3_model:.2f} | {f3(r.auc_gen3_model)} | {f3(r.auc_pooled_oof)} | '
                   f'{r.auc_gen3_model - r.auc_pooled_oof:+.3f} {ci(r.auc_diff_lo, r.auc_diff_hi)} |')
    x = pd.read_csv(R / 'tradition_transfer.csv')
    out += ['', '## D. A Catholic-trained model scored on Protestant traditions', '',
            '| tradition | item | n | share | Catholic-model mean prediction | AUC Catholic model | AUC own model | difference [95%] |',
            '|---|---|---:|---:|---:|---:|---:|---|']
    for _, r in x.iterrows():
        out.append(f'| {r.tradition} | {LABEL[r.target]} | {int(r.n)} | {r.base_rate:.2f} | {r.mean_pred_catholic_model:.2f} | '
                   f'{f3(r.auc_catholic_model)} | {f3(r.auc_own_oof)} | {r.auc_catholic_model - r.auc_own_oof:+.3f} '
                   f'{ci(r.auc_diff_lo, r.auc_diff_hi)} |')
    imp = pd.read_csv(R / 'importance_catholic.csv')
    out += ['', '## E. Catholics: the three answers that carry most signal for each item', '',
            'Permutation importance: rise in held-out log loss when the feature is shuffled.', '',
            '| item | 1st | 2nd | 3rd |', '|---|---|---|---|']
    for tg, grp in imp.groupby('target', sort=False):
        top = grp.sort_values('importance', ascending=False).head(3)
        out.append(f'| {LABEL[tg]} | ' + ' | '.join(f'{f} ({v:.3f})' for f, v in zip(top.feature, top.importance)) + ' |')
    (R / 'summary.md').write_text('\n'.join(out) + '\n')
    svg(w)
    print('wrote', R / 'summary.md')


def svg(w):
    """Dot plot: boosting AUC per item, one colour per tradition, prior AUC as a grey tick."""
    items = [t for t in gss.TARGETS]
    colours = {'Catholic': '#2a6fdb', 'Evangelical Protestant': '#d9822b',
               'Mainline Protestant': '#2e9e6a', 'Black Protestant': '#a34fb5'}
    left, top, rowh, width = 330, 50, 26, 420
    h = top + rowh * len(items) + 90
    xs = lambda a: left + (a - 0.5) / 0.5 * width
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {left + width + 30} {h}" font-family="sans-serif" font-size="13">',
         '<rect width="100%" height="100%" fill="#fff"/>',
         f'<text x="10" y="22" font-size="15" font-weight="bold">How well other answers predict an unasked GSS item (AUC, 5-fold CV)</text>']
    for v in (0.5, 0.6, 0.7, 0.8, 0.9, 1.0):
        s.append(f'<line x1="{xs(v):.1f}" y1="{top - 8}" x2="{xs(v):.1f}" y2="{top + rowh * len(items)}" stroke="#ddd"/>')
        s.append(f'<text x="{xs(v):.1f}" y="{top + rowh * len(items) + 16}" text-anchor="middle" fill="#555">{v:.1f}</text>')
    for i, it in enumerate(items):
        y = top + rowh * i + rowh / 2
        s.append(f'<text x="{left - 8}" y="{y + 4:.1f}" text-anchor="end">{LABEL[it].split(" (")[0]}</text>')
        for t in TRADS:
            r = w[(w.tradition == t) & (w.target == it)]
            if r.empty or pd.isna(r.hgb_auc.iloc[0]):
                continue
            s.append(f'<line x1="{xs(r.prior_auc.iloc[0]):.1f}" y1="{y - 6:.1f}" x2="{xs(r.prior_auc.iloc[0]):.1f}" y2="{y + 6:.1f}" stroke="#bbb"/>')
            s.append(f'<circle cx="{xs(r.hgb_auc.iloc[0]):.1f}" cy="{y:.1f}" r="5" fill="{colours[t]}" fill-opacity="0.85"/>')
    ly = top + rowh * len(items) + 40
    for i, (t, c) in enumerate(colours.items()):
        x, yy = 30 + 260 * (i % 3), ly + 20 * (i // 3)
        s.append(f'<circle cx="{x + 5}" cy="{yy - 4}" r="5" fill="{c}"/><text x="{x + 14}" y="{yy}">{t}</text>')
    x, yy = 30 + 260, ly + 20
    s.append(f'<line x1="{x + 5}" y1="{yy - 10}" x2="{x + 5}" y2="{yy + 2}" stroke="#bbb"/><text x="{x + 14}" y="{yy}">decade prior (boosting dots, 5-fold CV)</text>')
    s.append('</svg>')
    (R / 'auc_by_item.svg').write_text('\n'.join(s) + '\n')


if __name__ == '__main__':
    main()
