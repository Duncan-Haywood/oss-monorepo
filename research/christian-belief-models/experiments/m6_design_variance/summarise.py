#!/usr/bin/env python3
"""Summarise results/cells.csv and results/sims.csv into results/summary.md and results/total_ratio_by_n.svg.

    python3 experiments/m6_design_variance/summarise.py

Intervals for medians resample source->target pairs (cluster bootstrap, 2000 draws, seed 0), since
cells of one pair share a source model. Also checks the refit against m6_calibration/results/cells.csv.
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent / 'results'
CAL = Path(__file__).resolve().parents[1] / 'm6_calibration' / 'results' / 'cells.csv'
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / '_shared'))
from linefig import svg_lines  # noqa: E402


def cluster_median_ci(c, col, reps=2000, seed=0):
    rng = np.random.default_rng(seed)
    groups = [g[col].values for _, g in c.groupby('pair')]
    meds = [np.median(np.concatenate([groups[i] for i in rng.integers(0, len(groups), len(groups))]))
            for _ in range(reps)]
    return np.percentile(meds, [2.5, 97.5])


def med(c, col):
    lo, hi = cluster_median_ci(c, col)
    return f'{c[col].median():.3f} ({lo:.3f} to {hi:.3f})'


def main():
    c = pd.read_csv(HERE / 'cells.csv')
    s = pd.read_csv(HERE / 'sims.csv')
    ref = pd.read_csv(CAL)
    j = c.merge(ref, on=['pair', 'item'], suffixes=('', '_cal'))
    db = float((j.bias - j.bias_cal).abs().max())
    dr = float((j.var_ratio_cal - j.var_ratio).abs().max())
    c['deff_ratio'] = c.deff_r / c.deff_y
    L = ['# Milestone 6 (part): the calibration section under the GSS design (generated by summarise.py)', '',
         f'{len(c)} cells (pair x item) over {c.pair.nunique()} pairs; {len(s)} pair x item x n rows, '
         'each over the run\'s simple random calibration subsamples. Ultimate-cluster (with-replacement PSU) '
         'variances with GSS strata and PSUs; 1972-74 rows (no design codes) are their own PSUs.', '',
         f'Pipeline check against m6_calibration: {len(j)} of {len(ref)} cells matched; largest |bias| '
         f'difference {db * 100:.4f} points; largest var(y-f)/var(y) difference {dr:.5f}.', '',
         '## Design effects (full target sample, all rows asked)', '',
         f'- median deff of y: {med(c, "deff_y")}; quartiles {c.deff_y.quantile(.25):.3f}, {c.deff_y.quantile(.75):.3f}',
         f'- median deff of the residual y - f: {med(c, "deff_r")}',
         f'- median deff(r)/deff(y): {med(c, "deff_ratio")}; below 1 in {(c.deff_ratio < 1).mean():.0%} of cells',
         f'- variance ratio var(r)/var(y): Kish {med(c, "var_ratio_kish")}; design {med(c, "var_ratio_design")}',
         f'- median PSUs per cell: {c.n_psu.median():.0f}; median target rows per PSU: {(c.N / c.n_psu).median():.2f}', '',
         '| kind | cells | deff y | deff r | deff r / deff y | ratio Kish | ratio design |',
         '|---|---:|---:|---:|---:|---:|---:|']
    for k, g in c.groupby('kind'):
        L.append(f'| {k} | {len(g)} | {g.deff_y.median():.3f} | {g.deff_r.median():.3f} | {g.deff_ratio.median():.3f} | '
                 f'{g.var_ratio_kish.median():.3f} | {g.var_ratio_design.median():.3f} |')
    L += ['', '| item | cells | deff y | deff r | ratio Kish | ratio design |', '|---|---:|---:|---:|---:|---:|']
    for k, g in c.groupby('item'):
        L.append(f'| {k} | {len(g)} | {g.deff_y.median():.3f} | {g.deff_r.median():.3f} | '
                 f'{g.var_ratio_kish.median():.3f} | {g.var_ratio_design.median():.3f} |')
    L += ['', '## Against the population share, by calibration subsample size n', '',
          'V1 = design variance of the full target sample\'s share (common to M and D); V2 = phase-2 variance '
          'over subsamples around the sample share. total ratio = (V1 + V2_D)/(V1 + V2_M). inflation = '
          'sqrt((V1 + V2_D) / mean Kish interval variance of D), the factor by which m6_calibration\'s D '
          'intervals are too narrow for the population share. design est / target = mean over draws of '
          'the designer-computable design variance of D over V1 + V2_D; Kish est / target the same for '
          'the Kish variance.', '',
          '| n | cells | V1 share of M | phase-2 ratio D/M | total ratio D/M (95%) | inflation of D interval | '
          'design est / target | Kish est / target |', '|---:|---:|---:|---:|---:|---:|---:|---:|']
    fig = {'p2': [], 'tot': []}
    ns = sorted(s.n.unique())
    for n, g in s.groupby('n'):
        lo, hi = cluster_median_ci(g, 'total_ratio')
        L.append(f'| {n} | {len(g)} | {g.share_V1_M.median():.3f} | {g.phase2_ratio.median():.3f} | '
                 f'{g.total_ratio.median():.3f} ({lo:.3f} to {hi:.3f}) | {g.inflation_D.median():.3f} | '
                 f'{g.design_vD_over_target.median():.3f} | {g.kish_vD_over_target.median():.3f} |')
        fig['p2'].append(g.phase2_ratio.median())
        fig['tot'].append(g.total_ratio.median())
    L += ['', '| n | kind | cells | V1 share of M | total ratio D/M | inflation |', '|---:|---|---:|---:|---:|---:|']
    for (n, k), g in s.groupby(['n', 'kind']):
        L.append(f'| {n} | {k} | {len(g)} | {g.share_V1_M.median():.3f} | {g.total_ratio.median():.3f} | '
                 f'{g.inflation_D.median():.3f} |')
    q = s.groupby('n').design_vD_over_target.quantile([.1, .9]).unstack()
    L += ['', 'Design estimate / target, 10th to 90th percentile over cells: '
          + ', '.join(f'n = {n}: {r[0.1]:.2f} to {r[0.9]:.2f}' for n, r in q.iterrows()), '']
    (HERE / 'summary.md').write_text('\n'.join(L) + '\n')
    (HERE / 'total_ratio_by_n.svg').write_text(svg_lines(
        'Variance of the difference estimator relative to the plain mean (median over cells)',
        'Variance ratio of D to M against calibration subsample size, around the sample share and around the population share',
        'calibration subsample size n (log scale)', 'variance of D / variance of M',
        [('around the sample share (phase 2 only)', ns, fig['p2']),
         ('around the population share (with the GSS design)', ns, fig['tot'])], logx=True, hline=1.0))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
