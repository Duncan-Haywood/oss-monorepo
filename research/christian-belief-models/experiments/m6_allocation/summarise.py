#!/usr/bin/env python3
"""Summarise results/families.csv and results/groups.csv into results/summary.md and
results/loss_by_budget.svg.

    python3 experiments/m6_allocation/summarise.py [--quick]

Loss ratios are a strategy's family loss (mean over the family's groups of MSE) over D_eq's for the
same family and budget. Medians over families; intervals resample items (cluster bootstrap, 2000
draws, seed 0), since a family's groups share an item and the tradition families share items.
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent / 'results'
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / '_shared'))
from linefig import svg_lines  # noqa: E402

STRATS = ('M_eq', 'D_ney', 'C_or', 'FH_fam', 'FH_prior', 'FH2')
LABEL = {'M_eq': 'plain mean, equal split', 'D_eq': 'difference, equal split',
         'D_ney': 'difference, Neyman split', 'C_or': 'oracle composite, water-filled',
         'FH_fam': 'shrinkage, tau2 from the family', 'FH_prior': 'shrinkage, tau2 from other items',
         'FH2': 'shrinkage, pilot then water-filled'}


def med_ci(df, col, reps=2000, seed=0):
    rng = np.random.default_rng(seed)
    items = df.item.unique()
    by = {i: df.loc[df.item == i, col].values for i in items}
    meds = [np.median(np.concatenate([by[i] for i in rng.choice(items, len(items))])) for _ in range(reps)]
    lo, hi = np.percentile(meds, [2.5, 97.5])
    return float(df[col].median()), float(lo), float(hi)


def main():
    sfx = '_quick' if '--quick' in sys.argv else ''
    f = pd.read_csv(HERE / f'families{sfx}.csv')
    gr = pd.read_csv(HERE / f'groups{sfx}.csv')
    ref = f[f.strategy == 'D_eq'].set_index(['family', 'item', 'nbar'])
    f = f.join(ref[['loss', 'worst_rmse']].rename(columns={'loss': 'ref_loss', 'worst_rmse': 'ref_worst'}),
               on=['family', 'item', 'nbar'])
    f['ratio'] = f.loss / f.ref_loss
    f['worst_ratio'] = f.worst_rmse / f.ref_worst
    nb = sorted(f.nbar.unique())
    nfam = f.groupby('nbar').apply(lambda g: g[['family', 'item']].drop_duplicates().shape[0])
    L = ['# Milestone 6 (part): splitting a calibration budget across subgroups (generated by summarise.py)', '',
         f'{f[["family", "item"]].drop_duplicates().shape[0]} families (item x kind, tradition families per '
         f'source) with 2 to 4 groups; families per budget: '
         + ', '.join(f'n&#772; = {n}: {nfam[n]}' for n in nb) + '. Ratio = family loss (mean group MSE) '
         'over the difference estimator with an equal split (D_eq); below 1 is better. Median over '
         'families, item-cluster bootstrap 95% interval.', '',
         '## Loss ratio to D_eq', '', '| strategy | ' + ' | '.join(f'n&#772; = {n}' for n in nb) + ' |',
         '|---|' + '---:|' * len(nb)]
    fig = {}
    for s in STRATS:
        cells = []
        for n in nb:
            m, lo, hi = med_ci(f[(f.strategy == s) & (f.nbar == n)], 'ratio')
            cells.append(f'{m:.3f} ({lo:.3f}&ndash;{hi:.3f})')
            fig.setdefault(s, []).append(m)
        L.append(f'| {s}: {LABEL[s]} | ' + ' | '.join(cells) + ' |')
    L += ['', '## Root mean group MSE, points (median over families)', '',
          '| strategy | ' + ' | '.join(f'n&#772; = {n}' for n in nb) + ' |', '|---|' + '---:|' * len(nb)]
    for s in ('D_eq',) + STRATS:
        L.append(f'| {s} | ' + ' | '.join(
            f'{100 * np.sqrt(f[(f.strategy == s) & (f.nbar == n)].loss).median():.2f}' for n in nb) + ' |')
    L += ['', '## Worst group: ratio of the worst group\'s RMSE to D_eq\'s (median over families)', '',
          '| strategy | ' + ' | '.join(f'n&#772; = {n}' for n in nb) + ' |', '|---|' + '---:|' * len(nb)]
    for s in STRATS:
        L.append(f'| {s} | ' + ' | '.join(
            f'{f[(f.strategy == s) & (f.nbar == n)].worst_ratio.median():.3f}' for n in nb) + ' |')
    L += ['', '## By kind: median loss ratio to D_eq at n&#772; = 50 and 400', '',
          '| kind | families | ' + ' | '.join(f'{s} 50 / 400' for s in ('C_or', 'FH_prior', 'FH2')) + ' |',
          '|---|---:|' + '---:|' * 3]
    f['kind'] = f.family.str.split(':').str[0]
    for k, g in f.groupby('kind'):
        row = [k, str(g[['family', 'item']].drop_duplicates().shape[0])]
        for s in ('C_or', 'FH_prior', 'FH2'):
            a = g[(g.strategy == s) & (g.nbar == 50)].ratio.median()
            b = g[(g.strategy == s) & (g.nbar == 400)].ratio.median()
            row.append(f'{a:.3f} / {b:.3f}')
        L.append('| ' + ' | '.join(row) + ' |')
    # how often allocation gives a group nothing, and FH2's spread of n
    co = gr[gr.strategy == 'C_or']
    L += ['', '## Allocation', '',
          f'- oracle water-filling gives a group zero calibration respondents in '
          f'{(co.n == 0).mean():.0%} of group x budget cases (n&#772; = 50: '
          f'{(co[co.nbar == 50].n == 0).mean():.0%}; 400: {(co[co.nbar == 400].n == 0).mean():.0%})',
          f'- FH2 mean n per group relative to n&#772;: quartiles '
          + ', '.join(f'{q:.2f}' for q in (gr[gr.strategy == 'FH2'].n / gr[gr.strategy == 'FH2'].nbar)
                      .quantile([.25, .5, .75]))]
    # prediction checks
    def med(s, n, col='ratio'):
        return f[(f.strategy == s) & (f.nbar == n)][col].median()
    L += ['', '## Prediction checks (LOG.md, 2026-11-13)', '',
          f'1. D_ney median ratio in [0.97, 1.00] at every n&#772;: '
          + ', '.join(f'{med("D_ney", n):.3f}' for n in nb),
          f'2. C_or at most 0.60 at 50 ({med("C_or", 50):.3f}); 0.75 to 0.95 at 400 ({med("C_or", 400):.3f})',
          f'3. FH_prior at most (1 + C_or)/2 at 50 ({med("FH_prior", 50):.3f} vs '
          f'{(1 + med("C_or", 50)) / 2:.3f}) and 100 ({med("FH_prior", 100):.3f} vs '
          f'{(1 + med("C_or", 100)) / 2:.3f}); at most 1.02 at 400 ({med("FH_prior", 400):.3f})',
          f'4. FH_fam minus FH_prior at 50 at least 0.05: {med("FH_fam", 50) - med("FH_prior", 50):.3f}',
          f'5. FH2 / FH_prior loss within 5% at every n&#772;: '
          + ', '.join(f'{(f[(f.strategy == "FH2") & (f.nbar == n)].loss.values / f[(f.strategy == "FH_prior") & (f.nbar == n)].loss.values).mean():.3f} (mean)'
                      for n in nb),
          f'6. FH_prior worst-group RMSE ratio above 1 at 50: {med("FH_prior", 50, "worst_ratio"):.3f}',
          f'Refutation (FH_prior at 50 at least 0.97): {med("FH_prior", 50):.3f}']
    (HERE / f'summary{sfx}.md').write_text('\n'.join(L) + '\n')
    if not sfx:
        (HERE / 'loss_by_budget.svg').write_text(svg_lines(
            'Group-average MSE relative to the difference estimator with an equal split',
            'Median loss ratio against calibration respondents per group for Neyman, oracle and '
            'shrinkage strategies',
            'calibration respondents per group (log scale)', 'loss ratio to D_eq',
            [(LABEL[s], nb, fig[s]) for s in ('D_ney', 'C_or', 'FH_prior', 'FH2', 'FH_fam')],
            logx=True, hline=1.0))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
