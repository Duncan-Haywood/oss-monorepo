#!/usr/bin/env python3
"""Milestone 6 (part): can the per-kind choice of prior be made without the rotated item, and does it
keep the gain?

    python3 experiments/m6_kindsel/run.py

No microdata. Reads ../m6_allocation/results/cells.csv (bias b for every source->target pair x item) and
../m6_prior/results/groups.csv (per group x budget: each prior's m, tau2, MSE and interval coverage,
fitted with only the target cell hidden).

Leave-one-item-out: for held-out item j, column j is deleted from the bias matrix; every remaining cell
is predicted by COL, ADD and LR with that cell hidden too, P0 predicts 0. Per kind, the prior with the
smallest mean squared prediction error on that kind's remaining cells is chosen (KSEL). Item j's groups
are then scored with the chosen prior's existing columns in m6_prior/results/groups.csv.

Plan and predictions: LOG.md, 2026-11-16 (written before this ran).
Writes results/choices.csv, results/groups.csv, results/summary.md and results/mse_by_budget.svg.
"""
import importlib.util
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
EXP = HERE.parent
OUT = HERE / 'results'
sys.path.insert(0, str(HERE.parents[2] / '_shared'))
from linefig import svg_lines  # noqa: E402

_sp = importlib.util.spec_from_file_location('m6_prior', EXP / 'm6_prior' / 'run.py')
pr = importlib.util.module_from_spec(_sp)
sys.modules['m6_prior'] = pr
_sp.loader.exec_module(pr)

CANDIDATES = ('P0', 'COL', 'ADD', 'LR')
RULE = {'period': 'COL', 'generation': 'P0', 'tradition': 'ADD'}
SHOW = ('P0', 'COL', 'ADD', 'LR', 'SEL', 'KSEL', 'oracle')


# ---------- pure helpers (tested in test_kindsel.py) ----------

def loo_errors(B, kinds, held):
    """Squared prediction error of each candidate on every observed cell of B without column `held`,
    each cell predicted with itself hidden. Returns a DataFrame (pair, item, kind, err_<prior>)."""
    Bj = B.drop(columns=[held])
    rows = []
    for q in Bj.index:
        for k in Bj.columns:
            b = Bj.loc[q, k]
            if np.isnan(b):
                continue
            Bh = Bj.copy()
            Bh.loc[q, k] = np.nan
            d = {'pair': q, 'item': k, 'kind': kinds[q], 'err_P0': b ** 2}
            for name in CANDIDATES[1:]:
                d[f'err_{name}'] = (b - pr.PRED[name](Bh, kinds, q, k)) ** 2
            rows.append(d)
    return pd.DataFrame(rows)


def choose(errs):
    """Per kind: the candidate with the smallest mean squared error (ties go to the earlier candidate)."""
    out = {}
    for kind, x in errs.groupby('kind'):
        means = [x[f'err_{a}'].mean() for a in CANDIDATES]
        out[kind] = CANDIDATES[int(np.argmin(means))]
    return out


def apply_choice(g, choice):
    """Copy the chosen prior's columns into *_KSEL for each row of g (choice: {(item, kind): prior})."""
    g = g.copy()
    pick = [choice[(i, k)] for i, k in zip(g.item, g.kind)]
    g['ksel'] = pick
    for key in ('m', 'tau2', 'mse', 'cov_naive', 'cov_robust', 'hw_robust'):
        g[f'{key}_KSEL'] = [g.at[ix, f'{key}_{a}'] for ix, a in zip(g.index, pick)]
    return g


# ---------- run ----------

def _fold(args):
    B, kinds, j = args
    e = loo_errors(B, kinds, j)
    ch = choose(e)
    means = e.groupby('kind')[[f'err_{a}' for a in CANDIDATES]].mean()
    return j, ch, means


def main():
    OUT.mkdir(exist_ok=True)
    cells = pd.read_csv(EXP / 'm6_allocation' / 'results' / 'cells.csv')
    B = cells.pivot_table(index='pair', columns='item', values='bias', aggfunc='first')
    kinds = cells.drop_duplicates('pair').set_index('pair').kind.to_dict()
    g = pd.read_csv(EXP / 'm6_prior' / 'results' / 'groups.csv')
    with ProcessPoolExecutor(4) as ex:
        folds = list(ex.map(_fold, [(B, kinds, j) for j in B.columns]))
    choice, crow = {}, []
    for j, ch, means in folds:
        for kind, a in ch.items():
            choice[(j, kind)] = a
            d = {'held_item': j, 'kind': kind, 'chosen': a}
            d.update({f'rms_{c}': 100 * np.sqrt(means.loc[kind, f'err_{c}']) for c in CANDIDATES})
            crow.append(d)
    ch = pd.DataFrame(crow)
    ch.to_csv(OUT / 'choices.csv', index=False)
    g = apply_choice(g, choice)
    g.to_csv(OUT / 'groups.csv', index=False)
    summarise(g, ch)


def summarise(g, ch):
    ratio, boot = pr.ratio, pr.boot
    nb = sorted(g.nbar.unique())
    head = '| prior | ' + ' | '.join(f'n&#772; = {n}' for n in nb) + ' |'
    sep = '|---|' + '---:|' * len(nb)
    L = ['# Milestone 6 (part): the prior chosen per kind without the rotated item (generated by run.py)', '',
         f'{g[["pair", "item"]].drop_duplicates().shape[0]} groups, 13 leave-one-item-out folds. KSEL = per kind, '
         'the prior (P0, COL, ADD, LR) with the smallest leave-one-cell-out squared error on the other 12 items, '
         'column of the held-out item deleted. Ratios are mean group MSE over the reference\'s; '
         'item-cluster bootstrap 95% in brackets.', '',
         '## Choices: folds (of 13) picking each prior, by kind', '',
         '| kind | ' + ' | '.join(CANDIDATES) + ' |', '|---|' + '---:|' * len(CANDIDATES)]
    for k, x in ch.groupby('kind'):
        L.append(f'| {k} | ' + ' | '.join(str((x.chosen == a).sum()) for a in CANDIDATES) + ' |')
    L += ['', '## Folds that did not pick the modal prior', '', '| kind | held-out item | chosen | '
          + ' | '.join(f'RMS {a}' for a in CANDIDATES) + ' |', '|---|---|---|' + '---:|' * len(CANDIDATES)]
    for k, x in ch.groupby('kind'):
        mode = x.chosen.mode().iloc[0]
        for r in x[x.chosen != mode].itertuples():
            L.append(f'| {k} | {r.held_item} | {r.chosen} | '
                     + ' | '.join(f'{getattr(r, "rms_" + a):.2f}' for a in CANDIDATES) + ' |')
    L += ['', '## Mean MSE over the difference estimator D\'s', '', head, sep]
    for a in SHOW:
        L.append(f'| {a} | ' + ' | '.join(f'{ratio(g[g.nbar == n], a, "D"):.3f}' for n in nb) + ' |')
    L += ['', '## Mean MSE over P0\'s', '', head, sep]
    for a in SHOW[1:]:
        cells = []
        for n in nb:
            x = g[g.nbar == n]
            lo, hi = boot(x, a, 'P0')
            cells.append(f'{ratio(x, a, "P0"):.3f} ({lo:.2f}&ndash;{hi:.2f})')
        L.append(f'| {a} | ' + ' | '.join(cells) + ' |')
    g50 = g[g.nbar == 50]
    L += ['', '## By kind at n&#772; = 50: mean MSE over P0\'s', '',
          '| kind | groups | ' + ' | '.join(SHOW[1:]) + ' |', '|---|---:|' + '---:|' * len(SHOW[1:])]
    for k, x in g50.groupby('kind'):
        L.append(f'| {k} | {len(x)} | ' + ' | '.join(f'{ratio(x, a, "P0"):.3f}' for a in SHOW[1:]) + ' |')
    ssm_name = 'samesex_marr_no'
    ns = g[g.item != ssm_name]
    L += ['', f'## Without same-sex marriage ({ssm_name}) in the evaluation: mean MSE over P0\'s', '', head, sep]
    for a in SHOW[1:]:
        L.append(f'| {a} | ' + ' | '.join(f'{ratio(ns[ns.nbar == n], a, "P0"):.3f}' for n in nb) + ' |')
    L += ['', '## Robust EB interval: mean coverage (share of groups below 80%)', '', head, sep]
    for a in SHOW[:-1]:
        L.append(f'| {a} | ' + ' | '.join(
            f'{g[g.nbar == n]["cov_robust_" + a].mean():.1%} ({(g[g.nbar == n]["cov_robust_" + a] < .8).mean():.0%})'
            for n in nb) + ' |')
    cnt = {k: x.chosen.value_counts().to_dict() for k, x in ch.groupby('kind')}
    ns50 = ns[ns.nbar == 50]
    L += ['', '## Prediction checks (LOG.md, 2026-11-16)', '',
          f'1. period picks COL or ADD in at least 12 of 13: {cnt.get("period", {})}',
          f'2. generation picks P0 in at least 11 of 13: {cnt.get("generation", {})}',
          f'3. tradition picks ADD in at least 9 of 13: {cnt.get("tradition", {})}',
          f'4. KSEL at 50 at most 0.70 of P0 and at most ADD ({ratio(g50, "ADD", "P0"):.3f}): '
          f'{ratio(g50, "KSEL", "P0"):.3f}; at 400 at most 1.03: {ratio(g[g.nbar == 400], "KSEL", "P0"):.3f}',
          f'5. without same-sex marriage, KSEL at 50 at most 0.95 of P0: {ratio(ns50, "KSEL", "P0"):.3f}',
          '6. KSEL robust coverage at least 94% at every n&#772;: ' + ', '.join(
              f'{g[g.nbar == n]["cov_robust_KSEL"].mean():.1%}' for n in nb),
          f'Refutation (KSEL not at most 0.95 of P0 at 50): {ratio(g50, "KSEL", "P0"):.3f}']
    # post hoc (added after seeing the results, not pre-registered): the in-sample by-kind rule read off
    # m6_prior (COL for period, P0 for generation, ADD for tradition), and where KSEL departs from it
    g = g.copy()
    g['mse_RULE'] = [g.at[i, 'mse_' + RULE[k]] for i, k in zip(g.index, g.kind)]
    dev = g50.index[g50.ksel != g50.kind.map(RULE)]
    d50 = g.loc[dev]
    tot = g.loc[g50.index, 'mse_P0'].sum()
    L += ['', '## Post hoc (not pre-registered): the in-sample by-kind rule (period COL, generation P0, tradition ADD)', '',
          head, sep, '| RULE / P0 | ' + ' | '.join(f'{ratio(g[g.nbar == n], "RULE", "P0"):.3f}' for n in nb) + ' |',
          '| KSEL / P0 | ' + ' | '.join(f'{ratio(g[g.nbar == n], "KSEL", "P0"):.3f}' for n in nb) + ' |', '',
          f'At n&#772; = 50, KSEL departs from the rule on {len(d50)} of {len(g50)} groups; their excess MSE over P0 '
          f'is {(d50.mse_KSEL - d50.mse_P0).sum() / tot:+.3f} of all groups\' P0 MSE under KSEL and '
          f'{(d50.mse_RULE - d50.mse_P0).sum() / tot:+.3f} under the rule.', '',
          '| kind | item | groups | KSEL pick | MSE KSEL / P0 | MSE rule / P0 |', '|---|---|---:|---|---:|---:|']
    for (k, i), x in d50.groupby(['kind', 'item']):
        L.append(f'| {k} | {i} | {len(x)} | {x.ksel.iloc[0]} | {x.mse_KSEL.sum() / x.mse_P0.sum():.2f} | '
                 f'{x.mse_RULE.sum() / x.mse_P0.sum():.2f} |')
    (OUT / 'summary.md').write_text('\n'.join(L) + '\n')
    (OUT / 'mse_by_budget.svg').write_text(svg_lines(
        'Mean subgroup MSE relative to the difference estimator: the prior chosen per kind without the item',
        'Mean MSE ratio to the difference estimator against calibration respondents per group, for the zero '
        'prior, ADD, the in-sample per-cell selector, the nested per-kind selector and the known-bias oracle',
        'calibration respondents per group (log scale)', 'mean MSE / difference estimator\'s',
        [(a, nb, [ratio(g[g.nbar == n], a, 'D') for n in nb]) for a in ('P0', 'ADD', 'SEL', 'KSEL', 'oracle')],
        logx=True, hline=1.0))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
