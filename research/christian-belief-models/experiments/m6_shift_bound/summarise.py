#!/usr/bin/env python3
"""Summarise results/cells.csv into results/summary.md (the tables quoted in LOG.md and README.md).

    python3 experiments/m6_shift_bound/summarise.py

Errors are absolute errors in the target's weighted share, in percentage points. Intervals for mean
differences resample source->target pairs (cluster bootstrap, 2000 draws, seed 0), since cells of
one pair share a source model and a target sample.
"""
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = Path(__file__).resolve().parent / 'results'
EST = ['E0', 'E1', 'IW', 'E2', 'E3']
LABEL = {'E0': 'E0 transfer as is', 'E1': 'E1 source share', 'IW': 'IW covariate-shift correction',
         'E2': 'E2 median offset of asked items', 'E3': 'E3 signed, similarity-weighted offset'}


def cluster_boot(c, a, b, reps=2000, seed=0):
    """95% interval for mean(|a err|) - mean(|b err|), resampling pairs."""
    rng = np.random.default_rng(seed)
    groups = [g for _, g in c.groupby('pair')]
    out = []
    for _ in range(reps):
        s = pd.concat([groups[i] for i in rng.integers(0, len(groups), len(groups))])
        out.append(s[f'err_{a}'].mean() - s[f'err_{b}'].mean())
    return np.percentile(out, [2.5, 97.5])


def main():
    c = pd.read_csv(HERE / 'cells.csv')
    for e in EST:
        c[f'err_{e}'] = (c[e] - c.truth).abs() * 100
    L = [f'# Milestone 6 (part): transfer-error decomposition (generated by summarise.py)', '',
         f'{len(c)} cells (source->target pair x item) over {c.pair.nunique()} pairs. '
         'Errors: absolute error of the target\'s weighted share, points. '
         'Intervals: pair-cluster bootstrap 95%, 2000 draws.', '',
         '## Mean absolute error by estimator', '',
         '| estimator | all | generation | ethnicity | tradition | period | vs E0 [95%] | closer than E0 |',
         '|---|---:|---:|---:|---:|---:|---|---:|']
    for e in EST:
        by = c.groupby('kind')[f'err_{e}'].mean()
        if e == 'E0':
            ci, closer = '', ''
        else:
            lo, hi = cluster_boot(c, e, 'E0')
            ci = f'{c[f"err_{e}"].mean() - c.err_E0.mean():+.2f} [{lo:+.2f}, {hi:+.2f}]'
            closer = f'{(c[f"err_{e}"] < c.err_E0).mean():.0%}'
        L.append(f'| {LABEL[e]} | {c[f"err_{e}"].mean():.2f} | ' +
                 ' | '.join(f'{by.get(k, np.nan):.2f}' for k in ['generation', 'ethnicity', 'tradition', 'period'])
                 + f' | {ci} | {closer} |')
    lo, hi = cluster_boot(c, 'E3', 'E2')
    L += ['', f'E3 minus E2: {c.err_E3.mean() - c.err_E2.mean():+.2f} points [{lo:+.2f}, {hi:+.2f}].', '']
    A, B = c.A.abs() * 100, c.B.abs() * 100
    rho, pv = spearmanr((c.E3 - c.E0).abs(), c.bias.abs())
    L += ['## Decomposition b = A + B', '',
          f'- median |b| {c.bias.abs().median() * 100:.2f}, mean {c.bias.abs().mean() * 100:.2f} points',
          f'- median |A-hat| (covariate shift, label-free) {A.median():.2f} points; '
          f'|A-hat| < |B-hat| in {(A < B).mean():.0%} of cells',
          f'- median |B-hat| (concept shift) {B.median():.2f} points',
          f'- median importance-weight effective sample fraction {c.iw_ess_frac.median():.2f}',
          f'- Spearman(|E3 - E0|, |b|) = {rho:.2f} (p = {pv:.2g}, n = {len(c)} cells, not independent)',
          f'- sign of the E3 correction matches the sign needed in {(np.sign(c.E3 - c.E0) == -np.sign(c.bias)).mean():.0%} of cells',
          '', '## By item (mean absolute error, points)', '',
          '| item | cells | E0 | E2 | E3 |', '|---|---:|---:|---:|---:|']
    for it, g in c.groupby('item'):
        L.append(f'| {it} | {len(g)} | {g.err_E0.mean():.2f} | {g.err_E2.mean():.2f} | {g.err_E3.mean():.2f} |')
    L += ['', '## By pair (mean absolute error, points)', '',
          '| pair | cells | E0 | IW | E2 | E3 | median |A-hat| |', '|---|---:|---:|---:|---:|---:|---:|']
    for p, g in c.groupby('pair', sort=False):
        L.append(f'| {p} | {len(g)} | {g.err_E0.mean():.2f} | {g.err_IW.mean():.2f} | {g.err_E2.mean():.2f} | '
                 f'{g.err_E3.mean():.2f} | {g.A.abs().median() * 100:.2f} |')
    (HERE / 'summary.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
