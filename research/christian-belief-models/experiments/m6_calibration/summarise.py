#!/usr/bin/env python3
"""Summarise results/cells.csv and results/sims.csv into results/summary.md and results/rmse_by_n.svg.

    python3 experiments/m6_calibration/summarise.py

Errors are in percentage points of the target's weighted share. Each sims row is one pair x item x n
cell over R simple random calibration subsamples. Intervals for medians resample source->target pairs
(cluster bootstrap, 2000 draws, seed 0), since cells of one pair share a source model.
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent / 'results'
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / '_shared'))
from linefig import svg_lines  # noqa: E402

GOAL = 0.03  # target 95% half-width for the "subsample needed" table


def crossover(g, n_star):
    """Simulated n where D's RMSE falls to E0's |bias|: log-linear interpolation of rmse_D/|b| over n.
    None if the ratio does not cross 1 inside the grid."""
    g = g.sort_values('n')
    r = (g.rmse_D / g.abs_bias_E0).values
    n = g.n.values
    for k in range(len(n) - 1):
        if r[k] >= 1 > r[k + 1]:
            a, b = np.log(r[k]), np.log(r[k + 1])
            return float(np.exp(np.log(n[k]) + (0 - a) / (b - a) * (np.log(n[k + 1]) - np.log(n[k]))))
    return None


def cluster_median_ci(c, col, reps=2000, seed=0):
    rng = np.random.default_rng(seed)
    groups = [g[col].values for _, g in c.groupby('pair')]
    meds = [np.median(np.concatenate([groups[i] for i in rng.integers(0, len(groups), len(groups))]))
            for _ in range(reps)]
    return np.percentile(meds, [2.5, 97.5])


def main():
    c = pd.read_csv(HERE / 'cells.csv')
    s = pd.read_csv(HERE / 'sims.csv')
    c['saving'] = 1 - c.var_ratio
    lo, hi = cluster_median_ci(c, 'var_ratio')
    L = ['# Milestone 6 (part): calibration subsample size (generated by summarise.py)', '',
         f'{len(c)} cells (source->target pair x item) over {c.pair.nunique()} pairs; '
         f'{len(s)} pair x item x n combinations, each over the run\'s simple random subsamples. '
         'Errors in points of the target\'s weighted share.', '',
         '## Variance ratio: the fraction of the plain mean\'s sample the difference estimator needs', '',
         f'- median var(y - f) / var(y) over cells: {c.var_ratio.median():.3f} '
         f'(pair-cluster bootstrap 95% {lo:.3f} to {hi:.3f}); median saving {c.saving.median():.0%}',
         f'- cells with ratio < 1: {(c.var_ratio < 1).mean():.0%}; quartiles '
         f'{c.var_ratio.quantile(.25):.3f}, {c.var_ratio.quantile(.75):.3f}',
         f'- D RMSE below M RMSE in {(s.rmse_D < s.rmse_M).mean():.0%} of pair x item x n combinations', '',
         '| kind | cells | median ratio | median saving | median n* |', '|---|---:|---:|---:|---:|']
    for k, g in c.groupby('kind'):
        L.append(f'| {k} | {len(g)} | {g.var_ratio.median():.3f} | {g.saving.median():.0%} | {g.n_star.median():.0f} |')
    L += ['', '## By item', '',
          f'Subsample needed for a 95% half-width of {GOAL*100:.0f} points: 100 x (median half-width at n = 100 / '
          f'{GOAL*100:.0f})^2, from the simulated Wald half-widths (weights included, no design effect beyond them).', '',
          '| item | cells | median saving | median n* | n needed, plain mean | n needed, difference |',
          '|---|---:|---:|---:|---:|---:|']
    h100 = s[s.n == 100].groupby('item')[['halfw_M', 'halfw_D']].median()
    for it, g in c.groupby('item'):
        nm = nd = float('nan')
        if it in h100.index:
            nm = 100 * (h100.loc[it, 'halfw_M'] / GOAL) ** 2
            nd = 100 * (h100.loc[it, 'halfw_D'] / GOAL) ** 2
        L.append(f'| {it} | {len(g)} | {g.saving.median():.0%} | {g.n_star.median():.0f} | {nm:.0f} | {nd:.0f} |')
    # break-even n*: analytic vs simulated
    rows = []
    for (p, it), g in s.groupby(['pair', 'item']):
        cell = c[(c.pair == p) & (c.item == it)].iloc[0]
        x = crossover(g, cell.n_star)
        if x is not None:
            rows.append((cell.n_star, x))
    ratio = np.array([a / b for a, b in rows])
    L += ['', '## Break-even with the label-free transfer E0', '',
          f'- analytic n* = var(y - f) / b^2: median {c.n_star.median():.0f}, quartiles '
          f'{c.n_star.quantile(.25):.0f} to {c.n_star.quantile(.75):.0f}; '
          f'n* < 25 in {(c.n_star < 25).mean():.0%} of cells, > 400 in {(c.n_star > 400).mean():.0%}',
          f'- cells whose simulated crossover falls inside the n grid: {len(rows)}; analytic n* within a factor 2 '
          f'of it in {np.mean((ratio >= .5) & (ratio <= 2)):.0%} (median analytic/simulated {np.median(ratio):.2f})'
          if rows else '- no simulated crossover inside the grid', '',
          '## RMSE by n (median over cells, points) and Wald 95% coverage (pooled over draws)', '',
          '| n | cells | M | D | PPI++ | R | E0 abs bias | PPI/D | R/D | D < M | cover M | cover D | half-width D |',
          '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    fig = {k: [] for k in ('M', 'D', 'E0')}
    ns = sorted(s.n.unique())
    for n in ns:
        g = s[s.n == n]
        L.append(f'| {n} | {len(g)} | {g.rmse_M.median()*100:.2f} | {g.rmse_D.median()*100:.2f} | '
                 f'{g.rmse_PPI.median()*100:.2f} | {g.rmse_R.median()*100:.2f} | {g.abs_bias_E0.median()*100:.2f} | '
                 f'{(g.rmse_PPI / g.rmse_D).median():.3f} | {(g.rmse_R / g.rmse_D).median():.3f} | '
                 f'{(g.rmse_D < g.rmse_M).mean():.0%} | {g.cover_M.mean():.1%} | {g.cover_D.mean():.1%} | '
                 f'{g.halfw_D.median()*100:.2f} |')
        fig['M'].append(g.rmse_M.median() * 100)
        fig['D'].append(g.rmse_D.median() * 100)
        fig['E0'].append(g.abs_bias_E0.median() * 100)
    worst = s.groupby('n').cover_D.min()
    L += ['', 'Worst single-cell D coverage by n: ' + ', '.join(f'{n}: {v:.0%}' for n, v in worst.items()), '']
    (HERE / 'summary.md').write_text('\n'.join(L) + '\n')
    (HERE / 'rmse_by_n.svg').write_text(svg_lines(
        'Error in a group\'s share vs calibration subsample size (median over cells)',
        'RMSE in points against subsample size for the plain mean, the difference estimator and the label-free transfer',
        'calibration subsample size n (log scale)', 'RMSE, points',
        [('plain subsample mean', ns, fig['M']), ('difference (model + residual)', ns, fig['D']),
         ('transfer only, |bias|', ns, fig['E0'])], logx=True))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
