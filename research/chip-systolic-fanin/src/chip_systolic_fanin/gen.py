"""Generate Verilog for an output-stationary systolic array that runs the quantised F-F-4 MLP on a batch of R vectors.

R rows (one per batch vector) by C columns (neurons per pass). PE(r,c) multiplies the activation moving right along row r
by the weight moving down column c and accumulates in place. Row r's activations enter r cycles late, column c's weights
enter c cycles late, so PE(r,c) sees input k at cycle t = k + r + c. Weights come from baked-in ROM functions (as in
chip-accel). A pass lasts R+C+F-2 compute cycles plus 1 write-back; layers take ceil(N/C) passes.
"""
from .model import NOUT


def widths(f):
    """(neuron/k index bits, counter bits) for fan-in f."""
    nw = max(1, (f - 1).bit_length())
    return nw, max(4, nw + 1)


def cycles(c, r, f=8):
    """Cycles from start to done for one batch of r vectors: 1 load + 1 layer transfer + per pass (r + c + 6 compute + 1 write-back)."""
    return 2 + sum(-(-n // c) * (r + c + f - 1) for n in (f, NOUT))


def _rom(name, q, key, width_expr):
    nw, _ = widths(q["f"])
    lines = []
    if key == "W":
        for layer, w in enumerate((q["W0"], q["W1"])):
            for k in range(w.shape[0]):
                for n in range(w.shape[1]):
                    if w[k, n]:
                        lines.append(f"      {{1'd{layer}, {nw}'d{n}, {nw}'d{k}}}: {name} = {int(w[k, n])};")
        sig = f"input layer, input [{nw}-1:0] n, input [{nw}-1:0] k"
        sel = "{layer, n, k}"
    else:
        for layer, b in enumerate((q["B0"], q["B1"])):
            for n in range(len(b)):
                if b[n]:
                    lines.append(f"      {{1'd{layer}, {nw}'d{n}}}: {name} = {int(b[n])};")
        sig = f"input layer, input [{nw}-1:0] n"
        sel = "{layer, n}"
    body = "\n".join(lines)
    return (f"  function signed [{width_expr}-1:0] {name}({sig});\n    begin\n      {name} = 0;\n"
            f"      case ({sel})\n{body}\n      default: {name} = 0;\n      endcase\n    end\n  endfunction\n")


def verilog(q, c, r):
    f = NIN = NH = q["f"]
    nw, cw = widths(f)
    wb, aw = q["wb"], q["aw"]
    qmax = 2 ** (wb - 1) - 1
    last = r + c + f - 3
    return f"""// Generated by chip_systolic_fanin.gen: {r}x{c} output-stationary array, WB={wb}-bit, AW={aw}-bit accumulators.
module accel(input clk, input rst, input start, input [{r*NIN*wb}-1:0] x, output reg done, output [{r*NOUT*wb}-1:0] y);
  localparam R = {r}, C = {c}, WB = {wb}, AW = {aw};
  localparam signed [AW-1:0] QMAX = {qmax}, QMIN = -{qmax + 1};
{_rom('wrom', q, 'W', 'WB')}
{_rom('brom', q, 'B', 'AW')}
  localparam IDLE = 0, RUN = 1, WBK = 2, XFER = 3;
  reg [1:0] st;
  reg layer;
  reg [{cw-1}:0] tile;
  reg [7:0] t;
  reg [R*{NIN}*WB-1:0] act, nxt;
  reg [R*C*WB-1:0] areg, wreg;
  reg [R*C*AW-1:0] acc;
  genvar gr, gn;
  generate
    for (gr = 0; gr < R; gr = gr + 1) begin : yr
      for (gn = 0; gn < {NOUT}; gn = gn + 1) begin : yn
        assign y[(gr*{NOUT}+gn)*WB +: WB] = nxt[(gr*{NIN}+gn)*WB +: WB];
      end
    end
  endgenerate
  integer i, j, kk;
  reg signed [WB-1:0] ain, win;
  reg signed [AW-1:0] a, v;
  reg [{cw-1}:0] n;
  always @(posedge clk) begin
    done <= 0;
    if (rst) begin st <= IDLE; layer <= 0; tile <= 0; t <= 0; acc <= 0; areg <= 0; wreg <= 0; nxt <= 0; act <= 0; end
    else case (st)
      IDLE: if (start) begin act <= x; layer <= 0; tile <= 0; t <= 0; acc <= 0; areg <= 0; wreg <= 0; st <= RUN; end
      RUN: begin
        for (i = 0; i < R; i = i + 1)
          for (j = 0; j < C; j = j + 1) begin
            if (j == 0) begin
              kk = t - i;
              ain = (kk >= 0 && kk < {NIN}) ? act[(i*{NIN}+kk)*WB +: WB] : 0;
            end else ain = areg[(i*C+j-1)*WB +: WB];
            if (i == 0) begin
              kk = t - j;
              n = tile * C + j;
              win = (kk >= 0 && kk < {NIN}) ? wrom(layer, n, kk[{nw-1}:0]) : 0;
            end else win = wreg[((i-1)*C+j)*WB +: WB];
            a = acc[(i*C+j)*AW +: AW];
            acc[(i*C+j)*AW +: AW] <= a + ain * win;
            areg[(i*C+j)*WB +: WB] <= ain;
            wreg[(i*C+j)*WB +: WB] <= win;
          end
        if (t == {last}) st <= WBK; else t <= t + 1;
      end
      WBK: begin
        for (i = 0; i < R; i = i + 1)
          for (j = 0; j < C; j = j + 1) begin
            n = tile * C + j;
            if (n < (layer ? {NOUT} : {NH})) begin
              v = acc[(i*C+j)*AW +: AW] + brom(layer, n);
              if (layer == 0) begin
                v = (v < 0) ? 0 : (v >>> {q['s0']});
                if (v > QMAX) v = QMAX;
              end else begin
                v = v >>> {q['s1']};
                if (v > QMAX) v = QMAX;
                if (v < QMIN) v = QMIN;
              end
              nxt[(i*{NIN}+n)*WB +: WB] <= v[WB-1:0];
            end
          end
        acc <= 0; areg <= 0; wreg <= 0; t <= 0;
        if ((tile + 1) * C < (layer ? {NOUT} : {NH})) begin tile <= tile + 1; st <= RUN; end
        else if (layer == 0) begin layer <= 1; tile <= 0; st <= XFER; end
        else begin done <= 1; st <= IDLE; end
      end
      XFER: begin act <= nxt; st <= RUN; end
    endcase
  end
endmodule
"""
