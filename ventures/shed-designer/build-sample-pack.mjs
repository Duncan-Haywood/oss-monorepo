// Regenerates sample-build-pack.html from the real build pack on an invented builder, so the
// marketing page shows exactly what a buyer gets. Run: node build-sample-pack.mjs
import { writeFileSync } from "node:fs";
import { buildShed, normalize, PRESETS } from "./model.mjs";
import { estimate } from "./estimate.mjs";
import { buildInstructions } from "./instructions.mjs";
import { buildPackHtml } from "./buildpack.mjs";

const SAMPLE_LD = `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@type": "WebPage", name: "Sample shed build pack (invented builder)", description: "A sample of the shed designer's branded build pack, generated by the real code from an invented builder and the 8x12 preset. Not a real business; the pack is not on sale yet.", isPartOf: { "@type": "WebSite", name: "Shed designer" } })}</script>`;

export function samplePack() {
  const shed = buildShed(normalize(PRESETS["8x12"]()));
  const est = estimate(shed);
  const html = buildPackHtml(shed, est, buildInstructions(shed, est), { business: "Sample Sheds Co. (invented)", customer: "Sample customer", contact: "Sample only: not a real business", accent: "#784421", date: "2026-11-02", notes: "Delivery and site prep are quoted separately.\nCheck local code and permit rules before building." });
  // A published sample, not a product page: kept out of search results.
  return html.replace('<meta name="viewport"', `<meta name="robots" content="noindex">${SAMPLE_LD}<meta name="viewport"`);
}
if (process.argv[1] && process.argv[1].endsWith("build-sample-pack.mjs")) writeFileSync(new URL("./sample-build-pack.html", import.meta.url), samplePack());
