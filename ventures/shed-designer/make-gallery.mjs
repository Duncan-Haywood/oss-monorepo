// @ts-check
// Runs the gallery search (gallery.mjs) and writes its winners to
// gallery-data.mjs, which the page imports. Re-run after a change to the
// engine, the prices or the gallery entries:
//
//   node ventures/shed-designer/make-gallery.mjs           write the file
//   node ventures/shed-designer/make-gallery.mjs --check   exit 1 if it is stale
//
// It takes under a minute: two design searches (designsearch.mjs).

import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { generateGallery } from './gallery.mjs';

const OUT = fileURLToPath(new URL('./gallery-data.mjs', import.meta.url));

/** The module text for a generated gallery. @param {any[]} entries */
export function galleryModule(entries) {
  const rows = entries.map(({ id, title, reason, design }) => ({ id, title, reason, design }));
  return `// Generated by make-gallery.mjs from the searches in gallery.mjs. Do not edit by hand:
// gallery.test.mjs fails when this file and the engine disagree.
export const GALLERY_DESIGNS = ${JSON.stringify(rows, null, 1)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = galleryModule(generateGallery());
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (now !== text) { console.error('gallery-data.mjs is stale: run node ventures/shed-designer/make-gallery.mjs'); process.exit(1); }
    console.log('gallery-data.mjs is current');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
