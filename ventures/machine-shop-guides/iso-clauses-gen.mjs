// Writes iso-clauses.mjs: the 47 ISO 9001:2015 requirement clauses (numbers and headings only, the
// standard's table of contents) with CMMC Workspace's own "what a small shop keeps" prompt for each.
// The source is the workspace's clause library (ventures/cmmc/apps/cmmc/src/shared/quality/iso9001.ts,
// checked there against the contents page of ISO 9001:2015(E) on 2026-11-26), so the free checklist
// and the app's ISO 9001 tab and Audits tab list the same clauses. audit.test.mjs fails on drift.
// No requirement text of the standard is reproduced (ISO copyright).
//
// Run from this directory: node iso-clauses-gen.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SOURCE = new URL("../cmmc/apps/cmmc/src/shared/quality/iso9001.ts", import.meta.url);

/** Reads the ROWS literal out of iso9001.ts and the section headings above it. */
export function parse(ts) {
  const start = ts.indexOf("const ROWS: Row[] = [");
  const end = ts.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error("iso9001.ts: ROWS not found");
  const literal = ts.slice(ts.indexOf("= [", start) + 2, end + 2);
  // The literal is plain data (strings, arrays, true); JSON with trailing commas removed.
  const rows = JSON.parse(literal.replace(/,(\s*[\]}])/g, "$1"));
  const secBlock = ts.slice(ts.indexOf("export const ISO9001_SECTIONS = {"), ts.indexOf("} as const;"));
  const sections = Object.fromEntries([...secBlock.matchAll(/"(\d+)": "([^"]+)"/g)].map((m) => [m[1], m[2]]));
  return {
    sections,
    clauses: rows.map(([number, title, prompt, related, excl]) => ({
      number, title, prompt, related: related ?? [], ...(excl ? { oftenExcluded: true } : {}),
    })),
  };
}

export function render({ sections, clauses }) {
  return `// Generated by iso-clauses-gen.mjs from CMMC Workspace's ISO 9001 clause library
// (ventures/cmmc/apps/cmmc/src/shared/quality/iso9001.ts). Numbers and headings only, checked there
// against the contents page of ISO 9001:2015(E); each prompt is the workspace's own wording, not the
// standard's. Do not edit by hand.
export const SECTIONS = ${JSON.stringify(sections, null, 2)};

export const CLAUSES = [
${clauses.map((c) => `  ${JSON.stringify(c)},`).join("\n")}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("./iso-clauses.mjs", import.meta.url), render(parse(readFileSync(SOURCE, "utf8"))));
  console.log("iso-clauses.mjs written");
}
