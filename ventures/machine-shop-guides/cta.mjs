// The call to action at the foot of every machine-shop-guides page, switched in one place when a
// product opens (the pattern of ventures/pay-app-guides/cta.mjs).
//
// Each page keeps its own sentence about the two products (what each does for that page's job).
// What is shared, and written here so 21 pages cannot drift apart or keep saying "neither is
// released yet" after sign-ups open:
//   - the heading of the CTA card;
//   - the status: which product is open, what its free plan covers, and the sign-up link.
//
// Before launch (JOBSHOP_APP_URL null) the status is the sentence every page carried by hand before
// this file existed. Job Shop Quote (bet #2) opened on its free Early access plan with
// jobshop-quote-deploy run 46018975911 (2026-11-27, https://jobshop-quote.marisstella.app, health
// `{"ok":true,"email":true}`), so JOBSHOP_APP_URL is set. Each page links to
// `<app>/sign-up?from=machine-shop-guides/<page>`: `/sign-up` opens "Create your account"
// (apps/jobshop-quote/src/client/router.tsx) and `from` names the page that sent the visitor, for a
// later sign-up source report (the app ignores it today).
//
// The CMMC workspace (bet #4) is not open: set CMMC_APP_URL when its deploy answers healthy.
//
// Copy rules (ventures/jobshop-quote/apps/jobshop-site/README.md): no customer counts, ratings or
// outcomes; only what the Free plan does today (apps/jobshop-quote/src/shared/plans.ts, `free`);
// paid plans are not on sale until checkout is on (PAID_PLANS_ON); AI reading of RFQs ("Extract with
// AI") stays off until the owner sets its key (apps/jobshop-quote/docs/LAUNCH-REVIEW.md, section 1),
// so the status says so. page.test.mjs fails if a page's block is not what this file writes.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Job Shop Quote's origin (jobshop-quote-deploy run 46018975911). null shows the pre-launch text. */
export const JOBSHOP_APP_URL = "https://jobshop-quote.marisstella.app";
/** True once Paddle checkout is live in Job Shop Quote (apps/jobshop-quote/docs/BILLING.md). */
export const PAID_PLANS_ON = false;
/** True once "Extract with AI" has its key in production. */
export const AI_EXTRACTION_ON = false;
/** The CMMC workspace's origin once it is open; null while it is not. */
export const CMMC_APP_URL = null;

const INDUSTRY = "https://marisstella.app/industries/manufacturing/";

const START = "<!-- cta-status: generated by cta.mjs, do not edit by hand -->";
const END = "<!-- /cta-status -->";

// What the pages said by hand before this file.
const LEGACY_HEADING = "In development — early access";
const LEGACY_STATUS = "Neither is released yet.";
const LEGACY_READ = ` Read what is planned and how to get early access on the <a href="${INDUSTRY}">manufacturing page</a>.`;

export function signupUrl(appUrl, page) {
  const name = page.replace(/\.html$/, "");
  const from = name === "index" ? "machine-shop-guides" : `machine-shop-guides/${name}`;
  return `${appUrl.replace(/\/+$/, "")}/sign-up?from=${encodeURIComponent(from)}`;
}

export function heading(appUrl = JOBSHOP_APP_URL, cmmcUrl = CMMC_APP_URL) {
  if (!appUrl) return LEGACY_HEADING;
  return cmmcUrl ? "Both products are open, free to start" : "Quoting is open now; the CMMC workspace is coming";
}

export function status(page, opts = {}) {
  const { appUrl = JOBSHOP_APP_URL, paidOn = PAID_PLANS_ON, aiOn = AI_EXTRACTION_ON, cmmcUrl = CMMC_APP_URL } = opts;
  if (!appUrl) return `${LEGACY_STATUS}${LEGACY_READ}`;
  const link = signupUrl(appUrl, page).replace(/&/g, "&amp;");
  // The free plan's numbers are apps/jobshop-quote/src/shared/plans.ts (`free`); cta.test.mjs reads
  // that file so they cannot drift.
  const plan = paidOn
    ? "free for 40 RFQs a month and 3 users, then $199 or $399 a month"
    : "free early access for 40 RFQs a month and 3 users, no card; paid plans are not on sale yet";
  const ai = aiOn
    ? ""
    : " Reading an RFQ with AI is not switched on yet: you enter the part and the app prices it from your rate card, measures STEP, DXF, STL and IGES files, and writes the quote PDF.";
  const cmmc = cmmcUrl
    ? ` The <strong>CMMC workspace</strong> is open too: <a href="${cmmcUrl.replace(/\/+$/, "")}/">start it here</a>.`
    : ` The CMMC workspace is not released yet; read what is planned on the <a href="${INDUSTRY}">manufacturing page</a>.`;
  return `The RFQ-to-quote assistant, <strong>Job Shop Quote</strong>, is <strong>open now</strong>: ${plan}.${ai} <a href="${link}">Start free in Job Shop Quote</a>.${cmmc}`;
}

const SECTION = /(<section class="card cta" id="early-access">)([\s\S]*?)(<\/section>)/;
const H2 = /<h2>[^<]*<\/h2>/;

export function apply(html, page, opts = {}) {
  const m = SECTION.exec(html);
  if (!m) throw new Error(`${page}: no <section class="card cta" id="early-access">`);
  let body = m[2];
  if (!H2.test(body)) throw new Error(`${page}: CTA has no <h2>`);
  body = body.replace(H2, `<h2>${heading(opts.appUrl === undefined ? JOBSHOP_APP_URL : opts.appUrl, opts.cmmcUrl === undefined ? CMMC_APP_URL : opts.cmmcUrl)}</h2>`);
  const block = `${START}${status(page, opts)}${END}`;
  const at = body.indexOf(START);
  if (at >= 0) {
    body = body.slice(0, at) + block + body.slice(body.indexOf(END) + END.length);
  } else if (body.includes(LEGACY_STATUS)) {
    // Most pages end "Neither is released yet. Read what is planned ..."; one (the scoping
    // worksheet) has a sentence between the two. The block links the manufacturing page itself.
    body = body.replace(LEGACY_READ, "").replace(LEGACY_STATUS, block);
  } else {
    throw new Error(`${page}: CTA has neither the cta-status block nor the old status sentence`);
  }
  return html.slice(0, m.index) + m[1] + body + m[3] + html.slice(m.index + m[0].length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL("./", import.meta.url);
  let changed = 0;
  for (const name of readdirSync(dir).filter((f) => f.endsWith(".html"))) {
    const file = new URL(name, dir);
    const html = readFileSync(file, "utf8");
    const out = apply(html, name);
    if (out !== html) {
      writeFileSync(file, out);
      changed++;
    }
  }
  console.log(`cta.mjs: ${changed} page(s) updated`);
}
