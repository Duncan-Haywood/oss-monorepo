// The call to action at the foot of every machine-shop-guides page, written in one place so 21 pages
// cannot keep saying "neither is released yet" once the two products are open.
//
// The guides are the free front door to two paid bets that sell to the same small machine shops
// (portfolio/monetization/bets.md): #2 Job Shop Quote (ventures/jobshop-quote) and #4 CMMC Workspace
// (ventures/cmmc). Each page keeps its own sentence about what the products do for that page's job.
// This file writes the rest of the card:
//   - the heading;
//   - the product names in the lead ("an RFQ-to-quote assistant" becomes "Job Shop Quote, an
//     RFQ-to-quote assistant");
//   - the status sentence and the links at the end of the paragraph.
//
// A product with a null URL is described as in development, as every page said by hand before this
// file existed. With a URL, the page links to its sign-up page with `from=machine-shop-guides/<page>`,
// so a later sign-up source report can tell which guide sent the visitor:
//   - Job Shop Quote: `<url>/sign-up?from=...` (its router's sign-up route; live since
//     jobshop-quote-deploy run 46018975911, 2026-11-27);
//   - CMMC Workspace: `<url>/?signup&from=...` (opens "Create an account", apps/cmmc
//     src/client/lib/auth-mode.ts; live since cmmc-deploy run 46022366507, 2026-11-27).
// CMMC pages name the CMMC workspace first; quoting pages name Job Shop Quote first.
//
// Copy rules: no customer counts, ratings or outcomes; the free plans are stated as the apps' own
// plans.ts define them (cta.test.mjs reads both files); paid plans are "not on sale yet" until
// checkout is on; neither product certifies anyone (the card's note, which stays). Run `node cta.mjs`
// after a change here; page.test.mjs and cta.test.mjs fail if a page's card is not what this writes.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const PRODUCTS = {
  quote: {
    name: "Job Shop Quote",
    url: "https://jobshop-quote.marisstella.app",
    signupPath: "/sign-up?from=",
    // apps/jobshop-quote/src/shared/plans.ts, key "free" ("Early access").
    free: "40 RFQs a month and 3 users",
    paid: "its paid plans are not on sale yet",
    paidOn: false,
  },
  cmmc: {
    name: "CMMC Workspace",
    url: "https://cmmc.marisstella.app",
    signupPath: "/?signup&from=",
    // apps/cmmc/src/shared/plans.ts, key "free" ("Level 1").
    free: "Level 1, the 15 FAR 52.204-21 safeguards with evidence, the SSP and the pass/fail result, for 1 user",
    // Recording the 110 Level 2 requirements, the SPRS score and the POA&M is the paid Level 2 plan.
    paid: "Level 2, with the SPRS score and the POA&amp;M, is a paid plan that is not on sale yet",
    paidOn: false,
  },
};

const INDUSTRY = "https://marisstella.app/industries/manufacturing/";
const START = "<!-- cta-status: generated by cta.mjs, do not edit by hand -->";
const END = "<!-- /cta-status -->";

// What the pages said by hand before this file.
const LEGACY_HEADING = "<h2>In development — early access</h2>";
const LEGACY_LEAD = "We are building two paid products for small machine shops:";
const LEGACY_QUOTE = "an <strong>RFQ-to-quote assistant</strong> that";
const LEGACY_CMMC = "a <strong>CMMC Level 1/2 and ISO 9001 workspace</strong> that";
const LEGACY_NEITHER = "Neither is released yet. ";
const LEGACY_STATUS = `Read what is planned and how to get early access on the <a href="${INDUSTRY}">manufacturing page</a>.`;

const LIVE_LEAD = "Two hosted products for small machine shops:";
const LIVE_QUOTE = "<strong>Job Shop Quote</strong>, an RFQ-to-quote assistant that";
const LIVE_CMMC = "<strong>CMMC Workspace</strong>, a CMMC Level 1/2 and ISO 9001 workspace that";

const esc = (s) => s.replace(/&/g, "&amp;");

/** Pages about CMMC, NIST SP 800-171 or DFARS name the CMMC workspace first. */
export function isCmmcPage(page) {
  return /^(cmmc-|sprs-|nist-|ssp-|dfars-)/.test(page);
}

export function signupUrl(product, page) {
  const name = page.replace(/\.html$/, "");
  const from = name === "index" ? "machine-shop-guides" : `machine-shop-guides/${name}`;
  return `${product.url.replace(/\/+$/, "")}${product.signupPath}${encodeURIComponent(from)}`;
}

export function heading(products = PRODUCTS) {
  const open = [products.quote, products.cmmc].filter((p) => p.url).length;
  if (open === 0) return LEGACY_HEADING;
  return open === 2 ? "<h2>Open now, free to start</h2>" : "<h2>One open now, one in early access</h2>";
}

export function status(page, products = PRODUCTS) {
  const order = isCmmcPage(page) ? [products.cmmc, products.quote] : [products.quote, products.cmmc];
  const open = order.filter((p) => p.url);
  if (open.length === 0) return `${LEGACY_NEITHER.trim()} ${LEGACY_STATUS}`;
  const parts = order.map((p) =>
    p.url
      ? `${p.name} is open on a free plan with no card (${p.free})${p.paidOn ? "" : `; ${p.paid}`}.`
      : `${p.name} is in development, with early access.`,
  );
  const links = open.map((p) => `<a href="${esc(signupUrl(p, page))}">Start free in ${p.name}</a>`);
  links.push(`<a href="${INDUSTRY}">see both on the manufacturing page</a>`);
  return `${parts.join(" ")} ${links.join(" · ")}.`;
}

const SECTION = /(<section class="card cta" id="early-access">)([\s\S]*?)(<\/section>)/;

export function apply(html, page, products = PRODUCTS) {
  const m = SECTION.exec(html);
  if (!m) throw new Error(`${page}: no <section class="card cta" id="early-access">`);
  let body = m[2];
  const live = Boolean(products.quote.url || products.cmmc.url);
  // Heading: whatever h2 the card has becomes the generated one.
  body = body.replace(/<h2>[^<]*<\/h2>/, heading(products));
  // Lead and names, either direction.
  const swaps = live
    ? [[LEGACY_LEAD, LIVE_LEAD], [LEGACY_QUOTE, LIVE_QUOTE], [LEGACY_CMMC, LIVE_CMMC]]
    : [[LIVE_LEAD, LEGACY_LEAD], [LIVE_QUOTE, LEGACY_QUOTE], [LIVE_CMMC, LEGACY_CMMC]];
  for (const [from, to] of swaps) {
    body = body.replace(from, to);
    if (!body.includes(to)) throw new Error(`${page}: CTA lacks "${to}"`);
  }
  const block = `${START}${status(page, products)}${END}`;
  const at = body.indexOf(START);
  if (at >= 0) {
    body = body.slice(0, at) + block + body.slice(body.indexOf(END) + END.length);
  } else if (body.includes(LEGACY_STATUS)) {
    body = body.replace(LEGACY_NEITHER, "").replace(LEGACY_STATUS, block);
  } else {
    throw new Error(`${page}: CTA has neither the cta-status block nor the old status sentence`);
  }
  return html.slice(0, m.index) + m[1] + body + m[3] + html.slice(m.index + m[0].length);
}

export function pages(dir = new URL("./", import.meta.url)) {
  return readdirSync(dir).filter((f) => f.endsWith(".html") && SECTION.test(readFileSync(new URL(f, dir), "utf8")));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL("./", import.meta.url);
  for (const name of pages(dir)) {
    const file = new URL(name, dir);
    const html = readFileSync(file, "utf8");
    const out = apply(html, name);
    if (out !== html) {
      writeFileSync(file, out);
      console.log(`updated ${name}`);
    }
  }
}
