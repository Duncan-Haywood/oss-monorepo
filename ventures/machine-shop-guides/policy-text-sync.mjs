// Writes policy-text.mjs: the 110 NIST SP 800-171 Rev. 2 requirements in their official wording, the
// text the policy templates restate. The source is CMMC Workspace's official-text.json
// (ventures/cmmc/apps/cmmc/src/shared/controls/), which scripts/extract_official_text.py there
// extracts from NIST's own requirements spreadsheet (SP 800-171 Rev. 2, update 1), so the free page
// and the app's Policies tab restate the same words. policies.test.mjs fails when they drift.
//
// Run from this directory: node policy-text-sync.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SOURCE = new URL("../cmmc/apps/cmmc/src/shared/controls/official-text.json", import.meta.url);

export function render(official) {
  const rows = official.level2.map((r) => `  [${JSON.stringify(r.nistId)}, ${JSON.stringify(r.text)}],`);
  return `// Generated by policy-text-sync.mjs from CMMC Workspace's official-text.json, itself extracted from
// NIST's SP 800-171 Rev. 2 requirements spreadsheet:
// ${official.sources.reqs}
// Do not edit by hand.
export const REQUIREMENT_TEXT = new Map([
${rows.join("\n")}
]);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(JSON.parse(readFileSync(SOURCE, "utf8")));
  writeFileSync(new URL("./policy-text.mjs", import.meta.url), out);
  console.log("policy-text.mjs written");
}
