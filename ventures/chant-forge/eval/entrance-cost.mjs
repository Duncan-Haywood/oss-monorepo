// Short entrances: what a cost per section entrance trades on the 67-file corpus.
// node eval/entrance-cost.mjs > eval/entrance-cost-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc } from '../gabc.mjs';
import { splitVoices } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const events = files.map((f) => parseGabc(readFileSync(f, 'utf8')).events);
// Ranges are assumptions, not measurements: the same sets as eval/three-sections.mjs.
const SETS = [
  ['amateur', { low: 50, high: 65 }, { low: 47, high: 62 }, { low: 43, high: 60 }, 'T 50-65 D3-F4, Bar 47-62 B2-D4, B 43-60 G2-C4'],
  ['octave', { low: 52, high: 64 }, { low: 48, high: 60 }, { low: 45, high: 57 }, 'T 52-64 E3-E4, Bar 48-60 C3-C4, B 45-57 A2-A3'],
];
const COSTS = [0, 1, 2, 3, 4, 6, 8, 12, 16];
const pct = (a, b) => `${(100 * a / b).toFixed(1)}%`;
// entrances shorter than N notes: a section starts singing at a unit and stops again
// within N notes (counted per section from the tagged events, joins after the first note)
const lengths = [];
function shortEntrances(r, sections, n) {
  let short = 0, total = 0;
  const notes = r.events.filter((e) => e.type === 'note');
  for (const s of sections) {
    const sings = notes.map((e) => e.voice === 'all' || e.voice.split('+').includes(s));
    for (let i = 1; i < sings.length; i++) {
      if (!sings[i] || sings[i - 1]) continue;
      total++;
      let j = i; while (j < sings.length && sings[j]) j++;
      if (j < sings.length && j - i < n) short++;
      if (j < sings.length) lengths.push(j - i);
    }
  }
  return [short, total];
}
const out = [
  `# A cost on short entrances: corpus measurement (${files.length} files)`, '',
  'Generated by `node eval/entrance-cost.mjs`. `--entrance-cost N` charges each section entrance (a section starting to sing after the first note) N section-notes in the same currency as the notes a section does not sing, so a section that joins for a passage and leaves again is brought in only when it sings more than N notes there. Default mode (handoffs at a word only where no whole-phrase split fits), overlap on. Percentages are over the notes of the files that fit. "Short entrances" are entrances after which the section stops again within 4 notes. The textbook ranges are left out: with them the split is already nearly all full choir (14 changes of singer in 67 files).', '',
];
for (const [name, tenor, baritone, bass, label] of SETS) {
  out.push(`## ${name} (${label})`, '');
  for (const three of [false, true]) {
    const sections = three ? ['tenor', 'baritone', 'bass'] : ['tenor', 'bass'];
    out.push(`### ${three ? 'T, Bar, B' : 'T, B'}`, '', '| entrance cost | files that fit | full choir | two or more sections | one section alone | section-notes not sung | changes of singer | entrances | short entrances (< 4 notes) | breaks |', '|---|---|---|---|---|---|---|---|---|---|');
    for (const cost of COSTS) {
      let fit = 0, all = 0, notes = 0, twoPlus = 0, lone = 0, missing = 0, changes = 0, entrances = 0, short = 0, breaks = 0;
      for (const e of events) {
        const r = splitVoices(e, { tenor, bass, baritone: three ? baritone : null, overlap: true, entranceCost: cost });
        if (!r.fits) continue;
        fit++; all += r.allNotes; notes += r.notes; changes += r.changes; entrances += r.entrances; breaks += r.breaks;
        for (const [v, n] of Object.entries(r.voiceNotes)) {
          const size = v === 'all' ? sections.length : v.split('+').length;
          if (size >= 2) twoPlus += n; else lone += n;
          missing += (sections.length - size) * n;
        }
        short += shortEntrances(r, sections, 4)[0];
      }
      out.push(`| ${cost} | ${fit} | ${pct(all, notes)} | ${pct(twoPlus, notes)} | ${pct(lone, notes)} | ${missing} | ${changes} | ${entrances} | ${short} | ${breaks} |`);
    }
    out.push('');
  }
}
// how long a section sings after an entrance it later leaves, at cost 0 (octave, three sections)
lengths.length = 0;
{
  const [, tenor, baritone, bass] = SETS[1];
  for (const e of events) {
    const r = splitVoices(e, { tenor, bass, baritone, overlap: true });
    if (r.fits) shortEntrances(r, ['tenor', 'baritone', 'bass'], 4);
  }
  const bins = [[1, 3], [4, 7], [8, 15], [16, 31], [32, Infinity]];
  out.push('## How long an entering section stays (octave, T, Bar, B, cost 0)', '', 'Entrances the section later leaves again, by how many notes it sings before it leaves.', '', '| notes sung | entrances |', '|---|---|');
  for (const [a, b] of bins) out.push(`| ${b === Infinity ? `${a} or more` : `${a}-${b}`} | ${lengths.filter((x) => x >= a && x <= b).length} |`);
  const sorted = [...lengths].sort((x, y) => x - y);
  out.push('', `Median ${sorted[Math.floor(sorted.length / 2)]} notes over ${sorted.length} entrances.`, '');
}
console.log(out.join('\n'));
