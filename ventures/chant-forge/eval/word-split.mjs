// Handing over inside a phrase, at a word: what it buys on the 67-file corpus.
// node eval/word-split.mjs > eval/word-split-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc } from '../gabc.mjs';
import { splitVoices } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const events = files.map((f) => parseGabc(readFileSync(f, 'utf8')).events);
// Ranges are assumptions, not measurements: textbook sections, a narrower amateur
// pair, and octave-wide sections (a beginners' group).
const SETS = [
  ['textbook (T 48-69 C3-A4, B 40-64 E2-E4)', { low: 48, high: 69 }, { low: 40, high: 64 }],
  ['amateur (T 50-65 D3-F4, B 43-60 G2-C4)', { low: 50, high: 65 }, { low: 43, high: 60 }],
  ['octave (T 52-64 E3-E4, B 45-57 A2-A3)', { low: 52, high: 64 }, { low: 45, high: 57 }],
];
const MODES = [['never', 0, 'bars only'], ['needed', 0, 'words when needed (default)'], ['prefer', 3, '--split-words (cost 3)'], ['prefer', 0, '--split-words --word-cost 0']];
const out = [`# Handing over at a word: corpus measurement (${files.length} files)`, '', 'Generated by `node eval/word-split.mjs`. Full choir % is over the notes of the files that fit.', ''];
for (const [name, tenor, bass] of SETS) {
  out.push(`## ${name}`, '', '| mode | files that fit | full choir | changes of singer | handoffs inside a phrase | files with one |', '|---|---|---|---|---|---|');
  for (const [words, wordCost, label] of MODES) {
    let fit = 0, all = 0, notes = 0, changes = 0, handoffs = 0, withH = 0;
    for (const e of events) {
      const r = splitVoices(e, { tenor, bass, words, wordCost });
      if (!r.fits) continue;
      fit++; all += r.allNotes; notes += r.notes; changes += r.changes; handoffs += r.handoffs; if (r.handoffs) withH++;
    }
    out.push(`| ${label} | ${fit} | ${all} of ${notes} (${(100 * all / notes).toFixed(1)}%) | ${changes} | ${handoffs} | ${withH} |`);
  }
  out.push('');
}
console.log(out.join('\n'));
