// The fewest sections each --choir preset needs for every corpus file: unison, tenors
// and basses, three sections or TTBB. node eval/choir-presets.mjs > eval/choir-presets-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc, noteName } from '../gabc.mjs';
import { CHOIRS, CHOIR_NAMES, choirUnison, fewestSections, MENS_RANGE, suggestFinal } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const pieces = files.map((f) => ({ name: basename(f, '.gabc'), events: parseGabc(readFileSync(f, 'utf8')).events }));
const rn = (r) => `${noteName(r.low)}-${noteName(r.high)}`;
const LABEL = ['none fits', 'unison', 'T+B', 'T+Bar+B', 'TTBB'];
const out = [
  '# Choir presets: the fewest sections each choir needs',
  '',
  `Generated by \`node eval/choir-presets.mjs\` on ${files.length} corpus files. For each \`--choir\` preset the tool tries unison in the band every section reaches, then tenors and basses, then tenors, baritones and basses, then TTBB (\`fewestSections\` in voicefit.mjs; splits at a phrase, at a word only where no phrase split fits). The ranges are rules of thumb, not measurements of a choir. For comparison, the default unison range E2-E4 (the textbook bass range, which tenors cannot all reach) fits ${pieces.filter((p) => suggestFinal(p.events, MENS_RANGE).fits).length} of ${files.length}.`,
  '',
  '| choir | sections (T / T2 / Bar / B) | unison band | unison | T+B | T+Bar+B | TTBB | none fits |',
  '|---|---|---|---|---|---|---|---|',
];
const per = {};
for (const n of CHOIR_NAMES) {
  const c = CHOIRS[n];
  const counts = [0, 0, 0, 0, 0];
  per[n] = pieces.map((p) => { const v = fewestSections(p.events, c); counts[v.sections]++; return v.sections; });
  out.push(`| ${n} | ${rn(c.tenor)} / ${rn(c.tenor2)} / ${rn(c.baritone)} / ${rn(c.bass)} | ${rn(choirUnison(c))} | ${counts[1]} | ${counts[2]} | ${counts[3]} | ${counts[4]} | ${counts[0]} |`);
}
out.push('', '## Files that need more than tenors and basses, or that no preset fits', '', `| file | ${CHOIR_NAMES.join(' | ')} |`, `|---|${CHOIR_NAMES.map(() => '---').join('|')}|`);
pieces.forEach((p, i) => {
  if (CHOIR_NAMES.some((n) => per[n][i] === 0 || per[n][i] > 2)) out.push(`| ${p.name} | ${CHOIR_NAMES.map((n) => LABEL[per[n][i]]).join(' | ')} |`);
});
console.log(out.join('\n'));
