// Four sections (TTBB: first tenors, second tenors, baritones, basses) against three
// (tenors, baritones, basses) on the corpus.
// node eval/four-sections.mjs > eval/four-sections-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc } from '../gabc.mjs';
import { splitVoices } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const events = files.map((f) => parseGabc(readFileSync(f, 'utf8')).events);
const R = (low, high) => ({ low, high });
// Ranges are assumptions, not measurements. Each row compares a three-section choir from
// eval/three-sections.mjs with a TTBB choir built from it in two ways:
//   "split"  - the same tenors divided: first tenors keep the tenors' range, second tenors
//              take a range two semitones lower at the top (the choir's compass is unchanged);
//   "higher" - a first-tenor section a minor third above the tenors (the compass grows by 3).
const SETS = [
  ['textbook', R(48, 69), R(45, 65), R(40, 64), [
    ['split', R(48, 69), R(48, 67), 'T1 48-69 C3-A4, T2 48-67 C3-G4'],
    ['higher', R(51, 72), R(48, 69), 'T1 51-72 Eb3-C5, T2 48-69 C3-A4'],
  ], 'T 48-69 C3-A4, Bar 45-65 A2-F4, B 40-64 E2-E4'],
  ['amateur', R(50, 65), R(47, 62), R(43, 60), [
    ['split', R(50, 65), R(50, 63), 'T1 50-65 D3-F4, T2 50-63 D3-Eb4'],
    ['higher', R(53, 68), R(50, 65), 'T1 53-68 F3-Ab4, T2 50-65 D3-F4'],
  ], 'T 50-65 D3-F4, Bar 47-62 B2-D4, B 43-60 G2-C4'],
  ['octave', R(52, 64), R(48, 60), R(45, 57), [
    ['split', R(52, 64), R(50, 62), 'T1 52-64 E3-E4, T2 50-62 D3-D4'],
    ['higher', R(55, 67), R(52, 64), 'T1 55-67 G3-G4, T2 52-64 E3-E4'],
  ], 'T 52-64 E3-E4, Bar 48-60 C3-C4, B 45-57 A2-A3'],
];
const pct = (a, b) => (b ? `${(100 * a / b).toFixed(1)}%` : '-');
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor(s.length / 2)] : 0; };
function measure(opts) {
  const S = 3 + (opts.tenor2 ? 1 : 0);
  let fit = 0, notes = 0, all = 0, threePlus = 0, twoPlus = 0, lone = 0, changes = 0, entrances = 0, breaks = 0;
  const fitting = new Set();
  const secs = [];
  events.forEach((e, i) => {
    const r = splitVoices(e, { ...opts, overlap: true });
    if (!r.fits) return;
    fitting.add(basename(files[i]));
    fit++; notes += r.notes; all += r.allNotes; changes += r.changes; entrances += r.entrances; breaks += r.breaks;
    for (const [v, n] of Object.entries(r.voiceNotes)) {
      const size = v === 'all' ? r.sections.length : v.split('+').length;
      if (size >= 3) threePlus += n;
      if (size >= 2) twoPlus += n; else lone += n;
    }
    // mean sections singing per note, from each section's own note count
    secs.push(Object.values(r.sectionNotes).reduce((a, b) => a + b, 0) / r.notes);
  });
  return { S, fit, notes, all, threePlus, twoPlus, lone, changes, entrances, breaks, fitting, perNote: secs.length ? secs.reduce((a, b) => a + b, 0) / secs.length : 0, medPerNote: median(secs) };
}
const out = [
  `# Four sections (TTBB) against three: corpus measurement (${files.length} files)`, '',
  'Generated by `node eval/four-sections.mjs`, default word mode (a phrase is handed over at a word only where no whole-phrase split fits), overlap on. Percentages are over the notes of the files that fit with that choir. "Full choir" is every section singing; "three or more" and "two or more" count the notes sung by at least that many sections; "one alone" the notes a single section carries. "Sections per note" is the mean, over fitting files, of the number of sections singing a note, and "share of the choir" that number over the sections in the choir (with four sections the full choir is harder to reach, so the share compares the choirs more fairly than the full-choir column). Ranges are assumptions, not measurements.', '',
];
const gained = [];
for (const [name, tenor, baritone, bass, fours, label3] of SETS) {
  out.push(`## ${name}`, '', `Three sections: ${label3}. Four: the same baritones and basses with the tenors below.`, '',
    '| choir | tenors | files that fit | full choir | three or more | two or more | one alone | sections per note | share of the choir | changes of singer | entrances | breaks |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|');
  const three = measure({ tenor, baritone, bass });
  const row = (who, lab, m) => `| ${who} | ${lab} | ${m.fit} | ${pct(m.all, m.notes)} | ${pct(m.threePlus, m.notes)} | ${pct(m.twoPlus, m.notes)} | ${pct(m.lone, m.notes)} | ${m.perNote.toFixed(2)} | ${pct(m.perNote, m.S)} | ${m.changes} | ${m.entrances} | ${m.breaks} |`;
  out.push(row('T, Bar, B', label3.split(',')[0], three));
  for (const [kind, t1, t2, lab] of fours) {
    const four = measure({ tenor: t1, tenor2: t2, baritone, bass });
    out.push(row(`T1, T2, Bar, B (${kind})`, lab, four));
    // on the files both choirs fit: is the line carried by more sections with four?
    const both = [...three.fitting].filter((f) => four.fitting.has(f));
    gained.push([name, kind, [...four.fitting].filter((f) => !three.fitting.has(f)), [...three.fitting].filter((f) => !four.fitting.has(f)), both.length]);
  }
  out.push('');
}
out.push('## Files gained and lost', '');
for (const [name, kind, plus, minus, both] of gained) out.push(`- ${name}, ${kind}: fits with four only: ${plus.length ? plus.join(', ') : 'none'}; with three only: ${minus.length ? minus.join(', ') : 'none'}; both: ${both}`);
console.log(out.join('\n'));
