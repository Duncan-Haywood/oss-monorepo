// Overlapped handoffs: where tenors hand straight to basses (or back) inside a phrase, how
// often is there a note at the seam both sections can sing, so the line need not break?
// node eval/overlap-check.mjs > eval/overlap-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc } from '../gabc.mjs';
import { splitVoices } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const events = files.map((f) => parseGabc(readFileSync(f, 'utf8')).events);
// the same assumed ranges as eval/word-split.mjs
const SETS = [
  ['textbook (T 48-69 C3-A4, B 40-64 E2-E4)', { low: 48, high: 69 }, { low: 40, high: 64 }],
  ['amateur (T 50-65 D3-F4, B 43-60 G2-C4)', { low: 50, high: 65 }, { low: 43, high: 60 }],
  ['octave (T 52-64 E3-E4, B 45-57 A2-A3)', { low: 52, high: 64 }, { low: 45, high: 57 }],
];
const MODES = [['needed', 0, 'words when needed (default)'], ['prefer', 3, '--split-words (cost 3)'], ['prefer', 0, '--split-words --word-cost 0']];
const out = [
  `# Overlapped handoffs: corpus measurement (${files.length} files)`, '',
  'Generated by `node eval/overlap-check.mjs`. A *direct swap* is a handoff inside a phrase from tenors straight to basses or back (a handoff to or from the full choir never breaks the line). *Joins early*: the incoming section sings the outgoing section\'s last note with it; *holds on*: the outgoing section sings the incoming section\'s first note. *Breaks*: neither seam note is in both ranges.', '',
];
const examples = [];
for (const [name, tenor, bass] of SETS) {
  out.push(`## ${name}`, '', '| mode | files that fit | handoffs inside a phrase | direct swaps | joins early | holds on | breaks | full choir without / with overlap |', '|---|---|---|---|---|---|---|---|');
  for (const [words, wordCost, label] of MODES) {
    let fit = 0, handoffs = 0, early = 0, hold = 0, breaks = 0, all0 = 0, all1 = 0, notes = 0;
    events.forEach((e, n) => {
      const r0 = splitVoices(e, { tenor, bass, words, wordCost });
      const r = splitVoices(e, { tenor, bass, words, wordCost, overlap: true });
      if (!r.fits) return;
      fit++; handoffs += r.handoffs; breaks += r.breaks; notes += r.notes; all0 += r0.allNotes; all1 += r.allNotes;
      for (const o of r.overlaps) { if (o.how === 'joins early') early++; else hold++; }
      if (r.overlaps.length && examples.length < 6 && label.includes('cost 3')) examples.push(`- ${name.split(' ')[0]}, ${files[n].split('/').slice(-1)[0]}: ${r.overlaps.map((o) => `phrase ${o.phrase + 1}, ${o.from === "bass" ? "basses" : "tenors"} to ${o.to === "bass" ? "basses" : "tenors"}, ${o.how === 'joins early' ? 'joins early on' : 'holds on for'} ${o.note} "${o.syllable}"`).join('; ')}`);
    });
    const pct = (a) => `${(100 * a / notes).toFixed(1)}%`;
    out.push(`| ${label} | ${fit} | ${handoffs} | ${early + hold + breaks} | ${early} | ${hold} | ${breaks} | ${pct(all0)} / ${pct(all1)} |`);
  }
  out.push('');
}
out.push('## Examples (--split-words, cost 3)', '', ...examples, '');
console.log(out.join('\n'));
