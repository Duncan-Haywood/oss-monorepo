// Three sections (tenors, baritones, basses) against two, on the 67-file corpus.
// node eval/three-sections.mjs > eval/three-sections-report.md
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGabc } from '../gabc.mjs';
import { splitVoices } from '../voicefit.mjs';

const corpus = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const files = [
  ...readdirSync(join(corpus, 'gregobase-1908')).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, 'gregobase-1908', f)),
  ...readdirSync(corpus).filter((f) => f.endsWith('.gabc')).map((f) => join(corpus, f)),
];
const events = files.map((f) => parseGabc(readFileSync(f, 'utf8')).events);
// Ranges are assumptions, not measurements: the same three tenor/bass pairs as
// eval/word-split.mjs, each with a baritone section between them.
const SETS = [
  ['textbook', { low: 48, high: 69 }, { low: 45, high: 65 }, { low: 40, high: 64 }, 'T 48-69 C3-A4, Bar 45-65 A2-F4, B 40-64 E2-E4'],
  ['amateur', { low: 50, high: 65 }, { low: 47, high: 62 }, { low: 43, high: 60 }, 'T 50-65 D3-F4, Bar 47-62 B2-D4, B 43-60 G2-C4'],
  ['octave', { low: 52, high: 64 }, { low: 48, high: 60 }, { low: 45, high: 57 }, 'T 52-64 E3-E4, Bar 48-60 C3-C4, B 45-57 A2-A3'],
];
const MODES = [['needed', 0, 'words when needed (default)'], ['prefer', 3, '--split-words (cost 3)']];
const pct = (a, b) => `${(100 * a / b).toFixed(1)}%`;
const out = [
  `# Three sections against two: corpus measurement (${files.length} files)`, '',
  'Generated by `node eval/three-sections.mjs`. Percentages are over the notes of the files that fit with that choir. "Two or more sections" is the share of notes at least two sections sing together (with two sections, the full choir); "one section alone" is the share where a single section carries the line. Overlap is on (`--overlap`) for the last two columns.', '',
];
const gained = new Map();
for (const [name, tenor, baritone, bass, label] of SETS) {
  out.push(`## ${name} (${label})`, '', '| choir | mode | files that fit | full choir | two or more sections | one section alone | changes of singer | handoffs inside a phrase | overlaps | breaks |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const [words, wordCost, mlabel] of MODES) {
    for (const three of [false, true]) {
      let fit = 0, all = 0, notes = 0, twoPlus = 0, lone = 0, changes = 0, handoffs = 0, overlaps = 0, breaks = 0;
      events.forEach((e, i) => {
        const r = splitVoices(e, { tenor, bass, baritone: three ? baritone : null, words, wordCost, overlap: true });
        if (!r.fits) return;
        if (three && words === 'needed' && !splitVoices(e, { tenor, bass, words }).fits) {
          if (!gained.has(name)) gained.set(name, []);
          gained.get(name).push(basename(files[i]));
        }
        fit++; all += r.allNotes; notes += r.notes; changes += r.changes; handoffs += r.handoffs; overlaps += r.overlaps.length; breaks += r.breaks;
        for (const [v, n] of Object.entries(r.voiceNotes)) (v === 'all' || v.includes('+') ? (twoPlus += n) : (lone += n));
      });
      out.push(`| ${three ? 'T, Bar, B' : 'T, B'} | ${mlabel} | ${fit} | ${all} of ${notes} (${pct(all, notes)}) | ${pct(twoPlus, notes)} | ${pct(lone, notes)} | ${changes} | ${handoffs} | ${overlaps} | ${breaks} |`);
    }
  }
  out.push('');
}
out.push('## Files that fit only with baritones (default mode)', '');
for (const [name] of SETS) out.push(`- ${name}: ${gained.has(name) ? gained.get(name).join(', ') : 'none'}`);
console.log(out.join('\n'));
