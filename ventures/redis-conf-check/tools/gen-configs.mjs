#!/usr/bin/env node
// Regenerates redis70.mjs from Redis 7.0.15's src/config.c (the
// static_configs[] table) and a running redis-server 7.0.15 (COMMAND LIST,
// ACL CAT). Run once by hand; the output is committed.
//
//   (cd "$(mktemp -d)" && redis-server --port 7010 &)   # defaults only, no file
//   node tools/gen-configs.mjs path/to/redis-7.0.15/src/config.c 7010 > redis70.mjs
//
// Only names, types, bounds, defaults and enum values are taken: facts about
// the configuration format, not code. Redis 7.0 is BSD-3-Clause licensed.
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const [src, port] = process.argv.slice(2);
const c = readFileSync(src, "utf8");
const C = {
  INT_MAX: 2147483647n, INT_MIN: -2147483648n, UINT_MAX: 4294967295n,
  LONG_MAX: 9223372036854775807n, LLONG_MAX: 9223372036854775807n,
  ULLONG_MAX: 18446744073709551615n, SSIZE_MAX: 9223372036854775807n,
  CONFIG_DEFAULT_HZ: 10n, LOG_LOCAL0: 128n,
};
function num(expr) {
  let e = expr.trim().replace(/\b(\d+)(?:ll|LL|L|l)\b/g, "$1").replace(/\b0(\d+)\b/g, (m, d) => String(parseInt(d, 8)));
  e = e.replace(/\b[A-Z_][A-Z0-9_]*\b/g, (n) => { if (!(n in C)) throw new Error(`unknown constant ${n} in ${expr}`); return `(${C[n]}n)`; });
  e = e.replace(/\b(\d+)\b(?!n)/g, "$1n");
  return Function(`return (${e})`)();
}
const enums = {};
for (const m of c.matchAll(/configEnum (\w+)\[\] = \{([\s\S]*?)\{NULL/g)) enums[m[1]] = [...m[2].matchAll(/\{"([^"]+)",\s*([^}]+)\}/g)].map((x) => x[1]);
const table = c.slice(c.indexOf("standardConfig static_configs[] = {"), c.indexOf("{NULL}\n};"));
const out = [];
let tls = false;
for (const line of table.split("\n")) {
  if (/#ifdef USE_OPENSSL/.test(line)) tls = true;
  if (/#endif/.test(line)) tls = false;
  const m = line.match(/create(\w+)Config\((.*)\),?\s*(\/\*.*)?$/);
  if (!m) continue;
  const args = []; let depth = 0, cur = "", q = false;
  for (const ch of m[2]) {
    if (ch === '"') q = !q;
    if (!q && ch === "(") depth++;
    if (!q && ch === ")") depth--;
    if (!q && depth === 0 && ch === ",") { args.push(cur.trim()); cur = ""; } else cur += ch;
  }
  args.push(cur.trim());
  const str = (s) => (s === "NULL" ? null : s.startsWith("\"") ? JSON.parse(s) : undefined);
  const kind = m[1];
  const e = { name: str(args[0]), alias: str(args[1]), flags: args[2].split("|").map((s) => s.trim().replace(/_CONFIG$/, "").toLowerCase()) };
  if (tls) e.tls = true;
  if (kind === "Bool") Object.assign(e, { type: "bool", def: args[4] === "1" ? "yes" : "no" });
  else if (kind === "String" || kind === "SDS") Object.assign(e, { type: "string", emptyIsNull: args[3] === "EMPTY_STRING_IS_NULL", def: str(args[5]) === null ? "" : str(args[5]), valid: args[6] === "NULL" ? null : args[6] });
  else if (kind === "Enum") {
    const vals = enums[args[3]];
    Object.assign(e, { type: "enum", values: vals, valid: args[7] === "NULL" ? null : args[7] });
  } else if (kind === "Special") Object.assign(e, { type: "special" });
  else {
    const numericType = { Int: "int", UInt: "uint", ULong: "ulong", LongLong: "longlong", ULongLong: "ulonglong", SizeT: "size_t", SSizeT: "ssize_t", TimeT: "time_t", OffT: "off_t" }[kind];
    const nflags = args[7].split("|").map((s) => s.trim().replace(/_CONFIG$/, "").toLowerCase()).filter((f) => f !== "integer");
    Object.assign(e, { type: "numeric", numericType, min: String(num(args[3])), max: String(num(args[4])), def: String(num(args[6])), numFlags: nflags });
  }
  out.push(e);
}
const cli = (...a) => execFileSync("redis-cli", ["-p", port, ...a], { encoding: "utf8" }).replace(/\n$/, "").split("\n");
const commands = cli("COMMAND", "LIST").sort();
const categories = cli("ACL", "CAT");
const byCategory = Object.fromEntries(categories.map((cat) => [cat, cli("ACL", "CAT", cat).filter(Boolean).sort()]));
// Enum defaults as CONFIG GET prints them, from the live server.
const live = cli("CONFIG", "GET", "*");
const liveMap = {}; for (let i = 0; i < live.length; i += 2) liveMap[live[i]] = live[i + 1];
for (const e of out) if (e.type !== "numeric" && e.type !== "bool") e.def = liveMap[e.name] ?? null;
// dir is the server's working directory, not a fixed default.
for (const e of out) if (e.name === "dir") e.def = null;
process.stdout.write(`// Generated by tools/gen-configs.mjs from Redis 7.0.15 (src/config.c's
// static_configs[] table, and COMMAND LIST / ACL CAT on redis-server 7.0.15).
// Redis 7.0 is BSD-3-Clause; this is a table of facts about its configuration
// format. Do not edit by hand.
export const VERSION = "7.0.15";
export const CONFIGS = ${JSON.stringify(out, null, 0).replace(/\},\{/g, "},\n  {")};
export const COMMANDS = ${JSON.stringify(commands)};
export const CATEGORIES = ${JSON.stringify(categories)};
export const CATEGORY_COMMANDS = ${JSON.stringify(byCategory)};
`);
