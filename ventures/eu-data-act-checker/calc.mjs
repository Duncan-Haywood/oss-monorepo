// EU Data Act (Regulation (EU) 2023/2854) applicability check from a business's role, size and EU
// reach. Pure functions, no I/O. Bad input is rejected with a message, never clamped. Encodes the
// micro and small enterprise exemptions (Art 7 for Chapter II, Art 14 for business-to-government
// requests) on the Recommendation 2003/361/EC ceilings, and the dates in Art 50, Art 3(1), Art 13
// and Art 29. It does not model partner-enterprise proportional size; the answer is a first read.

export const ROLES = [
  { id: "none", label: "None of the roles below", chapter: null },
  { id: "manufacturer", label: "Manufacturer of a connected product (a product that gets or generates data about its use and can send it)", chapter: "II" },
  { id: "service", label: "Provider of a related service (software or app connected to the product that affects what it does)", chapter: "II" },
  { id: "holder", label: "Data holder (you hold or control data generated by a customer's connected product and can make it available)", chapter: "II" },
  { id: "cloud", label: "Provider of a data processing service (cloud, SaaS, IaaS, PaaS or edge service customers can switch away from)", chapter: "VI" },
  { id: "recipient", label: "Third party that asks a data holder for a user's connected-product data", chapter: "III" },
];

export const SIZES = ["micro", "small", "notsmall"];
export const SIZE_LABEL = { micro: "microenterprise", small: "small enterprise", notsmall: "medium or large enterprise" };

// Recommendation 2003/361/EC Article 2: micro under 10 people and EUR 2M turnover or balance sheet;
// small under 50 people and EUR 10M. Whole-group figures; linked enterprises count in full.
export function sizeClass(staff, turnoverM, balanceM) {
  if (staff < 10 && (turnoverM <= 2 || balanceM <= 2)) return "micro";
  if (staff < 50 && (turnoverM <= 10 || balanceM <= 10)) return "small";
  return "notsmall";
}

function num(raw, name, errors) {
  const s = raw === undefined || raw === null ? "" : String(raw).trim().replace(/[€,\s]/g, "");
  if (s === "") { errors.push(`${name} is required (enter 0 if none).`); return 0; }
  const v = Number(s);
  if (!Number.isFinite(v)) { errors.push(`${name} must be a number.`); return 0; }
  if (v < 0) { errors.push(`${name} cannot be negative.`); return 0; }
  return v;
}

const yes = (v) => Boolean(v) && v !== "0" && v !== "no";

export function parse(input) {
  const errors = [];
  const i = input || {};
  const role = ROLES.find((r) => r.id === i.role);
  if (!role) errors.push("Choose your role.");
  const staff = num(i.staff, "Staff (people employed, whole group)", errors);
  const turnover = num(i.turnover, "Annual turnover (EUR millions)", errors);
  const balance = num(i.balance, "Annual balance sheet total (EUR millions)", errors);
  const eu = ["yes", "no", "unsure"].includes(i.eu) ? i.eu : "yes";
  return { errors, role, staff, turnover, balance, eu, partner: yes(i.partner), subcontract: yes(i.subcontract) };
}

// One decision. `size` is the size class the group is treated as having.
export function classify({ role, size, eu = "yes", partner = false, subcontract = false }) {
  if (eu === "no") {
    return { status: "out", via: "Art 1(3)", reason: "The Regulation reaches products placed on the Union market, users in the Union and data recipients there, wherever you are established. Without any of those, it does not apply directly." };
  }
  if (!role || role.chapter === null) {
    return { status: "out", via: "Art 1, Art 2", reason: "None of the roles the Regulation addresses describes you, so it does not apply directly." };
  }
  if (role.chapter === "VI") {
    return { status: "in", via: "Art 23 to 31", reason: "The switching duties for data processing services have no size exemption. Small providers are covered; Article 31 only eases some duties for custom-built services and non-production versions." };
  }
  if (role.chapter === "III") {
    return { status: "in", via: "Art 5, Art 6", reason: "Third parties receiving a user's data carry the conditions in Article 6 whatever their size. A gatekeeper under the Digital Markets Act cannot be one (Art 5(3))." };
  }
  const small = size === "micro" || size === "small";
  if (small && !partner && !subcontract) {
    return { status: "exempt-small", via: "Art 7", reason: "Micro and small enterprises are exempt from the Chapter II data-access duties for the connected products they make and services they provide, provided they have no larger partner or linked enterprise and are not subcontracted to make or design the product for one." };
  }
  if (small) {
    return { status: "in", via: `Art 2, Art 7, ${role.chapter === "II" ? "Art 3 to 5" : ""}`.replace(/, $/, ""), reason: partner ? "A larger partner or linked enterprise removes the small-enterprise exemption: size is judged on the group." : "Being subcontracted to make or design the product or service for a larger company removes the small-enterprise exemption." };
  }
  return { status: "in", via: "Art 3 to 5", reason: "You are not a micro or small enterprise, so the Chapter II duties on connected-product data apply to you." };
}

