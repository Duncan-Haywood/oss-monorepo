export function compute(input) {
  const p = parse(input);
  if (p.errors.length) return { errors: p.errors };
  const size = sizeClass(p.staff, p.turnover, p.balance);
  const base = { role: p.role, eu: p.eu, partner: p.partner, subcontract: p.subcontract };
  const verdict = classify({ ...base, size });
  const ladder = SIZES.map((s) => ({ size: s, ...classify({ ...base, size: s }) }));
  const findings = [];
  const inScope = verdict.status === "in";
  if (inScope) {
    findings.push({ severity: "high", title: `Likely in scope (${verdict.via}). The Regulation has applied since 12 September 2025.` });
    if (p.role.id === "manufacturer") findings.push({ severity: "medium", title: "The access-by-design duty in Art 3(1) applies to connected products placed on the market after 12 September 2026. Products already on the market still carry the Art 4 and Art 5 request duties." });
    findings.push({ severity: "medium", title: "Enforcement and penalties are set by each Member State's competent authorities (Art 37, Art 40). Personal data stays under the GDPR; the Data Act does not replace it." });
    if (p.role.chapter === "II") findings.push({ severity: "info", title: "Contract terms imposed on another business about data access are tested for unfairness (Art 13). From 12 September 2027 that also reaches older indefinite or long-running contracts." });
  } else if (verdict.status === "exempt-small") {
    findings.push({ severity: "medium", title: "Exempt from the Chapter II duties as a micro or small enterprise (Art 7). The exemption is judged on the whole group and is lost with a larger partner or linked enterprise. A medium enterprise keeps it for about a year after growing past small, so recheck when you grow." });
    findings.push({ severity: "info", title: "Customers and larger partners may still ask for data access by contract. If another company makes your product data available, that company has the duty." });
  } else {
    findings.push({ severity: "info", title: "Not in scope directly on these answers." });
  }
  if (p.eu === "unsure") findings.push({ severity: "medium", title: "You answered unsure on whether you reach the Union. Settle that first: it decides whether the Regulation applies at all." });
  if ((p.partner || p.subcontract) && p.role && p.role.chapter === "II" && (size === "micro" || size === "small")) findings.push({ severity: "medium", title: "You marked a larger partner, linked enterprise or subcontracting. That removes the Art 7 exemption even at this size." });
  findings.push({ severity: "info", title: "Partner-enterprise proportional size rules are not applied here beyond the yes or no answer above. Enter whole-group figures." });
  return {
    errors: [], size, sizeLabel: SIZE_LABEL[size], role: p.role, verdict, ladder, findings,
    obligations: inScope ? OBLIGATIONS[p.role.id] : [],
    input: { staff: p.staff, turnover: p.turnover, balance: p.balance, eu: p.eu, partner: p.partner, subcontract: p.subcontract },
  };
}

export const SAMPLE = { role: "manufacturer", staff: "35", turnover: "6", balance: "4", eu: "yes", partner: "", subcontract: "" };

const STATUS_TEXT = { in: "in scope", "exempt-small": "exempt as a micro or small enterprise", out: "not in scope directly" };

export function summaryText(r) {
  const v = r.verdict;
  const lines = [
    "EU Data Act check (first read, not legal advice)",
    `Role: ${r.role.label}`,
    `Size on whole-group figures: ${r.sizeLabel} (${r.input.staff} people, EUR ${r.input.turnover}M turnover, EUR ${r.input.balance}M balance sheet)`,
    `Result: ${STATUS_TEXT[v.status]} [${v.via}]`,
    v.reason,
    "",
    "Same business at each size class:",
    ...r.ladder.map((l) => `  ${SIZE_LABEL[l.size]}: ${STATUS_TEXT[l.status]}`),
  ];
  if (r.obligations.length) lines.push("", "Main duties:", ...r.obligations.map((o) => `  - ${o}`));
  lines.push("", "The Regulation is enforced by national authorities and some dates depend on when a product was placed on the market. Confirm with your authority or counsel.");
  return lines.join("\n");
}

export function ladderCsv(r) {
  return ["size,status,basis", ...r.ladder.map((l) => [SIZE_LABEL[l.size], l.status, l.via].map((c) => `"${String(c).replace(/"/g, '""')}"`).join(","))].join("\n");
}
