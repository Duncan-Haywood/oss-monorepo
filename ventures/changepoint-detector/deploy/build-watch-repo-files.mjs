#!/usr/bin/env node
// Writes watch-repo-files.mjs: the text files deploy/make-watch-repo.sh writes or copies that the published site does
// not serve (the workflow, LICENSE, the README, package.json, .gitignore), so the watch page can build the same
// repository in the browser without a terminal. The site serves the .mjs modules themselves, so they are fetched,
// not copied in here.
//   node deploy/build-watch-repo-files.mjs          rewrite watch-repo-files.mjs
//   node deploy/build-watch-repo-files.mjs --check  exit 1 if it is out of date (watch-repo.test.mjs runs this)
import { readFileSync, writeFileSync } from 'node:fs';

const here = (p) => new URL(`../${p}`, import.meta.url);
const sh = readFileSync(here('deploy/make-watch-repo.sh'), 'utf8');

// The README is the script's heredoc; package.json and .gitignore are its printf lines. Read them from the script so
// the two ways of making the repository cannot drift apart.
const readme = sh.match(/cat > "\$DEST\/README\.md" <<'MD'\n([\s\S]*?)\nMD\n/);
if (!readme) throw new Error('README heredoc not found in make-watch-repo.sh');
const printf = (target) => {
  const m = sh.match(new RegExp(`printf '((?:[^'\\\\]|\\\\.)*)' > "\\$DEST/${target.replace('.', '\\.')}"`));
  if (!m) throw new Error(`printf for ${target} not found in make-watch-repo.sh`);
  return m[1].replace(/\\n/g, '\n');
};
const list = sh.match(/^for f in ([^;]+); do get/m);
if (!list) throw new Error('file list not found in make-watch-repo.sh');
const copied = list[1].trim().split(/\s+/);

export function render() {
  const files = {
    'README.md': `${readme[1]}\n`,
    'package.json': printf('package.json'),
    '.gitignore': printf('.gitignore'),
    LICENSE: readFileSync(here('LICENSE'), 'utf8'),
  };
  const workflow = readFileSync(here('deploy/watch-metric.yml'), 'utf8');
  return `// Generated by deploy/build-watch-repo-files.mjs from deploy/make-watch-repo.sh, deploy/watch-metric.yml and LICENSE.
// Do not edit: change those and run \`node deploy/build-watch-repo-files.mjs\`.
export const MODULES = ${JSON.stringify(copied.filter((f) => f.endsWith('.mjs')))};
export const TEXT_FILES = ${JSON.stringify(files, null, 2)};
export const WORKFLOW_PATH = '.github/workflows/watch-metric.yml';
// One string per line, so no line of this file reads as a minified bundle (platform/ci/check_third_party.py).
export const WORKFLOW = [
${workflow.split('\n').map((l) => `  ${JSON.stringify(l)},`).join('\n')}
].join('\\n');
`;
}

const isMain = process.argv[1] && new URL(import.meta.url).pathname === process.argv[1];
if (isMain) {
  const out = here('watch-repo-files.mjs');
  const next = render();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
    if (now !== next) { console.error('watch-repo-files.mjs is out of date: run node deploy/build-watch-repo-files.mjs'); process.exit(1); }
  } else {
    writeFileSync(out, next);
    console.log('wrote watch-repo-files.mjs');
  }
}
