/** spread (logits) -> what the column means to a reader. */
export const KINDS = [
  { spread: 100, key: "clear", label: "Clear-cut", gloss: "never picks against their own order" },
  { spread: 6, key: "ordinary", label: "Ordinary", gloss: "picks their favourite over their least favourite 998 times in 1,000, but finds neighbours on a 15-option list a 61/39 call" },
  { spread: 3, key: "close", label: "Close calls", gloss: "picks their favourite over their least favourite 95 times in 100, and finds neighbours on a 15-option list a 55/45 call" },
];

export function loadRows(path = DATA) {
  return readFileSync(path, "utf8").trim().split("\n").map((l) => JSON.parse(l));
}

/** One row per list length: { n, allPairs, sortBound, cap, clear: {...}, ordinary: {...}, close: {...} }. */
export function byLength(rows) {
  const out = new Map();
  for (const r of rows) {
    const kind = KINDS.find((k) => k.spread === r.spread);
    if (!kind) continue;
    const row = out.get(r.n) || { n: r.n, allPairs: r.allPairs, sortBound: r.sortBound, cap: r.cap };
    row[kind.key] = { mean: Math.round(r.picksMean), min: r.picksMin, max: r.picksMax, atCap: r.atCap, runs: r.runs, spearman: r.trueSpearman, topRight: r.topRight, onceSpearman: r.allPairsSpearman, onceTopRight: r.allPairsTopRight };
    out.set(r.n, row);
  }
  return [...out.values()].filter((r) => KINDS.every((k) => r[k.key])).sort((a, b) => a.n - b.n);
}

export function renderModule(table) {
  const compact = table.map((r) => [r.n, r.clear.mean, r.ordinary.mean, r.close.mean]);
  return `// GENERATED by scripts/build-picks-page.mjs from docs/picks-needed-2026-11-14.jsonl. Do not edit.
// [options, mean picks to stop: clear-cut, ordinary, close calls] on simulated people
// running the ranker's own question picker, stop rule and cap.
export const PICKS_MEASURED = ${JSON.stringify(compact)};

/**
 * Measured picks for a list of n options, interpolated between measured
 * lengths: { at, clear, ordinary, close }. Past the longest measured list it
 * returns that list's numbers with \`at\` set to its length, so the caller
 * can say so rather than extrapolate.
 */
export function picksGuide(n) {
  const t = PICKS_MEASURED;
  const longest = t.at(-1);
  if (n > longest[0]) return { at: longest[0], clear: longest[1], ordinary: longest[2], close: longest[3] };
  let i = t.findIndex((r) => r[0] >= n);
  if (i === -1) i = t.length - 1;
  if (i === 0) i = 1;
  const [n0, ...a] = t[i - 1], [n1, ...b] = t[i];
  const w = Math.min(1, Math.max(0, (n - n0) / (n1 - n0)));
  const at = (k) => Math.max(1, Math.round(a[k] + w * (b[k] - a[k])));
  return { at: n, clear: at(0), ordinary: at(1), close: at(2) };
}
`;
}

const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const pct = (k, d) => `${Math.round((100 * k) / d)}%`;

/** The few sentences the page states as findings, each computed from the table (never typed in). */
export function findings(table) {
  const at = (n) => table.find((r) => r.n === n);
  const firstBeat = table.find((r) => r.ordinary.mean < r.allPairs);
  const big = table.at(-1);
  const mid = at(20) || table[Math.floor(table.length / 2)];
  const shortCap = table.filter((r) => r.n <= 6);
  const capShare = shortCap.reduce((s, r) => s + r.close.atCap, 0) / shortCap.reduce((s, r) => s + r.close.runs, 0);
  const short = table.filter((r) => r.n < (firstBeat ? firstBeat.n : Infinity));
  return { firstBeat, big, mid, shortCap, capShare, short };
}

/** How the clear-cut column compares with log2(n!), worded from the numbers. */
export function sortVerdict(table) {
  const above = table.filter((r) => r.clear.mean > r.sortBound), below = table.filter((r) => r.clear.mean < r.sortBound);
  const a = above.at(-1), b = below[0];
  let t = a ? `At ${a.n} options the minimum is ${a.sortBound} and a never-wrong person was asked ${a.clear.mean}: the ranker allows for the odd slip, so it won't call an order settled on one answer per pair.` : "";
  if (b) t += ` From ${b.n} options it stopped below the minimum (${b.clear.mean} against ${b.sortBound}${table.at(-1) !== b ? `; ${table.at(-1).clear.mean} against ${table.at(-1).sortBound} at ${table.at(-1).n}` : ""}), because it stops when the order is 90% settled, not exact: those orders scored ${b.clear.spearman.toFixed(2)} Spearman, nearly but not always perfect.`;
  return t.trim();
}

/** A verdict on every-pair-once for short lists, worded from the numbers, not chosen in advance. */
export function shortVerdict(short) {
  if (!short.length) return "";
  const gap = short.reduce((s, r) => s + (r.ordinary.spearman - r.ordinary.onceSpearman), 0) / short.length;
  if (gap > 0.02) return `the ranker's extra questions buy a better order (${gap.toFixed(2)} Spearman on average), so they are worth answering if you have the minute.`;
  if (gap < -0.02) return `the single round was more accurate as well as shorter, so for a list this short, a round of every pair is the better tool.`;
  return `about as good (within ${Math.abs(gap).toFixed(2)} on average), so on a list this short a single round of every pair is a fine shortcut.`;
}

