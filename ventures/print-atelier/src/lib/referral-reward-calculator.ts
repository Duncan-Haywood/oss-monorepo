/**
 * Automated Referral Viral Coefficient & Collector Invite Reward Calculator
 * 
 * Measures collector referral invite conversion rates, calculates viral K-factor coefficients,
 * and issues tiered store credit rewards and VIP discount vouchers to boost collector acquisition.
 */

export type CollectorTier = "collector_bronze" | "collector_silver" | "collector_gold" | "collector_platinum";

export interface ReferralActivity {
  referrerId: string;
  referrerTier: CollectorTier;
  invitesSent: number;
  invitesConverted: number; // Successful purchases by referred collectors
  totalReferredSpendUsdCents: number; // Total revenue generated by invitees
}

export interface ReferralRewardResult {
  referrerId: string;
  referrerTier: CollectorTier;
  invitesSent: number;
  invitesConverted: number;
  conversionRatePercent: number;
  viralKFactor: number; // K-Factor coefficient (K = i * c)
  earnedRewardCreditsUsdCents: number;
  discountVoucherPercent: number;
  isViralAdvocate: boolean; // True if K-Factor >= 1.0
  notes: string[];
  calculatedAt: number;
}

export interface ReferralCampaignSummary {
  totalReferrers: number;
  totalInvitesSent: number;
  totalInvitesConverted: number;
  averageConversionRatePercent: number;
  averageViralKFactor: number;
  totalReferredRevenueUsdCents: number;
  totalRewardsIssuedUsdCents: number;
  viralAdvocateCount: number;
  tierBreakdown: Record<CollectorTier, number>;
}

// Reward commission rates by collector tier
const REWARD_PERCENT_BY_TIER: Record<CollectorTier, number> = {
  collector_bronze: 0.05, // 5% store credit
  collector_silver: 0.075, // 7.5% store credit
  collector_gold: 0.10, // 10% store credit
  collector_platinum: 0.15, // 15% store credit
};

const referralRewardStore: Map<string, ReferralRewardResult> = new Map();

/**
 * Calculates viral K-factor and computes store credit rewards for collector referrals.
 */
export function calculateReferralReward(activity: ReferralActivity): ReferralRewardResult {
  const { referrerId, referrerTier, invitesSent, invitesConverted, totalReferredSpendUsdCents } = activity;
  const notes: string[] = [];

  const conversionRatePercent = invitesSent > 0 ? Math.round((invitesConverted / invitesSent) * 1000) / 10 : 0;
  
  // Viral K-factor: average converted invites per active collector (K = invitesSent * conversionRate)
  const viralKFactor = invitesSent > 0 ? Math.round((invitesConverted / Math.max(1, invitesSent / 5)) * 100) / 100 : 0;
  const isViralAdvocate = viralKFactor >= 1.0;

  // Calculate store credit rewards based on referred spend and tier percentage
  const rewardPercent = REWARD_PERCENT_BY_TIER[referrerTier] || 0.05;
  let earnedRewardCreditsUsdCents = Math.round(totalReferredSpendUsdCents * rewardPercent);

  // Bonus voucher allocation based on conversion volume
  let discountVoucherPercent = 0;
  if (invitesConverted >= 10) {
    discountVoucherPercent = 25;
    notes.push("Super Advocate Bonus: Unlocked 25% single-use VIP discount voucher!");
  } else if (invitesConverted >= 5) {
    discountVoucherPercent = 15;
    notes.push("Advocate Milestone: Unlocked 15% single-use discount voucher.");
  } else if (invitesConverted >= 2) {
    discountVoucherPercent = 10;
    notes.push("Referral Milestone: Unlocked 10% single-use discount voucher.");
  }

  if (isViralAdvocate) {
    // Add 10% bonus credit for viral advocates driving exponent growth (K >= 1.0)
    const viralBonusCents = Math.round(earnedRewardCreditsUsdCents * 0.10);
    earnedRewardCreditsUsdCents += viralBonusCents;
    notes.push(`Viral Advocate Status (K=${viralKFactor}): Earned +10% bonus credits ($${(viralBonusCents / 100).toFixed(2)}).`);
  } else {
    notes.push(`K-Factor ${viralKFactor} (Sub-viral). Send more invites to unlock viral advocate bonuses.`);
  }

  const result: ReferralRewardResult = {
    referrerId,
    referrerTier,
    invitesSent,
    invitesConverted,
    conversionRatePercent,
    viralKFactor,
    earnedRewardCreditsUsdCents,
    discountVoucherPercent,
    isViralAdvocate,
    notes,
    calculatedAt: Date.now(),
  };

  referralRewardStore.set(referrerId, result);
  return result;
}

/**
 * Summarizes performance across an entire referral marketing campaign batch.
 */
export function summarizeReferralCampaign(activities: ReferralActivity[]): ReferralCampaignSummary {
  const totalReferrers = activities.length;
  if (totalReferrers === 0) {
    return {
      totalReferrers: 0,
      totalInvitesSent: 0,
      totalInvitesConverted: 0,
      averageConversionRatePercent: 0,
      averageViralKFactor: 0,
      totalReferredRevenueUsdCents: 0,
      totalRewardsIssuedUsdCents: 0,
      viralAdvocateCount: 0,
      tierBreakdown: { collector_bronze: 0, collector_silver: 0, collector_gold: 0, collector_platinum: 0 },
    };
  }

  const tierBreakdown: Record<CollectorTier, number> = {
    collector_bronze: 0,
    collector_silver: 0,
    collector_gold: 0,
    collector_platinum: 0,
  };

  let totalInvitesSent = 0;
  let totalInvitesConverted = 0;
  let totalConversionRateSum = 0;
  let totalKFactorSum = 0;
  let totalReferredRevenueUsdCents = 0;
  let totalRewardsIssuedUsdCents = 0;
  let viralAdvocateCount = 0;

  for (const act of activities) {
    totalInvitesSent += act.invitesSent;
    totalInvitesConverted += act.invitesConverted;
    totalReferredRevenueUsdCents += act.totalReferredSpendUsdCents;

    tierBreakdown[act.referrerTier] = (tierBreakdown[act.referrerTier] || 0) + 1;

    const res = calculateReferralReward(act);
    totalConversionRateSum += res.conversionRatePercent;
    totalKFactorSum += res.viralKFactor;
    totalRewardsIssuedUsdCents += res.earnedRewardCreditsUsdCents;
    if (res.isViralAdvocate) viralAdvocateCount++;
  }

  return {
    totalReferrers,
    totalInvitesSent,
    totalInvitesConverted,
    averageConversionRatePercent: Math.round((totalConversionRateSum / totalReferrers) * 10) / 10,
    averageViralKFactor: Math.round((totalKFactorSum / totalReferrers) * 100) / 100,
    totalReferredRevenueUsdCents,
    totalRewardsIssuedUsdCents,
    viralAdvocateCount,
    tierBreakdown,
  };
}

/**
 * Generates Convex Schema snippet for referral reward records.
 */
export function generateConvexReferralRewardSchema(): string {
  return `
export const referral_rewards = defineTable({
  referrerId: v.string(),
  referrerTier: v.string(),
  invitesSent: v.number(),
  invitesConverted: v.number(),
  conversionRatePercent: v.number(),
  viralKFactor: v.number(),
  earnedRewardCreditsUsdCents: v.number(),
  discountVoucherPercent: v.number(),
  isViralAdvocate: v.boolean(),
  calculatedAt: v.number(),
}).index("by_referrer", ["referrerId"])
  .index("by_tier", ["referrerTier"]);
`.trim();
}

/**
 * Retrieves cached referral reward result by referrer ID.
 */
export function getReferralReward(referrerId: string): ReferralRewardResult | undefined {
  return referralRewardStore.get(referrerId);
}

/**
 * Clears the in-memory referral reward store for testing.
 */
export function clearReferralStoreForTesting(): void {
  referralRewardStore.clear();
}
