/**
 * Converts ../docs HTML and Markdown into semantic TSX (JSX) under src/generated
 * and thin page.tsx wrappers under src/app. Run before `next build`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { convert as htmlToJsx } from "./html-to-jsx.mjs";
import { marked } from "marked";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = path.resolve(__dirname, "../../docs");
const APP_ROOT = process.env.DOCS_APP_ROOT ? path.resolve(process.env.DOCS_APP_ROOT) : path.resolve(__dirname, "../src/app");
const GENERATED_ROOT = process.env.DOCS_GENERATED_ROOT ? path.resolve(process.env.DOCS_GENERATED_ROOT) : path.resolve(__dirname, "../src/generated");
const CONTENT_ROOT = path.resolve(GENERATED_ROOT, "doc-content");
const MANIFEST_FILE = path.resolve(GENERATED_ROOT, "manifest.ts");

const HTML_SLUGS = {
  "commercial-viability-report.html": "commercial-viability-assessment",
  "COMMERCIAL_VIABILITY_REPORT.html": "commercial-viability-report",
  "commercial-viability-deep-dive.html": "commercial-viability-deep-dive",
  "COMMERCIAL_VIABILITY_DEEP_DIVE_REPORT.html": "commercial-viability-deep-dive-report",
  "commercial-viability-deep-dive-8600.html": "commercial-viability-deep-dive-8600",
};

const MD_SLUGS = {
  "PRODUCT_STRATEGY.md": "product-strategy",
  "DESIGN_DECISIONS.md": "design-decisions",
  "BUSINESS_PLAN.md": "business-plan",
  "TERMS_AND_CONDITIONS_DRAFT.md": "terms-and-conditions",
  "WORKFLOW_AUTHORITY.md": "workflow-authority",
  "CONTINUATION_NOTES.md": "continuation-notes",
};

const HAND_AUTHORED_DOC_SLUGS = new Set([
  "architecture",
  "cli-reference",
  "security",
]);

function extractTitle(html) {
  const m = html.match(/<title[^>]*>([^<]+)<\/title>/i);
  return m ? m[1].trim() : "Untitled";
}

function extractStyles(html) {
  const styles = [];
  const re = /<style[^>]*>([\s\S]*?)<\/style>/gi;
  let m;
  while ((m = re.exec(html)) !== null) {
    styles.push(m[1].trim());
  }
  return styles.join("\n");
}

function extractMainHtml(html) {
  const main = html.match(/<main[^>]*>([\s\S]*?)<\/main>/i);
  if (main) return main[1].trim();
  const body = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  if (body) return body[1].trim();
  return html;
}

function slugFromFilename(filename) {
  return filename
    .replace(/\.html$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function componentName(slug) {
  return slug
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function contentExportName(slug) {
  return `${componentName(slug)}Content`;
}

function htmlToJsxFragment(html) {
  let jsx = htmlToJsx(html).trim();
  const wrapped = jsx.match(/^<div>\s*([\s\S]*)\s*<\/div>$/);
  if (wrapped) {
    jsx = wrapped[1].trim();
  }
  return jsx;
}

function indentBlock(text, spaces) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length ? pad + line : line))
    .join("\n");
}

function writeFile(filePath, source) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, source, "utf8");
}

function emitContentModule({ slug, kind, styles, bodyHtml }) {
  const exportName = contentExportName(slug);
  const jsxBody = htmlToJsxFragment(bodyHtml);
  const wrapperClass = kind === "html" ? "ingested-html" : "ingested-markdown";
  const stylesConst = styles
    ? `const PAGE_STYLES = ${JSON.stringify(styles)};\n\n`
    : "";
  const stylesJsx = styles
    ? `      <style dangerouslySetInnerHTML={{ __html: PAGE_STYLES }} />\n`
    : "";

  const source = `/* eslint-disable */
/** Generated by scripts/build-docs.mjs — semantic TSX from repository source. */
${stylesConst}export function ${exportName}() {
  return (
    <>
${stylesJsx}      <div className="${wrapperClass}">
${indentBlock(jsxBody, 8)}
      </div>
    </>
  );
}
`;

  writeFile(path.join(CONTENT_ROOT, `${slug}.tsx`), source);
  return exportName;
}

function emitPageWrapper({
  slug,
  title,
  sourceFile,
  exportName,
  routePrefix,
  subtitle,
}) {
  const pageName = `${componentName(slug)}Page`;
  const source = `/* eslint-disable */
/** Generated by scripts/build-docs.mjs */
import { DocsLayout } from "@/components/DocsLayout";
import { FULL_NAV } from "@/lib/navigation";
import { ${exportName} } from "@/generated/doc-content/${slug}";

export default function ${pageName}() {
  return (
    <DocsLayout
      title={${JSON.stringify(title)}}
      subtitle={${JSON.stringify(subtitle)}}
      sourceFile={${JSON.stringify(sourceFile)}}
      nav={FULL_NAV}
    >
      <${exportName} />
    </DocsLayout>
  );
}
`;

  writeFile(path.join(APP_ROOT, routePrefix, slug, "page.tsx"), source);
}

function emitDocPage({ slug, title, sourceFile, kind, styles, bodyHtml, routePrefix }) {
  const subtitle =
    kind === "html"
      ? "Commercial viability report (TSX rewritten from repository HTML)"
      : "Documentation (TSX rewritten from repository markdown)";
  const exportName = emitContentModule({ slug, kind, styles, bodyHtml });
  emitPageWrapper({ slug, title, sourceFile, exportName, routePrefix, subtitle });
  return {
    slug,
    title,
    sourceFile,
    href: `/${routePrefix}/${slug}`.replace(/\/+/g, "/"),
    kind,
  };
}

function ingestHtml() {
  const pages = [];
  const usedSlugs = new Set();
  const ingestedFiles = new Set();

  function pushPage(filename, slug) {
    const filePath = path.join(DOCS_ROOT, filename);
    if (!fs.existsSync(filePath)) {
      console.warn(`skip missing html: ${filename}`);
      return;
    }
    let finalSlug = slug;
    if (usedSlugs.has(finalSlug)) {
      let n = 2;
      while (usedSlugs.has(`${slug}-${n}`)) n += 1;
      finalSlug = `${slug}-${n}`;
    }
    usedSlugs.add(finalSlug);
    ingestedFiles.add(filename);
    const raw = fs.readFileSync(filePath, "utf8");
    pages.push(
      emitDocPage({
        slug: finalSlug,
        title: extractTitle(raw),
        sourceFile: filename,
        kind: "html",
        styles: extractStyles(raw),
        bodyHtml: extractMainHtml(raw),
        routePrefix: "docs/reports",
      }),
    );
  }

  for (const [filename, slug] of Object.entries(HTML_SLUGS)) {
    pushPage(filename, slug);
  }

  for (const filename of fs.readdirSync(DOCS_ROOT)) {
    if (!filename.toLowerCase().endsWith(".html") || ingestedFiles.has(filename)) {
      continue;
    }
    pushPage(filename, slugFromFilename(filename));
  }

  return pages.sort((a, b) => a.title.localeCompare(b.title));
}

function ingestMarkdown() {
  const pages = [];
  for (const [filename, slug] of Object.entries(MD_SLUGS)) {
    if (HAND_AUTHORED_DOC_SLUGS.has(slug)) {
      console.warn(`skip md (hand-authored): ${filename}`);
      continue;
    }
    const filePath = path.join(DOCS_ROOT, filename);
    if (!fs.existsSync(filePath)) {
      console.warn(`skip missing md: ${filename}`);
      continue;
    }
    const raw = fs.readFileSync(filePath, "utf8");
    const firstLine = raw.split("\n").find((l) => l.startsWith("# "));
    const title = firstLine
      ? firstLine.replace(/^#\s+/, "").trim()
      : slug.replace(/-/g, " ");
    pages.push(
      emitDocPage({
        slug,
        title,
        sourceFile: filename,
        kind: "markdown",
        styles: "",
        bodyHtml: marked.parse(raw),
        routePrefix: "docs",
      }),
    );
  }
  return pages.sort((a, b) => a.title.localeCompare(b.title));
}

function emitManifest(reportPages, docPages) {
  const serialize = (pages) =>
    pages
      .map(
        (p) => `  {
    slug: ${JSON.stringify(p.slug)},
    title: ${JSON.stringify(p.title)},
    sourceFile: ${JSON.stringify(p.sourceFile)},
    href: ${JSON.stringify(p.href)},
    kind: ${JSON.stringify(p.kind)},
  }`,
      )
      .join(",\n");

  const source = `/* eslint-disable */
/** Generated by scripts/build-docs.mjs — navigation metadata only. */
export interface GeneratedDocPage {
  slug: string;
  title: string;
  sourceFile: string;
  href: string;
  kind: "html" | "markdown";
}

export const GENERATED_REPORT_PAGES: GeneratedDocPage[] = [
${serialize(reportPages)}
];

export const GENERATED_SOURCE_DOC_PAGES: GeneratedDocPage[] = [
${serialize(docPages)}
];
`;

  writeFile(MANIFEST_FILE, source);
}

function resetGeneratedContent() {
  if (fs.existsSync(CONTENT_ROOT)) {
    fs.rmSync(CONTENT_ROOT, { recursive: true, force: true });
  }
  fs.mkdirSync(CONTENT_ROOT, { recursive: true });

  const docBody = path.resolve(__dirname, "../src/components/DocBody.tsx");
  if (fs.existsSync(docBody)) {
    fs.unlinkSync(docBody);
  }
}

resetGeneratedContent();
const reportPages = ingestHtml();
const docPages = ingestMarkdown();
emitManifest(reportPages, docPages);
console.log(
  `wrote ${reportPages.length} report pages and ${docPages.length} doc pages as semantic TSX`,
);
