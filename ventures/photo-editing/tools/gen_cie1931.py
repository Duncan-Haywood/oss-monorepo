"""Regenerate src/shootflow/cie1931.py from colour-science's copy of the CIE table.

    python -m venv v && v/bin/pip install colour-science
    v/bin/python tools/gen_cie1931.py > src/shootflow/cie1931.py

Values are printed to 10 significant digits (the CIE's table has at most 7).
"""

import warnings

warnings.filterwarnings("ignore")

import colour  # noqa: E402

cmfs = colour.MSDS_CMFS["CIE 1931 2 Degree Standard Observer"]
lines = [
    '"""CIE 1931 2-degree standard observer colour-matching functions, 360-830 nm in 1 nm steps.',
    "",
    "The CIE's published table (ISO/CIE 11664-1), as distributed by colour-science",
    f'{colour.__version__} (``MSDS_CMFS["CIE 1931 2 Degree Standard Observer"]``); generated by',
    "``tools/gen_cie1931.py``. Used to find the white of a spectral IlluminantData",
    "tag (DNG 1.6). Row i is (xbar, ybar, zbar) at 360 + i nm.",
    '"""',
    "",
    "CIE1931_2DEG_360_830 = (",
]
for lam in range(360, 831):
    lines.append("    (%s)," % ", ".join("%.10g" % float(v) for v in cmfs[lam]))
lines.append(")")
print("\n".join(lines))
