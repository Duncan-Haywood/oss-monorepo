import test from "node:test";
import assert from "node:assert/strict";
import { run } from "./cli.mjs";

test("plan prints the budget and policy and exits 0 for 99.9", async () => {
  const r = await run(["plan", "--slo", "99.9"]);
  assert.equal(r.exitCode, 0);
  assert.match(r.output, /43m 12s/);
  assert.match(r.output, /14\.4x burn\s+1h\/5m/);
});

test("plan exits 1 when a threshold is unreachable", async () => {
  const r = await run(["plan", "--slo", "90"]);
  assert.equal(r.exitCode, 1);
  assert.match(r.output, /UNREACHABLE/);
});

test("--fail-on warn turns a low-traffic warning into exit 1", async () => {
  assert.equal((await run(["plan", "--slo", "99.9", "--rps", "0.05"])).exitCode, 0);
  assert.equal((await run(["plan", "--slo", "99.9", "--rps", "0.05", "--fail-on", "warn"])).exitCode, 1);
});

test("--json is parseable", async () => {
  const r = await run(["plan", "--slo", "99.95", "--period", "28", "--json"]);
  const j = JSON.parse(r.output);
  assert.equal(j.policy.length, 4);
  assert.equal(j.policy[0].burnRate, 13.44);
});

test("rules prints YAML; missing selectors exit 2", async () => {
  const ok = await run(["rules", "--slo", "99.9", "--name", "api", "--errors", 'e{a="b"}', "--total", 't{a="b"}']);
  assert.equal(ok.exitCode, 0);
  assert.match(ok.output, /^# Generated by/);
  assert.match(ok.output, /groups:/);
  assert.equal((await run(["rules", "--slo", "99.9", "--name", "api"])).exitCode, 2);
});

test("bad input exits 2", async () => {
  assert.equal((await run(["plan", "--slo", "100"])).exitCode, 2);
  assert.equal((await run([])).exitCode, 1);
  assert.equal((await run(["nope", "--slo", "99"])).exitCode, 2);
  assert.equal((await run(["plan", "--slo", "99", "--bogus"])).exitCode, 2);
});
