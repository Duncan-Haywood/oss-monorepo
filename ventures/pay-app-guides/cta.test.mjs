test("a status block at the very start of the section is still replaced, not an error", () => {
  const start = "<!-- cta-status: generated by cta.mjs, do not edit by hand -->";
  const html = `<section class="card cta" id="early-access">${start}stale<!-- /cta-status --> We are building hosted x.</section>`;
  const out = apply(html, "x.html", "https://a.example");
  assert.doesNotMatch(out, /stale/);
  assert.match(out, /Start free in PayApps/);
});

test("node cta.mjs rewrites a stale page once, then leaves it alone", () => {
  const dir = mkdtempSync(join(tmpdir(), "cta-"));
  try {
    copyFileSync(new URL("./cta.mjs", import.meta.url), join(dir, "cta.mjs"));
    writeFileSync(join(dir, "lien-waiver-log.html"), PAGE);
    const run = () => execFileSync(process.execPath, [join(dir, "cta.mjs")], { encoding: "utf8" });
    assert.equal(run().trim(), "updated lien-waiver-log.html");
    assert.equal(readFileSync(join(dir, "lien-waiver-log.html"), "utf8"), apply(PAGE, "lien-waiver-log.html", null));
    assert.equal(run().trim(), "", "a second run changes nothing");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
