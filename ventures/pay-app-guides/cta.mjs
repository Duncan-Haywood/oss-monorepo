// The "PayApps" call to action at the foot of every pay-app-guides page, switched in one place
// when the app opens.
//
// Each page keeps its own heading and its own sentence about what the app does for that page's
// job. Two parts are shared and written here, so 30 pages cannot drift apart or keep saying
// "nothing is for sale" after sign-ups open:
//   - the lead: "We are building hosted ..." before launch, "PayApps is hosted ..." after;
//   - the status sentence and link at the end of the paragraph.
//
// Before launch (APP_URL null) the status says the product is in development and links to the
// construction industry page, which is what every page said by hand before this file existed.
// At launch, set APP_URL to the deployed app's origin (the `payapps-deploy` run's summary prints it)
// and run `node cta.mjs`: every page then links to `<APP_URL>/?signup&from=<page>`, which opens the
// app on "Create an account" (apps/payapps/src/client/lib/auth-mode.ts). `from` names the guide
// that sent the visitor, so a later sign-up source report has something to read.
//
// Copy rules (ventures/payapps/apps/payapps-site/README.md, "Honesty rules"): no customer counts,
// ratings or outcomes; paid plans are described as not on sale until checkout is on
// (PAID_PLANS_ON). page.test.mjs fails if a page's block is not what this file writes.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The deployed app's origin (payapps-deploy run 45949861746, 2026-11-27). null shows the pre-launch text. */
export const APP_URL = "https://payapps.marisstella.app";
/** True once Paddle checkout is live in the app (apps/payapps/docs/BILLING.md). */
export const PAID_PLANS_ON = false;

const PRE_LEAD = "We are building hosted";
const LIVE_LEAD = "PayApps is hosted";
// Spanish pages (<html lang="es">, es-*.html): the same switch in Spanish. The app itself is in
// English, and the status says so, so nobody signs up expecting a Spanish screen.
const ES_PRE_LEAD = "Estamos construyendo un servicio en línea";
const ES_LIVE_LEAD = "PayApps es un servicio en línea";
const isSpanish = (html) => /^<!doctype html>\s*<html lang="es"/i.test(html);
const INDUSTRY = "https://marisstella.app/industries/construction/";

const START = "<!-- cta-status: generated by cta.mjs, do not edit by hand -->";
const END = "<!-- /cta-status -->";

// What the pages said by hand before this file (one sentence, identical on all 30).
const LEGACY = `It is <strong>in development, with early access</strong>; nothing is for sale yet. <a href="${INDUSTRY}">See the construction tools and join early access</a>.`;

export function signupUrl(appUrl, page) {
  const name = page.replace(/\.html$/, "");
  const from = name === "index" ? "pay-app-guides" : `pay-app-guides/${name}`;
  return `${appUrl.replace(/\/+$/, "")}/?signup&from=${encodeURIComponent(from)}`;
}

export function statusEs(page, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  if (!appUrl) return `Está <strong>en desarrollo, con acceso anticipado</strong>; todavía no se vende nada. <a href="${INDUSTRY}">Vea las herramientas para construcción (en inglés)</a>.`;
  const plans = paidOn
    ? "gratis en una obra, y luego de $99 a $249 al mes según las obras activas"
    : "solicitudes de pago con retención y órdenes de cambio, gratis en una obra, sin tarjeta. Las renuncias de gravamen, QuickBooks y los costos por obra están en los planes de pago, que todavía no están a la venta";
  return `Está <strong>abierto ahora</strong>: ${plans}. La aplicación está en inglés por ahora. <a href="${signupUrl(appUrl, page).replace(/&/g, "&amp;")}">Empiece gratis en PayApps</a>.`;
}

export function status(page, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  if (!appUrl) return LEGACY;
  const plans = paidOn
    ? "free on one job, then $99 to $249 a month by active jobs"
    : // The Free plan has no lien waivers, QuickBooks or job costing (apps/payapps/src/shared/plans.ts),
      // and many guides are waiver pages: say so, so nobody signs up expecting a form Free cannot print.
      "pay applications with retainage and change orders, free on one job, no card. Lien waivers, QuickBooks and job costing are in the paid plans, which are not on sale yet";
  return `It is <strong>open now</strong>: ${plans}. <a href="${signupUrl(appUrl, page).replace(/&/g, "&amp;")}">Start free in PayApps</a>.`;
}

const SECTION = /(<section class="card cta" id="early-access">)([\s\S]*?)(<\/section>)/;

export function apply(html, page, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  const m = SECTION.exec(html);
  if (!m) throw new Error(`${page}: no <section class="card cta" id="early-access">`);
  let body = m[2];
  const es = isSpanish(html);
  const block = `${START}${(es ? statusEs : status)(page, appUrl, paidOn)}${END}`;
  const at = body.indexOf(START);
  if (at >= 0) {
    body = body.slice(0, at) + block + body.slice(body.indexOf(END) + END.length);
  } else if (body.includes(LEGACY)) {
    body = body.replace(LEGACY, block);
  } else {
    throw new Error(`${page}: CTA has neither the cta-status block nor the old status sentence`);
  }
  const [pre, live] = es ? [ES_PRE_LEAD, ES_LIVE_LEAD] : [PRE_LEAD, LIVE_LEAD];
  const [from, to] = appUrl ? [pre, live] : [live, pre];
  body = body.replace(from, to);
  if (!body.includes(to)) throw new Error(`${page}: CTA does not start "${pre}" or "${live}"`);
  return html.slice(0, m.index) + m[1] + body + m[3] + html.slice(m.index + m[0].length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL("./", import.meta.url);
  for (const name of readdirSync(dir).filter((f) => f.endsWith(".html"))) {
    const file = new URL(name, dir);
    const html = readFileSync(file, "utf8");
    const out = apply(html, name);
    if (out !== html) { writeFileSync(file, out); console.log(`updated ${name}`); }
  }
}
