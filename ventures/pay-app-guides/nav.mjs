const START = "<!-- all-guides: generated by nav.mjs, do not edit by hand -->";
const END = "<!-- /all-guides -->";

export function block(current) {
  const groups = GROUPS.map(([title, links]) => {
    const items = links.map(([href, text]) => {
      const url = href === "index.html" ? "./" : href;
      const here = href === current ? ' aria-current="page"' : "";
      return `      <li><a href="${url}"${here}>${text}</a></li>`;
    }).join("\n");
    return `    <div>\n      <h2>${title}</h2>\n      <ul>\n${items}\n      </ul>\n    </div>`;
  }).join("\n");
  return `${START}\n<nav class="all-guides" id="all-guides" aria-label="All pay app tools and guides">\n${groups}\n</nav>\n${END}`;
}

export function apply(html, name) {
  const at = html.indexOf(START);
  if (at >= 0) return html.slice(0, at) + block(name) + html.slice(html.indexOf(END) + END.length);
  const foot = html.indexOf("<footer>");
  if (foot < 0) throw new Error(`${name}: no <footer> to put the guides block before`);
  return html.slice(0, foot) + block(name) + "\n" + html.slice(foot);
}

export const listed = () => GROUPS.flatMap(([, links]) => links.map(([href]) => href));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL("./", import.meta.url);
  const pages = readdirSync(dir).filter((f) => f.endsWith(".html"));
  const missing = pages.filter((p) => !listed().includes(p));
  if (missing.length) throw new Error(`add to GROUPS in nav.mjs: ${missing.join(", ")}`);
  for (const name of pages) {
    const file = new URL(name, dir);
    const html = readFileSync(file, "utf8");
    const out = apply(html, name);
    if (out !== html) { writeFileSync(file, out); console.log(`updated ${name}`); }
  }
}
