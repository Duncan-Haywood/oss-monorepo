import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { STATES, slugOf, HUB, build, packagePresent, statutoryForms } from "./state-forms.mjs";

const page = (name) => readFileSync(new URL(`./${name}`, import.meta.url), "utf8");

// The pages print from ventures/payapps/packages/lien-waivers. Outside this monorepo (a copy of the
// venture alone) the package is absent and only the committed pages are checked.
const pkgTest = packagePresent() ? test : test.skip;

pkgTest("every state page and the hub's links match a fresh build (run node state-forms.mjs)", async () => {
  const files = await build();
  for (const [name, html] of Object.entries(files)) assert.equal(page(name), html, `${name} is out of date: node state-forms.mjs`);
});

pkgTest("every page prints each verified statutory form of its state, word for word", async () => {
  const pkg = await import("../payapps/packages/lien-waivers/src/index.ts");
  for (const [code, name] of STATES) {
    const html = page(slugOf(name));
    const { forms } = statutoryForms(pkg, code);
    assert.ok(forms.length >= 1, name);
    for (const { form } of forms) {
      assert.equal(form.citation.verification.status, "verified", form.id);
      // Every sentence of the statute's text appears, with its blanks as rules.
      for (const b of form.body) {
        if (!("text" in b)) continue;
        const words = b.text.split(/\{\{\w+\}\}/).map((t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")).filter((t) => t.trim());
        for (const w of words) assert.ok(html.includes(w), `${form.id}: "${w.slice(0, 60)}" missing`);
      }
    }
  }
});

test("each state page links its statute, says not legal advice, and the hub links every page", () => {
  const hub = page(HUB);
  for (const [, name] of STATES) {
    const file = slugOf(name);
    const html = page(file);
    assert.match(html, /<!-- generated by state-forms\.mjs/, file);
    assert.match(html, /are not legal advice/, file);
    assert.match(html, /class="statutory-form"/, file);
    assert.match(html, /Print this form/, file);
    assert.ok(hub.includes(`href="${file}"`), `${HUB} does not link ${file}`);
  }
});

test("Georgia prints at the statute's 12 point minimum", () => {
  assert.match(page(slugOf("Georgia")), /class="statutory-form" style="font-size: max\(1em, 12pt\)"/);
});

// Red team 2026-11-27: state-forms.mjs wrote the old CTA sentence and cta.mjs rewrote it, so each
// generator's check failed on the other's output and main went red. The build now runs cta.mjs.
pkgTest("a fresh build carries cta.mjs's status block, so the launch switch reaches the state pages", async () => {
  const files = await build();
  for (const [, name] of STATES) {
    assert.match(files[slugOf(name)], /<!-- cta-status: generated by cta\.mjs[^]*<!-- \/cta-status -->/, slugOf(name));
  }
});
