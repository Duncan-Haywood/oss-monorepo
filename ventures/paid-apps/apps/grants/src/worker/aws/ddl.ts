// SQLite (drizzle-kit, migrations/*.sql) -> Postgres DDL for the AWS runtime (docs/AWS.md).
//
// The D1 migrations stay the source of truth; `scripts/aws/gen-pg-migrations.ts` writes
// migrations-pg/ from them and a unit test fails when that output is stale. Column types keep
// D1's storage model so every Drizzle query and every migrated row means the same thing on both:
//   integer -> bigint (epoch-ms timestamps, cents, 0/1 booleans), real -> double precision,
//   blob -> bytea, text -> text; DEFAULT true/false -> 1/0.
// Foreign keys move to ALTER TABLE statements at the end of each file, because SQLite accepts a
// reference to a table created later in the same migration and Postgres does not. They are
// DEFERRABLE INITIALLY IMMEDIATE: the app sees normal checks, and the one-off D1 data load
// (scripts/aws/d1-to-postgres.ts) defers them to COMMIT so table order does not matter.

const TYPE_MAP: Record<string, string> = {
  integer: "bigint",
  real: "double precision",
  blob: "bytea",
  numeric: "numeric",
  text: "text",
};

/** Postgres stand-ins for the SQLite built-ins the schema and health check use. */
export const PG_COMPAT_PRELUDE = `-- SQLite compatibility for the shared Drizzle (sqlite-core) schema. Generated: do not edit.
CREATE OR REPLACE FUNCTION instr(haystack text, needle text) RETURNS integer
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS 'SELECT strpos(haystack, needle)';
--> statement-breakpoint
CREATE OR REPLACE VIEW sqlite_master AS
  SELECT 'table'::text AS type, table_name::text AS name, table_name::text AS tbl_name
  FROM information_schema.tables WHERE table_schema = current_schema();
`;

export interface PgMigration {
  sql: string;
  /** Tables created by this file, in order. */
  tables: string[];
}

const FK_LINE = /^\s*FOREIGN KEY \(([^)]*)\) REFERENCES "([^"]+)"\(([^)]*)\)(.*?)\s*,?\s*$/;

function splitStatements(sqlite: string): string[] {
  return sqlite
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

function convertColumn(line: string): string {
  const m = /^(\s*"[^"]+") (integer|real|blob|numeric|text)\b(.*)$/.exec(line);
  if (!m) return line;
  const [, name, type, rest] = m as unknown as [string, string, string, string];
  const fixedRest = rest
    .replace(/DEFAULT false\b/g, "DEFAULT 0")
    .replace(/DEFAULT true\b/g, "DEFAULT 1");
  return `${name} ${TYPE_MAP[type] ?? type}${fixedRest}`;
}

/** Converts one drizzle-kit SQLite migration file to Postgres. */
export function sqliteMigrationToPg(sqlite: string): PgMigration {
  const out: string[] = [];
  const fks: string[] = [];
  const tables: string[] = [];
  for (const raw of splitStatements(sqlite)) {
    if (/^PRAGMA\b/i.test(raw)) continue;
    const stmt = raw.replace(/`/g, '"');
    const create = /^CREATE TABLE "([^"]+)" \(\n([\s\S]*)\n\);?$/.exec(stmt);
    if (!create) {
      out.push(stmt.endsWith(";") ? stmt : `${stmt};`);
      continue;
    }
    const [, table, body] = create as unknown as [string, string, string];
    tables.push(table);
    const kept: string[] = [];
    for (const line of body.split("\n")) {
      const fk = FK_LINE.exec(line);
      if (fk) {
        const [, cols, refTable, refCols, actions] = fk as unknown as [
          string,
          string,
          string,
          string,
          string,
        ];
        fks.push(
          `ALTER TABLE "${table}" ADD FOREIGN KEY (${cols}) REFERENCES "${refTable}"(${refCols})${actions} DEFERRABLE INITIALLY IMMEDIATE;`,
        );
        continue;
      }
      kept.push(convertColumn(line));
    }
    // Dropping FK lines can leave a trailing comma on the last kept line.
    const last = kept.length - 1;
    if (last >= 0) kept[last] = (kept[last] as string).replace(/,\s*$/, "");
    out.push(`CREATE TABLE "${table}" (\n${kept.join("\n")}\n);`);
  }
  return { sql: [...out, ...fks].join("\n--> statement-breakpoint\n").concat("\n"), tables };
}

export const GENERATED_HEADER =
  "-- Generated by scripts/aws/gen-pg-migrations.ts from migrations/ (D1). Do not edit.\n";

/** All Postgres migration files for the given D1 migration files (name order). */
export function generatePgMigrations(
  files: { name: string; sql: string }[],
): { name: string; sql: string }[] {
  return [
    { name: "0000_000_sqlite_compat.sql", sql: PG_COMPAT_PRELUDE },
    ...files.map((f) => ({ name: f.name, sql: GENERATED_HEADER + sqliteMigrationToPg(f.sql).sql })),
  ];
}
