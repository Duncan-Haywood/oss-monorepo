#!/usr/bin/env bash
# Starts Grant Autopilot in OFFLINE DEMO MODE for UI QA screenshots (scripts/qa-screens.mjs).
# A copy of scripts/e2e-server.sh with its own port/state so it can run next to the e2e server:
#
#  - Port 5177 (QA_PORT), isolated local state in .wrangler/qa.
#  - Fresh D1 each run: schema = `drizzle-kit export --sql` applied with `wrangler d1 execute --local`.
#    Set QA_KEEP_STATE=1 to keep existing data (the schema is then applied with IF NOT EXISTS, so
#    columns added to the Drizzle schema since the state was created are NOT added: if API calls start
#    failing with "Failed query", start fresh and delete $QA_OUT/state.json).
#  - Vars/secrets come from a generated `.dev.vars.qa` (CLOUDFLARE_ENV=qa makes wrangler and the
#    Vite plugin read it INSTEAD of a developer's `.dev.vars`, which is never read or written).
#  - FAKE_EXTERNALS=true (fake LLM/embeddings/email/web) and INLINE_JOBS=true (queue jobs run inline).
set -euo pipefail

cd "$(dirname "$0")/.."

PORT="${QA_PORT:-5177}"
PERSIST=".wrangler/qa"
export QA_PORT="$PORT"
export CLOUDFLARE_ENV=qa
export WRANGLER_SEND_METRICS=false
export CLOUDFLARE_INCLUDE_PROCESS_ENV=false

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if [[ "${QA_KEEP_STATE:-0}" != "1" ]]; then
  rm -rf "$PERSIST"
fi
mkdir -p "$PERSIST"

echo "[qa] exporting D1 schema"
pnpm exec drizzle-kit export --sql >"$TMP/raw.sql"
# Idempotent DDL so re-applying onto kept state is a no-op.
sed -E \
  -e 's/^CREATE TABLE `/CREATE TABLE IF NOT EXISTS `/' \
  -e 's/^CREATE (UNIQUE )?INDEX `/CREATE \1INDEX IF NOT EXISTS `/' \
  "$TMP/raw.sql" >"$TMP/schema.sql"

echo "[qa] applying schema to local D1 in $PERSIST"
pnpm exec wrangler d1 execute DB --local --persist-to "$PERSIST" --file "$TMP/schema.sql" >"$TMP/d1.log" 2>&1 ||
  { cat "$TMP/d1.log"; exit 1; }

# Dedicated, generated env file (gitignored via `.dev.vars.*`). Values are QA-only, not secrets.
cat >.dev.vars.qa <<EOF
# GENERATED by scripts/qa-server.sh for UI QA runs. Safe to delete.
APP_ENV=development
APP_URL=http://localhost:${PORT}
FAKE_EXTERNALS=true
INLINE_JOBS=true
DEMO_MODE=true
AUTH_SECRET=qa-only-auth-secret-0123456789abcdef0123456789ab
INTERNAL_API_TOKEN=qa-only-internal-token
ANTHROPIC_API_KEY=
RESEND_API_KEY=
EOF

echo "[qa] starting vite dev on :$PORT"
exec pnpm exec vite dev --config scripts/vite.qa.config.ts --port "$PORT" --strictPort
