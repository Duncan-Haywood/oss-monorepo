#!/usr/bin/env bash
# Starts Grant Autopilot for Playwright in OFFLINE DEMO MODE (playwright.config.ts `webServer`).
#
#  - Isolated local state in .wrangler/e2e (never touches the developer's .wrangler/state).
#  - Fresh D1 each run: schema = `drizzle-kit export --sql` applied with `wrangler d1 execute --local`.
#    Set E2E_KEEP_STATE=1 to keep existing data (the schema is then applied with IF NOT EXISTS).
#  - Vars/secrets come from a generated `.dev.vars.e2e` (CLOUDFLARE_ENV=e2e makes wrangler and the
#    Vite plugin read it INSTEAD of a developer's `.dev.vars`, which is never read or written).
#  - FAKE_EXTERNALS=true (fake LLM/embeddings/email/web) and INLINE_JOBS=true (queue jobs run inline).
set -euo pipefail

cd "$(dirname "$0")/.."

PORT="${E2E_PORT:-5199}"
PERSIST=".wrangler/e2e"
export CLOUDFLARE_ENV=e2e
export WRANGLER_SEND_METRICS=false
export CLOUDFLARE_INCLUDE_PROCESS_ENV=false

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if [[ "${E2E_KEEP_STATE:-0}" != "1" ]]; then
  rm -rf "$PERSIST"
fi
mkdir -p "$PERSIST"

echo "[e2e] exporting D1 schema"
pnpm exec drizzle-kit export --sql >"$TMP/raw.sql"
# Idempotent DDL so re-applying onto kept state is a no-op.
sed -E \
  -e 's/^CREATE TABLE `/CREATE TABLE IF NOT EXISTS `/' \
  -e 's/^CREATE (UNIQUE )?INDEX `/CREATE \1INDEX IF NOT EXISTS `/' \
  "$TMP/raw.sql" >"$TMP/schema.sql"

echo "[e2e] applying schema to local D1 in $PERSIST"
pnpm exec wrangler d1 execute DB --local --persist-to "$PERSIST" --file "$TMP/schema.sql" >"$TMP/d1.log" 2>&1 ||
  { cat "$TMP/d1.log"; exit 1; }

# Dedicated, generated env file (gitignored via `.dev.vars.*`). Values are e2e-only, not secrets.
cat >.dev.vars.e2e <<EOF
# GENERATED by scripts/e2e-server.sh for Playwright runs. Safe to delete.
APP_ENV=development
APP_URL=http://localhost:${PORT}${E2E_BASE_PATH:-}
BASE_PATH=${E2E_BASE_PATH:-}
FAKE_EXTERNALS=true
INLINE_JOBS=true
DEMO_MODE=true
AUTH_SECRET=e2e-only-auth-secret-0123456789abcdef0123456789
INTERNAL_API_TOKEN=e2e-only-internal-token
ANTHROPIC_API_KEY=
RESEND_API_KEY=
EOF

echo "[e2e] starting vite dev on :$PORT"
exec pnpm exec vite dev --config test/e2e/vite.e2e.config.ts --port "$PORT" --strictPort
