#!/usr/bin/env bash
# Local OFFLINE demo: no Anthropic key, no network. Fake LLM/embeddings/email/web, queue jobs inline.
#
#   scripts/demo.sh          # writes .dev.vars (only if absent), prepares local D1, runs `pnpm dev`
#
# Then open http://localhost:5173, sign up (no email verification over plain http in fake mode), and
# load the fictional sample org with "POST /api/demo/seed" (or the in-app demo button when present):
#   curl -X POST http://localhost:5173/api/demo/seed -H 'Cookie: <session cookie>'
set -euo pipefail

cd "$(dirname "$0")/.."

rand() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    node -e 'console.log(require("node:crypto").randomBytes(32).toString("hex"))'
  fi
}

if [[ -e .dev.vars ]]; then
  echo "[demo] keeping existing .dev.vars"
  if ! grep -Eq '^FAKE_EXTERNALS="?true"?' .dev.vars; then
    echo "[demo] WARNING: .dev.vars does not set FAKE_EXTERNALS=true: real external services may be used." >&2
    echo "[demo]          Move it aside (mv .dev.vars .dev.vars.bak) for a fully offline demo." >&2
  fi
else
  umask 077
  cat >.dev.vars <<VARS
# GENERATED by scripts/demo.sh for the local offline demo (gitignored; never commit .dev.vars).
APP_ENV=development
APP_URL=http://localhost:5173
FAKE_EXTERNALS=true
INLINE_JOBS=true
DEMO_MODE=true
AUTH_SECRET=$(rand)
INTERNAL_API_TOKEN=$(rand)
ANTHROPIC_API_KEY=
VARS
  echo "[demo] wrote .dev.vars (offline demo settings, random local secrets)"
fi

scripts/local-db.sh

echo "[demo] starting pnpm dev on http://localhost:5173"
exec pnpm dev
