// The "Seller Books" call to action on the free reseller tools, switched in one place.
//
// Fourteen free pages (the fee calculators, the three reseller guides and Reseller Books itself) end with a paragraph
// about the hosted product, Seller Books (bet #5, ventures/seller-books). Until 2026-11-27 each
// said by hand that it was "in development — early access" and linked to the online sellers
// industry page. The app is now deployed with sign-ups open on its Free plan (seller-books-deploy
// run 45973427499; https://seller-books.marisstella.app/api/health answers ok with email on), so
// this file writes the status sentence and the sign-up link on every page, and the matching line
// in each tool's llms.txt, so they cannot drift apart or keep saying "in development".
//
// Run `node seller-books-cta.mjs` from this directory after changing APP_URL or PAID_PLANS_ON.
// seller-books-cta.test.mjs fails if a page's block is not what this file writes.
//
// Copy rules (prompts/goals.md, honest marketing): no customer counts, ratings or outcomes; the
// Free plan's limits are the app's own (apps/seller-books/src/shared/plans.ts: one platform, one
// user, up to 25 orders a month, every report on every plan); paid plans are described as not on
// sale until Paddle checkout is on (apps/seller-books/docs/BILLING.md).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The deployed app's origin (seller-books-deploy, custom domain, 2026-11-27). */
export const APP_URL = "https://seller-books.marisstella.app";
/** True once Paddle checkout is live in the app. */
export const PAID_PLANS_ON = false;

/** Pages that carry the paragraph, relative to ventures/. */
export const PAGES = Object.freeze([
  "depop-fee-calculator/index.html",
  "ebay-fee-calculator/index.html",
  "ebay-fee-calculator/cost-of-goods-sold-for-resellers.html",
  "ebay-fee-calculator/how-to-reconcile-marketplace-payouts-to-sales.html",
  "ebay-fee-calculator/schedule-c-worksheet-for-resellers.html",
  "etsy-profit-calculator/index.html",
  "facebook-marketplace-fee-calculator/index.html",
  "grailed-fee-calculator/index.html",
  "mercari-fee-calculator/index.html",
  "poshmark-fee-calculator/index.html",
  "stockx-seller-payout-calculator/index.html",
  "tiktok-shop-fee-calculator/index.html",
  "whatnot-seller-payout/index.html",
  // The free in-browser version of the product: added with the launch, already in the generated form.
  "reseller-books/index.html",
]);

/** llms.txt files whose "Tools for online sellers" line describes Seller Books. */
export const LLMS = Object.freeze([...new Set(PAGES.map((p) => p.split("/")[0]))].map((d) => `${d}/llms.txt`));

const INDUSTRY = "https://marisstella.app/industries/online-sellers/";
const OLD_STATUS = `<strong>in development &mdash; early access</strong>: see <a href="${INDUSTRY}">tools for online sellers</a>.`;
// The two hand-written forms before this file existed.
const LEGACY_CALC = `We are building that as <strong>Seller Books</strong>, a hosted product that is ${OLD_STATUS}`;
const LEGACY_GUIDE_LEAD = "This is the job we are building <strong>Seller Books</strong> for:";
const LEGACY_GUIDE_STATUS = `It is ${OLD_STATUS}`;
const GUIDE_LEAD = "This is the job <strong>Seller Books</strong> does:";

const START = "<!-- seller-books-cta: generated by reseller-books/seller-books-cta.mjs, do not edit by hand -->";
const END = "<!-- /seller-books-cta -->";

const OLD_LLMS = "In development, early access; do not describe it as available.";
const LLMS_START = "Status (generated by reseller-books/seller-books-cta.mjs):";

/** `from` names the page that sent the visitor, so a later sign-up source report has something to read. */
export function signupUrl(page, appUrl = APP_URL) {
  const from = page.replace(/\/index\.html$/, "").replace(/\.html$/, "");
  return `${appUrl.replace(/\/+$/, "")}/signup?from=${encodeURIComponent(from)}`;
}

function plans(paidOn) {
  return paidOn
    ? "free for one platform and up to 25 orders a month, then from $15 a month for more platforms"
    : "free for one platform and up to 25 orders a month, no card, with every report (profit by platform and month, the stock report, the Schedule C worksheet); plans for more platforms are not on sale yet";
}

export function status(page, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  return `It is <strong>open now</strong>: ${plans(paidOn)}. <a href="${signupUrl(page, appUrl)}">Start free in Seller Books</a>.`;
}

/** The calculators' paragraph says "We are building that as Seller Books"; it becomes this. */
function calcBlock(page, appUrl, paidOn) {
  return `That is what <strong>Seller Books</strong> does, hosted. ${status(page, appUrl, paidOn)}`;
}

export function apply(html, page, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  const at = html.indexOf(START);
  if (at >= 0) {
    // Regenerate in place. The block knows which form it is by its first words.
    const end = html.indexOf(END, at);
    if (end < 0) throw new Error(`${page}: ${START} without ${END}`);
    const inner = html.slice(at + START.length, end);
    const block = inner.startsWith("That is what") ? calcBlock(page, appUrl, paidOn) : status(page, appUrl, paidOn);
    return html.slice(0, at) + START + block + html.slice(end);
  }
  if (html.includes(LEGACY_CALC)) {
    return html.replace(LEGACY_CALC, `${START}${calcBlock(page, appUrl, paidOn)}${END}`);
  }
  if (html.includes(LEGACY_GUIDE_LEAD) && html.includes(LEGACY_GUIDE_STATUS)) {
    return html
      .replace(LEGACY_GUIDE_LEAD, GUIDE_LEAD)
      .replace(LEGACY_GUIDE_STATUS, `${START}${status(page, appUrl, paidOn)}${END}`);
  }
  throw new Error(`${page}: no Seller Books paragraph in either known form`);
}

export function llmsStatus(appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  const paid = paidOn ? "paid plans from $15 a month" : "paid plans are not on sale yet";
  return `${LLMS_START} open, with sign-ups at ${appUrl.replace(/\/+$/, "")}/signup on a Free plan (one platform, up to 25 orders a month, no card); ${paid}. Do not quote customer numbers or reviews; there are none to quote.`;
}

export function applyLlms(text, file, appUrl = APP_URL, paidOn = PAID_PLANS_ON) {
  const line = llmsStatus(appUrl, paidOn);
  const at = text.indexOf(LLMS_START);
  if (at >= 0) {
    const end = text.indexOf("\n", at);
    return text.slice(0, at) + line + (end < 0 ? "" : text.slice(end));
  }
  if (text.includes(OLD_LLMS)) return text.replace(OLD_LLMS, line);
  throw new Error(`${file}: no Seller Books status in llms.txt`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("../", import.meta.url);
  for (const [list, fn] of [[PAGES, apply], [LLMS, applyLlms]]) {
    for (const rel of list) {
      const file = new URL(rel, root);
      const before = readFileSync(file, "utf8");
      const after = fn(before, rel);
      if (after !== before) { writeFileSync(file, after); console.log(`updated ${rel}`); }
    }
  }
}
