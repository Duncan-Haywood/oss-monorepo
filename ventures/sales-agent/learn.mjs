// A second opinion for replies the rules cannot read: multinomial naive Bayes over words and word pairs, trained on
// every labelled reply file in eval/ (replies, heldout and fresh-*; since 2026-11-11, when leave-one-set-out scoring
// in eval/guess-cv.mjs showed the wider model reads more hand-offs right and drafts less often where it should not).
// Its answer is a guess: runInbox shows it and pauses the prospect, and never acts on it (no suppression, no stage).
//   node learn.mjs --write   rebuilds model.mjs from the training files
import { MODEL } from "./model.mjs";

export const tokens = (subject, body) => {
  const w = `${String(subject || "").replace(/^(re|fwd?|aw|sv):\s*/i, "")} ${body || ""}`.toLowerCase().replace(/[^a-z0-9' ]+/g, " ").split(/\s+/).filter(Boolean);
  return [...w, ...w.slice(1).map((x, i) => `${w[i]}_${x}`)];
};

export function train(rows) {
  const docs = {}, counts = {}, totals = {}, vocab = new Set();
  for (const r of rows) {
    docs[r.label] = (docs[r.label] || 0) + 1;
    counts[r.label] ??= {};
    for (const t of tokens(r.subject, r.body)) { counts[r.label][t] = (counts[r.label][t] || 0) + 1; totals[r.label] = (totals[r.label] || 0) + 1; vocab.add(t); }
  }
  return { n: rows.length, docs, counts, totals, vocab: vocab.size };
}

/** -> { category, margin } where margin is the log-odds lead over the runner-up (bigger is surer), or null with no model. */
export function guess(reply, model = MODEL) {
  if (!model?.n) return null;
  const toks = tokens(reply.subject, reply.body), scores = [];
  for (const c of Object.keys(model.docs)) {
    let s = Math.log(model.docs[c] / model.n);
    for (const t of toks) s += Math.log(((model.counts[c][t] || 0) + 1) / (model.totals[c] + model.vocab));
    scores.push([c, s]);
  }
  scores.sort((a, b) => b[1] - a[1]);
  return { category: scores[0][0], margin: +(scores[0][1] - (scores[1]?.[1] ?? scores[0][1])).toFixed(2) };
}

// Labels the engine has no category for. One reply in fresh-2026-11-03c is labelled "wrong_person" (the engine files that as
// left_company); trained as its own class, a guess of it crashed runInbox (fixed 2026-11-11). Unknown labels are dropped.
const ALIAS = { wrong_person: "left_company" };
const KNOWN = new Set(["unsubscribe", "bounce", "not_interested", "left_company", "out_of_office", "not_now", "objection", "question", "interested", "unclear"]);
export const trainingLabel = (r) => { const label = Object.hasOwn(ALIAS, r.label) ? ALIAS[r.label] : r.label; return KNOWN.has(label) ? { ...r, label } : null; };

export const TRAINING_FILE = /^(replies|heldout|fresh-[\d-]+[a-z]?)\.jsonl$/;

if (typeof process !== "undefined" && import.meta.url === `file://${process.argv[1]}` && process.argv.includes("--write")) {
  const { readFileSync, writeFileSync, readdirSync } = await import("node:fs");
  const dir = new URL("./eval/", import.meta.url);
  const files = readdirSync(dir).filter((f) => TRAINING_FILE.test(f)).sort();
  const rows = files.flatMap((f) => readFileSync(new URL(f, dir), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l))).map(trainingLabel).filter(Boolean);
  writeFileSync(new URL("./model.mjs", import.meta.url), `// Generated by \`node learn.mjs --write\` from ${files.length} labelled reply files in eval/ (see learn.mjs). Do not edit.\nexport const MODEL = ${JSON.stringify(train(rows))};\n`);
  console.log(`model.mjs: ${rows.length} replies from ${files.length} files`);
}
