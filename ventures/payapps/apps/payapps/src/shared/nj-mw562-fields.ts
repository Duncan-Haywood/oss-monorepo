/** Every field name the map knows: a chosen PDF is the 2/25 form when it has them all. */
export function mw562FieldNames(): string[] {
  const out: string[] = [
    ...Object.values(MW562_HEADER),
    ...MW562_DATES,
    ...Object.values(MW562_PAGE2),
  ];
  for (const row of MW562_ROWS) {
    for (const v of Object.values(row)) {
      if (typeof v === "string") out.push(v);
      else out.push(...v);
    }
  }
  for (let k = 0; k < 18; k++) out.push(...Object.values(mw562ProgramRow(k)));
  return out;
}
