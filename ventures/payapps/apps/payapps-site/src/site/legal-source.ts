// Node only: reads the app's legal documents from disk and writes the bundled copy the site builds
// from (src/site/legal-docs.ts). Used by scripts/sync-legal.ts and its drift test; never imported by
// the Worker or by the page build.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
/** The app's legal folder: the one source of the documents a customer accepts. */
export const APP_LEGAL_DIR = join(ROOT, "..", "payapps", "docs", "legal");
export const LEGAL_DOCS_FILE = join(ROOT, "src", "site", "legal-docs.ts");
/** The documents the site publishes. Privacy is left out: the site has its own notice, which links the app's. */
export const SITE_LEGAL_KEYS = ["terms", "refunds", "acceptable-use"] as const;

export function legalDocsSource(): string {
  let body = `// GENERATED by scripts/sync-legal.ts from apps/payapps/docs/legal/*.md; do not edit by hand.
// Regenerate with \`pnpm sync:legal\` after the app's legal documents change.

export const SITE_LEGAL_MARKDOWN = {
`;
  for (const key of SITE_LEGAL_KEYS) {
    const md = readFileSync(join(APP_LEGAL_DIR, `${key}.md`), "utf8");
    body += `  ${JSON.stringify(key)}: ${JSON.stringify(md)},\n`;
  }
  return `${body}} as const;\n`;
}
