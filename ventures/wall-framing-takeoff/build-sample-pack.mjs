// Regenerates sample-bid-package.html from the real bid-package code on an invented plan
// (the built-in example house), so the marketing page shows exactly what a buyer gets.
// Run: node build-sample-pack.mjs
import { writeFileSync } from "node:fs";
import { main } from "./cli.mjs";
import { samplePlan } from "./engine.mjs";
import { proposal } from "./bidletter.mjs";
import { bidPackageHtml } from "./bidpackage.mjs";

const SAMPLE_LD = `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@type": "WebPage", name: "Sample bid package (invented job)", description: "A sample of the wall framing takeoff's branded bid package, generated by the real code from the built-in example house with invented prices. Not a real bid; the package is not on sale yet.", isPartOf: { "@type": "WebSite", name: "Wall Framing Takeoff" } })}</script>`;

const SAMPLE_ICON = '<link rel="icon" href="data:image/svg+xml,%3Csvg%20xmlns=\'http://www.w3.org/2000/svg\'%20viewBox=\'0%200%2032%2032\'%3E%3Crect%20width=\'32\'%20height=\'32\'%20rx=\'7\'%20fill=\'%237e1b26\'/%3E%3Ctext%20x=\'16\'%20y=\'23\'%20font-size=\'20\'%20font-family=\'system-ui,sans-serif\'%20font-weight=\'700\'%20text-anchor=\'middle\'%20fill=\'%23fff\'%3EW%3C/text%3E%3C/svg%3E">';

export function samplePack() {
  const plan = {
    ...samplePlan(),
    prices: { laborWallFoot: 6, laborOpening: 45, wallSheet: 24 },
    proposal: { client: "Sample Customer (invented)", project: "Sample house framing (invented)", date: "2026-01-01", validDays: 30 },
  };
  const out = main(["plan.json", "--budget", "--json"], () => JSON.stringify(plan));
  if (out.code !== 0) throw new Error(out.out);
  const b = JSON.parse(out.out);
  const q = proposal(b, plan.proposal);
  if (!q.ok) throw new Error(q.error || "proposal refused");
  const html = bidPackageHtml(q, b, { company: "Sample Framing Co. (invented)", address: "Sample only", phone: "555-0100", licenseNo: "SAMPLE-0", accent: "#7e1b26" });
  // A published sample, not a product page: kept out of search results.
  // The sample page is ours, not the buyer's bid, so it carries the site's no-warranty line (PRODUCT_PLAYBOOK.md 5b).
  const note = '<p class="small"><strong>No warranty.</strong> This sample uses invented names and prices; it is provided as-is and is not engineering, construction, legal or financial advice.</p>';
  return html.replace('</body>', `${note}</body>`).replace('</head>', `<meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex">${SAMPLE_ICON}${SAMPLE_LD}</head>`);
}
if (process.argv[1] && process.argv[1].endsWith("build-sample-pack.mjs")) writeFileSync(new URL("./sample-bid-package.html", import.meta.url), samplePack());
