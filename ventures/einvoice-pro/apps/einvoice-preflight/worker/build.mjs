// @ts-check
// Writes worker/files.generated.mjs: the files the Cloudflare Worker (worker/index.mjs) serves or
// reads, embedded because a Worker has no disk. Run before `wrangler dev` / `wrangler deploy`
// (docs/HOSTING.md, "On Cloudflare Workers"). Proprietary (see ../LICENSE, part 2).
//
//   node worker/build.mjs
//
// Embedded: the workspace page (pro/web/), the legal texts (pro/legal/, every language), the
// generator's PDF fonts (fonts/*.ttf) and the plain-JS rule sets (plain/*.json, the official
// Schematron compiled to JSON, run by fontoxpath). Text stays text (it compresses best); fonts
// are base64. The generated file is git-ignored: it is a build output of files already in the tree.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const APP = new URL("../", import.meta.url);
export const OUT = new URL("./files.generated.mjs", import.meta.url);

/** The folders the Worker needs, each with the file names it takes. */
export const SOURCES = /** @type {const} */ ([
  { dir: "pro/web", match: /^(index\.html|app\.js|app\.css|workspace-lib\.mjs)$/, binary: false },
  { dir: "pro/legal", match: /^(terms|privacy|dpa)\.md$/, binary: false },
  { dir: "pro/legal/de", match: /^(terms|privacy|dpa)\.md$/, binary: false },
  { dir: "pro/legal/fr", match: /^(terms|privacy|dpa)\.md$/, binary: false },
  { dir: "fonts", match: /^[A-Za-z0-9-]+\.ttf$/, binary: true },
  { dir: "plain", match: /^[\w.-]+\.json$/, binary: false },
]);

/** @returns {{ text: Record<string, string>, base64: Record<string, string> }} */
export function collect() {
  /** @type {Record<string, string>} */
  const text = {};
  /** @type {Record<string, string>} */
  const base64 = {};
  for (const s of SOURCES) {
    for (const name of readdirSync(new URL(`${s.dir}/`, APP)).sort()) {
      if (!s.match.test(name)) continue;
      const rel = `${s.dir}/${name}`;
      const bytes = readFileSync(new URL(rel, APP));
      if (s.binary) base64[rel] = bytes.toString("base64");
      else text[rel] = bytes.toString("utf8");
    }
  }
  return { text, base64 };
}

/** @param {{ text: Record<string, string>, base64: Record<string, string> }} files */
export function render(files) {
  return [
    "// Generated by worker/build.mjs. Do not edit; do not commit.",
    `export const TEXT = ${JSON.stringify(files.text)};`,
    `export const BASE64 = ${JSON.stringify(files.base64)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = collect();
  const out = render(files);
  writeFileSync(OUT, out);
  const n = Object.keys(files.text).length + Object.keys(files.base64).length;
  console.log(`wrote ${fileURLToPath(OUT)}: ${n} files, ${(out.length / 1048576).toFixed(1)} MB`);
}
