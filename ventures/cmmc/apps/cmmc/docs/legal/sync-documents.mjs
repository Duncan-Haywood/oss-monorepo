// Copied from apps/jobshop-quote/docs/legal/sync-documents.mjs (originally apps/payapps).
// Regenerates src/worker/services/legal/documents.ts from the markdown files in this folder.
// Workers cannot read the repo at runtime, so the documents are bundled as string constants.
// Run from apps/cmmc:  node docs/legal/sync-documents.mjs
// A unit test (src/worker/services/legal/documents.test.ts) fails if the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const keys = ["terms", "privacy", "refunds", "acceptable-use"];
const out = join(here, "../../src/worker/services/legal/documents.ts");

const literal = (s) =>
  `\`${s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;

let body = `// GENERATED by docs/legal/sync-documents.mjs from docs/legal/*.md — do not edit by hand.
import type { LegalDocKey } from "@shared/legal";

export interface LegalDocumentSource {
  title: string;
  /** ISO date the document text last changed (from its "Version" line). */
  updatedAt: string;
  markdown: string;
}

export const LEGAL_DOCUMENTS: Record<LegalDocKey, LegalDocumentSource> = {
`;
for (const key of keys) {
  const md = readFileSync(join(here, `${key}.md`), "utf8");
  const title = md.match(/^# (.+)$/m)?.[1]?.trim();
  const updatedAt = md.match(/\*\*Version (\d{4}-\d{2}-\d{2})\*\*/)?.[1];
  if (!title || !updatedAt)
    throw new Error(`${key}.md needs a "# Title" and a "**Version YYYY-MM-DD**" line`);
  const prop = /^[a-z]+$/.test(key) ? key : JSON.stringify(key);
  body += `  ${prop}: {\n    title: ${JSON.stringify(title)},\n    updatedAt: ${JSON.stringify(updatedAt)},\n    markdown: ${literal(md)},\n  },\n`;
}
body += "};\n";
writeFileSync(out, body);
console.log(`wrote ${out}`);
