// Extracts what the "NIST SP 800-171 Rev. 2 vs Rev. 3" page needs from NIST's own OSCAL catalog of
// SP 800-171 Rev. 3 (usnistgov/oscal-content, nist.gov/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json):
// every requirement number 03.01.01 to 03.17.03, its title, whether NIST withdrew it and where to
// ("incorporated_into" / "addressed_by" links), its organization-defined parameters (ODPs), its
// statement with each ODP shown as "[Assignment: organization-defined ...]" and its count of
// SP 800-171A Rev. 3 determination statements. Nothing is reworded.
//
//   curl -sO https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json
//   node scripts/extract-rev3.mjs NIST_SP800-171_rev3_catalog.json 2026-11-28
//
// Writes fixtures/nist-800-171r3/rev3-extract.json with the source file's sha256 and the read date.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_URL =
  "https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json";

const leafCount = (p) => (p.parts?.length ? p.parts.reduce((s, x) => s + leafCount(x), 0) : 1);

/** Each "{{ insert: param, ID }}" shown as NIST prints it: "[Assignment: organization-defined ...]". */
function fill(prose, params) {
  return prose.replace(/\{\{ insert: param, ([^ }]+) \}\}/g, (_, id) => {
    const odp = params.get(id);
    if (!odp) throw new Error(`unknown parameter ${id}`);
    return `[Assignment: ${odp.usage ?? odp.label}]`;
  });
}

/** One statement item and its sub-items, flattened, with ODP placeholders filled from the params. */
function items(part, params, depth = 0, out = []) {
  for (const p of part.parts ?? []) {
    if (p.name !== "item") continue;
    const label = (p.props ?? []).find((x) => x.name === "label")?.value ?? "";
    out.push({ label: label.replace(/^SR-/, ""), depth, text: fill(p.prose ?? "", params) });
    items(p, params, depth + 1, out);
  }
  return out;
}

/** @param {Buffer} raw the catalog file as downloaded */
export function extract(raw, readOn) {
  const catalog = JSON.parse(raw.toString("utf8")).catalog;
  const requirements = [];
  for (const g of catalog.groups) {
    for (const c of g.controls) {
      const id = c.id.replace(/^SP_800_171_/, "");
      const props = c.props ?? [];
      const withdrawn = props.some((p) => p.name === "status" && p.value === "withdrawn");
      const links = (c.links ?? []).filter((l) => l.rel !== "reference");
      const params = new Map((c.params ?? []).map((p) => [p.id, p]));
      const statement = (c.parts ?? []).find((p) => p.name === "statement");
      const objectives = (c.parts ?? [])
        .filter((p) => p.name === "assessment-objective")
        .reduce((s, p) => s + leafCount(p), 0);
      requirements.push({
        id,
        family: g.id.replace(/^SP_800_171_/, ""),
        title: withdrawn ? null : c.title,
        withdrawn,
        incorporatedInto: links.filter((l) => l.rel === "incorporated_into").map((l) => l.href),
        addressedBy: links.filter((l) => l.rel === "addressed_by").map((l) => l.href),
        odps: [...params.values()].map((p) => p.usage ?? p.label),
        statement: statement
          ? statement.prose
            ? [{ label: id, depth: 0, text: fill(statement.prose, params) }]
            : items(statement, params)
          : [],
        objectives,
      });
    }
  }
  return {
    _about:
      "Generated by scripts/extract-rev3.mjs from NIST's OSCAL catalog of SP 800-171 Rev. 3. Do not edit by hand.",
    source: SOURCE_URL,
    sha256: createHash("sha256").update(raw).digest("hex"),
    readOn,
    catalogVersion: catalog.metadata.version,
    catalogLastModified: catalog.metadata["last-modified"],
    families: catalog.groups.map((g) => ({ id: g.id.replace(/^SP_800_171_/, ""), title: g.title })),
    requirements,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [file, readOn] = process.argv.slice(2);
  if (!file || !/^\d{4}-\d{2}-\d{2}$/.test(readOn ?? ""))
    throw new Error("usage: node scripts/extract-rev3.mjs <catalog.json> <YYYY-MM-DD read on>");
  const out = join(
    dirname(fileURLToPath(import.meta.url)),
    "../fixtures/nist-800-171r3/rev3-extract.json",
  );
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${JSON.stringify(extract(readFileSync(file), readOn), null, 1)}\n`);
  console.log(`wrote ${out}`);
}
