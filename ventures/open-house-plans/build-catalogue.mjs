#!/usr/bin/env node
// @ts-check
// Regenerate the catalogue: node build-catalogue.mjs [--check]
//
// For each brief in catalogue.mjs, writes catalogue/<id>/ (README.md,
// design.json, view.svg, plan.svg, lumber-order.csv) and catalogue-data.mjs, the summaries the
// page shows. --check exits 1 if anything on disk differs from a fresh run,
// which is how the tests keep the catalogue in step with the engine.

import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { designFiles } from "./engine.mjs";
import { CATALOGUE } from "./catalogue.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const KEEP = ["README.md", "design.json", "view.svg", "plan.svg", "lumber-order.csv"];

export function buildCatalogue() {
  const out = {};
  const data = [];
  for (const c of CATALOGUE) {
    const r = designFiles({ ...c.brief, name: c.name });
    if (r.error) throw new Error(`${c.id}: ${r.error}`);
    for (const f of KEEP) out[`catalogue/${c.id}/${f}`] = r.files[f];
    const s = r.design;
    data.push({
      id: c.id, name: c.name, blurb: c.blurb, brief: c.brief, title: s.title,
      width: s.footprint.width, depth: s.footprint.depth, area: s.footprint.conditioned,
      cost: s.cost.total, perSqFt: s.cost.perSqFt, style: s.style.label, checksPassed: s.checks.passed, checksFailed: s.checks.failed.length,
    });
  }
  out["catalogue-data.mjs"] = `// Generated by build-catalogue.mjs from catalogue.mjs. Do not edit.\nexport const CATALOGUE_DATA = ${JSON.stringify(data, null, 1)};\n`;
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const files = buildCatalogue();
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(HERE, rel);
    const same = existsSync(p) && readFileSync(p, "utf8") === text;
    if (check) { if (!same) { stale++; console.error(`stale: ${rel}`); } continue; }
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  if (check) { console.log(stale ? `${stale} catalogue files are stale; run node build-catalogue.mjs` : "catalogue is current"); process.exitCode = stale ? 1 : 0; }
  else console.log(`wrote ${Object.keys(files).length} files`);
}
