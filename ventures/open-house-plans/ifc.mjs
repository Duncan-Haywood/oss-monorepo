// @ts-check
// IFC4 (ISO 16739) export, written as STEP text with no library. The model
// carries a site, building and storey; walls, slabs, the roof, windows and
// doors as faceted solids from model3d.mjs; openings that void the walls; and
// one IfcSpace per room with its name and floor area. Units are metres.
// Checked by reading it back with IfcOpenShell (see README, Verification).

import { bbox, area as polyArea } from "./geom.mjs";
import { faceNormal } from "./model3d.mjs";

const M = 0.3048;
const B64 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_$";

/** Deterministic 22-character IFC GlobalId from a string. */
export function guid(seed) {
  // two 64-bit FNV-1a style hashes give 128 bits
  let h1 = 0xcbf29ce484222325n, h2 = 0x84222325cbf29ce4n;
  const P = 0x100000001b3n, MASK = (1n << 64n) - 1n;
  for (let i = 0; i < seed.length; i++) {
    const c = BigInt(seed.charCodeAt(i));
    h1 = ((h1 ^ c) * P) & MASK;
    h2 = ((h2 ^ (c + 7n)) * P) & MASK;
  }
  let n = (h1 << 64n) | h2;
  let s = "";
  // first char carries 2 bits, then 21 chars of 6 bits
  s += B64[Number(n >> 126n) & 3];
  for (let i = 20; i >= 0; i--) s += B64[Number((n >> BigInt(i * 6)) & 63n)];
  return s;
}

const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "''").replace(/[^\x20-\x7e]/g, "")}'`;
const num = (v) => {
  const r = Math.round(v * 1e6) / 1e6;
  const t = r.toString();
  return t.includes(".") || t.includes("e") ? t.toUpperCase() : `${t}.`;
};

export function toIFC(plan, model, brief, { name = "House", timestamp = 0 } = {}) {
  const lines = [];
  let id = 0;
  const E = (s) => { lines.push(`#${++id}=${s};`); return `#${id}`; };
  const pt3 = (p) => E(`IFCCARTESIANPOINT((${num(p[0] * M)},${num(p[1] * M)},${num(p[2] * M)}))`);
  const origin = E("IFCCARTESIANPOINT((0.,0.,0.))");
  const zDir = E("IFCDIRECTION((0.,0.,1.))");
  const xDir = E("IFCDIRECTION((1.,0.,0.))");
  const place3 = E(`IFCAXIS2PLACEMENT3D(${origin},${zDir},${xDir})`);
  const ctx = E(`IFCGEOMETRICREPRESENTATIONCONTEXT($,'Model',3,1.E-05,${place3},$)`);
  const body = E(`IFCGEOMETRICREPRESENTATIONSUBCONTEXT('Body','Model',*,*,*,*,${ctx},$,.MODEL_VIEW.,$)`);
  const units = [
    E("IFCSIUNIT(*,.LENGTHUNIT.,$,.METRE.)"),
    E("IFCSIUNIT(*,.AREAUNIT.,$,.SQUARE_METRE.)"),
    E("IFCSIUNIT(*,.VOLUMEUNIT.,$,.CUBIC_METRE.)"),
    E("IFCSIUNIT(*,.PLANEANGLEUNIT.,$,.RADIAN.)"),
  ];
  const ua = E(`IFCUNITASSIGNMENT((${units.join(",")}))`);
  const project = E(`IFCPROJECT('${guid(name + "/project")}',$,${str(name)},${str("Generated by Open House Plans. CC0 1.0. Not for construction.")},$,$,$,(${ctx}),${ua})`);
  const lp0 = E(`IFCLOCALPLACEMENT($,${place3})`);
  const site = E(`IFCSITE('${guid(name + "/site")}',$,'Site',$,$,${lp0},$,$,.ELEMENT.,$,$,$,$,$)`);
  const lp1 = E(`IFCLOCALPLACEMENT(${lp0},${place3})`);
  const building = E(`IFCBUILDING('${guid(name + "/building")}',$,${str(name)},$,$,${lp1},$,$,.ELEMENT.,$,$,$)`);
  const lp2 = E(`IFCLOCALPLACEMENT(${lp1},${place3})`);
  const storey = E(`IFCBUILDINGSTOREY('${guid(name + "/storey")}',$,'Ground floor',$,$,${lp2},$,$,.ELEMENT.,0.)`);
  E(`IFCRELAGGREGATES('${guid(name + "/agg1")}',$,$,$,${project},(${site}))`);
  E(`IFCRELAGGREGATES('${guid(name + "/agg2")}',$,$,$,${site},(${building}))`);
  E(`IFCRELAGGREGATES('${guid(name + "/agg3")}',$,$,$,${building},(${storey}))`);
  const lpEl = E(`IFCLOCALPLACEMENT(${lp2},${place3})`);

  const brep = (faces) => {
    const fs = faces.map((f) => {
      const pts = f.pts.map(pt3);
      const loop = E(`IFCPOLYLOOP((${pts.join(",")}))`);
      const bound = E(`IFCFACEOUTERBOUND(${loop},.T.)`);
      return E(`IFCFACE((${bound}))`);
    });
    const shell = E(`IFCCLOSEDSHELL((${fs.join(",")}))`);
    return E(`IFCFACETEDBREP(${shell})`);
  };
  const shape = (items) => {
    const rep = E(`IFCSHAPEREPRESENTATION(${body},'Body','Brep',(${items.join(",")}))`);
    return E(`IFCPRODUCTDEFINITIONSHAPE($,$,(${rep}))`);
  };
  // group solids into products
  const contained = [];
  let n = 0;
  const product = (ifcType, label, solids, tail) => {
    const items = solids.map((faces) => brep(faces));
    const s = shape(items);
    const ref = E(`${ifcType}('${guid(`${name}/${ifcType}/${++n}/${label}`)}',$,${str(label)},$,$,${lpEl},${s},$${tail})`);
    contained.push(ref);
    return ref;
  };
  const els = model.elements;
  // walls: one IfcWall per outside side, and one per partition wall
  const bySide = new Map();
  for (const el of els) if (el.kind === "wall" || el.kind === "gable") {
    const k = el.side || el.name;
    if (!bySide.has(k)) bySide.set(k, []);
    bySide.get(k).push(el.faces);
  }
  const wallRef = {};
  for (const [k, solids] of bySide) wallRef[k] = product("IFCWALL", `Exterior wall (${k})`, solids, ",.STANDARD.");
  const parts = new Map();
  for (const el of els) if (el.kind === "partition") {
    if (!parts.has(el.wall)) parts.set(el.wall, { name: el.name, solids: [] });
    parts.get(el.wall).solids.push(el.faces);
  }
  for (const [wid, p] of parts) wallRef[wid] = product("IFCWALL", p.name, p.solids, ",.PARTITIONING.");
  // floor slab, porch
  for (const el of els) if (el.kind === "foundation") product("IFCSLAB", "Floor slab", [el.faces], ",.FLOOR.");
  for (const el of els) if (el.kind === "porch" || el.kind === "step") product("IFCSLAB", el.name, [el.faces], ",.LANDING.");
  for (const el of els) if (el.kind === "post") product("IFCCOLUMN", el.name, [el.faces], ",.COLUMN.");
  // roof: an IfcRoof made of IfcSlab ROOF parts
  const roofParts = els.filter((el) => el.kind === "roof").map((el) => product("IFCSLAB", el.name, [el.faces], ",.ROOF."));
  if (roofParts.length) {
    const roof = E(`IFCROOF('${guid(name + "/roof")}',$,'Roof',$,$,${lpEl},$,$,.${model.roofType || "GABLE_ROOF"}.)`);
    contained.push(roof);
    E(`IFCRELAGGREGATES('${guid(name + "/roofagg")}',$,$,$,${roof},(${roofParts.join(",")}))`);
    // the parts belong to the roof, not directly to the storey
    for (const r of roofParts) contained.splice(contained.indexOf(r), 1);
  }
  // windows and doors, with openings that void their wall
  const wallsById = new Map(plan.walls.map((w) => [w.id, w]));
  const h = model.h;
  for (const el of els) {
    if (el.kind !== "glass" && el.kind !== "door") continue;
    const o = plan.openings.find((x) => x.id === el.opening);
    if (!o) continue;
    const isWin = o.kind === "window";
    const w = wallsById.get(o.wall);
    const side = w.dir === "h" ? (Math.abs(w.c) < 1e-6 ? "front" : "back") : Math.abs(w.c) < 1e-6 ? "left" : "right";
    const fill = product(isWin ? "IFCWINDOW" : "IFCDOOR", el.name, [el.faces], `,${num(o.height * M)},${num(o.width * M)},${isWin ? ".WINDOW.,.SINGLE_PANEL.,$" : `.${o.kind === "garage" ? "GATE" : "DOOR"}.,.SINGLE_SWING_LEFT.,$`}`);
    // opening box through the wall
    const z0 = h.base + (isWin ? o.sill : 0), z1 = z0 + o.height;
    const a = o.pos - o.width / 2, b = o.pos + o.width / 2;
    const t0 = -0.1, t1 = 0.7;
    const P = w.dir === "h" ? (s, t, z) => [s, Math.abs(w.c) < 1e-6 ? t : plan.D - t, z] : (s, t, z) => [Math.abs(w.c) < 1e-6 ? t : plan.W - t, s, z];
    const bx = [[a, t0], [b, t0], [b, t1], [a, t1]];
    const quads = [];
    const bottom = bx.map(([s, t]) => P(s, t, z0)), top = bx.map(([s, t]) => P(s, t, z1));
    quads.push(bottom, top.slice().reverse());
    for (let i = 0; i < 4; i++) { const j = (i + 1) % 4; quads.push([bottom[i], top[i], top[j], bottom[j]]); }
    // orient outward
    const c = [(a + b) / 2, 0, 0];
    const cen = P((a + b) / 2, (t0 + t1) / 2, (z0 + z1) / 2);
    const faces = quads.map((q) => {
      const nrm = faceNormal(q);
      const qc = q.reduce((s, p) => [s[0] + p[0] / 4, s[1] + p[1] / 4, s[2] + p[2] / 4], [0, 0, 0]);
      const d = (qc[0] - cen[0]) * nrm[0] + (qc[1] - cen[1]) * nrm[1] + (qc[2] - cen[2]) * nrm[2];
      return { pts: d < 0 ? q.slice().reverse() : q };
    });
    void c;
    const opening = E(`IFCOPENINGELEMENT('${guid(`${name}/opening/${o.id}`)}',$,'Opening',$,$,${lpEl},${shape([brep(faces)])},$,.OPENING.)`);
    const host = wallRef[side];
    if (host) E(`IFCRELVOIDSELEMENT('${guid(`${name}/voids/${o.id}`)}',$,$,$,${host},${opening})`);
    E(`IFCRELFILLSELEMENT('${guid(`${name}/fills/${o.id}`)}',$,$,$,${opening},${fill})`);
  }
  // spaces: the room footprint extruded to the ceiling
  const spaces = [];
  for (const r of plan.rooms) {
    const pts = r.poly.map(([x, y]) => E(`IFCCARTESIANPOINT((${num(x * M)},${num(y * M)}))`));
    const poly = E(`IFCPOLYLINE((${[...pts, pts[0]].join(",")}))`);
    const prof = E(`IFCARBITRARYCLOSEDPROFILEDEF(.AREA.,${str(r.name)},${poly})`);
    const basePt = E(`IFCCARTESIANPOINT((0.,0.,${num(h.base * M)}))`);
    const pl = E(`IFCAXIS2PLACEMENT3D(${basePt},${zDir},${xDir})`);
    const solid = E(`IFCEXTRUDEDAREASOLID(${prof},${pl},${zDir},${num(plan.ceiling * M)})`);
    const rep = E(`IFCSHAPEREPRESENTATION(${body},'Body','SweptSolid',(${solid}))`);
    const pds = E(`IFCPRODUCTDEFINITIONSHAPE($,$,(${rep}))`);
    const sp = E(`IFCSPACE('${guid(`${name}/space/${r.id}`)}',$,${str(r.name)},$,$,${lpEl},${pds},${str(r.kind)},.ELEMENT.,.INTERNAL.,$)`);
    const q = E(`IFCQUANTITYAREA('GrossFloorArea',$,$,${num(polyArea(r.poly) * M * M)},$)`);
    const qs = E(`IFCELEMENTQUANTITY('${guid(`${name}/qto/${r.id}`)}',$,'Qto_SpaceBaseQuantities',$,$,(${q}))`);
    E(`IFCRELDEFINESBYPROPERTIES('${guid(`${name}/defq/${r.id}`)}',$,$,$,(${sp}),${qs})`);
    spaces.push(sp);
  }
  if (spaces.length) E(`IFCRELAGGREGATES('${guid(name + "/spaces")}',$,$,$,${storey},(${spaces.join(",")}))`);
  E(`IFCRELCONTAINEDINSPATIALSTRUCTURE('${guid(name + "/contains")}',$,$,$,(${contained.join(",")}),${storey})`);

  const ts = new Date(timestamp).toISOString().slice(0, 19);
  const head = [
    "ISO-10303-21;",
    "HEADER;",
    "FILE_DESCRIPTION(('ViewDefinition [DesignTransferView]'),'2;1');",
    `FILE_NAME(${str(name + ".ifc")},'${ts}',('Open House Plans'),('CC0 1.0'),'open-house-plans','open-house-plans','');`,
    "FILE_SCHEMA(('IFC4'));",
    "ENDSEC;",
    "DATA;",
  ];
  return [...head, ...lines, "ENDSEC;", "END-ISO-10303-21;", ""].join("\n");
}
