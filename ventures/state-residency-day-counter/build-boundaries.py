#!/usr/bin/env python3
"""Regenerate state-boundaries.mjs from the us-atlas `states-10m.json` TopoJSON
(US Census cartographic boundary files, public domain; npm package us-atlas).

    python3 build-boundaries.py path/to/states-10m.json > state-boundaries.mjs

Rings are simplified (Douglas-Peucker, 0.002 degrees, roughly 200 m) and stored
as flat [lon, lat, lon, lat, ...] arrays rounded to 3 decimals.
"""
import json
import sys

FIPS = {
    "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE",
    "11": "DC", "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA",
    "20": "KS", "21": "KY", "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN",
    "28": "MS", "29": "MO", "30": "MT", "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM",
    "36": "NY", "37": "NC", "38": "ND", "39": "OH", "40": "OK", "41": "OR", "42": "PA", "44": "RI",
    "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT", "50": "VT", "51": "VA", "53": "WA",
    "54": "WV", "55": "WI", "56": "WY",
}
TOL = 0.002


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    out = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        out.append(pts)
    return out


def ring_points(arcs, ids):
    pts = []
    for i in ids:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        n = dx * dx + dy * dy
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            if n == 0:
                d = ((px - x1) ** 2 + (py - y1) ** 2) ** 0.5
            else:
                d = abs(dy * (px - x1) - dx * (py - y1)) / n ** 0.5
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def main(path):
    topo = json.load(open(path))
    arcs = decode_arcs(topo)
    states = {}
    for g in topo["objects"]["states"]["geometries"]:
        code = FIPS.get(g["id"])
        if not code:
            continue
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        rings = []
        for poly in polys:
            for ring in poly:
                pts = dp(ring_points(arcs, ring), TOL)
                if len(pts) >= 4:
                    rings.append([round(v, 3) for p in pts for v in p])
        states[code] = rings
    print("// Generated by build-boundaries.py from the US Census cartographic boundary")
    print("// files via the us-atlas package (states-10m). Simplified to ~200 m; do not edit.")
    print("// Each state is a list of rings, each ring a flat [lon, lat, lon, lat, ...] array.")
    print("export const STATE_RINGS = " + json.dumps(states, separators=(",", ":")) + ";")


main(sys.argv[1])
