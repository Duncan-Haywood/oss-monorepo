"""Regenerate data.mjs from the reference packages.

    python3 -m venv /tmp/pv && /tmp/pv/bin/pip install "packaging>=26" trove-classifiers
    /tmp/pv/bin/python eval/build-data.py > data.mjs

The SPDX lists come from packaging.licenses._spdx (SPDX License List data, CC0) and the
classifiers from trove-classifiers (the list PyPI accepts). Both are facts, copied as data.
"""
import json
import importlib.metadata as md
from packaging.licenses._spdx import LICENSES, EXCEPTIONS, VERSION as SPDX_VERSION
import trove_classifiers as tc

lic = {k: [v["id"], 1 if v["deprecated"] else 0] for k, v in sorted(LICENSES.items())}
exc = {k: [v["id"], 1 if v["deprecated"] else 0] for k, v in sorted(EXCEPTIONS.items())}
print("// Generated by eval/build-data.py; do not edit by hand.")
print(f"// SPDX License List {SPDX_VERSION} (via packaging {md.version('packaging')}), trove-classifiers {md.version('trove-classifiers')}.")
print(f"export const SPDX_VERSION = {json.dumps(SPDX_VERSION)};")
print(f"export const CLASSIFIERS_VERSION = {json.dumps(md.version('trove-classifiers'))};")
print("// lower-case id -> [canonical id, deprecated]")
print(f"export const LICENSES = {json.dumps(lic, separators=(',', ':'))};")
print(f"export const EXCEPTIONS = {json.dumps(exc, separators=(',', ':'))};")
print(f"export const CLASSIFIERS = {json.dumps(sorted(tc.classifiers), separators=(',', ':'))};")
print(f"export const DEPRECATED_CLASSIFIERS = {json.dumps(dict(sorted(tc.deprecated_classifiers.items())), separators=(',', ':'))};")
