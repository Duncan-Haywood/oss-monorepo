#!/usr/bin/env node
// Folds `presets/*.json` into `presets.mjs`, the trade takeoffs the page imports.
//
//   node build-presets.mjs           # rewrite presets.mjs
//   node build-presets.mjs --check   # exit 1 if presets.mjs is stale or a profile is invalid
//
// The page should not make 119 requests to start, so the presets ship as one
// module. Each profile stays its own JSON file so it can be reviewed against
// the specialist calculator it was taken from (see presets/SCHEMA.md).

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TRADES_DIR = join(HERE, 'presets');
const VENTURES_DIR = join(HERE, '..');
const OUT = join(HERE, 'presets.mjs');

export const GROUPS = Object.freeze([
  'Cleaning & janitorial',
  'Exterior & roofing',
  'Paving, concrete & masonry',
  'Landscaping & outdoor',
  'Interior & finishes',
  'Mechanical, electrical & plumbing',
  'Specialty & remediation',
  'Vehicles & mobile',
  'Events & other services',
]);

const NUMERIC = ['crewSize', 'setupHours', 'minOnSiteHours', 'hourlyWage', 'burdenRate',
  'overheadRate', 'targetMargin', 'milesOneWay', 'tripFee'];
const ITEM_NUMERIC = ['qty', 'hoursPerUnit', 'materialPerUnit'];

export function validateProfile(profile, file, { venturesDir = VENTURES_DIR } = {}) {
  const problems = [];
  const say = (msg) => problems.push(`${file}: ${msg}`);
  const expected = `${file.replace(/\.json$/, '')}-bid-calculator`;
  if (profile.slug !== expected) say(`slug must be "${expected}"`);
  else if (!existsSync(join(venturesDir, profile.slug, 'calc.mjs'))) say(`no specialist at ventures/${profile.slug}`);
  for (const key of ['name', 'summary', 'specialistModels']) {
    if (typeof profile[key] !== 'string' || !profile[key].trim()) say(`${key} is required`);
  }
  if (typeof profile.summary === 'string' && profile.summary.length > 140) say('summary is over 140 characters');
  if (!GROUPS.includes(profile.group)) say(`group "${profile.group}" is not one of the listed groups`);
  if (!['good', 'partial'].includes(profile.fit)) say('fit must be "good" or "partial"');
  for (const key of NUMERIC) {
    if (profile[key] === undefined || profile[key] === null) continue;
    if (typeof profile[key] !== 'number' || !Number.isFinite(profile[key]) || profile[key] < 0) say(`${key} must be a non-negative number`);
  }
  if (profile.crewSize !== undefined && profile.crewSize < 1) say('crewSize must be at least 1');
  if (profile.targetMargin !== undefined && profile.targetMargin >= 100) say('targetMargin must be under 100');
  if (!Array.isArray(profile.items) || profile.items.length < 1 || profile.items.length > 8) {
    say('items must hold 1-8 line items');
  } else {
    profile.items.forEach((item, i) => {
      if (typeof item.label !== 'string' || !item.label.trim()) say(`items[${i}].label is required`);
      if (typeof item.unit !== 'string' || !item.unit.trim()) say(`items[${i}].unit is required`);
      if (typeof item.source !== 'string' || !item.source.trim()) say(`items[${i}].source is required`);
      for (const key of ITEM_NUMERIC) {
        if (typeof item[key] !== 'number' || !Number.isFinite(item[key]) || item[key] < 0) say(`items[${i}].${key} must be a non-negative number`);
      }
    });
    if (profile.items.every(item => item.hoursPerUnit === 0)) say('no line item carries any labor');
  }
  return problems;
}

export function loadProfiles(dir = TRADES_DIR) {
  const files = readdirSync(dir).filter(f => f.endsWith('.json')).sort();
  const profiles = [];
  const problems = [];
  for (const file of files) {
    let profile;
    try {
      profile = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    } catch (err) {
      problems.push(`${file}: not valid JSON (${err.message})`);
      continue;
    }
    problems.push(...validateProfile(profile, file));
    profile.id = file.replace(/\.json$/, '');
    profiles.push(profile);
  }
  profiles.sort((a, b) => a.name.localeCompare(b.name));
  return { profiles, problems };
}

export function render(profiles) {
  // `source` notes stay in the JSON for review; the page does not need them.
  const slim = profiles.map(({ id, slug, name, group, summary, fit, specialistModels, items, ...rest }) => {
    const out = { id, slug, name, group, summary, fit, specialistModels };
    for (const key of NUMERIC) if (rest[key] !== undefined && rest[key] !== null) out[key] = rest[key];
    out.items = items.map(({ label, unit, qty, hoursPerUnit, materialPerUnit }) => ({ label, unit, qty, hoursPerUnit, materialPerUnit }));
    return out;
  });
  return '// Generated by build-presets.mjs from presets/*.json. Do not edit by hand.\n'
    + `export const GROUPS = ${JSON.stringify(GROUPS)};\n`
    // One preset per line: small enough for the offline bundle, still diffable.
    + `export const PRESETS = [\n${slim.map(p => JSON.stringify(p)).join(',\n')}\n];\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { profiles, problems } = loadProfiles();
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  const text = render(profiles);
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('presets.mjs is stale: run node build-presets.mjs');
      process.exit(1);
    }
    console.log(`ok: ${profiles.length} presets`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote presets.mjs: ${profiles.length} presets`);
  }
}
