// Regenerates ../example-data.mjs from co2_mm_mlo.csv (NOAA GML, see SOURCE.md).
// Usage: node data/build-example.mjs
import { readFileSync, writeFileSync } from "node:fs";

const here = (p) => new URL(p, import.meta.url);
const rows = readFileSync(here("./co2_mm_mlo.csv"), "utf8")
  .split(/\r?\n/)
  .filter((l) => l && !l.startsWith("#") && !l.startsWith("year"))
  .map((l) => l.split(","));
const labels = rows.map((c) => `${c[0]}-${c[1].padStart(2, "0")}`);
const values = rows.map((c) => Number(c[3]));
if (values.some((v) => !(v > 0))) throw new Error("unexpected non-positive or missing CO2 value");
writeFileSync(
  here("../example-data.mjs"),
  `// NOAA Mauna Loa monthly mean CO2 (ppm), column "average" of data/co2_mm_mlo.csv.
// Source, licence and citation: data/SOURCE.md. Generated by data/build-example.mjs
// from the file retrieved 2026-10-20; do not edit by hand.
export const EXAMPLE = {
  column: "co2_ppm",
  source: "NOAA Global Monitoring Laboratory, Mauna Loa Observatory monthly mean CO2 (gml.noaa.gov/ccgg/trends/); March 1958 to April 1974 from the Scripps Institution of Oceanography. Credit: Dr. Xin Lan, NOAA/GML (gml.noaa.gov/ccgg/trends/) and Dr. Ralph Keeling, Scripps Institution of Oceanography (scrippsco2.ucsd.edu/). Retrieved 2026-10-20.",
  labels: ${JSON.stringify(labels)},
  values: ${JSON.stringify(values)},
};
`,
);
console.log(`wrote ${values.length} values, ${labels[0]} to ${labels.at(-1)}`);
