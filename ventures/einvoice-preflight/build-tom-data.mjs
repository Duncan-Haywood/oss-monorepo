// Reads the IBGE -> TOM (SIAFI) municipality code table that OpenAC.Net.NFSe keeps (MIT,
// src/OpenAC.Net.NFSe/Commom/Types/CodigoTOM.<UF>.cs, one AddCidade("IBGE", "TOM"); // Name/UF
// line per city) into tom-data.mjs. DSF's layout (dsf.mjs) writes its city codes as TOM codes,
// four digits (CodCidade 6291 is Campinas, whose IBGE code is 3509502).
//   node build-tom-data.mjs            (downloads the 27 files at the pinned commit)
//   OPENAC_ROOT=<checkout>/src/OpenAC.Net.NFSe node build-tom-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OPENAC_COMMIT = "cac2bb13ebe583e62e921229313c41fe0bbcf94f";
const ROOT = `https://raw.githubusercontent.com/OpenAC-Net/OpenAC.Net.NFSe/${OPENAC_COMMIT}/src/OpenAC.Net.NFSe`;
const UFS = "AC AL AM AP BA CE DF ES GO MA MG MS MT PA PB PE PI PR RJ RN RO RR RS SC SE SP TO".split(" ");
async function load(rel) {
  if (process.env.OPENAC_ROOT) return readFileSync(join(process.env.OPENAC_ROOT, rel), "utf8");
  const r = await fetch(`${ROOT}/${rel}`);
  if (!r.ok) throw new Error(`${rel}: HTTP ${r.status}`);
  return r.text();
}
const rows = [];
for (const uf of UFS) {
  const text = await load(`Commom/Types/CodigoTOM.${uf}.cs`);
  for (const m of text.matchAll(/AddCidade\("(\d{7})",\s*"(\d{4})"\);\s*\/\/\s*([^\r\n]+)/g)) rows.push([m[1], m[2], m[3].trim()]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const ibge = new Set(), tom = new Map();
for (const [i, t] of rows) {
  if (ibge.has(i)) throw new Error(`IBGE ${i} listed twice`);
  ibge.add(i);
  tom.set(t, (tom.get(t) ?? 0) + 1);
}
const dupTom = [...tom].filter(([, n]) => n > 1).map(([t]) => t);
// One row per city: IBGE code, TOM code, "Name/UF", tab-separated, newline-joined.
const body = `// Generated by build-tom-data.mjs from OpenAC.Net.NFSe at ${OPENAC_COMMIT.slice(0, 12)} (MIT); do not edit, rebuild.\n` +
  `// IBGE code, TOM (SIAFI) code and name of each Brazilian municipality, tab-separated.\n` +
  `export const SOURCE = ${JSON.stringify(`OpenAC.Net.NFSe CodigoTOM tables at ${OPENAC_COMMIT.slice(0, 12)} (MIT)`)};\n` +
  `export default ${JSON.stringify(rows.map((r) => r.join("\t")).join("\n"))};\n`;
writeFileSync(new URL("./tom-data.mjs", import.meta.url), body);
console.log(`${rows.length} cities, ${tom.size} distinct TOM codes${dupTom.length ? ` (shared: ${dupTom.join(", ")})` : ""}, ${body.length} bytes`);
