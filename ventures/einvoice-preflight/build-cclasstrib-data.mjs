// Reads Brazil's official table of IBS/CBS tax situation codes (CST) and tax
// classification codes (cClassTrib), the one the tax-reform layouts of NF-e, NFC-e and the
// national NFS-e point to, into cclasstrib-data.mjs, the table cclasstrib.mjs checks files
// against:
//   node build-cclasstrib-data.mjs [saved copy of the page]
// Without a file it downloads the SVRS portal's "Classificação Tributária" page (the
// Portal DF-e of Rio Grande do Sul's SEFAZ, which hosts the national DF-e tables), whose
// script carries the whole table as JSON (`var dadosOriginais = [...]`). The same table is
// published as a spreadsheet by the Portal da Conformidade; this page is the one that
// answered from a cloud build host (2026-11-13). Only facts are kept: each code's CST, its
// short name, its IBS and CBS rate reductions (percent), the dates it is in force, and
// whether the table allows it on an NF-e, an NFC-e and an NFS-e. Official tables are not
// copyright-protected in Brazil (Lei 9.610/1998 art. 8, IV); the source is cited anyway.
import { readFileSync, writeFileSync } from "node:fs";

export const SOURCE = "https://dfe-portal.svrs.rs.gov.br/DFE/ClassificacaoTributaria";

async function load() {
  const file = process.argv[2];
  if (file) return readFileSync(file, "utf8");
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
  return res.text();
}

/** Pull the JSON array out of the page's script. */
export function extractTable(html) {
  const marker = "var dadosOriginais = ";
  const at = html.indexOf(marker);
  if (at < 0) throw new Error("the page no longer carries `var dadosOriginais`; the layout changed");
  // The array ends where a bracket at depth 0 closes, outside strings.
  let depth = 0, inStr = false, esc = false, i = at + marker.length;
  for (; i < html.length; i++) {
    const c = html[i];
    if (inStr) { if (esc) esc = false; else if (c === "\\") esc = true; else if (c === '"') inStr = false; continue; }
    if (c === '"') inStr = true;
    else if (c === "[" || c === "{") depth++;
    else if (c === "]" || c === "}") { depth--; if (depth === 0) break; }
  }
  return JSON.parse(html.slice(at + marker.length, i + 1));
}

const day = (s) => (s ? String(s).slice(0, 10) : null);

/** Reduce the page's table to the facts the checks use. */
export function compact(table) {
  const cst = {}, codes = {};
  let published = "";
  for (const row of table) {
    cst[row.Cst] = { name: row.NomeCst, exigeTrib: !!row.IndExigeTrib, reducaoAliq: !!row.IndReducaoAliq, from: day(row.DthIniVig), to: day(row.DthFimVig) };
    for (const c of row.ClassificacoesTributarias || []) {
      if (c.Cst !== row.Cst) throw new Error(`${c.CodClassTrib}: listed under CST ${row.Cst} but says ${c.Cst}`);
      codes[c.CodClassTrib] = {
        cst: c.Cst,
        name: (c.NomeReduzido || c.NomeClassTrib || "").trim(),
        redIbs: Number(c.PercRedIbs) || 0,
        redCbs: Number(c.PercRedCbs) || 0,
        from: day(c.DthIniVig),
        to: day(c.DthFimVig),
        docs: (c.IndNfe ? "e" : "") + (c.IndNfce ? "c" : "") + (c.IndNfse ? "s" : ""),
        regular: !!c.IndTribRegular,
      };
      if (c.DthPublicacao > published) published = c.DthPublicacao;
    }
  }
  return { cst, codes, published: day(published) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { cst, codes, published } = compact(extractTable(await load()));
  const out = `// Generated by build-cclasstrib-data.mjs from ${SOURCE}
// (the SVRS Portal DF-e's CST and cClassTrib table; newest code published ${published}). Do not edit by hand; rebuild.
// docs: e = allowed on an NF-e (model 55), c = an NFC-e (model 65), s = a national NFS-e.
// redIbs / redCbs: the rate reduction in percent (60 = the rate is cut by 60%).
export const SOURCE = ${JSON.stringify(SOURCE)};
export const PUBLISHED = ${JSON.stringify(published)};
export const CST = ${JSON.stringify(cst)};
export const CCLASSTRIB = ${JSON.stringify(codes)};
`;
  writeFileSync(new URL("./cclasstrib-data.mjs", import.meta.url), out);
  console.log(`cclasstrib-data.mjs: ${Object.keys(cst).length} CST, ${Object.keys(codes).length} cClassTrib, newest published ${published}, ${out.length} bytes`);
}
