// Reads the Carta Porte 3.1 catalogue columns the checks in cartaporte31.mjs need, columns
// CartaPorte31.xsd and catCartaPorte.xsd do not carry, into cartaporte-data.mjs:
//   node build-cartaporte-data.mjs [dir holding the four .sql files and catCartaPorte.xsd]
// Without a directory it downloads them from phpcfdi/resources-sat-catalogs on GitHub
// (Unlicense: a public-domain copy of SAT's catCartaPorte spreadsheet as SQLite dumps).
// Read 2026-11-12. What is kept:
//   ESTACIONES   c_Estaciones codes by transport mode (column "Clave transporte": 02 sea,
//                03 air, 04 rail), so a station can be matched to the transport node;
//                5,280 rows. catCartaPorte.xsd lists 8,447 codes: the other 3,167 (EA001..,
//                EF001.., EF0001..) have no row in the mirror, so no mode, and are kept
//                in SIN_MODO: the code is accepted and the mode check skipped for them;
//   PELIGROSOS   every c_MaterialPeligroso code in catCartaPorte.xsd (4,686: UN numbers
//                and M codes; the mirror's table holds only 2,346 of them);
//   PROD_MP      c_ClaveProdServCP codes whose "Material peligroso" column is "1" or
//                "0,1" (every other code has "0");
//   CONFIG       c_ConfigAutotransporte's "Remolque" column: "0", "1" or "0,1";
//   PERMISOS     c_TipoPermiso's "Clave transporte" column (TPXX00 lists 01,02,03).
// String code sets are stored as {prefix|digits: base-36 gaps}: "PM|3": "1,1,1" is PM001,
// PM002, PM003.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIRROR = "https://raw.githubusercontent.com/phpcfdi/resources-sat-catalogs/master/database/data";
const XSD = "https://raw.githubusercontent.com/phpcfdi/resources-sat-xml/master/resources/www.sat.gob.mx/sitio_internet/cfd/catalogos/CartaPorte/catCartaPorte.xsd";

async function load(name) {
  const dir = process.argv[2];
  const file = name.endsWith(".xsd") ? name : `${name}.sql`;
  if (dir) return readFileSync(join(dir, file), "utf8");
  const res = await fetch(name.endsWith(".xsd") ? XSD : `${MIRROR}/${file}`);
  if (!res.ok) throw new Error(`${name}.sql: HTTP ${res.status}`);
  return res.text();
}

/** The VALUES(...) tuples of a SQLite dump, as arrays of strings ('' quotes undone). */
function rows(sql) {
  const out = [];
  for (const line of sql.split("\n")) {
    const i = line.indexOf("VALUES(");
    if (!line.startsWith("INSERT") || i < 0) continue;
    const body = line.slice(i + 7, line.lastIndexOf(")"));
    const vals = [];
    for (const m of body.matchAll(/'((?:[^']|'')*)'|([^,]+)/g)) vals.push(m[1] !== undefined ? m[1].replace(/''/g, "'") : m[2].trim());
    out.push(vals);
  }
  return out;
}

/** A set of codes as {prefix|width: gaps}. */
function packCodes(codes) {
  const groups = {};
  for (const c of new Set(codes)) {
    const m = /^(.*?)(\d*)$/.exec(c);
    (groups[`${m[1]}|${m[2].length}`] ||= []).push(m[2] === "" ? 0 : Number(m[2]));
  }
  const out = {};
  for (const k of Object.keys(groups).sort()) {
    let prev = -1;
    out[k] = groups[k].sort((a, b) => a - b).map((x) => { const d = x - prev; prev = x; return d.toString(36); }).join(",");
  }
  return out;
}

const estaciones = {};
for (const r of rows(await load("ccp_31_estaciones"))) {
  const [code, , modo] = r;
  if (!/^0[234]$/.test(modo)) throw new Error(`station ${code}: transport ${modo}`);
  (estaciones[modo] ||= []).push(code);
}
const xsd = await load("catCartaPorte.xsd");
const enumOf = (name) => {
  const m = new RegExp(`<xs:simpleType name="${name}">([\\s\\S]*?)</xs:simpleType>`).exec(xsd);
  if (!m) throw new Error(`${name} not in catCartaPorte.xsd`);
  return [...m[1].matchAll(/enumeration value="([^"]*)"/g)].map((x) => x[1]);
};
const withMode = new Set(Object.values(estaciones).flat());
const xsdStations = enumOf("c_Estaciones");
for (const c of withMode) if (!xsdStations.includes(c)) throw new Error(`station ${c} not in the XSD`);
const sinModo = xsdStations.filter((c) => !withMode.has(c));
const peligrosos = enumOf("c_MaterialPeligroso");
const prodMp = { "1": [], "0,1": [] };
for (const [code, , , mp] of rows(await load("ccp_31_productos_servicios"))) {
  const flag = mp.replace(/\s/g, "");
  if (flag === "0") continue;
  if (!prodMp[flag]) throw new Error(`product ${code}: material peligroso ${mp}`);
  prodMp[flag].push(code);
}
const config = {};
for (const r of rows(await load("ccp_31_configuraciones_autotransporte"))) config[r[0]] = r[4].replace(/\s/g, "");
const permisos = {};
for (const r of rows(await load("ccp_31_tipos_permiso"))) permisos[r[0]] = r[2].replace(/\s/g, "");

const body = `// Generated by build-cartaporte-data.mjs from phpcfdi/resources-sat-catalogs (public domain
// copy of SAT's catCartaPorte, Carta Porte 3.1). Do not edit by hand; rebuild.
export const ESTACIONES = ${JSON.stringify(Object.fromEntries(Object.entries(estaciones).map(([k, v]) => [k, packCodes(v)])))};
export const SIN_MODO = ${JSON.stringify(packCodes(sinModo))};
export const PELIGROSOS = ${JSON.stringify(packCodes(peligrosos))};
export const PROD_MP = ${JSON.stringify(Object.fromEntries(Object.entries(prodMp).map(([k, v]) => [k, packCodes(v)])))};
export const CONFIG = ${JSON.stringify(config)};
export const PERMISOS = ${JSON.stringify(permisos)};
`;
writeFileSync(new URL("./cartaporte-data.mjs", import.meta.url), body);
console.log(`stations ${withMode.size} + ${new Set(sinModo).size} without a mode, hazardous ${peligrosos.length}, products 1:${prodMp["1"].length} 0,1:${prodMp["0,1"].length}, ${body.length} bytes`);
