// Reads the parts of SAT's c_CodigoPostal and c_Colonia catalogues that tie a Mexican postal
// code to its municipality, locality and colonias into mx-address-data.mjs, for the address
// checks in mx-address.mjs (used by cce20.mjs and cartaporte31.mjs):
//   node build-mx-address-data.mjs [dir holding the two .sql files]
// Without a directory it downloads them from phpcfdi/resources-sat-catalogs on GitHub
// (Unlicense: a public-domain copy of SAT's catCFDI spreadsheet as SQLite dumps). Read
// 2026-11-12. What is kept:
//   CP_MUN      every c_CodigoPostal row that names a municipality (32,808 of 95,748; the
//               rest are unassigned codes inside a state's block, with the columns empty),
//               as "gap.estado.municipio.localidad" entries, gap in base 36 from the previous
//               code; a bare "gap" repeats the previous entry's state, municipality and
//               locality;
//   COLONIAS    c_Colonia's codes for each postal code (145,366 rows over 32,333 codes), as
//               "gap:runs" where each run is "d" or "d-n" (n more consecutive codes), d the
//               signed base-36 step from the previous run's last code less one ("_" marks a
//               negative step), running across postal codes because SAT numbers colonias in
//               near-sequence. The colonia names are not kept: the checks need the codes only.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIRROR = "https://raw.githubusercontent.com/phpcfdi/resources-sat-catalogs/master/database/data";

async function load(name) {
  const dir = process.argv[2];
  if (dir) return readFileSync(join(dir, `${name}.sql`), "utf8");
  const res = await fetch(`${MIRROR}/${name}.sql`);
  if (!res.ok) throw new Error(`${name}.sql: HTTP ${res.status}`);
  return res.text();
}

/** The VALUES(...) tuples of a SQLite dump (as build-cce20-data.mjs reads them; importing
 * that script would run its build). */
function rows(sql) {
  const out = [];
  for (const line of sql.split("\n")) {
    const i = line.indexOf("VALUES(");
    if (!line.startsWith("INSERT") || i < 0) continue;
    const body = line.slice(i + 7, line.lastIndexOf(")"));
    const vals = [];
    for (const m of body.matchAll(/'((?:[^']|'')*)'|([^,]+)/g)) vals.push(m[1] !== undefined ? m[1].replace(/''/g, "'") : m[2].trim());
    out.push(vals);
  }
  return out;
}

const b36 = (n) => (n >= 0 ? n.toString(36) : `_${(-n).toString(36)}`);

const cps = rows(await load("cfdi_40_codigos_postales"))
  .filter((r) => r[2])
  .map((r) => [Number(r[0]), `${r[1]}.${r[2]}.${r[3]}`])
  .sort((a, b) => a[0] - b[0]);
const mun = [];
let prevCp = 0, prevKey = "";
for (const [n, key] of cps) {
  mun.push(key === prevKey ? b36(n - prevCp) : `${b36(n - prevCp)}.${key}`);
  prevCp = n; prevKey = key;
}

const byCp = new Map();
for (const [code, cp] of rows(await load("cfdi_40_colonias"))) {
  if (!/^\d{4}$/.test(code) || !/^\d{5}$/.test(cp)) throw new Error(`unexpected colonia ${code} ${cp}`);
  if (!byCp.has(+cp)) byCp.set(+cp, new Set());
  byCp.get(+cp).add(+code);
}
const col = [];
let prev = 0, last = 0, total = 0;
for (const cp of [...byCp.keys()].sort((a, b) => a - b)) {
  const a = [...byCp.get(cp)].sort((x, y) => x - y);
  total += a.length;
  const runs = [];
  for (let i = 0; i < a.length;) {
    let j = i;
    while (j + 1 < a.length && a[j + 1] === a[j] + 1) j++;
    const d = b36(a[i] - last - 1);
    runs.push(j > i ? `${d}-${(j - i).toString(36)}` : d);
    last = a[j]; i = j + 1;
  }
  col.push(`${cp - prev === 1 ? "" : b36(cp - prev)}:${runs.join(".")}`);
  prev = cp;
}

const body = `// Generated by build-mx-address-data.mjs from SAT's c_CodigoPostal and c_Colonia catalogues
// (phpcfdi/resources-sat-catalogs, public domain). Do not edit by hand; rebuild.
export const CP_MUN = ${JSON.stringify(mun.join(" "))};
export const COLONIAS = ${JSON.stringify(col.join(" "))};
`;
writeFileSync(new URL("./mx-address-data.mjs", import.meta.url), body);
console.log(`postal codes with a municipality ${cps.length}, colonias ${total} over ${byCp.size} postal codes, ${body.length} bytes`);
