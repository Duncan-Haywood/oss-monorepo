export function plainFix(ruleId) {
  const id = String(ruleId || "");
  if (FIXES[id]) return FIXES[id];
  for (const [pattern, text] of FAMILIES) if (pattern.test(id)) return text;
  return "Correct the field named in the message and re-run the check.";
}

export function hasSpecificFix(ruleId) {
  return Object.hasOwn(FIXES, String(ruleId || ""));
}
