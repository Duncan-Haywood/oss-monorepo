// Reads the SAT catalogue columns the Comercio Exterior 2.0 checks (cce20.mjs) need, columns
// the XSDs do not carry, into cce20-data.mjs:
//   node build-cce20-data.mjs [dir holding the six .sql files]
// Without a directory it downloads them from phpcfdi/resources-sat-catalogs on GitHub
// (Unlicense: a public-domain copy of SAT's catCFDI and catComExt spreadsheets as SQLite
// dumps). Read 2026-11-12. What is kept:
//   PAISES      c_Pais rows with a postal-code pattern, a tax-id pattern, an online
//               check or a grouping (Unión Europea, TLCAN); every other country has none;
//   ESTADOS     c_Estado codes by country (MEX, USA, CAN are the only countries listed);
//   MUNICIPIOS  c_Municipio codes by Mexican state; LOCALIDADES the same for c_Localidad;
//   CP_ESTADO   c_CodigoPostal as [first code, state] boundaries: the state of a postal
//               code is the last boundary at or below it (34 boundaries for 95,748 codes);
//   FRACCIONES  c_FraccionArancelaria by UMT (the tariff's unit of measure, c_UnidadAduana),
//               each list sorted and stored as base-36 gaps; VIGENCIA the codes whose
//               validity is not "from 2024-01-18, open-ended".
// The colonia catalogue (c_Colonia by postal code, about 145,000 rows) and the municipio and
// locality of each postal code are not kept: they would add about 1 MB, and the checker says
// so in `skipped` when a file's address leans on them.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIRROR = "https://raw.githubusercontent.com/phpcfdi/resources-sat-catalogs/master/database/data";
const FILES = ["cfdi_40_paises", "cfdi_40_estados", "cfdi_40_municipios", "cfdi_40_localidades", "cfdi_40_codigos_postales", "cce_20_fracciones_arancelarias"];

async function load(name) {
  const dir = process.argv[2];
  if (dir) return readFileSync(join(dir, `${name}.sql`), "utf8");
  const res = await fetch(`${MIRROR}/${name}.sql`);
  if (!res.ok) throw new Error(`${name}.sql: HTTP ${res.status}`);
  return res.text();
}

/** The VALUES(...) tuples of a SQLite dump, as arrays of strings ('' quotes undone). */
export function rows(sql) {
  const out = [];
  for (const line of sql.split("\n")) {
    const i = line.indexOf("VALUES(");
    if (!line.startsWith("INSERT") || i < 0) continue;
    const body = line.slice(i + 7, line.lastIndexOf(")"));
    const vals = [];
    for (const m of body.matchAll(/'((?:[^']|'')*)'|([^,]+)/g)) vals.push(m[1] !== undefined ? m[1].replace(/''/g, "'") : m[2].trim());
    out.push(vals);
  }
  return out;
}

const gaps = (codes) => {
  const n = [...new Set(codes.map(Number))].sort((a, b) => a - b);
  let prev = 0;
  return n.map((x) => { const d = x - prev; prev = x; return d.toString(36); }).join(",");
};

const paises = {};
for (const [code, , cp, rit, online, group] of rows(await load("cfdi_40_paises"))) {
  if (cp || rit || online || group) paises[code] = { ...(cp && { cp }), ...(rit && { rit: rit.replace(/\n|\\n/g, "") }), ...(online && { online }), ...(group && { group }) };
}
const estados = {};
for (const [code, pais] of rows(await load("cfdi_40_estados"))) (estados[pais] ||= []).push(code);
const byState = (r) => {
  const out = {};
  for (const [code, estado] of r) (out[estado] ||= []).push(code);
  for (const k of Object.keys(out)) out[k] = [...new Set(out[k])].sort().join(" ");
  return out;
};
const municipios = byState(rows(await load("cfdi_40_municipios")));
const localidades = byState(rows(await load("cfdi_40_localidades")));

const cps = rows(await load("cfdi_40_codigos_postales")).map((r) => [Number(r[0]), r[1]]).sort((a, b) => a[0] - b[0]);
const cpEstado = [];
for (const [n, e] of cps) if (!cpEstado.length || cpEstado[cpEstado.length - 1][1] !== e) cpEstado.push([n, e]);

const byUmt = {}, vigencia = {};
for (const [code, , start, end, umt] of rows(await load("cce_20_fracciones_arancelarias"))) {
  if (!/^\d{10}$/.test(code)) throw new Error(`unexpected fraccion ${code}`);
  (byUmt[umt] ||= []).push(code);
  if (start !== "2024-01-18" || end) vigencia[code] = [start, end || ""];
}
const fracciones = Object.fromEntries(Object.entries(byUmt).sort().map(([u, c]) => [u, gaps(c)]));

const body = `// Generated by build-cce20-data.mjs from SAT's catCFDI and catComExt catalogues
// (phpcfdi/resources-sat-catalogs, public domain). Do not edit by hand; rebuild.
export const PAISES = ${JSON.stringify(paises)};
export const ESTADOS = ${JSON.stringify(estados)};
export const MUNICIPIOS = ${JSON.stringify(municipios)};
export const LOCALIDADES = ${JSON.stringify(localidades)};
export const CP_ESTADO = ${JSON.stringify(cpEstado)};
export const FRACCIONES = ${JSON.stringify(fracciones)};
export const VIGENCIA = ${JSON.stringify(vigencia)};
`;
writeFileSync(new URL("./cce20-data.mjs", import.meta.url), body);
console.log(`paises ${Object.keys(paises).length}, cp boundaries ${cpEstado.length}, fracciones ${Object.values(byUmt).reduce((s, c) => s + c.length, 0)} in ${Object.keys(byUmt).length} UMTs, ${body.length} bytes`);
