// Builds verifactu-errors-data.mjs from AEAT's own list of VERI*FACTU error codes,
// fixtures/verifactu/aeat-errores.properties.txt, kept byte for byte as AEAT serves it
// (ISO-8859-1) at
// https://prewww2.aeat.es/static_files/common/internet/dep/aplicaciones/es/aeat/tikeV1.0/cont/ws/errores.properties
// (read 2026-11-15; Last-Modified Thu, 30 Jul 2026 11:45:16 GMT). The file has three
// sections, each opened by a line of asterisks: codes that reject the whole submission,
// codes that reject the record (or the whole request when the fault is in the header),
// and codes that accept the record but must be corrected later.
//
//   node build-verifactu-errors.mjs            writes verifactu-errors-data.mjs
//   node build-verifactu-errors.mjs --check    exits 1 when the data file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

const SRC = new URL("./fixtures/verifactu/aeat-errores.properties.txt", import.meta.url);
const OUT = new URL("./verifactu-errors-data.mjs", import.meta.url);
const SCOPES = ["submission", "record", "accepted"];

export function parseErroresProperties(bytes) {
  const text = new TextDecoder("latin1").decode(bytes);
  const codes = {};
  let section = -1;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (/^\*{3,}/.test(line)) { section++; continue; }
    const m = /^(\d{4})\s*=\s*(.*)$/.exec(line);
    if (!m) throw new Error(`Unexpected line in errores.properties: ${line.slice(0, 80)}`);
    if (section < 0 || section > 2) throw new Error("Code outside the three sections");
    if (Object.hasOwn(codes, m[1])) throw new Error(`Code ${m[1]} listed twice`);
    codes[m[1]] = { scope: SCOPES[section], es: m[2].trim() };
  }
  return codes;
}

export function render(bytes) {
  const codes = parseErroresProperties(bytes);
  const sha = createHash("sha256").update(bytes).digest("hex");
  const rows = Object.entries(codes).map(([k, v]) => `  "${k}": { scope: "${v.scope}", es: ${JSON.stringify(v.es)} },`).join("\n");
  return `// Generated by build-verifactu-errors.mjs from AEAT's errores.properties; do not edit.
// The Spanish text is AEAT's own, as served (including its typos, e.g. code 1214).
export const AEAT_ERRORS_SOURCE = {
  url: "https://prewww2.aeat.es/static_files/common/internet/dep/aplicaciones/es/aeat/tikeV1.0/cont/ws/errores.properties",
  read: "2026-11-15",
  lastModified: "Thu, 30 Jul 2026 11:45:16 GMT",
  sha256: "${sha}",
};
// scope: "submission" (the whole submission is rejected), "record" (the record is
// rejected, or the whole request when the fault is in the header), "accepted" (the
// record is registered but must be corrected).
export const AEAT_ERRORS = {
${rows}
};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = render(readFileSync(SRC));
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== out) { console.error("verifactu-errors-data.mjs is stale: run node build-verifactu-errors.mjs"); process.exit(1); }
    console.log("verifactu-errors-data.mjs is current");
  } else {
    writeFileSync(OUT, out);
    console.log(`wrote ${Object.keys(parseErroresProperties(readFileSync(SRC))).length} codes`);
  }
}
