// Reads SAT's c_RegimenFiscal and c_UsoCFDI catalogues (CFDI 4.0) into
// cfdi-regimen-data.mjs, the table cfdi.mjs checks MX-015..MX-017 against:
//   node build-cfdi-regimen.mjs [dir holding cfdi_40_regimenes_fiscales.sql and cfdi_40_usos_cfdi.sql]
// Without a directory it downloads the two tables from phpcfdi/resources-sat-catalogs
// on GitHub (public domain, The Unlicense), a SQL transcription of SAT's catCFDI.xls.
// The XSD (catCFDI.xsd) lists the codes only; the columns read here, "Persona Física",
// "Persona Moral" and, for each use, the receiver regimes it is allowed with, exist
// only in the spreadsheet. Rows whose vigencia_hasta has passed are dropped.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIRROR = "https://raw.githubusercontent.com/phpcfdi/resources-sat-catalogs/master/database/data";
const TABLES = ["cfdi_40_regimenes_fiscales", "cfdi_40_usos_cfdi"];

async function load(name) {
  const dir = process.argv[2];
  if (dir) return readFileSync(join(dir, `${name}.sql`), "utf8");
  const res = await fetch(`${MIRROR}/${name}.sql`);
  if (!res.ok) throw new Error(`${name}.sql: HTTP ${res.status}`);
  return res.text();
}

/** The value tuples of every INSERT in a SQLite dump, as arrays of strings/numbers. */
export function rows(sql) {
  const out = [];
  for (const m of sql.matchAll(/INSERT INTO \S+ VALUES\((.*)\);\s*$/gm)) {
    const vals = [];
    const re = /'((?:[^']|'')*)'|(-?\d+(?:\.\d+)?)|NULL/g;
    let t;
    while ((t = re.exec(m[1]))) vals.push(t[1] !== undefined ? t[1].replace(/''/g, "'") : t[2] !== undefined ? Number(t[2]) : null);
    out.push(vals);
  }
  return out;
}

const today = new Date().toISOString().slice(0, 10);
const live = (hasta) => !hasta || hasta >= today;

const REGIMEN = {}, USO = {};
for (const [id, texto, fisica, moral, , hasta] of rows(await load(TABLES[0]))) {
  if (live(hasta)) REGIMEN[id] = { texto, fisica: fisica === 1, moral: moral === 1 };
}
for (const [id, texto, fisica, moral, , hasta, regs] of rows(await load(TABLES[1]))) {
  if (!live(hasta)) continue;
  const regimenes = regs.split(",").map((s) => s.trim()).filter(Boolean).sort();
  for (const r of regimenes) if (!REGIMEN[r]) throw new Error(`UsoCFDI ${id} names regime ${r}, not in c_RegimenFiscal`);
  USO[id] = { texto, fisica: fisica === 1, moral: moral === 1, regimenes };
}
if (Object.keys(REGIMEN).length < 15 || Object.keys(USO).length < 20) throw new Error("catalogue looks truncated");

const table = (o) => `{\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n")},\n}`;
const body = `// Generated by build-cfdi-regimen.mjs from SAT's catCFDI c_RegimenFiscal and c_UsoCFDI
// (CFDI 4.0), via phpcfdi/resources-sat-catalogs (public domain). Do not edit by hand.
// fisica / moral: the code applies to a person (13-character RFC) / a company (12).
// USO[code].regimenes: the receiver regimes (RegimenFiscalReceptor) the use is allowed with.
export const REGIMEN = ${table(REGIMEN)};
export const USO = ${table(USO)};
`;
writeFileSync(new URL("./cfdi-regimen-data.mjs", import.meta.url), body);
console.log(`cfdi-regimen-data.mjs: ${Object.keys(REGIMEN).length} regimes, ${Object.keys(USO).length} uses`);
