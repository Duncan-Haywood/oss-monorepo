// Reads Brazil's presumed-credit table (cCredPres, the "Tabela de Crédito Presumido" of
// the tax reform, LC 214/2025, Anexo IV of NT 2025.002 / IT 2025.002) into
// ccredpres-data.mjs, the table ccredpres.mjs checks an NF-e item's gCredPresOper against:
//   node build-ccredpres-data.mjs [path to a CSV copy]
// SVRS publishes it at dfe-portal.svrs.rs.gov.br/DFE/TabelaCreditoPresumido (and as JSON
// behind a certificate at /CFF/Servicos). That host refused the build host's connection on
// 2026-11-14, so without an argument this downloads a transcription committed to a public
// MIT repository (biuspoly/RNFe, which also records each column's change history in its
// mudancas_ibs_cbs.csv), pinned below by commit and SHA-256. Two older independent copies
// were compared with it on 2026-11-14 (README, "Brazil: the cCredPres table"): every code,
// tax group flag and start date agrees; the only differences are the "appropriated in the
// document" flag of codes 01 and 03, which IT 2025.002 version 1.70 (published 2026-10-01)
// switched off, and both older copies predate it.
// The table is an official act (Lei 9.610/1998, art. 8, IV: not protected by copyright);
// the data module keeps only the fields the checks read.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

export const SOURCE_REPO = "biuspoly/RNFe";
export const SOURCE_COMMIT = "b744e7d4cd9b1d5ba14a3cf3b2408ea6f2bfd47b";
export const SOURCE_PATH = "inst/extdata/tabelas/credito_presumido_ibs_cbs.csv";
export const SOURCE_SHA256 = "f7b2a1e09f9354ca087bb47655b09946e8856af6cda080bbcfe9c7725005c574";
// The table version the copy carries (its mudancas_ibs_cbs.csv: last change to this table
// in IT 2025.002 1.70, published 2026-10-01, in production 2026-10-16).
export const TABLE_VERSION = { it: "1.70", published: "2026-10-01", production: "2026-10-16" };

async function load() {
  if (process.argv[2]) return readFileSync(process.argv[2], "utf8");
  const res = await fetch(`https://raw.githubusercontent.com/${SOURCE_REPO}/${SOURCE_COMMIT}/${SOURCE_PATH}`);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.text();
}

/** RFC 4180 CSV: quoted fields may hold commas, quotes ("") and line breaks. */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') q = false;
      else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c !== ""));
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  const text = await load();
  const sha = createHash("sha256").update(text).digest("hex");
  if (!process.argv[2] && SOURCE_SHA256 !== "PLACEHOLDER" && sha !== SOURCE_SHA256) throw new Error(`SHA-256 ${sha} is not the pinned ${SOURCE_SHA256}`);
  const [head, ...body] = parseCsv(text);
  const col = (name) => { const i = head.indexOf(name); if (i < 0) throw new Error(`no column ${name}`); return i; };
  const flag = (r, name) => r[col(name)] === "1";
  const date = (r, name) => (/^\d{4}-\d{2}-\d{2}$/.test(r[col(name)]) ? r[col(name)] : null);
  const codes = {};
  for (const r of body) {
    const code = r[col("codigo")];
    if (!/^\d{2}$/.test(code)) throw new Error(`bad code ${code}`);
    const ref = r[col("orientacao_classificacao_referenciada")];
    codes[code] = {
      name: r[col("descricao")].replace(/\s+/g, " ").trim(),
      ibs: flag(r, "grupo_credito_ibs"), cbs: flag(r, "grupo_credito_cbs"),
      inDoc: flag(r, "apropria_no_documento"), byEvent: flag(r, "apropria_por_evento"), deducts: flag(r, "deduz_do_tributo"),
      nfe: flag(r, "permitido_na_nfe"), nfce: flag(r, "permitido_na_nfce"), cte: flag(r, "permitido_no_cte"), nfse: flag(r, "permitido_na_nfse"),
      fromIBS: date(r, "inicio_ibs"), toIBS: date(r, "fim_ibs"), fromCBS: date(r, "inicio_cbs"), toCBS: date(r, "fim_cbs"),
      ref: /^\d{6}$/.test(ref) ? ref : null,
    };
  }
  const out = `// Generated by build-ccredpres-data.mjs from ${SOURCE_REPO}@${SOURCE_COMMIT.slice(0, 12)}:${SOURCE_PATH}
// (SHA-256 ${sha.slice(0, 16)}...), the cCredPres table of IT 2025.002 ${TABLE_VERSION.it} (published ${TABLE_VERSION.published}).
// Do not edit by hand; rebuild.
export const TABLE = ${JSON.stringify({ version: TABLE_VERSION.it, published: TABLE_VERSION.published, sha256: sha, codes: Object.keys(codes).length })};
export const CODES = ${JSON.stringify(codes)};
`;
  writeFileSync(new URL("./ccredpres-data.mjs", import.meta.url), out);
  console.log(`ccredpres-data.mjs: ${Object.keys(codes).length} codes, sha256 ${sha}`);
}
