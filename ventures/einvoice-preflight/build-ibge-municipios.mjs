// Reads the list of Brazil's 5,570 municipalities (IBGE codes) into ibge-municipios-data.mjs:
//   node build-ibge-municipios.mjs [municipios.csv]
// Without a path it downloads csv/municipios.csv from kelvins/municipios-brasileiros on
// GitHub (MIT, pinned commit below; the codes are IBGE's). Only the codes are kept, sorted
// and stored as base-36 gaps. It also records the codes whose seventh digit does not follow
// the IBGE check-digit rule (weights 1,2,1,2,1,2 over the first six digits, the digits of
// each product summed, check = (10 - sum mod 10) mod 10): measured on this list, not assumed.
import { readFileSync, writeFileSync } from "node:fs";

const KELVINS_COMMIT = "503e2f70bbf1b4b7ec0b1f68b09086ccc38fe861";
const URL_CSV = `https://raw.githubusercontent.com/kelvins/municipios-brasileiros/${KELVINS_COMMIT}/csv/municipios.csv`;

const text = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (await fetch(URL_CSV)).text();
const lines = text.trim().split(/\r?\n/);
if (!lines[0].startsWith("codigo_ibge,")) throw new Error("unexpected header");
const codes = [...new Set(lines.slice(1).map((l) => Number(l.split(",")[0])))].sort((a, b) => a - b);
if (codes.length < 5500 || codes.some((c) => c < 1100000 || c > 5399999)) throw new Error("unexpected codes");

function ibgeCheckDigit(first6) {
  let s = 0;
  for (let i = 0; i < 6; i++) { const p = Number(first6[i]) * (i % 2 ? 2 : 1); s += Math.floor(p / 10) + (p % 10); }
  return (10 - (s % 10)) % 10;
}
const off = codes.filter((c) => ibgeCheckDigit(String(c)) !== Number(String(c)[6]));
let prev = 0;
const gaps = codes.map((c) => { const g = (c - prev).toString(36); prev = c; return g; }).join(",");
writeFileSync(new URL("./ibge-municipios-data.mjs", import.meta.url), `// Generated by build-ibge-municipios.mjs from kelvins/municipios-brasileiros at ${KELVINS_COMMIT.slice(0, 12)} (MIT; IBGE codes). Do not edit.
export const COUNT = ${codes.length};
export const GAPS = ${JSON.stringify(gaps)};
export const CHECK_DIGIT_EXCEPTIONS = ${JSON.stringify(off)};
`);
console.log(`${codes.length} municipalities, ${off.length} off the check-digit rule: ${off.join(", ")}; ${gaps.length} bytes of gaps`);
