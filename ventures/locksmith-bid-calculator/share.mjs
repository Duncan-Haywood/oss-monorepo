// A mobile locksmith re-enters the same labor rate, emergency premium, parts
// markup, overhead, and minimum charge on every single call. Losing them when
// the tab closes is the reason a pricing tool gets used once and never again,
// so this module keeps the whole form: to the visitor's own browser between
// calls, and into a link they can send themselves, a partner covering the
// dispatch, or the customer.
//
// Same shared-bid-spec shape as this portfolio's other per-job trade
// calculators (`ventures/tuckpointing-bid-calculator/share.mjs`,
// `ventures/appliance-repair-quote-calculator/share.mjs`), trimmed to the
// two kinds this venture actually has -- numbers and one flag
// (`emergencyCall`) -- since there is no preset select and no per-job row
// list to price here.
//
// Spec shape, built by the caller from its existing id lists:
//   { key: 'locksmith-bid', numbers: [...], flags: ['emergencyCall'] }
//
// Nothing here is transmitted. `localStorage` is the visitor's own disk, and
// the link is only ever built in their browser and copied by them. The call
// travels in the URL *fragment* (`#...`), never the query string: a fragment
// is not sent in the request line a server logs, nor in the `Referer` header
// a later click would carry, so the numbers a locksmith typed stay off the
// machines they pass through on the way to the recipient.

const VERSION = 1;

// The proposal panel's terms -- see `withProposalTerms`. Two numbers and
// three blocks of prose, named here rather than in the page because the
// page's copy of the list is generated by `platform/proposal/adopt.mjs` and a
// second hand-kept copy beside it is the exact defect this module's header
// warns about. `platform/proposal/term-ids.test.mjs` asserts the two agree.
export const PROPOSAL_TERM_NUMBERS = Object.freeze(['depositPercent', 'validDays']);
export const PROPOSAL_TERM_TEXT = Object.freeze([
  'proposalExclusions', 'paymentTerms', 'proposalNotes',
]);

// A ceiling on one block of prose, matching `MAX_LINK_VALUE` in
// `platform/pages/link.mjs` so the two share mechanisms on this site agree
// about what fits in a fragment.
export const MAX_TERM_TEXT = 512;

function usableNumber(value) {
  if (value === '' || value === null || value === undefined) return null;
  const result = Number(value);
  return Number.isFinite(result) && result >= 0 ? result : null;
}

function usableText(value) {
  if (typeof value !== 'string') return null;
  // eslint-disable-next-line no-control-regex
  const clean = value.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '').trim();
  if (!clean) return null;
  return clean.length > MAX_TERM_TEXT ? null : clean;
}

function specNumbers(spec) {
  return Array.isArray(spec?.numbers) ? spec.numbers : [];
}

function specFlags(spec) {
  return Array.isArray(spec?.flags) ? spec.flags : [];
}

function specText(spec) {
  return Array.isArray(spec?.text) ? spec.text : [];
}

/**
 * The spec, plus the proposal terms this page also puts in front of the
 * setter. Idempotent: folding the terms in twice leaves one copy, so a
 * caller that wraps at every call site cannot grow the spec.
 */
export function withProposalTerms(spec) {
  if (!spec || typeof spec !== 'object') return spec;
  const numbers = specNumbers(spec);
  const text = specText(spec);
  return {
    ...spec,
    numbers: [...numbers, ...PROPOSAL_TERM_NUMBERS.filter((id) => !numbers.includes(id))],
    text: [...text, ...PROPOSAL_TERM_TEXT.filter((id) => !text.includes(id))],
  };
}

/**
 * The form's values, plus whichever term fields this page actually has.
 * `lookup` is the page's own `el` -- id to element, or null.
 */
export function readProposalTerms(values, lookup) {
  const out = { ...(values || {}) };
  if (typeof lookup !== 'function') return out;
  for (const id of [...PROPOSAL_TERM_NUMBERS, ...PROPOSAL_TERM_TEXT]) {
    let field = null;
    try {
      field = lookup(id);
    } catch {
      // `el` throws on some pages when the id is absent. Absent is the answer.
    }
    if (field && typeof field.value === 'string') out[id] = field.value;
  }
  return out;
}

/** Which term fields are too long to ride in a link. */
export function overlongTerms(values) {
  return PROPOSAL_TERM_TEXT.filter((id) => {
    const raw = values?.[id];
    return typeof raw === 'string' && raw.trim().length > MAX_TERM_TEXT;
  });
}

const TERM_LABELS = Object.freeze({
  proposalExclusions: 'not-included list',
  paymentTerms: 'payment terms',
  proposalNotes: 'notes',
});

/** The sentence a page shows when a term did not fit, or `''` when all of them did. */
export function overlongTermsNote(values) {
  const left = overlongTerms(values).map((id) => TERM_LABELS[id] ?? id);
  if (left.length === 0) return '';
  const named = left.length === 1
    ? left[0]
    : `${left.slice(0, -1).join(', ')} and ${left[left.length - 1]}`;
  return `your ${named} ${left.length === 1 ? 'is' : 'are'} too long to fit in a link `
    + `and stayed behind — send ${left.length === 1 ? 'it' : 'them'} separately if the wording matters`;
}

// values object -> query string (no leading '?'). Field order follows the
// spec, so the same call always encodes to the same string.
export function encodeBid(spec, values) {
  const params = new URLSearchParams();
  for (const id of specNumbers(spec)) {
    const value = usableNumber(values?.[id]);
    if (value !== null) params.set(id, String(value));
  }
  for (const id of specFlags(spec)) {
    if (values?.[id] === undefined) continue;
    params.set(id, values[id] ? '1' : '0');
  }
  for (const id of specText(spec)) {
    const value = usableText(values?.[id]);
    if (value !== null) params.set(id, value);
  }
  return params.toString();
}

// query string -> values object. Accepts a bare query string or one with a
// leading '?' or '#'. Only ids named in the spec survive and numbers must
// parse, so a crafted link cannot inject anything this calculator does not
// already ask for.
export function decodeBid(spec, source) {
  if (typeof source !== 'string') return {};
  const params = new URLSearchParams(source.replace(/^[?#]/, ''));
  const values = {};
  for (const id of specNumbers(spec)) {
    if (!params.has(id)) continue;
    const value = usableNumber(params.get(id));
    if (value !== null) values[id] = String(value);
  }
  for (const id of specFlags(spec)) {
    if (!params.has(id)) continue;
    values[id] = params.get(id) === '1';
  }
  for (const id of specText(spec)) {
    if (!params.has(id)) continue;
    const value = usableText(params.get(id));
    if (value !== null) values[id] = value;
  }
  return values;
}

/** Writes the call to the visitor's own storage. Wrapped: a browser with site
 * data blocked throws on access rather than returning null. */
export function saveBid(storage, spec, values) {
  if (!storage || !spec?.key) return false;
  try {
    storage.setItem(spec.key, JSON.stringify({ v: VERSION, values: decodeBid(spec, encodeBid(spec, values)) }));
    return true;
  } catch {
    return false;
  }
}

/** Reads a previously saved call back, re-validated through the same spec. */
export function loadBid(storage, spec) {
  if (!storage || !spec?.key) return {};
  try {
    const raw = storage.getItem(spec.key);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    if (!parsed || parsed.v !== VERSION || typeof parsed.values !== 'object') return {};
    return decodeBid(spec, encodeBid(spec, parsed.values));
  } catch {
    return {};
  }
}

export function clearBid(storage, spec) {
  if (!storage || !spec?.key) return false;
  try {
    storage.removeItem(spec.key);
    return true;
  } catch {
    return false;
  }
}

/** A link wins over storage: a locksmith who opens a call someone sent them
 * means to see that call, not the one they last priced. */
export function restoreBid(spec, { search = '', storage = null } = {}) {
  const fromLink = decodeBid(spec, search);
  if (Object.keys(fromLink).length > 0) return { values: fromLink, source: 'link' };
  const stored = loadBid(storage, spec);
  if (Object.keys(stored).length > 0) return { values: stored, source: 'storage' };
  return { values: {}, source: 'none' };
}
