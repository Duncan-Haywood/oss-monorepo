// Merge JSON outputs of eval/bowling-lane-table.py into bowling-lane-table.mjs (sorted keys).
// node eval/bowling-lane-table-merge.mjs part1.json part2.json ... > bowling-lane-table.mjs
import { readFileSync } from "node:fs";
const all = {};
for (const f of process.argv.slice(2)) {
  const text = readFileSync(f, "utf8").trim();
  if (text) Object.assign(all, JSON.parse(text));
}
const keys = Object.keys(all).sort((a, b) => { const [n1, w1] = a.split(",").map(Number), [n2, w2] = b.split(",").map(Number); return n1 - n2 || w1 - w2; });
console.log(`// Generated by eval/bowling-lane-table.py (CaDiCaL via python-sat) and eval/bowling-lane-table-merge.mjs:
// lane-pair assignments at the bound for seasons the page's search misses. Key "teams,weeks" (round-robin
// weeks played); value: the pair of each match of roundRobin(teams), week by week, one base-36 digit each.
// bowling.mjs re-checks an entry against the bound before it uses one.
export const LANE_TABLE = {`);
for (const k of keys) console.log(`  "${k}": "${all[k]}",`);
console.log("};");
