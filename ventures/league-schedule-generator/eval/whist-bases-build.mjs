// Turn whist-search JSON lines into whist-bases.mjs, keeping only bases whose developed design
// passes checkWhist (each pair partners once, opposes twice).
// Usage: node eval/whist-bases-build.mjs eval/whist-search.txt
import { readFileSync, writeFileSync } from "node:fs";
const lines = readFileSync(process.argv[2], "utf8").split("\n").filter((l) => l.startsWith("{"));
const bases = {};
for (const l of lines) { const r = JSON.parse(l); if (r.tables) bases[r.n] = { mods: r.mods, tables: r.tables }; }
const src = (b) => `// Generated by eval/whist-bases-build.mjs from eval/whist-search.txt: one base round per size.\n// A table [a, b, x, y] is a&b vs x&y; -1 is the fixed player "infinity" (sizes 4k).\nexport const WHIST_BASES = {\n${Object.entries(b).map(([n, v]) => `  ${n}: { mods: ${JSON.stringify(v.mods)}, tables: ${JSON.stringify(v.tables)} },`).join("\n")}\n};\n`;
const out = new URL("../whist-bases.mjs", import.meta.url);
writeFileSync(out, src(bases));
const { whistDesign, checkWhist } = await import(`../whist.mjs?${Date.now()}`);
for (const n of Object.keys(bases)) {
  const ok = checkWhist(+n, whistDesign(+n));
  console.log(n, ok ? "ok" : "FAILS");
  if (!ok) delete bases[n];
}
writeFileSync(out, src(bases));
