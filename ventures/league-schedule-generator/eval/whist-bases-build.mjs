// Turn whist-search JSON lines into whist-bases.mjs, keeping only bases whose developed design
// passes checkWhist (each pair partners once, opposes twice).
// Usage: node eval/whist-bases-build.mjs eval/whist-search.txt eval/whist-multiplier.txt eval/whist-search-c.txt eval/whist-anneal.txt
// When two files have a base for the same size, the first file's is kept (stored designs stay put).
import { readFileSync, writeFileSync } from "node:fs";
const bases = {};
for (const f of process.argv.slice(2)) {
  const lines = readFileSync(f, "utf8").split("\n").filter((l) => l.startsWith("{"));
  for (const l of lines) { const r = JSON.parse(l); if (r.tables && r.n % 4 !== 2 && !bases[r.n]) bases[r.n] = { mods: r.mods, tables: r.tables }; }
}
const src = (b) => `// Generated by eval/whist-bases-build.mjs from eval/whist-search.txt, eval/whist-multiplier.txt, eval/whist-search-c.txt and eval/whist-anneal.txt: one base round per size.\n// A table [a, b, x, y] is a&b vs x&y; -1 is the fixed player "infinity" (sizes 4k).\nexport const WHIST_BASES = {\n${Object.entries(b).map(([n, v]) => `  ${n}: { mods: ${JSON.stringify(v.mods)}, tables: ${JSON.stringify(v.tables)} },`).join("\n")}\n};\n`;
const out = new URL("../whist-bases.mjs", import.meta.url);
const sorted = (b) => Object.fromEntries(Object.entries(b).sort((x, y) => x[0] - y[0]));
writeFileSync(out, src(sorted(bases)));
const { whistDesign, checkWhist } = await import(`../whist.mjs?${Date.now()}`);
for (const n of Object.keys(bases)) {
  const ok = checkWhist(+n, whistDesign(+n));
  console.log(n, ok ? "ok" : "FAILS");
  if (!ok) delete bases[n];
}
writeFileSync(out, src(sorted(bases)));
