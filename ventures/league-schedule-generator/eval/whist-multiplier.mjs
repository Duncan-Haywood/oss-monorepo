// Whist base rounds the plain search (eval/whist-search.mjs) could not reach: 40, 41, 45, 48, 49.
//
// 4k+1 players, built directly (no search). Take a finite ring R = GF(q1) x ... x GF(qr) with
// every qi = 1 mod 4 (41 = GF(41), 45 = GF(9) x GF(5), 49 = GF(49)) and E in R with E^2 = -1
// (one fourth root of unity in each field). Multiplying by E splits R \ {0} into orbits
// {a, Ea, -a, -Ea} of four. Make each orbit a table a & -a vs Ea & -Ea. Then
//   partner differences  +-2a, +-2Ea        = 2 * orbit(a)          (once each),
//   opponent differences +-(1-E)a, +-(1+E)a = (1-E) * orbit(a), twice (since 1+E = E(1-E)).
// 2 and 1-E are units (1-E is nonzero in every field), so over all orbits the partner differences
// cover every nonzero element once and the opponent differences twice: a whist base round on the
// additive group of R. (Any prime power q = 1 mod 4 works the same way; products need each factor
// to be a field so that 1-E stays a unit.)
//
// 4k players: the base round on Z_{4k-1} + infinity is searched, but only among rounds that a
// multiplier group H of units maps onto itself (each table's images under H are tables of the
// round), so the search places one table per H-orbit. 40: Z39 with H = <16> (order 3; 0, 13, 26
// fixed, so the infinity table is {inf, 0, 13, 26}); 48: Z47 with H = {1, -1}.
//
// Usage: node eval/whist-multiplier.mjs [40 41 45 48 49 ...] > eval/whist-multiplier.txt
// Each line is JSON like eval/whist-search.txt; eval/whist-bases-build.mjs reads both files.
import { pathToFileURL } from "node:url";
import { mulberry32 } from "../calc.mjs";

const mod = (a, m) => ((a % m) + m) % m;
const powmod = (b, e, m) => { let r = 1; b = mod(b, m); while (e > 0) { if (e & 1) r = (r * b) % m; b = (b * b) % m; e >>= 1; } return r; };
const isPrime = (p) => { if (p < 2) return false; for (let d = 2; d * d <= p; d++) if (p % d === 0) return false; return true; };

// A finite field GF(p) or GF(p^2) with elements as coordinate arrays (length 1 or 2) over Z_p.
function field(q) {
  if (isPrime(q)) {
    const p = q;
    return {
      mods: [p], size: q,
      el: (i) => [i], add: (a, b) => [mod(a[0] + b[0], p)], neg: (a) => [mod(-a[0], p)],
      mul: (a, b) => [(a[0] * b[0]) % p], one: [1],
    };
  }
  const p = Math.round(Math.sqrt(q));
  if (p * p !== q || !isPrime(p)) throw new Error(`GF(${q}) not supported (prime or prime squared only)`);
  // GF(p^2) = Z_p[t]/(t^2 - r) with r a non-residue.
  let r = 2; while (powmod(r, (p - 1) / 2, p) !== p - 1) r++;
  return {
    mods: [p, p], size: q,
    el: (i) => [i % p, Math.floor(i / p)],
    add: (a, b) => [mod(a[0] + b[0], p), mod(a[1] + b[1], p)],
    neg: (a) => [mod(-a[0], p), mod(-a[1], p)],
    mul: (a, b) => [mod(a[0] * b[0] + r * a[1] * b[1], p), mod(a[0] * b[1] + a[1] * b[0], p)],
    one: [1, 0],
  };
}

// Split n into prime-power factors, each must be a prime or prime squared and = 1 mod 4.
function fieldFactors(n) {
  const out = [];
  let m = n;
  for (let p = 2; p <= m; p++) {
    if (m % p) continue;
    let q = 1; while (m % p === 0) { m /= p; q *= p; }
    out.push(q);
  }
  return out.every((q) => q % 4 === 1) ? out : null;
}

/** Direct whist base round for n = 4k+1 players when every prime-power factor of n is 1 mod 4. */
export function directBase(n) {
  const qs = fieldFactors(n);
  if (!qs) return null;
  const F = qs.map(field);
  // E: in each field an element with E^2 = -1.
  const E = F.map((f) => {
    for (let i = 1; i < f.size; i++) {
      const x = f.el(i), x2 = f.mul(x, x), m1 = f.neg(f.one);
      if (x2.every((c, j) => c === m1[j])) return x;
    }
    throw new Error("no fourth root of unity");
  });
  const mods = F.flatMap((f) => f.mods);
  // Ring element = list of field elements; encode as the mixed-radix number whist.mjs uses
  // (first coordinate least significant).
  const enc = (x) => x.flat().reduceRight((acc, c, i) => acc * mods[i] + c, 0);
  const all = [];
  const idx = (i) => { const out = []; for (const f of F) { out.push(f.el(i % f.size)); i = Math.floor(i / f.size); } return out; };
  for (let i = 1; i < n; i++) all.push(idx(i));
  const mulE = (x) => x.map((c, j) => F[j].mul(c, E[j]));
  const neg = (x) => x.map((c, j) => F[j].neg(c));
  const seen = new Set(), tables = [];
  for (const a of all) {
    if (seen.has(enc(a))) continue;
    const t = [a, neg(a), mulE(a), neg(mulE(a))];
    for (const x of t) seen.add(enc(x));
    tables.push(t.map(enc));
  }
  return { n, mods, tables };
}

/**
 * Search a base round for n = 4k players on Z_v + infinity (v = n-1) that the multiplier group
 * generated by `mult` maps onto itself. Randomised backtracking with restarts.
 */
export function multiplierSearch(n, mult, { seed = 1, tries = 1e6, budget = 2e5, ms = 600000 } = {}) {
  const fourK1 = n % 4 === 1;
  const v = fourK1 ? n : n - 1, k = Math.floor(n / 4), INF = -1;
  const H = [1]; for (let h = mult; h !== 1; h = (h * mult) % v) H.push(h);
  const img = (p, h) => (p === INF ? INF : (p * h) % v);
  const fixed = [...Array(v).keys()].filter((x) => H.every((h) => img(x, h) === x));
  const t0 = Date.now();
  const rng = mulberry32(seed);
  // Infinity table candidates: fixed by H as a table (each image is the same table).
  const sameTable = (a, b) => {
    const pairs = (t) => [[t[0], t[1]].sort((x, y) => x - y).join(), [t[2], t[3]].sort((x, y) => x - y).join()].sort().join("|");
    return pairs(a) === pairs(b);
  };
  const orbitTables = (t) => { const out = []; for (const h of H) { const u = t.map((p) => img(p, h)); if (!out.some((w) => sameTable(w, u))) out.push(u); } return out; };
  const infCands = [];
  if (!fourK1) for (let a = 0; a < v; a++) for (let b = 0; b < v; b++) for (let c = b + 1; c < v; c++) {
    if (a === b || a === c) continue;
    const t = [INF, a, b, c];
    const o = orbitTables(t);
    if (o.length === 1) infCands.push(t);
  }
  for (let attempt = 0; attempt < tries && Date.now() - t0 < ms; attempt++) {
    const pc = new Int8Array(v), oc = new Int8Array(v), used = new Uint8Array(v + 1);
    const u = (p) => (p === INF ? v : p);
    const tables = [];
    let nodes = 0;
    const apply = (tabs, s) => {
      let ok = true;
      for (const [a, b, x, y] of tabs) {
        for (const [p, q] of [[a, b], [x, y]]) if (p !== INF && q !== INF) { const d1 = mod(p - q, v), d2 = mod(q - p, v); pc[d1] += s; pc[d2] += s; if (pc[d1] > 1 || pc[d2] > 1) ok = false; }
        for (const [p, q] of [[a, x], [a, y], [b, x], [b, y]]) if (p !== INF && q !== INF) { const d1 = mod(p - q, v), d2 = mod(q - p, v); oc[d1] += s; oc[d2] += s; if (oc[d1] > 2 || oc[d2] > 2) ok = false; }
      }
      return ok;
    };
    const place = (tabs) => {
      const pts = tabs.flat();
      if (new Set(pts.map(u)).size !== pts.length || pts.some((p) => used[u(p)])) return null;
      if (!apply(tabs, 1)) { apply(tabs, -1); return null; }
      for (const p of pts) used[u(p)] = 1;
      return pts;
    };
    const unplace = (tabs, pts) => { apply(tabs, -1); for (const p of pts) used[u(p)] = 0; };
    if (fourK1) used[0] = 1; // 0 sits out the base round
    else {
      const it = infCands[Math.floor(rng() * infCands.length)];
      if (!place([it])) continue;
      tables.push(it);
    }
    const shuffled = (arr) => { const a = arr.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
    const rec = () => {
      if (tables.length === k) return true;
      if (++nodes > budget) return false;
      let first = -1; for (let x = 0; x < v; x++) if (!used[x]) { first = x; break; }
      const free = shuffled([...Array(v).keys()].filter((x) => !used[x] && x !== first));
      // Table [first, b, x, y]: first & b vs x & y (x < y as a pair).
      for (const b of free) for (const x of free) for (const y of free) {
        if (b === x || b === y || x >= y) continue;
        const t = [first, b, x, y];
        const tabs = orbitTables(t);
        if (tabs.length !== 1 && tabs.length !== H.length) continue;
        const pts = place(tabs);
        if (!pts) continue;
        tables.push(...tabs);
        if (tables.length <= k && rec()) return true;
        tables.length -= tabs.length;
        unplace(tabs, pts);
        if (nodes > budget) return false;
      }
      return false;
    };
    if (rec() && tables.length === k) return { n, mods: [v], ms: Date.now() - t0, attempts: attempt + 1, multiplier: mult, fixed, tables };
  }
  return { n, mods: [v], ms: Date.now() - t0, multiplier: mult, tables: null };
}

/**
 * Multiplier -1 (the only one Z_47 and Z_59 have besides squares of odd order). A pair of tables T,
 * -T repeats T's partner differences, so every table must be fixed by -1, and the only fixed shape
 * that keeps partners once is a & -a vs b & -b. Writing c(y) for the class {y, -y}: partner
 * differences are +-2a, +-2b (all classes once, automatically), opponent differences are the classes
 * c(a-b) and c(a+b), twice each. With 4k players the infinity table is inf & 0 vs x & -x, which takes
 * class c(x) twice. So the base round is a matching of the other classes into pairs {a, b} whose
 * classes c(a+b), c(a-b) are all different and miss c(x). Backtracking over that matching.
 */
export function negationSearch(n, { seed = 1, ms = 600000 } = {}) {
  const fourK1 = n % 4 === 1, v = fourK1 ? n : n - 1, h = (v - 1) / 2;
  const c = (y) => { y = mod(y, v); return Math.min(y, v - y); };
  const rng = mulberry32(seed), t0 = Date.now();
  const shuffle = (a) => { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
  for (let attempt = 1; Date.now() - t0 < ms; attempt++) {
    const matched = new Uint8Array(h + 1), made = new Uint8Array(h + 1);
    const x = fourK1 ? 0 : 1 + Math.floor(rng() * h);
    if (x) { matched[x] = 1; made[x] = 1; }
    const pairs = [];
    let nodes = 0;
    const rec = () => {
      let a = 0; for (let i = 1; i <= h; i++) if (!matched[i]) { a = i; break; }
      if (!a) return true;
      if (++nodes > 2e6) return false;
      matched[a] = 1;
      for (const b of shuffle([...Array(h).keys()].map((i) => i + 1).filter((i) => !matched[i]))) {
        const p = c(a + b), q = c(a - b);
        if (p === q || made[p] || made[q]) continue;
        matched[b] = made[p] = made[q] = 1; pairs.push([a, b]);
        if (rec()) return true;
        matched[b] = made[p] = made[q] = 0; pairs.pop();
        if (nodes > 2e6) break;
      }
      matched[a] = 0;
      return false;
    };
    if (rec()) {
      const tables = pairs.map(([a, b]) => [a, v - a, b, v - b]);
      if (!fourK1) tables.unshift([-1, 0, x, v - x]);
      return { n, mods: [v], ms: Date.now() - t0, attempts: attempt, multiplier: v - 1, tables };
    }
  }
  return { n, mods: [v], ms: Date.now() - t0, multiplier: v - 1, tables: null };
}

// The multiplier used per size: a unit of order 3 fixing 0 and the two elements of order 3 (they
// join infinity at its table), else -1 (negationSearch).
export const MULT = { 40: 16, 64: 4 };
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const ns = process.argv.slice(2).map(Number);
  for (const n of ns.length ? ns : [40, 41, 45, 48, 49]) {
    if (n % 4 === 1 && fieldFactors(n)) {
      const t0 = Date.now();
      const b = directBase(n);
      console.log(JSON.stringify(b ? { n, mods: b.mods, ms: Date.now() - t0, method: "direct", tables: b.tables } : { n, method: "direct", tables: null }));
    } else {
      const v = n % 4 === 1 ? n : n - 1;
      const m = MULT[n] ?? v - 1;
      const r = m === v - 1 ? negationSearch(n) : multiplierSearch(n, m);
      console.log(JSON.stringify({ ...r, method: `multiplier ${r.multiplier}` }));
    }
  }
}
