// Writes odd-designs.mjs from the JSON that eval/odd-night-sat.py or eval/odd-cyclic.py prints.
//   node eval/write-odd-designs.mjs out/*.json
//   node eval/write-odd-designs.mjs --append out/29-5x9.json   (keep the stored designs, add these)
// Each design is re-checked here (a 1-factorization of K_(n+1), team n the bye, whose every night
// of three rounds has a back-to-back layout on `courts` x `times`: the solver's own rows, checked
// match by match) before it is stored. Per n and time-slot count only the design on the fewest
// courts is kept, and a longer night's design only when it needs fewer courts than a shorter one
// (a 6-slot design also fits 9 slots, since nights.mjs takes any design with times <= the league's).
// One character per team per round: the team's opponent in a 64-letter alphabet, rounds
// concatenated, n + 1 characters a round (the bye team n last).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ALPHA = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-_";
const best = new Map();
const args = process.argv.slice(2);
const append = args.includes("--append");
for (const f of args.filter((a) => a !== "--append")) {
  const text = readFileSync(f, "utf8").trim();
  if (!text) continue; // a run that timed out prints nothing
  const d = JSON.parse(text);
  if (!d.sat) continue;
  const { n, rounds, rows, courts, times } = d;
  const N = n + 1;
  const seen = new Set();
  let code = "";
  for (const r of rounds) {
    const o = Array(N).fill(-1);
    for (const [a, b] of r) {
      if (o[a] >= 0 || o[b] >= 0) throw new Error(`${f}: a team twice in a round`);
      o[a] = b; o[b] = a;
      const k = Math.min(a, b) * 100 + Math.max(a, b);
      if (seen.has(k)) throw new Error(`${f}: a pair meets twice`);
      seen.add(k);
    }
    if (o.includes(-1)) throw new Error(`${f}: a round is not perfect`);
    code += o.map((t) => ALPHA[t]).join("");
  }
  if (rounds.length !== n || seen.size !== (N * (N - 1)) / 2) throw new Error(`${f}: not every pair meets`);
  rows.forEach((night, t) => {
    const load = Array(times).fill(0);
    const at = new Map();
    for (const [a, b, h] of night) {
      load[h]++;
      for (const v of [a, b]) { if (!at.has(v)) at.set(v, []); at.get(v).push(h); }
    }
    if (Math.max(...load) > courts) throw new Error(`${f}: night ${t} over ${courts} courts`);
    for (const hs of at.values()) {
      hs.sort((x, y) => x - y);
      if (new Set(hs).size !== hs.length || hs[hs.length - 1] - hs[0] !== hs.length - 1) throw new Error(`${f}: night ${t} has a wait`);
    }
  });
  // the solver's rows, night by night, each night's matches in (low team, high team) order: one
  // digit per match (the time row), so the tool can lay a night out without searching for it
  let layout = "";
  for (const night of rows) layout += night.map(([a, b, h]) => [Math.min(a, b), Math.max(a, b), h]).sort((x, y) => x[0] - y[0] || x[1] - y[1]).map(([, , h]) => ALPHA[h]).join("");
  const key = `${n}x${times}`;
  const prev = best.get(key);
  if (!prev || courts < prev.courts) best.set(key, { n, courts, times, code, layout });
}
if (append) {
  // The earlier solver output is not kept in the tree; the stored codes are (re-checked by doubleheader.test.mjs).
  const { ODD_DESIGNS } = await import("../odd-designs.mjs");
  for (const d of ODD_DESIGNS) {
    const key = `${d.n}x${d.times}`;
    const prev = best.get(key);
    if (!prev || d.courts < prev.courts) best.set(key, { n: d.n, courts: d.courts, times: d.times, code: d.code, layout: d.layout });
  }
}
const designs = [...best.values()]
  .filter((d) => ![...best.values()].some((e) => e.n === d.n && e.times < d.times && e.courts <= d.courts))
  .sort((a, b) => a.n - b.n || a.times - b.times);
const out = `// Generated by eval/write-odd-designs.mjs from eval/odd-night-sat.py, eval/odd-cyclic.py, eval/odd-orbit.py and eval/odd-lns.py; do not edit by hand.
//
// Round robins for odd leagues, three games a night, whose every night can be laid out with each
// team's games back to back on \`courts\` x \`times\` (the fewest courts the solver found one for), found
// by a SAT solver (README, "Odd leagues, three games a night"). nights.mjs (oddDesigns) decodes
// them; doubleheader.test.mjs re-checks every one with the tool's own layout. Each \`code\` is n
// rounds of n + 1 characters: the opponent of team t in round r is ALPHA.indexOf(code[r * (n + 1) + t]),
// and team n is the bye. \`layout\` is the solver's own time rows, one character per match, night by
// night (rounds 3t to 3t + 2), each night's matches in (low team, high team) order.
export const ODD_DESIGNS = [
${designs.map((d) => `  { n: ${d.n}, courts: ${d.courts}, times: ${d.times}, code: ${JSON.stringify(d.code)}, layout: ${JSON.stringify(d.layout)} },`).join("\n")}
];
`;
writeFileSync(fileURLToPath(new URL("../odd-designs.mjs", import.meta.url)), out);
console.log(`${designs.length} designs: ${designs.map((d) => `${d.n} on ${d.courts}x${d.times}`).join(", ")}`);
