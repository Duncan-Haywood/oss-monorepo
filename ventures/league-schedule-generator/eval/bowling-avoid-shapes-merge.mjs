// Merge JSON outputs of eval/bowling-avoid-shapes.py into bowling-avoid-shapes.mjs (sorted keys).
// node eval/bowling-avoid-shapes-merge.mjs part1.json part2.json ... > bowling-avoid-shapes.mjs
// A .mjs argument (the current bowling-avoid-shapes.mjs) is read as a part too, so new answers can
// be added to the stored ones: write to a temporary file, then move it over.
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
const all = {};
for (const f of process.argv.slice(2)) {
  if (f.endsWith(".mjs")) { Object.assign(all, (await import(pathToFileURL(resolve(f)).href)).LANE_SHAPES); continue; }
  const text = readFileSync(f, "utf8").trim();
  if (text) Object.assign(all, JSON.parse(text));
}
const num = (k) => k.split("|")[0].split(",").map(Number);
const keys = Object.keys(all).sort((a, b) => { const [n1, w1] = num(a), [n2, w2] = num(b); return n1 - n2 || w1 - w2 || a.localeCompare(b); });
console.log(`// Generated by eval/bowling-avoid-shapes.py (CaDiCaL via python-sat) and eval/bowling-avoid-shapes-merge.mjs:
// lane-pair assignments that keep a shape of lane limits and put every count inside laneTargets(), for
// seasons the page's search misses. Key "teams,weeks|shape" (round-robin weeks played; shape "slot:pair,pair;..."
// on circle-method slots (0, 1, ... unless that dealing was UNSAT or slow, eval/bowling-avoid-slots.py) and pairs 0..); value: the pair of each match of roundRobin(teams), week by
// week, one base-36 digit each. bowling.mjs (shapePlan) re-checks an entry before it uses one.
export const LANE_SHAPES = {`);
for (const k of keys) console.log(`  "${k}": "${all[k]}",`);
console.log("};");
