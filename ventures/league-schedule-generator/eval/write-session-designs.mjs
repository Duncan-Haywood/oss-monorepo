// Writes session-designs.mjs from the JSON that eval/session-design-sat.py prints.
//   node eval/write-session-designs.mjs out/*.json
//   node eval/write-session-designs.mjs --append out/40-3x9.json   (keep the stored designs, add or replace these)
// Each design is re-checked here (a 1-factorization of K_n whose nights of three split into
// closed blocks of at most `hi` teams, `sessions` of them) before it is stored. One character per
// team per round: the team's opponent in a 64-letter alphabet, rounds concatenated.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ALPHA = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-_";
const args = process.argv.slice(2);
const append = args.includes("--append");
const designs = [];
for (const f of args.filter((a) => a !== "--append")) {
  const d = JSON.parse(readFileSync(f, "utf8"));
  if (!d.sat) continue;
  const { n, rounds, sessions, courts } = d;
  const seen = new Set();
  let code = "";
  for (const r of rounds) {
    const o = Array(n).fill(-1);
    for (const [a, b] of r) {
      if (o[a] >= 0 || o[b] >= 0) throw new Error(`${f}: a team twice in a round`);
      o[a] = b; o[b] = a;
      const k = Math.min(a, b) * 100 + Math.max(a, b);
      if (seen.has(k)) throw new Error(`${f}: a pair meets twice`);
      seen.add(k);
    }
    if (o.includes(-1)) throw new Error(`${f}: a round is not perfect`);
    code += o.map((t) => ALPHA[t]).join("");
  }
  if (seen.size !== (n * (n - 1)) / 2) throw new Error(`${f}: not every pair meets`);
  designs.push({ n, sessions, hi: 2 * courts, code });
}
if (append) {
  // The earlier solver output is not kept in the tree; the stored codes are (re-checked by doubleheader.test.mjs).
  const { SESSION_DESIGNS } = await import("../session-designs.mjs");
  for (const d of SESSION_DESIGNS) if (!designs.some((x) => x.n === d.n && x.sessions === d.sessions)) designs.push(d);
}
designs.sort((a, b) => a.n - b.n || a.sessions - b.sessions);
const out = `// Generated by eval/write-session-designs.mjs from eval/session-design-sat.py; do not edit by hand.
//
// Round robins for three games a night in two or three sessions whose every night splits into
// closed blocks of at most \`hi\` teams (\`sessions\` blocks), found by a SAT solver
// (eval/session-design-sat.py; 40 and 46 teams in three sessions by eval/session-orbit.py, one night
// turned by a group of order k) (README, "Closed sessions for every league size" and "Three sessions
// at 40 and 46 teams"). nights.mjs (designedRounds) decodes them;
// doubleheader.test.mjs re-checks every one. Each \`code\` is n - 1 rounds of n characters: the
// opponent of team t in round r is ALPHA.indexOf(code[r * n + t]).
export const ALPHA = ${JSON.stringify(ALPHA)};
export const SESSION_DESIGNS = [
${designs.map((d) => `  { n: ${d.n}, sessions: ${d.sessions}, hi: ${d.hi}, code: ${JSON.stringify(d.code)} },`).join("\n")}
];
`;
writeFileSync(fileURLToPath(new URL("../session-designs.mjs", import.meta.url)), out);
console.log(`${designs.length} designs: ${designs.map((d) => `${d.n}/${d.sessions}`).join(" ")}`);
