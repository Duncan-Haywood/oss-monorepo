// Fold the answers of eval/bowling-repeat-sat.py into bowling-lane-table.mjs: per key, the stored
// answer with the fewest back-to-back repeats wins (an existing entry is kept unless a new one has
// fewer); a key not stored yet is added. Every answer is re-checked at the bound before it is kept.
// node eval/bowling-repeat-merge.mjs case1.jsonl case2.jsonl ... > bowling-lane-table.next.mjs
// A summary per key goes to stderr.
import { readFileSync } from "node:fs";
import { LANE_TABLE } from "../bowling-lane-table.mjs";
import { roundRobin } from "../calc.mjs";

function check(key, code) {
  const [n, W] = key.split(",").map(Number), P = n / 2;
  const cyc = roundRobin(n);
  if (code.length !== W * P) return null;
  const cnt = Array.from({ length: n }, () => new Array(P).fill(0)), last = new Array(n).fill(-1);
  let rep = 0;
  for (let w = 0; w < W; w++) {
    const seen = new Set();
    cyc[w % cyc.length].matches.forEach(([a, b], m) => {
      const p = parseInt(code[w * P + m], 36); seen.add(p);
      for (const t of [a, b]) { cnt[t][p]++; if (last[t] === p) rep++; last[t] = p; }
    });
    if (seen.size !== P) return null;
  }
  const lo = Math.floor(W / P), hi = Math.ceil(W / P);
  for (const row of cnt) for (const c of row) if (c < lo || c > hi) return null;
  return rep;
}

const best = {};
for (const [k, code] of Object.entries(LANE_TABLE)) best[k] = { code, repeats: check(k, code), was: check(k, code), proved: false };
for (const f of process.argv.slice(2)) {
  for (const line of readFileSync(f, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const r = JSON.parse(line);
    const rep = check(r.key, r.code);
    if (rep === null) { console.error(`${r.key}: an answer off the bound, skipped`); continue; }
    const cur = best[r.key];
    if (!cur || cur.repeats === null || rep < cur.repeats || (rep === cur.repeats && r.proved)) best[r.key] = { code: r.code, repeats: rep, was: cur ? cur.was : null, proved: !!r.proved };
  }
}
const keys = Object.keys(best).sort((a, b) => { const [n1, w1] = a.split(",").map(Number), [n2, w2] = b.split(",").map(Number); return n1 - n2 || w1 - w2; });
for (const k of keys) console.error(`${k}: ${best[k].was ?? "-"} -> ${best[k].repeats}${best[k].proved ? " (least, proved)" : ""}`);
console.log(`// Generated by eval/bowling-lane-table.py (CaDiCaL via python-sat) and eval/bowling-lane-table-merge.mjs:
// lane-pair assignments at the bound for seasons the page's search misses. Key "teams,weeks" (round-robin
// weeks played); value: the pair of each match of roundRobin(teams), week by week, one base-36 digit each.
// bowling.mjs re-checks an entry against the bound before it uses one.
// 2026-11-18: re-solved with a cap on back-to-back repeats (eval/bowling-repeat-sat.py,
// eval/bowling-repeat-merge.mjs), and pinned seasons the search reaches added for their repeats.
export const LANE_TABLE = {`);
for (const k of keys) console.log(`  "${k}": "${best[k].code}",`);
console.log("};");
