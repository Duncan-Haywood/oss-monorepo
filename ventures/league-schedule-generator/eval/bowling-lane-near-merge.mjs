// Write bowling-lane-near.mjs: seasons with no answer at the bound where eval/bowling-lane-tabu.c got
// closer than the page's own search. Each answer is re-checked here with the page's offBound.
// node eval/bowling-lane-near-merge.mjs <start-dir> <tabu-out>... > bowling-lane-near.mjs
//   <start-dir> holds s<n>x<W>.json from eval/bowling-lane-start.mjs (its "off" = the page's own search,
//   measured before this table existed); an answer is kept only if strictly closer than that. Seasons
//   already in LANE_TABLE (at the bound) are skipped. For several answers to one season, the closest.
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { offBound } from "../bowling.mjs";
import { roundRobin } from "../calc.mjs";
import { LANE_TABLE } from "../bowling-lane-table.mjs";
const [startDir, ...files] = process.argv.slice(2);
const best = {};
for (const f of files) {
  const text = readFileSync(f, "utf8").trim();
  if (!text) continue;
  const j = JSON.parse(text);
  const key = `${j.n},${j.W}`, P = j.n / 2;
  if (LANE_TABLE[key]) continue;
  const sf = join(startDir, `s${j.n}x${j.W}.json`);
  if (!existsSync(sf)) { console.error(`${key}: no start file, skipped`); continue; }
  const pageOff = JSON.parse(readFileSync(sf, "utf8")).off;
  const cyc = roundRobin(j.n);
  const plan = [];
  for (let w = 0; w < j.W; w++) plan.push(cyc[w % cyc.length].matches.map(([a, b], m) => [a, b, parseInt(j.code[w * P + m], 36)]));
  if (!plan.every((wk) => new Set(wk.map((m) => m[2])).size === P)) { console.error(`${key}: not a permutation`); continue; }
  const off = offBound(plan, j.n, P);
  if (off >= pageOff) { console.error(`${key}: off ${off}, page ${pageOff}: not kept`); continue; }
  if (!best[key] || off < best[key].off) best[key] = { off, code: j.code, pageOff };
}
const keys = Object.keys(best).sort((a, b) => { const [n1, w1] = a.split(",").map(Number), [n2, w2] = b.split(",").map(Number); return n1 - n2 || w1 - w2; });
console.log(`// Generated by eval/bowling-lane-tabu.c and eval/bowling-lane-near-merge.mjs (2026-11-23): lane-pair
// assignments for seasons no solver has put at the bound, each closer to it than the page's own search.
// Key "teams,weeks"; off = total out-of-bounds count (eval/bowling-lane-table.txt's "off"); code as in
// bowling-lane-table.mjs. bowling.mjs (nearPlan) re-checks an entry and starts its search from it.
// page = the off of the page's own search on the same rounds before this table (seed 1).
export const LANE_NEAR = {`);
for (const k of keys) console.log(`  "${k}": { off: ${best[k].off}, page: ${best[k].pageOff}, code: "${best[k].code}" },`);
console.log("};");
