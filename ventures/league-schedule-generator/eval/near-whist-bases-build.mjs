// Turn near-whist-search JSON lines into near-whist-bases.mjs, keeping only bases whose developed
// design passes checkNearWhist (whist.mjs).
// Usage: node eval/near-whist-bases-build.mjs eval/near-whist-search.txt eval/whist-anneal.txt
// Several files: the first base found for a size is kept (stored designs stay put); lines that are
// not 4k+2 sizes (whist-anneal.txt also holds whist bases) are skipped.
import { readFileSync, writeFileSync } from "node:fs";
const bases = {};
for (const f of process.argv.slice(2)) {
  const lines = readFileSync(f, "utf8").split("\n").filter((l) => l.startsWith("{"));
  for (const l of lines) { const r = JSON.parse(l); if (r.tables && r.n % 4 === 2 && !bases[r.n]) bases[r.n] = { mods: r.mods, tables: r.tables }; }
}
const sorted = (b) => Object.fromEntries(Object.entries(b).sort((x, y) => x[0] - y[0]));
const src = (b) => `// Generated by eval/near-whist-bases-build.mjs from eval/near-whist-search.txt and eval/whist-anneal.txt: one base round per
// 4k+2 size, on Z_n. A table [a, b, x, y] is a&b vs x&y; the two points not seated sit out.
export const NEAR_WHIST_BASES = {\n${Object.entries(b).map(([n, v]) => `  ${n}: { mods: ${JSON.stringify(v.mods)}, tables: ${JSON.stringify(v.tables)} },`).join("\n")}\n};\n`;
const out = new URL("../near-whist-bases.mjs", import.meta.url);
writeFileSync(out, src(sorted(bases)));
const { whistDesign, checkNearWhist } = await import(`../whist.mjs?${Date.now()}`);
for (const n of Object.keys(bases)) {
  const ok = checkNearWhist(+n, whistDesign(+n));
  console.log(n, ok ? "ok" : "FAILS");
  if (!ok) delete bases[n];
}
writeFileSync(out, src(sorted(bases)));
