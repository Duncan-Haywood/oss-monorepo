// Turn near-whist-search JSON lines into near-whist-bases.mjs, keeping only bases whose developed
// design passes checkNearWhist (whist.mjs).
// Usage: node eval/near-whist-bases-build.mjs eval/near-whist-search.txt
import { readFileSync, writeFileSync } from "node:fs";
const lines = readFileSync(process.argv[2], "utf8").split("\n").filter((l) => l.startsWith("{"));
const bases = {};
for (const l of lines) { const r = JSON.parse(l); if (r.tables) bases[r.n] = { mods: r.mods, tables: r.tables }; }
const src = (b) => `// Generated by eval/near-whist-bases-build.mjs from eval/near-whist-search.txt: one base round per
// 4k+2 size, on Z_n. A table [a, b, x, y] is a&b vs x&y; the two points not seated sit out.
export const NEAR_WHIST_BASES = {\n${Object.entries(b).map(([n, v]) => `  ${n}: { mods: ${JSON.stringify(v.mods)}, tables: ${JSON.stringify(v.tables)} },`).join("\n")}\n};\n`;
const out = new URL("../near-whist-bases.mjs", import.meta.url);
writeFileSync(out, src(bases));
const { whistDesign, checkNearWhist } = await import(`../whist.mjs?${Date.now()}`);
for (const n of Object.keys(bases)) {
  const ok = checkNearWhist(+n, whistDesign(+n));
  console.log(n, ok ? "ok" : "FAILS");
  if (!ok) delete bases[n];
}
writeFileSync(out, src(bases));
