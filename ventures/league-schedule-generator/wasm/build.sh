#!/bin/sh
# Rebuilds wasm/minplus.wasm and the base64 copy in wasm/minplus-wasm.mjs that orient.mjs imports.
# Needs clang 18 or later with the wasm32 target (no libc, no emscripten).
set -e
cd "$(dirname "$0")"
clang --target=wasm32 -O3 -msimd128 -nostdlib -fno-builtin -Wl,--no-entry -Wl,--strip-all \
  -Wl,--initial-memory=9437184 -o minplus.wasm minplus.c
node -e '
const b = require("fs").readFileSync("minplus.wasm").toString("base64");
require("fs").writeFileSync("minplus-wasm.mjs", "// Generated by wasm/build.sh from wasm/minplus.c; do not edit.\nexport const MINPLUS_WASM = \"" + b + "\";\n");
'
wc -c minplus.wasm
