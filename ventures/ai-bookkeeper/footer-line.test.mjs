// Found by a packaging probe over fixtures/: a footer such as "Total transactions,,"
// after the last row was joined onto that row's description (the wrapped-line
// rule for OCBC's two-line rows). Rows below are made up.
import test from "node:test";
import assert from "node:assert/strict";
import { readStatement } from "./bank.mjs";

const body = "Date,Description,Amount\n2026-03-02,ACH CREDIT NORTHWIND LLC,4200.00\n2026-03-03,ADOBE CREATIVE CLD,-59.99\n";

test("a 'Total transactions' footer does not change the last description", () => {
  const base = readStatement(body);
  for (const f of ["\nTotal transactions,,\n", "Total transactions,,\n", "\nPage 1 of 2,,\n", "\nGenerated by Example Bank,,\n"]) {
    const r = readStatement(body + f);
    assert.deepEqual(r.rows.map((x) => x.desc), base.rows.map((x) => x.desc), f);
  }
});

test("a wrapped second line still joins the row above", () => {
  const r = readStatement("Date,Description,Amount\n2026-03-03,CARD 4417,-59.99\n,MERCHANT NAME,\n");
  assert.equal(r.rows.length, 1);
  assert.equal(r.rows[0].desc, "CARD 4417 MERCHANT NAME");
});

test("a footer after a header-less file does not stop it being read", () => {
  const t = '"03/02/2026","4200.00","*","","DEPOSIT NORTHWIND LLC"\n"03/03/2026","-59.99","*","","PURCHASE ADOBE"\n"03/05/2026","-850.00","*","1007","CHECK # 1007"\n';
  const base = readStatement(t);
  assert.equal(base.rows.length, 3);
  const r = readStatement(t + "\nTotal transactions,,\n");
  assert.deepEqual(r.rows.map((x) => [x.date, x.cents, x.desc]), base.rows.map((x) => [x.date, x.cents, x.desc]));
});
