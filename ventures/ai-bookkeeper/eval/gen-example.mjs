// Writes ../example-data.mjs: three synthetic months (seed 7) as a checking
// statement with a running balance and a card statement. Run from the repo:
//   node ventures/ai-bookkeeper/eval/gen-example.mjs
import { writeFileSync } from "node:fs";
import { generateYear, toCsv } from "./synth.mjs";

const lines = generateYear({ seed: 7, year: 2026, months: 3, oneOffPerMonth: 4 });
const out = `// Generated by eval/gen-example.mjs from eval/synth.mjs (seed 7): three months of
// SYNTHETIC lines for a made-up design studio, not anyone's real bank data.
export const SAMPLE_CHECKING = ${JSON.stringify(toCsv(lines, "checking", { opening: 1200000 }))};
export const SAMPLE_CARD = ${JSON.stringify(toCsv(lines, "card"))};
`;
writeFileSync(new URL("../example-data.mjs", import.meta.url), out);
console.log(`${lines.length} lines written`);
