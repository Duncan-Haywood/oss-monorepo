// Writes IDS files the editor would write, for validation against
// buildingSMART's IDS 1.0 XML schema (eval/editor-xsd-check.py runs IfcTester's
// validator on them). Per schema: one specification per offered (class, set)
// pair with a valued first property, and a showcase of every facet, value
// kind, cardinality and optionality the page can produce.
// Usage: node eval/editor-xsd-sample.mjs OUT_DIR
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { resources } from "../node.mjs";
import { classesWithSets, setsFor, propertiesOf, buildIds, entityFacet, PARTOF_RELATIONS, predefinedTypes } from "../editor.mjs";

const dir = process.argv[2];
if (!dir) { console.error("usage: node eval/editor-xsd-sample.mjs OUT_DIR"); process.exit(2); }
mkdirSync(dir, { recursive: true });
const { schemas, typeMap, psets } = resources();
const valueFor = (p, S) => {
  if (!p.dataType) return null;
  if (p.enum) return { oneOf: p.enum.slice(0, 2) };
  const prim = S.prim(p.dataType);
  if (prim === "boolean" || prim === "logical") return { equals: "false" };
  if (prim === "double") return { min: "0.5", max: "12.25" };
  if (prim === "integer") return { min: "1", max: "9" };
  return { pattern: "[A-Z]{2}-[0-9]+" };
};
for (const id of ["IFC2X3", "IFC4", "IFC4X3"]) {
  const S = schemas[id];
  const tm = id === "IFC2X3" ? typeMap : null;
  const specs = [];
  for (const cls of classesWithSets(psets[id], S, tm)) {
    for (const set of setsFor(psets[id], S, cls, tm)) {
      const p = propertiesOf(psets[id], S, set)[0];
      if (!p) continue;
      specs.push({ name: `${cls} ${set}.${p.name}`, applicability: [entityFacet(S, cls)], requirements: [{ kind: "property", set, name: p.name, dataType: p.dataType, value: valueFor(p, S) }] });
    }
  }
  const wall = entityFacet(S, "IFCWALL", { withSubclasses: true });
  const pt = predefinedTypes(S, "IFCWALL");
  specs.push(
    { name: "Every Pset_WallCommon property, valued & escaped <ok>", description: "A \"quoted\" & <bracketed> description", instructions: "Fill in R&D's values", applicability: [wall], requirements: propertiesOf(psets[id], S, "Pset_WallCommon").map((p, i) => ({ kind: "property", set: "Pset_WallCommon", name: p.name, dataType: p.dataType, value: valueFor(p, S), cardinality: ["required", "optional", "prohibited"][i % 3] })) },
    { name: "All facet kinds", applicability: [entityFacet(S, "IFCWALL", { predefinedType: pt[0] })], requirements: [
      { kind: "material", value: { pattern: ".*[Cc]oncrete.*" } },
      { kind: "property", set: "Pset_WallCommon", name: "IsExternal", dataType: "IFCBOOLEAN", value: { equals: "true" } },
      { kind: "attribute", name: "Name", value: { equals: "W-01" } },
      { kind: "classification", system: "Uniclass 2015", value: { pattern: "EF_25_10.*" } },
      { kind: "partOf", relation: "IFCRELCONTAINEDINSPATIALSTRUCTURE", entity: "IFCBUILDINGSTOREY" },
      { kind: "attribute", name: "PredefinedType", value: { oneOf: pt.slice(0, 2) }, cardinality: "optional" },
      { kind: "material", cardinality: "required" },
      { kind: "classification", system: "OmniClass", cardinality: "prohibited" },
    ] },
    ...Object.keys(PARTOF_RELATIONS).map((rel) => ({ name: `partOf ${rel}`, optionality: "optional", applicability: [wall], requirements: [{ kind: "partOf", relation: rel, entity: "IFCELEMENTASSEMBLY" }] })),
    { name: "No proxies", optionality: "prohibited", applicability: [entityFacet(S, "IFCBUILDINGELEMENTPROXY")], requirements: [{ kind: "material" }] },
    { name: "No class at all", applicability: [], requirements: [] },
  );
  const xml = buildIds({ title: `Editor sample ${id} & co`, description: "Generated by eval/editor-xsd-sample.mjs", date: "2026-11-16", schema: id, specs }, S);
  writeFileSync(join(dir, `editor-${id}.ids`), xml);
  console.log(`${id}: ${specs.length} specifications, ${(xml.length / 1e6).toFixed(2)} MB`);
}
