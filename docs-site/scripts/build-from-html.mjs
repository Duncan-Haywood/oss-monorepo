/**
 * Ingest standalone HTML reports from ../docs and emit generated modules
 * consumed by the Next.js docs site at build time.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_DOCS = path.resolve(__dirname, "../../docs");
const OUT_DIR = path.resolve(__dirname, "../src/generated");
const MANIFEST_PATH = path.join(OUT_DIR, "html-manifest.json");

/** Prefer canonical filenames; skip duplicate uppercase copies when a kebab-case twin exists. */
const SKIP_WHEN_CANONICAL_EXISTS = new Map([
  ["COMMERCIAL_VIABILITY_REPORT", "commercial-viability-report"],
  ["COMMERCIAL_VIABILITY_DEEP_DIVE_REPORT", "commercial-viability-deep-dive"],
]);

function slugFromFilename(filename) {
  return filename.replace(/\.html$/i, "").toLowerCase().replace(/_/g, "-");
}

function extractTag(html, tag) {
  const re = new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`, "i");
  const match = html.match(re);
  return match ? match[1].trim() : "";
}

function extractAllStyles(html) {
  const styles = [];
  const re = /<style[^>]*>([\s\S]*?)<\/style>/gi;
  let m;
  while ((m = re.exec(html))) {
    styles.push(m[1].trim());
  }
  return styles.join("\n\n");
}

function extractBodyInner(html) {
  const main = extractTag(html, "main");
  if (main) return main;

  const wrap = html.match(/<div[^>]*class="wrap"[^>]*>([\s\S]*?)<\/div>\s*<\/body>/i);
  if (wrap) return wrap[1].trim();

  const body = extractTag(html, "body");
  return body.replace(/<script[\s\S]*?<\/script>/gi, "").trim();
}

function extractTitle(html) {
  const title = extractTag(html, "title");
  if (title) return title.replace(/\s+/g, " ").trim();
  return "Untitled report";
}

async function listHtmlFiles() {
  const entries = await fs.readdir(REPO_DOCS, { withFileTypes: true });
  return entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith(".html"))
    .map((e) => e.name);
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const files = await listHtmlFiles();
  const slugsSeen = new Set();
  const manifest = [];

  for (const filename of files.sort()) {
    const base = filename.replace(/\.html$/i, "");
    const canonical = SKIP_WHEN_CANONICAL_EXISTS.get(base);
    if (canonical && files.some((f) => slugFromFilename(f) === canonical)) {
      continue;
    }

    const slug = slugFromFilename(filename);
    if (slugsSeen.has(slug)) continue;
    slugsSeen.add(slug);

    const raw = await fs.readFile(path.join(REPO_DOCS, filename), "utf8");
    const title = extractTitle(raw);
    const styles = extractAllStyles(raw);
    const bodyHtml = extractBodyInner(raw);

    const payload = {
      slug,
      sourceFile: filename,
      title,
      styles,
      bodyHtml,
      builtAt: new Date().toISOString(),
    };

    await fs.writeFile(
      path.join(OUT_DIR, `${slug}.json`),
      JSON.stringify(payload, null, 2),
      "utf8",
    );

    manifest.push({
      slug,
      title,
      sourceFile: filename,
      href: `/reports/${slug}`,
    });
  }

  manifest.sort((a, b) => a.title.localeCompare(b.title));

  await fs.writeFile(
    MANIFEST_PATH,
    JSON.stringify({ pages: manifest, generatedAt: new Date().toISOString() }, null, 2),
    "utf8",
  );

  await fs.writeFile(
    path.join(OUT_DIR, "html-manifest.ts"),
    `/* eslint-disable */\n/** Auto-generated by scripts/build-from-html.mjs — do not edit */\nimport type { HtmlReportManifest } from "@/lib/types";\n\nexport const htmlReportManifest: HtmlReportManifest = ${JSON.stringify({ pages: manifest }, null, 2)} as const;\n`,
    "utf8",
  );

  console.log(`Built ${manifest.length} HTML report(s) into src/generated/`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
