/**
 * End-customer Commerce "Buy now" orders — see /docs/product-bundles (Commerce add-on).
 *
 * A completed commerce_sku Stripe Checkout Session (POST /api/commerce/checkout)
 * is money from the lead's own customer for one catalog SKU. It is NOT Local
 * Site Studio's own revenue (that is `orders`/OrderRecord — Starter/Growth/
 * Complete/Commerce bundle sales) and must never be written into the `orders`
 * table: several eligibility predicates (orderEligibleForBillingPortal,
 * leadEligibleForStarterUpsell, leadEligibleForCommerceCatalog) treat any
 * `orders` row with commerceAddon=true as "this lead already subscribes to the
 * Commerce add-on," and revenueTotalUsd/orderCount on the dashboard are read
 * as Local Site Studio's own sales. Mixing pass-through customer revenue into
 * that table would falsely suppress upsell/billing-portal eligibility and
 * inflate the operator's own revenue number with money that isn't theirs.
 * Keep this a separate, append-only ledger instead.
 */

export interface CommerceOrderRecord {
  id: string;
  leadSlug: string;
  skuId: string;
  skuName: string;
  /** USD dollars (not cents) — matches OrderRecord.amountPaid's unit convention. */
  amountPaidUsd: number;
  stripeSessionId: string;
  createdAt: string;
}

export interface InsertCommerceOrderInput {
  leadSlug: string;
  skuId: string;
  skuName: string;
  amountPaidUsd: number;
  stripeSessionId: string;
}

/**
 * Stable app-owned id for a new commerce order row, generated by the caller
 * (src/lib/db.ts) before persisting — same pattern as newCommerceSkuId and the
 * packId/inquiryId columns every other ledger (clientVoicePacks, marketingPacks,
 * clientInquiries) stores explicitly, so both the SQLite and Convex backends
 * return the same shape instead of the Convex row silently lacking an id.
 */
export function newCommerceOrderId(): string {
  return `corder_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
}

/** Sum of all recorded commerce-order amounts (USD dollars). Pure — no I/O. */
export function sumCommerceOrdersRevenueUsd(
  orders: ReadonlyArray<{ amountPaidUsd: number }>,
): number {
  let total = 0;
  for (const order of orders) {
    if (typeof order.amountPaidUsd === "number" && Number.isFinite(order.amountPaidUsd)) {
      total += order.amountPaidUsd;
    }
  }
  return total;
}

/**
 * Per-lead rollup of pass-through Buy now orders for manual payout
 * reconciliation until Stripe Connect ships. Pure — no I/O.
 *
 * Sort: highest total owed first, then most-recent order, then slug.
 * Within each lead, orders are newest-first (createdAt desc).
 */
export interface CommerceOrdersByLeadSummary {
  leadSlug: string;
  orderCount: number;
  totalUsd: number;
  latestCreatedAt: string;
  /** Newest-first slice of this lead's orders (caller may already have capped the input list). */
  orders: CommerceOrderRecord[];
}

export function summarizeCommerceOrdersByLead(
  orders: ReadonlyArray<CommerceOrderRecord>,
): CommerceOrdersByLeadSummary[] {
  const bySlug = new Map<string, CommerceOrderRecord[]>();
  for (const order of orders) {
    const existing = bySlug.get(order.leadSlug);
    if (existing) {
      existing.push(order);
    } else {
      bySlug.set(order.leadSlug, [order]);
    }
  }

  const summaries: CommerceOrdersByLeadSummary[] = [];
  for (const [leadSlug, leadOrders] of bySlug) {
    const sorted = [...leadOrders].sort((a, b) =>
      b.createdAt.localeCompare(a.createdAt),
    );
    const latest = sorted[0];
    if (!latest) continue;
    summaries.push({
      leadSlug,
      orderCount: sorted.length,
      totalUsd: sumCommerceOrdersRevenueUsd(sorted),
      latestCreatedAt: latest.createdAt,
      orders: sorted,
    });
  }

  return summaries.sort((a, b) => {
    if (b.totalUsd !== a.totalUsd) return b.totalUsd - a.totalUsd;
    const byDate = b.latestCreatedAt.localeCompare(a.latestCreatedAt);
    if (byDate !== 0) return byDate;
    return a.leadSlug.localeCompare(b.leadSlug);
  });
}
