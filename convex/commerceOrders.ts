import { mutation, query } from "./_generated/server";
import { v } from "convex/values";

const orderReturn = v.object({
  id: v.string(),
  leadSlug: v.string(),
  skuId: v.string(),
  skuName: v.string(),
  amountPaidUsd: v.number(),
  stripeSessionId: v.string(),
  createdAt: v.string(),
  paidOutAt: v.optional(v.string()),
});

/**
 * Idempotent on stripeSessionId — Stripe may resend checkout.session.completed
 * for the same session, and the webhook must never double-count revenue.
 * Returns null (no insert) when a row for this session already exists.
 *
 * orderId is an app-owned id generated by the caller (newCommerceOrderId in
 * src/lib/commerce/orders.ts, same pattern as packId/inquiryId on the other
 * ledgers) — stored as its own column so `id` round-trips on every read, the
 * same way clientVoicePacks/marketingPacks/clientInquiries already do.
 */
export const insert = mutation({
  args: {
    orderId: v.string(),
    leadSlug: v.string(),
    skuId: v.string(),
    skuName: v.string(),
    amountPaidUsd: v.number(),
    stripeSessionId: v.string(),
    createdAt: v.string(),
  },
  returns: v.union(orderReturn, v.null()),
  handler: async (ctx, args) => {
    const existing = await ctx.db
      .query("commerceOrders")
      .withIndex("by_stripeSessionId", (q) =>
        q.eq("stripeSessionId", args.stripeSessionId),
      )
      .unique();
    if (existing) return null;

    await ctx.db.insert("commerceOrders", args);
    return {
      id: args.orderId,
      leadSlug: args.leadSlug,
      skuId: args.skuId,
      skuName: args.skuName,
      amountPaidUsd: args.amountPaidUsd,
      stripeSessionId: args.stripeSessionId,
      createdAt: args.createdAt,
    };
  },
});

export const list = query({
  args: { limit: v.optional(v.number()) },
  returns: v.array(orderReturn),
  handler: async (ctx, args) => {
    const limit = Math.min(Math.max(args.limit ?? 200, 1), 500);
    const rows = await ctx.db.query("commerceOrders").order("desc").take(limit);
    return rows.map((row) => ({
      id: row.orderId,
      leadSlug: row.leadSlug,
      skuId: row.skuId,
      skuName: row.skuName,
      amountPaidUsd: row.amountPaidUsd,
      stripeSessionId: row.stripeSessionId,
      createdAt: row.createdAt,
      paidOutAt: row.paidOutAt,
    }));
  },
});

/**
 * Every unpaid pass-through Buy now order for manual payout reconciliation.
 * Must not reuse list()'s 200/500 newest cap — once volume exceeds that window,
 * older unpaid rows vanish from owed totals / Mark paid out lookups.
 *
 * Collect + filter is intentional: unpaid liability is a bounded operator ledger
 * until Stripe Connect, and completeness beats a truncated recent page.
 */
export const listUnpaid = query({
  args: {},
  returns: v.array(orderReturn),
  handler: async (ctx) => {
    const rows = await ctx.db.query("commerceOrders").order("desc").collect();
    return rows
      .filter((row) => row.paidOutAt === undefined)
      .map((row) => ({
        id: row.orderId,
        leadSlug: row.leadSlug,
        skuId: row.skuId,
        skuName: row.skuName,
        amountPaidUsd: row.amountPaidUsd,
        stripeSessionId: row.stripeSessionId,
        createdAt: row.createdAt,
        paidOutAt: row.paidOutAt,
      }));
  },
});

/** Lookup one commerce order by Stripe Checkout Session id (Mark paid out). */
export const getByStripeSessionId = query({
  args: { stripeSessionId: v.string() },
  returns: v.union(orderReturn, v.null()),
  handler: async (ctx, args) => {
    const row = await ctx.db
      .query("commerceOrders")
      .withIndex("by_stripeSessionId", (q) =>
        q.eq("stripeSessionId", args.stripeSessionId),
      )
      .unique();
    if (!row) return null;
    return {
      id: row.orderId,
      leadSlug: row.leadSlug,
      skuId: row.skuId,
      skuName: row.skuName,
      amountPaidUsd: row.amountPaidUsd,
      stripeSessionId: row.stripeSessionId,
      createdAt: row.createdAt,
      paidOutAt: row.paidOutAt,
    };
  },
});

/**
 * Marks a commerce order as manually paid out to the client. Keyed on
 * stripeSessionId (unique, always present) rather than the Convex row id —
 * matches the checkoutSessions mutation pattern (recordRecoverySent).
 */
export const markPaidOut = mutation({
  args: { stripeSessionId: v.string(), paidOutAt: v.string() },
  returns: v.null(),
  handler: async (ctx, args) => {
    const order = await ctx.db
      .query("commerceOrders")
      .withIndex("by_stripeSessionId", (q) =>
        q.eq("stripeSessionId", args.stripeSessionId),
      )
      .unique();
    if (order) {
      await ctx.db.patch(order._id, { paidOutAt: args.paidOutAt });
    }
    return null;
  },
});
