import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { TrustClaimError } from "./guard.ts";
import { grantsProfile } from "./profiles/grants.ts";
import { generateSecurityTxt, securityTxtForProfile } from "./security-txt.ts";

const NOW = new Date("2026-11-24T12:00:00Z");
const IN_90_DAYS = new Date("2027-02-22T00:00:00Z");

describe("generateSecurityTxt", () => {
  it("writes Contact and Expires (RFC 3339) plus optional fields", () => {
    const txt = generateSecurityTxt(
      {
        contact: ["mailto:security@example.test", "https://example.test/report"],
        expires: IN_90_DAYS,
        preferredLanguages: ["en", "es"],
        canonical: ["https://example.test/.well-known/security.txt"],
        policy: ["https://example.test/security/disclosure"],
        comments: ["Generated by @private-monorepo/trust-page"],
      },
      NOW,
    );
    assert.equal(
      txt,
      [
        "# Generated by @private-monorepo/trust-page",
        "Contact: mailto:security@example.test",
        "Contact: https://example.test/report",
        "Expires: 2027-02-22T00:00:00.000Z",
        "Preferred-Languages: en, es",
        "Canonical: https://example.test/.well-known/security.txt",
        "Policy: https://example.test/security/disclosure",
        "",
      ].join("\n"),
    );
  });
  it("requires a contact", () => {
    assert.throws(() => generateSecurityTxt({ contact: [], expires: IN_90_DAYS }, NOW), /Contact/);
  });
  it("refuses a contact that is not a URI", () => {
    assert.throws(
      () => generateSecurityTxt({ contact: ["security@example.test"], expires: IN_90_DAYS }, NOW),
      TrustClaimError,
    );
  });
  it("refuses an expiry in the past or more than a year ahead", () => {
    const c = ["mailto:s@example.test"];
    assert.throws(
      () => generateSecurityTxt({ contact: c, expires: new Date("2026-01-01") }, NOW),
      /past/,
    );
    assert.throws(
      () => generateSecurityTxt({ contact: c, expires: new Date("2027-12-01T00:00:00Z") }, NOW),
      /at most 365 days/,
    );
    assert.throws(
      () => generateSecurityTxt({ contact: c, expires: new Date("nope") }, NOW),
      /valid date/,
    );
  });
  it("refuses http URIs and header injection", () => {
    const c = ["mailto:s@example.test"];
    assert.throws(
      () =>
        generateSecurityTxt({ contact: c, expires: IN_90_DAYS, policy: ["http://x.test/p"] }, NOW),
      /https/,
    );
    assert.throws(
      () =>
        generateSecurityTxt({ contact: c, expires: IN_90_DAYS, comments: ["a\nContact: x"] }, NOW),
      /single-line/,
    );
    assert.throws(
      () =>
        generateSecurityTxt({ contact: c, expires: IN_90_DAYS, preferredLanguages: ["en\n"] }, NOW),
      /language tag/,
    );
  });
});

describe("securityTxtForProfile", () => {
  it("fails closed while the product has no security contact", () => {
    assert.equal(grantsProfile.securityContact, null);
    assert.throws(
      () => securityTxtForProfile(grantsProfile, { expires: IN_90_DAYS }, NOW),
      /no security contact/,
    );
  });
  it("uses the profile's contact and policy", () => {
    const txt = securityTxtForProfile(
      {
        ...grantsProfile,
        securityContact: "mailto:security@example.test",
        disclosurePolicyUrl: "https://example.test/security/disclosure",
      },
      { expires: IN_90_DAYS, canonicalUrl: "https://example.test/.well-known/security.txt" },
      NOW,
    );
    assert.match(txt, /^Contact: mailto:security@example.test$/m);
    assert.match(txt, /^Policy: https:\/\/example.test\/security\/disclosure$/m);
    assert.match(txt, /^Canonical: https:\/\/example.test\/.well-known\/security.txt$/m);
    assert.match(txt, /^Preferred-Languages: en$/m);
  });
});
