import type { Block, BlockTemplate, FormDefinition, RenderResult, WaiverData } from "./types.ts";
import { validate } from "./validate.ts";

const PLACEHOLDER = /\{\{(\w+)\}\}/g;
const BLANK = "________________";

/** Every `{{key}}` used in a body. */
export function placeholdersOf(body: readonly BlockTemplate[]): Set<string> {
  const keys = new Set<string>();
  for (const b of body) {
    const texts =
      b.type === "field"
        ? [b.value]
        : b.type === "signature"
          ? (b.lines ?? []).map((l) => l.value)
          : "text" in b
            ? [b.text]
            : [];
    for (const text of texts) for (const m of text.matchAll(PLACEHOLDER)) if (m[1]) keys.add(m[1]);
  }
  return keys;
}

/** Placeholders a body uses that the form does not declare as fields. */
export function undeclaredPlaceholders(form: FormDefinition): string[] {
  if (!form.body) return [];
  const declared = new Set(form.fields.map((f) => f.key));
  return [...placeholdersOf(form.body)].filter((k) => !declared.has(k));
}

function fill(text: string, values: Readonly<Record<string, string>>, blank = BLANK): string {
  return text.replace(PLACEHOLDER, (_, key: string) => {
    const v = values[key];
    return v === undefined || v === "" ? blank : v;
  });
}

/**
 * A body's blocks with every `{{key}}` replaced by its formatted value (a printed rule where the
 * value is blank; signature lines stay empty for a hand signature). Values come from `validate`.
 */
export function fillBlocks(
  body: readonly BlockTemplate[],
  values: Readonly<Record<string, string>>,
): Block[] {
  return body.map((b): Block => {
    switch (b.type) {
      case "field":
        return { type: "field", label: b.label, value: fill(b.value, values) };
      case "signature":
        if (b.lines) {
          return {
            type: "signature",
            lines: b.lines.map((l) => ({ label: l.label, value: fill(l.value, values, "") })),
          };
        }
        return {
          type: "signature",
          lines: [
            { label: "Claimant's Signature", value: "" },
            { label: "Claimant's Title", value: values.signerTitle ?? "" },
            { label: "Name", value: values.signerName ?? "" },
            { label: "Date of Signature", value: values.signedDate ?? "" },
          ],
        };
      case "spacer":
        return b;
      default:
        return { type: b.type, text: fill(b.text, values) };
    }
  });
}

/**
 * Validate `data` and render `form` into a structured document of PDF-ready blocks.
 * A statutory form whose verified text is not encoded is refused, never substituted.
 */
export function render(form: FormDefinition, data: WaiverData): RenderResult {
  if (!form.body && form.absent) {
    return {
      ok: false,
      errors: [{ field: null, code: "NO_STATUTORY_FORM", message: form.absent }],
    };
  }
  if (!form.body) {
    const cite = form.citation?.text ?? "This statutory form";
    const url = form.citation?.officialUrl;
    return {
      ok: false,
      errors: [
        {
          field: null,
          code: "STATUTORY_TEXT_NOT_ENCODED",
          message: `${cite}: verified statutory text is not encoded in this package. Use the official statutory form${url ? ` (${url})` : ""}.`,
        },
      ],
    };
  }
  const v = validate(form, data);
  if (!v.ok) return v;
  const { values } = v;

  const blocks = fillBlocks(form.body, values);

  return {
    ok: true,
    document: {
      formId: form.id,
      state: form.state,
      kind: form.kind,
      source: form.source,
      title: form.title,
      citation: form.citation?.text ?? null,
      disclaimers: [
        ...form.notes,
        "Generated by software; not legal advice. Have counsel review before relying on it.",
      ],
      values,
      blocks,
      ...(form.minFontPt ? { minFontPt: form.minFontPt } : {}),
    },
  };
}

/** Plain-text rendering of a document (previews, email bodies, snapshot tests). */
export function toPlainText(doc: { blocks: readonly Block[] }): string {
  const out: string[] = [];
  for (const b of doc.blocks) {
    switch (b.type) {
      case "title":
        out.push(b.text.toUpperCase(), "");
        break;
      case "heading":
      case "paragraph":
      case "notice":
        out.push(b.text, "");
        break;
      case "field":
        out.push(`${b.label}: ${b.value}`);
        break;
      case "signature":
        for (const l of b.lines) out.push(`${l.label}: ${l.value || BLANK}`);
        break;
      case "spacer":
        out.push("");
        break;
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}
