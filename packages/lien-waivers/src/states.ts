export type UsState = (typeof US_STATES)[number];

export function normalizeState(input: string): UsState {
  const code = input.trim().toUpperCase();
  const found = US_STATES.find((s) => s === code);
  if (!found) throw new RangeError(`Unknown US state code: ${JSON.stringify(input)}`);
  return found;
}
