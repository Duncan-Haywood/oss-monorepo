/**
 * Copies standalone HTML reports into the docs Vite app and emits a TS manifest.
 * Run before `vite build` (wired in apps/docs package.json).
 */
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  { dir: join(root, "docs"), label: "docs" },
  { dir: join(root, "reports"), label: "reports" },
];
const publicDir = join(root, "apps/docs/public/reports");
const generatedDir = join(root, "apps/docs/src/generated");
const manifestPath = join(generatedDir, "htmlReports.ts");

function slugFromFilename(name: string): string {
  return basename(name, ".html")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function extractTitle(html: string, fallback: string): string {
  const match = html.match(/<title[^>]*>([^<]+)<\/title>/i);
  return match?.[1]?.trim() || fallback;
}

export interface HtmlReportEntry {
  slug: string;
  title: string;
  /** Path under site root after build, e.g. reports/foo.html */
  assetPath: string;
  sourceLabel: "docs" | "reports";
  sourceFile: string;
}

const entries: HtmlReportEntry[] = [];

mkdirSync(publicDir, { recursive: true });
mkdirSync(generatedDir, { recursive: true });

for (const { dir, label } of sources) {
  let files: string[];
  try {
    files = readdirSync(dir).filter((f) => f.endsWith(".html"));
  } catch {
    continue;
  }

  for (const file of files.sort()) {
    const src = join(dir, file);
    const slug = slugFromFilename(file);
    const html = readFileSync(src, "utf8");
    const title = extractTitle(html, basename(file, ".html"));
    const destName = `${slug}.html`;
    const dest = join(publicDir, destName);

    copyFileSync(src, dest);
    entries.push({
      slug,
      title,
      assetPath: `reports/${destName}`,
      sourceLabel: label as "docs" | "reports",
      sourceFile: relative(root, src),
    });
    console.log(`  ✓ ${relative(root, src)} → apps/docs/public/${entries.at(-1)!.assetPath}`);
  }
}

const manifest = `/** Generated by scripts/ingest-html-docs.ts — do not edit manually. */
export interface HtmlReportEntry {
  slug: string;
  title: string;
  assetPath: string;
  sourceLabel: "docs" | "reports";
  sourceFile: string;
}

export const htmlReports: HtmlReportEntry[] = ${JSON.stringify(entries, null, 2)} as const;
`;

writeFileSync(manifestPath, manifest, "utf8");
console.log(`\n✓ Ingested ${entries.length} HTML report(s) → ${relative(root, manifestPath)}`);
