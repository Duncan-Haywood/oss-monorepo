/**
 * Copies standalone HTML reports into the docs app public folder and
 * generates a TS manifest for HashRouter pages that embed them.
 */
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  join(root, "docs"),
  join(root, "reports"),
];
const publicDir = join(root, "apps/docs/public/html-reports");
const generatedDir = join(root, "apps/docs/src/generated");
const manifestPath = join(generatedDir, "htmlReportManifest.ts");

interface HtmlReportEntry {
  slug: string;
  title: string;
  sourceLabel: string;
  assetPath: string;
}

function collectHtmlFiles(dir: string): string[] {
  const found: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      found.push(...collectHtmlFiles(full));
    } else if (name.endsWith(".html")) {
      found.push(full);
    }
  }
  return found;
}

function extractTitle(html: string, fallback: string): string {
  const match = html.match(/<title[^>]*>([^<]+)<\/title>/i);
  if (!match) return fallback;
  return match[1].replace(/\s*[—–-]\s*Retail Pilot Intel\s*$/i, "").trim() || fallback;
}

function toSlug(relPath: string): string {
  return relPath.replace(/\.html$/i, "").replace(/[/\\]/g, "-");
}

mkdirSync(publicDir, { recursive: true });
mkdirSync(generatedDir, { recursive: true });

const entries: HtmlReportEntry[] = [];

for (const sourceRoot of sources) {
  const label = basename(sourceRoot);
  for (const file of collectHtmlFiles(sourceRoot)) {
    const rel = relative(sourceRoot, file);
    const slug = toSlug(`${label}/${rel}`);
    const html = readFileSync(file, "utf8");
    const title = extractTitle(html, basename(rel, ".html"));
    const destName = `${slug}.html`;
    const dest = join(publicDir, destName);
    copyFileSync(file, dest);
    entries.push({
      slug,
      title,
      sourceLabel: `${label}/${rel}`,
      assetPath: `html-reports/${destName}`,
    });
    console.log(`  synced ${label}/${rel} → html-reports/${destName}`);
  }
}

entries.sort((a, b) => a.title.localeCompare(b.title));

const manifestSource = `// AUTO-GENERATED by scripts/sync-html-docs.ts — do not edit by hand.
export interface HtmlReportEntry {
  slug: string;
  title: string;
  sourceLabel: string;
  assetPath: string;
}

export const htmlReportManifest: HtmlReportEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(manifestPath, manifestSource, "utf8");
console.log(`\n✓ ${entries.length} HTML report(s) → apps/docs/public/html-reports/`);
console.log(`✓ Manifest → apps/docs/src/generated/htmlReportManifest.ts`);
