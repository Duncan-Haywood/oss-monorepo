/**
 * Build step: ingest standalone HTML/Markdown from docs/ and reports/
 * into generated TS modules consumed by the TSX docs site.
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "apps/docs/src/generated");
const contentDir = join(outDir, "content");

type Category = "docs" | "reports";

interface SourceRoot {
  dir: string;
  category: Category;
}

const SOURCES: SourceRoot[] = [
  { dir: join(root, "docs"), category: "docs" },
  { dir: join(root, "reports"), category: "reports" },
];

interface DiscoveredFile {
  absPath: string;
  category: Category;
  relFromRoot: string;
  slug: string;
  ext: ".html" | ".md";
}

function walk(dir: string, category: Category, acc: DiscoveredFile[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    const absPath = join(dir, name);
    const st = statSync(absPath);
    if (st.isDirectory()) {
      if (name === "node_modules" || name.startsWith(".")) continue;
      walk(absPath, category, acc);
      continue;
    }
    const ext = name.endsWith(".md")
      ? ".md"
      : name.endsWith(".html")
        ? ".html"
        : null;
    if (!ext) continue;
    const base = basename(name, ext);
    if (base.toLowerCase() === "readme") continue;
    acc.push({
      absPath,
      category,
      relFromRoot: relative(root, absPath).replace(/\\/g, "/"),
      slug: slugify(base),
      ext,
    });
  }
}

function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function stripScripts(html: string): string {
  return html.replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "");
}

function extractFromHtml(raw: string): { title: string; bodyHtml: string } {
  const titleMatch = raw.match(/<title[^>]*>([^<]*)<\/title>/i);
  const bodyMatch = raw.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  const h1Match = raw.match(/<h1[^>]*>([^<]*)<\/h1>/i);
  const bodyHtml = stripScripts((bodyMatch?.[1] ?? raw).trim());
  const title =
    titleMatch?.[1]?.trim() ||
    h1Match?.[1]?.trim() ||
    "Untitled document";
  return { title, bodyHtml };
}

function extractFromMarkdown(raw: string, fallbackTitle: string): {
  title: string;
  bodyHtml: string;
} {
  const lines = raw.split("\n");
  let title = fallbackTitle;
  if (lines[0]?.startsWith("# ")) {
    title = lines[0].slice(2).trim();
  }
  const bodyHtml = marked.parse(raw, { async: false }) as string;
  return { title, bodyHtml: stripScripts(bodyHtml) };
}

function discover(): DiscoveredFile[] {
  const files: DiscoveredFile[] = [];
  for (const { dir, category } of SOURCES) {
    walk(dir, category, files);
  }
  const bySlug = new Map<string, DiscoveredFile>();
  for (const f of files) {
    const existing = bySlug.get(f.slug);
    if (existing) {
      throw new Error(
        `Duplicate HTML doc slug "${f.slug}": ${existing.relFromRoot} vs ${f.relFromRoot}`,
      );
    }
    bySlug.set(f.slug, f);
  }
  return files.sort((a, b) => a.slug.localeCompare(b.slug));
}

function writeContentModule(
  slug: string,
  meta: { title: string; category: Category; sourcePath: string },
  bodyHtml: string,
): void {
  const filePath = join(contentDir, `${slug}.ts`);
  const contents = `/** Auto-generated by scripts/sync-html-docs.ts — do not edit */
export const meta = ${JSON.stringify(meta, null, 2)} as const;

export const bodyHtml = ${JSON.stringify(bodyHtml)} as const;
`;
  writeFileSync(filePath, contents, "utf8");
}

function writeManifest(
  entries: Array<{
    slug: string;
    title: string;
    category: Category;
    sourcePath: string;
  }>,
): void {
  const manifestPath = join(outDir, "htmlManifest.ts");
  const contents = `/** Auto-generated by scripts/sync-html-docs.ts — do not edit */
export type HtmlDocCategory = "docs" | "reports";

export interface HtmlDocMeta {
  slug: string;
  title: string;
  category: HtmlDocCategory;
  sourcePath: string;
}

export const htmlDocs: HtmlDocMeta[] = ${JSON.stringify(entries, null, 2)} as const;
`;
  writeFileSync(manifestPath, contents, "utf8");
}

function writeContentIndex(slugs: string[]): void {
  const imports = slugs
    .map((s) => `import * as doc_${s.replace(/-/g, "_")} from "./content/${s}";`)
    .join("\n");
  const mapEntries = slugs
    .map((s) => `  "${s}": doc_${s.replace(/-/g, "_")},`)
    .join("\n");
  const contents = `/** Auto-generated by scripts/sync-html-docs.ts — do not edit */
${imports}

export interface GeneratedHtmlDoc {
  meta: {
    slug: string;
    title: string;
    category: "docs" | "reports";
    sourcePath: string;
  };
  bodyHtml: string;
}

export const htmlDocBySlug: Record<string, GeneratedHtmlDoc> = {
${mapEntries}
};
`;
  writeFileSync(join(outDir, "htmlDocBySlug.ts"), contents, "utf8");
}

function main(): void {
  mkdirSync(contentDir, { recursive: true });
  const files = discover();
  const manifest: Array<{
    slug: string;
    title: string;
    category: Category;
    sourcePath: string;
  }> = [];

  for (const f of files) {
    const raw = readFileSync(f.absPath, "utf8");
    const fallbackTitle = basename(f.absPath, f.ext)
      .replace(/-/g, " ")
      .replace(/\b\w/g, (c) => c.toUpperCase());
    const { title, bodyHtml } =
      f.ext === ".html"
        ? extractFromHtml(raw)
        : extractFromMarkdown(raw, fallbackTitle);
    const meta = {
      slug: f.slug,
      title,
      category: f.category,
      sourcePath: f.relFromRoot,
    };
    writeContentModule(f.slug, meta, bodyHtml);
    manifest.push(meta);
  }

  writeManifest(manifest);
  writeContentIndex(manifest.map((m) => m.slug));

  console.log(`✓ Synced ${manifest.length} HTML/Markdown doc(s) → apps/docs/src/generated`);
  for (const m of manifest) {
    console.log(`  · ${m.slug} ← ${m.sourcePath}`);
  }
}

main();
