/**
 * Registers TSX report modules for routing and nav.
 * Run before docs dev/build (apps/docs prebuild).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reportsDir = join(root, "apps/docs/src/reports");
const manifestPath = join(root, "apps/docs/src/generated/report-manifest.ts");

interface ReportMeta {
  slug: string;
  title: string;
  legacySlugs: string[];
  sourcePath: string;
  componentName: string;
  modulePath: string;
}

function parseReportMeta(filePath: string): ReportMeta | null {
  const src = readFileSync(filePath, "utf8");
  const slug = src.match(/slug:\s*"([^"]+)"/)?.[1];
  const title = src.match(/title:\s*"((?:\\.|[^"\\])*)"/)?.[1];
  const sourcePath = src.match(/sourcePath:\s*"([^"]+)"/)?.[1];
  const legacyRaw = src.match(/legacySlugs:\s*(\[[^\]]*\])/);
  const exportFn = src.match(/export function (\w+)\(/);

  if (!slug || !title || !sourcePath || !exportFn) return null;

  let legacySlugs: string[] = [];
  if (legacyRaw) {
    legacySlugs = JSON.parse(legacyRaw[1].replace(/'/g, '"')) as string[];
  }

  const file = basename(filePath);
  return {
    slug,
    title: title.replace(/\\"/g, '"'),
    legacySlugs,
    sourcePath,
    componentName: exportFn[1],
    modulePath: `../reports/${file.replace(/\.tsx$/, "")}`,
  };
}

const entries: ReportMeta[] = [];
for (const file of readdirSync(reportsDir)) {
  if (!file.endsWith(".tsx")) continue;
  const full = join(reportsDir, file);
  const meta = parseReportMeta(full);
  if (meta) entries.push(meta);
}

entries.sort((a, b) => a.title.localeCompare(b.title));

const slugSeen = new Set<string>();
for (const e of entries) {
  if (slugSeen.has(e.slug)) {
    throw new Error(`Duplicate report slug: ${e.slug}`);
  }
  slugSeen.add(e.slug);
}

const builtAt = new Date().toISOString();

const imports = entries
  .map((e) => `import { ${e.componentName}, reportMeta as ${e.componentName}Meta } from "${e.modulePath}";`)
  .join("\n");

const registry = entries
  .map(
    (e) =>
      `  {
    slug: ${e.componentName}Meta.slug,
    title: ${e.componentName}Meta.title,
    legacySlugs: ${e.componentName}Meta.legacySlugs ?? [],
    sourcePath: ${e.componentName}Meta.sourcePath,
    View: ${e.componentName},
  }`,
  )
  .join(",\n");

const legacyRedirects = entries.flatMap((e) =>
  (e.legacySlugs ?? []).map(
    (legacy) => `  { from: ${JSON.stringify(legacy)}, to: ${JSON.stringify(e.slug)} },`,
  ),
);

const manifestTs = `/** Generated by scripts/build-report-manifest.ts — do not edit. */
import type { ComponentType } from "react";
${imports}

export interface ReportRegistryEntry {
  slug: string;
  title: string;
  legacySlugs: readonly string[];
  sourcePath: string;
  View: ComponentType;
}

export const reportRegistry: ReportRegistryEntry[] = [
${registry}
];

export const reportLegacyRedirects: { from: string; to: string }[] = [
${legacyRedirects.join("\n")}
];

export const reportsBuiltAt = ${JSON.stringify(builtAt)};
`;

writeFileSync(manifestPath, manifestTs, "utf8");
console.log(`✓ Registered ${entries.length} TSX report(s) → apps/docs/src/generated/report-manifest.ts`);
