#!/usr/bin/env bash
# One place every agent and every script reads a secret from.
#
# WHY THIS EXISTS
#
# Every credential this repository needs lives in GitHub Actions secrets, and
# an Actions secret is readable by exactly one thing: a runner. Runners here are
# metered and the allowance is spent (`portfolio/ledger/infra_state.yaml`,
# `github-actions-runners: down`, re-measured across four dispatches on
# 2026-09-05). So the secrets became unreachable at the same moment, and for the
# same reason, as the thing they were supposed to unblock. That is not a
# coincidence to work around — it is a single point of failure that was never
# named, because "the secret is in Actions" reads like the secret is stored.
#
# It is worse than one outage. The three routes to a public surface all run on
# something else that is down (CLAUDE.md, "Pipeline and new ventures"), and the
# one route that needs neither a runner nor the cluster — SSH to a box whose
# `:22` has answered the whole time — is the one whose credential is *only* in
# Actions. `bootstrap/restore-cluster.sh` is the whole recovery and it runs from
# any laptop, so the missing piece was never compute. It was a place to keep a
# key that a laptop, Cursor, or a local Claude Code session can read.
#
# WHERE SECRETS LIVE NOW
#
# Resolution order, per secret, first hit wins:
#
#   1. the process environment          — CI, and one-off overrides
#   2. $SECRETS_DIR/<NAME>              — one file per secret, mode 600
#                                         (default ~/.config/marisstella/secrets)
#   3. infra/secrets/<NAME>.age         — committed, age-encrypted, opened with
#                                         the identity in $AGE_IDENTITY_FILE
#
# (2) is the store: a directory of plain files on the machine that runs your
# agents. No vendor, no network, no runner, and multi-line material like an SSH
# private key needs no escaping. (3) is the same secrets travelling with the
# repository so a fresh checkout on another machine is one `age` identity away
# from working; it is optional and this script is useful without it.
#
# There is deliberately no fourth source. A hosted secret manager (Vault,
# 1Password, Doppler, Infisical) was measured on 2026-09-06 from a Claude Code
# web session and every one of them is refused by the agent egress proxy with
# `403 to CONNECT` — see infra/SECRETS.md. A store the automation cannot reach
# is the problem this script exists to fix, not a different shape of it.
#
# USAGE
#
#   bootstrap/scripts/load-secrets.sh                    # what is present, no values
#   bootstrap/scripts/load-secrets.sh --get GH_TOKEN     # one value on stdout
#   eval "$(bootstrap/scripts/load-secrets.sh --export)" # into this shell
#   bootstrap/scripts/load-secrets.sh --exec -- CONFIRM=restore-cluster \
#       bootstrap/restore-cluster.sh                     # into one child, only
#   bootstrap/scripts/load-secrets.sh --put HETZNERSSHKEY < id_ed25519
#   bootstrap/scripts/load-secrets.sh --encrypt HETZNERSSHKEY
#
# Prefer `--exec`. It puts the secrets in one child process and nowhere else:
# not in your shell, not in your history, not in a file the next command can
# read. It also starts a throwaway ssh-agent holding HETZNERSSHKEY, so the
# restore scripts authenticate without you touching your own agent or ~/.ssh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SECRETS_DIR="${SECRETS_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/marisstella/secrets}"
ENC_DIR="${SECRETS_ENC_DIR:-$ROOT/infra/secrets}"
REGISTRY="$ENC_DIR/registry.tsv"
RECIPIENTS="$ENC_DIR/recipients.txt"
# Same default path bootstrap/scripts/gen-age-key.sh writes to, and the same one
# sops reads, so an identity generated by either is found by this without
# configuration.
AGE_IDENTITY_FILE="${AGE_IDENTITY_FILE:-${SOPS_AGE_KEY_FILE:-${XDG_CONFIG_HOME:-$HOME/.config}/sops/age/keys.txt}}"

die() { echo "load-secrets: $*" >&2; exit 1; }

# ---------------------------------------------------------------- the registry
#
# The names are in a committed file rather than in this script because two other
# things need the same list: infra/SECRETS.md documents it, and
# gitops/tests/test_load_secrets.py asserts the two agree. A list restated in
# three places is three lists, and CLAUDE.md records twice what that has cost
# here.
registry_names() {
  [[ -f "$REGISTRY" ]] || die "no registry at $REGISTRY"
  # Field 1 of every non-comment, non-blank line.
  awk -F'\t' '!/^#/ && NF && $1 != "" { print $1 }' "$REGISTRY"
}

registry_field() {
  awk -F'\t' -v want="$1" -v col="$2" '!/^#/ && $1 == want { print $col; exit }' "$REGISTRY"
}

# ----------------------------------------------------------------- resolution
#
# Sets REPLY to the value and SOURCE to where it came from. Returns 1 when the
# secret is nowhere, which is a normal answer and not an error: most routes need
# a subset, and `--check` reports the whole picture rather than stopping at the
# first gap.
resolve() {
  local name="$1"
  REPLY=""; SOURCE=""

  if [[ -n "${!name:-}" ]]; then
    REPLY="${!name}"; SOURCE="environment"; return 0
  fi

  if [[ -f "$SECRETS_DIR/$name" ]]; then
    REPLY="$(cat "$SECRETS_DIR/$name")"; SOURCE="file"; return 0
  fi

  if [[ -f "$ENC_DIR/$name.age" ]]; then
    command -v age >/dev/null 2>&1 || die "$name is encrypted but age is not installed (https://github.com/FiloSottile/age)"
    [[ -f "$AGE_IDENTITY_FILE" ]] || die "$name is encrypted but no age identity at $AGE_IDENTITY_FILE"
    REPLY="$(age -d -i "$AGE_IDENTITY_FILE" "$ENC_DIR/$name.age")" \
      || die "could not decrypt $ENC_DIR/$name.age with $AGE_IDENTITY_FILE"
    SOURCE="encrypted"; return 0
  fi

  return 1
}

# Classify key material without printing it.
#
# This exists because of the single most expensive reading in this repository:
# HETZNERSSHKEY has held a *public* key since it was first pasted (run
# 33884253173), so every SSH route has been dead for reasons no route could
# report. That was only discoverable by burning a workflow dispatch. Here it is
# a property of the stored secret, checkable on a laptop, with no runner and no
# network — which is the whole argument for moving the store off Actions.
describe() {
  local name="$1" value="$2"
  case "$name" in
    *SSHKEY*|*SSH_KEY*)
      if [[ "$value" == ssh-* || "$value" == ecdsa-sha2-* ]]; then
        echo "PUBLIC key — cannot open a session; store the private half"
        return 1
      fi
      if [[ "$value" != *"PRIVATE KEY"* ]]; then
        echo "not an OpenSSH/PEM private key"
        return 1
      fi
      echo "private key, $(wc -l <<<"$value" | tr -d ' ') lines"
      ;;
    *TOKEN*|*PAT*|*API_KEY*|*APIKEY*)
      # Deliberately no brand-prefix matching here. Writing the literal token
      # prefixes into this file would trip `test_no_live_secrets_in_git`, whose
      # needle list is "does any committed file contain something shaped like a
      # credential" -- and a scanner that has to special-case the file most
      # likely to discuss credentials is a scanner one exception from useless.
      # What is left is the failure that actually happens to a pasted token:
      # a space or a line break came along with it, and the API rejects it for
      # reasons that never mention whitespace.
      if [[ "$value" =~ [[:space:]] ]]; then
        echo "contains whitespace — probably a bad paste"
        return 1
      fi
      echo "${#value} chars"
      ;;
    *) echo "${#value} chars" ;;
  esac
  return 0
}

# ---------------------------------------------------------------------- modes

cmd_check() {
  local rc=0 name value source shown
  printf '%-22s %-12s %s\n' SECRET SOURCE NOTE
  printf '%-22s %-12s %s\n' ---------------------- ------------ ----
  while read -r name; do
    if resolve "$name"; then
      value="$REPLY"; source="$SOURCE"
      if shown="$(describe "$name" "$value")"; then
        printf '%-22s %-12s %s\n' "$name" "$source" "$shown"
      else
        printf '%-22s %-12s %s\n' "$name" "$source" "BAD: $shown"
        rc=1
      fi
    else
      printf '%-22s %-12s %s\n' "$name" "-" "missing — gates: $(registry_field "$name" 2)"
    fi
  done < <(registry_names)

  echo
  echo "store:    $SECRETS_DIR"
  echo "encrypted: $ENC_DIR/<NAME>.age  (identity: $AGE_IDENTITY_FILE)"
  echo "docs:     infra/SECRETS.md"
  return "$rc"
}

cmd_get() {
  local name="${1:-}"
  [[ -n "$name" ]] || die "--get needs a secret name"
  resolve "$name" || die "$name is not set anywhere (see: load-secrets.sh --check)"
  printf '%s\n' "$REPLY"
}

cmd_export() {
  local name
  while read -r name; do
    if resolve "$name"; then
      # printf %q, so a newline-bearing private key survives `eval` intact.
      printf 'export %s=%q\n' "$name" "$REPLY"
    fi
  done < <(registry_names)
}

cmd_put() {
  local name="${1:-}"
  [[ -n "$name" ]] || die "--put needs a secret name"
  mkdir -p "$SECRETS_DIR"; chmod 700 "$SECRETS_DIR"
  # Written by redirect from stdin so the value never appears in argv, where
  # every local user can read it out of `ps` for as long as the command runs.
  ( umask 077; cat > "$SECRETS_DIR/$name" )
  chmod 600 "$SECRETS_DIR/$name"
  echo "wrote $SECRETS_DIR/$name"
  resolve "$name" && describe "$name" "$REPLY" || true
}

cmd_encrypt() {
  local name="${1:-}"
  [[ -n "$name" ]] || die "--encrypt needs a secret name"
  command -v age >/dev/null 2>&1 || die "install age: https://github.com/FiloSottile/age"
  [[ -f "$RECIPIENTS" ]] || die "no recipients at $RECIPIENTS — add your age public key first"
  grep -q '^age1' "$RECIPIENTS" || die "$RECIPIENTS holds no age1… recipient"
  [[ -f "$SECRETS_DIR/$name" ]] || die "no plaintext at $SECRETS_DIR/$name"
  mkdir -p "$ENC_DIR"
  # --armor: ASCII, so the committed file diffs as text rather than as a binary
  # blob git can only report as "changed".
  age --armor -R "$RECIPIENTS" -o "$ENC_DIR/$name.age" "$SECRETS_DIR/$name"
  echo "wrote $ENC_DIR/$name.age (safe to commit)"
}

cmd_exec() {
  [[ $# -gt 0 ]] || die "--exec needs a command after --"
  local name env_args=()
  while read -r name; do
    resolve "$name" && env_args+=("$name=$REPLY")
  done < <(registry_names)

  # An ssh-agent scoped to this one command. restore-cluster.sh and the host
  # installers call plain `ssh`, which takes an identity from an agent or from
  # ~/.ssh and from nowhere else — so without this, "the secret is available"
  # still would not make the deploy work, and the owner would be back to
  # ssh-add'ing a key by hand. It is killed on exit, touches neither ~/.ssh nor
  # your own agent, and its key file lives in a mode-700 temp dir.
  local agent_dir="" started_agent=0
  if resolve HETZNERSSHKEY && command -v ssh-agent >/dev/null 2>&1 \
     && [[ "${NO_SSH_AGENT:-0}" != "1" ]]; then
    agent_dir="$(mktemp -d)"; chmod 700 "$agent_dir"
    # Reuses the classifier rather than restating it: it normalises the two ways
    # a pasted key breaks (literal \n escapes, CRLF) and refuses a public key
    # with a specific message.
    if HETZNERSSHKEY="$REPLY" "$ROOT/bootstrap/scripts/load-ssh-key.sh" "$agent_dir/id" >/dev/null; then
      eval "$(ssh-agent -s)" >/dev/null
      started_agent=1
      ssh-add -q "$agent_dir/id" 2>/dev/null || echo "load-secrets: ssh-add refused the key" >&2
      env_args+=("SSH_AUTH_SOCK=$SSH_AUTH_SOCK")
    else
      echo "load-secrets: HETZNERSSHKEY is unusable; running without an ssh-agent" >&2
    fi
  fi

  cleanup() {
    [[ "$started_agent" == 1 ]] && ssh-agent -k >/dev/null 2>&1 || true
    [[ -n "$agent_dir" ]] && rm -rf "$agent_dir" || true
  }
  trap cleanup EXIT

  # `env --` and not `export`: the values land in the child's environment and in
  # no shell that outlives it.
  env "${env_args[@]}" "$@"
}

MODE="${1:---check}"
[[ $# -gt 0 ]] && shift || true
case "$MODE" in
  --check|check)     cmd_check "$@" ;;
  --get|get)         cmd_get "$@" ;;
  --export|export)   cmd_export "$@" ;;
  --put|put)         cmd_put "$@" ;;
  --encrypt|encrypt) cmd_encrypt "$@" ;;
  --exec|exec)       [[ "${1:-}" == "--" ]] && shift; cmd_exec "$@" ;;
  -h|--help)         sed -n '2,60p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' ;;
  *)                 die "unknown mode '$MODE' (try --help)" ;;
esac
