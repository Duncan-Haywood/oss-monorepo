const CATEGORY_OF = Object.fromEntries(Object.entries(BY_CATEGORY).flatMap(([c, s]) => s.split(/\s+/).map((slug) => [slug, c])));

export function listTrades() {
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name.endsWith("-bid-calculator"))
    .map((d) => {
      const slug = d.name.replace(/-bid-calculator$/, "");
      const trade = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
      return { slug, trade, category: CATEGORY_OF[slug] ?? null, calculator: d.name };
    })
    .sort((a, b) => a.trade.localeCompare(b.trade));
}

export function renderModule(trades) {
  return `// Generated by build-trades.mjs. Do not edit by hand.\nexport const CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2)};\nexport const TRADES = ${JSON.stringify(trades, null, 1).replace(/\n\s+/g, " ").replace(/\[ /, "[\n ").replace(/ \]$/, "\n]")};\n`.replace(/\}, \{/g, "},\n {");
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const trades = listTrades();
  const missing = trades.filter((t) => !t.category).map((t) => t.slug);
  if (missing.length) { console.error("No category for:", missing.join(", ")); process.exit(1); }
  writeFileSync(new URL("./trades.mjs", import.meta.url), renderModule(trades));
  console.log(`wrote trades.mjs (${trades.length} trades)`);
}
